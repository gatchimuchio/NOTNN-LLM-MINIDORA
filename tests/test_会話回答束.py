    def test_意味側から同伴条件を落としても保持閉包から免除しない(self):
        # 下流の意味不足返却だけを隔離。公開APIは先に既存子validatorでも改変を拒否する。
        包 = 契約を作る("「装置A」を二文以内で説明してください。")
        子 = 子を作る(包, {"甲": 能力結果(True, "装置Aは文書を送信する。ただし休業日は送信しない。")})[0]["成果"]
        行 = 会話目的を読む(包, 所有セッション=所有)[0]
        改変 = deepcopy(子)
        意味 = 改変.データ["意味成果"]
        条件ID = next(項["ID"] for 項 in 意味["記載関係"] if 項["資料作用"]["条件候補"])
        意味["使用記載"].remove(条件ID)
        意味["意味"]["命題"] = [項 for 項 in 意味["意味"]["命題"] if 項["種別"] != "限定記載"]
        for 項 in 意味["意味"]["命題"]:
            項["根拠"] = [名 for 名 in 項["根拠"] if 名 != 条件ID]
            項["条件"] = []
        with self.assertRaisesRegex(ValueError, "資料意味不足.*条件.*" + 条件ID):
            _保持を照合(行, 改変)

