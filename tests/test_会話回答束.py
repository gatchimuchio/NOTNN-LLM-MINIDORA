def 契約を作る(制御, 本文=None, *, 形式=None):
    原文 = 制御 if 本文 is None else 制御 + "\n\n" + 本文
    座標 = ()
    if 本文 is not None:
        座標 = tuple(HDS座標("入力:" + 名, "情報源.会話入力区分", {"役割": 名, "本文": 原文[始:終]},
                        原文範囲=(始, 終), 由来="公開HDS 入力区分")
                   for 名, 始, 終 in (("制御", 0, len(制御)), ("区切り", len(制御), len(制御) + 2),
                                    ("提示本文", len(制御) + 2, len(原文))))
    ir = HDS会話文節を形成(HDSIR(原文, 制御, "局所人工束", 座標, (), (), (), HDS実行核()))
    if 形式 is not None:
        for 番号, 目的 in enumerate([項 for 項 in ir.座標 if 項.種別 == "目的.会話操作"]):
            名 = "形式:" + str(番号)
            項 = HDS座標(名, "表現.会話形式", {"値": 形式, "原文": "", "根拠": "既定", "前束参照": None},
                        由来=会話射影由来)
            辺 = HDS関係(名 + ":適用", (名,), (目的.座標ID,), "表現適用", 由来=会話射影由来)
            座標 = (*ir.座標, 項)
            作用 = replace(ir.意味作用履歴[-1], 出力参照=tuple(項.座標ID for 項 in 座標 if 項.由来 == 会話射影由来))
            ir = replace(ir, 座標=座標, 関係=(*ir.関係, 辺), 意味作用履歴=(作用,))
    return 会話契約を形成(ir, 所有セッション=所有)


def 子を作る(包, 資料=None, *, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=(), 提示資料名="提示資料"):
    列 = []
    ctx = {"前採用包": 前採用包, "文脈証明": 文脈証明, "前命令包": 前命令包, "命令証明": 命令証明}
    for 行 in 会話目的を読む(包, 所有セッション=所有, **ctx):
        要求 = 行["要求"]
        本文群 = {提示資料名: 能力結果(True, 要求["提示本文"])} if 要求["提示本文"] else 資料
        構造 = 資料意味を選ぶ(本文群, 要求)
        列.append({"目的ID": 行["目的ID"], "成果": 資料文章を照合(構造, _文章(構造))})
    return 列


def 束を作る(列, 包, **ctx):
    仕様 = 会話束内容仕様を構成(列, 包, 所有セッション=所有, **ctx)
    文 = 文章を作る({名: 能力結果を復元(値) for 名, 値 in 仕様["素材"].items()}, 文章仕様を復元(仕様["仕様"]))
    return 会話束回答を照合(列, 包, 文, 所有セッション=所有, **ctx)


def 前束契約を作る(制御, 前包, *, 先証明=()):
    # 実COMMITではなく独立callerの人工証明。元包の実座標と適用辺を参照する。
    from test_会話目的束 import _基礎, _証明
    証明 = _証明(前包)
    証明[0]["所有セッション"] = 所有
    証明[0]["原記録ID"] = "人工採用:" + 前包["意味束印"]
    証明.extend(deepcopy(先証明))
    ctx = {"前採用包": 前包, "文脈証明": 証明}
    ir = HDS会話文節を形成(_基礎(制御), **ctx)
    return 会話契約を形成(ir, 所有セッション=所有, 文脈証明=証明), ctx


class 会話回答束試験(unittest.TestCase):
    def test_別目的の要求数量を混ぜず全子を既存writerで保護(self):
        包 = 契約を作る("「装置A」を一文で説明し、「装置B」を二文以内で要約してください。")
        列 = 子を作る(包, {"甲": 能力結果(True, "装置Aは文書を送信する。"), "乙": 能力結果(True, "装置Bはログを確認する。")})
        前 = deepcopy((包, 列))
        束 = 束を作る(列, 包)
        self.assertEqual(束.本文, "\n\n".join(子["成果"].本文 for 子 in 列))
        self.assertEqual(束.データ["版"], "HDS会話目的束回答-v3")
        self.assertIsNone(束.データ["前採用包"])
        self.assertEqual(束.データ["文脈証明"], [])
        self.assertEqual(束.データ["種別"], "会話目的束回答")
        self.assertEqual([行["照合"]["数量"][0]["実測"]["数"] for 行 in 束.データ["目的成果"]], [1, 1])
        self.assertTrue(all(単位["必須"] and 単位["保護"] for 単位 in 束.データ["内容仕様"]["仕様"]["単位群"]))
        self.assertTrue(会話束回答を検査(束, 所有セッション=所有))
        self.assertTrue(会話束回答を検査(結果を復元(結果を保存(束)), 所有セッション=所有))
        self.assertEqual((包, 列), 前)

    def test_例外と否定を落とさず二文を成立させる(self):
        包 = 契約を作る("例外と否定を保持して二文で要約してください。", "作業員は荷札を検査する。ただし休業日は検査しない。")
