from __future__ import annotations

import unittest

from minidora.HDS実行主体 import (
    HDS実行主体, HDS実行状態, HDS関数作用, HDS作用結果, HDS作用状態, HDS終端,
)

F = frozenset


class 原子的読取更新非退行試験(unittest.TestCase):
    def test_読取更新した成果で自分の段階状態を即時失効しない(self):
        呼出 = []

        def 参照更新(状態):
            呼出.append("参照")
            現在 = tuple(状態.成果辞書().get("参照群", ()))
            return HDS作用結果(
                HDS作用状態.成立,
                追加状態=F({"追加参照済み"}),
                成果=(("参照群", 現在 + ("追加",)),),
            )

        def 再評価(状態):
            呼出.append("再評価")
            return HDS作用結果(
                HDS作用状態.成立,
                追加状態=F({"回答確定"}),
                解消残差=F({"回答未閉包"}),
                成果=(("回答ラベル", "A"),),
            )

        参照 = HDS関数作用(
            "追加参照", 参照更新,
            入力状態=("初期評価済み",), 出力状態=("追加参照済み",),
            読取成果=("参照群",), 資源負荷=4,
        )
        評価 = HDS関数作用(
            "再評価", 再評価,
            入力状態=("追加参照済み",), 出力状態=("回答確定",),
            解消対象=("回答未閉包",), 読取成果=("参照群",),
            資源負荷=1, 優先度=3,
        )
        状態 = HDS実行状態(
            要求状態=F({"回答確定"}), 成立状態=F({"初期評価済み"}),
            残差=F({"回答未閉包"}), 成果=(("参照群", ("初期",)),),
        )
        結果 = HDS実行主体((参照, 評価), 最大作用回数=4).実行(状態)
        self.assertEqual(結果.終端, HDS終端.採用, 結果.理由)
        self.assertEqual(呼出, ["参照", "再評価"])
        self.assertEqual([x.作用ID for x in 結果.履歴], ["追加参照", "再評価"])
        self.assertNotIn("状態:追加参照済み", 結果.履歴[0].状態差.失効対象)

    def test_後続再評価の回答は後の参照変更で失効する(self):
        def 参照更新(状態):
            現在 = tuple(状態.成果辞書().get("参照群", ()))
            return HDS作用結果(
                HDS作用状態.成立,
                追加状態=F({"追加参照済み"}),
                成果=(("参照群", 現在 + ("追加",)),),
            )

        def 再評価(_状態):
            return HDS作用結果(
                HDS作用状態.成立,
                追加状態=F({"回答確定"}),
                解消残差=F({"回答未閉包"}),
                成果=(("回答ラベル", "A"),),
            )

        参照 = HDS関数作用(
            "追加参照", 参照更新, 入力状態=("初期評価済み",),
            出力状態=("追加参照済み",), 読取成果=("参照群",),
        )
        評価 = HDS関数作用(
            "再評価", 再評価, 入力状態=("追加参照済み",),
            出力状態=("回答確定",), 解消対象=("回答未閉包",),
            読取成果=("参照群",),
        )
        状態 = HDS実行状態(
            要求状態=F({"回答確定"}), 成立状態=F({"初期評価済み"}),
            残差=F({"回答未閉包"}), 成果=(("参照群", ("初期",)),),
        )
        完了 = HDS実行主体((参照, 評価), 最大作用回数=4).実行(状態)
        self.assertEqual(完了.終端, HDS終端.採用)
        更新後, 差 = HDS実行主体._状態更新(
            完了.状態,
            HDS作用結果(HDS作用状態.成立, 成果=(("参照群", ("別資料",)),)),
        )
        self.assertNotIn("回答確定", 更新後.成立状態)
        self.assertNotIn("回答ラベル", 更新後.成果辞書())
        self.assertIn("状態:回答確定", 差.失効対象)
        self.assertIn("成果:回答ラベル", 差.失効対象)


if __name__ == "__main__":
    unittest.main()
