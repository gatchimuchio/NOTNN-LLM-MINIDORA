"""未充足の説明を採用へ載せず、原支持と確認内容を保持する有限対照。"""
from copy import deepcopy
import unittest

from minidora.HDS運用.意味資料 import 資料意味を選ぶ
from minidora.HDS運用.資料回答 import (
    回答意味を構成, 資料内容不足, 資料内容不足を読む, 資料内容不足版, 資料回答版,
)
from minidora.HDS運用.一般接続 import 一般資料能力
from minidora.能力合成 import _結果辞書
from minidora.製品版.型 import 能力結果
from minidora.製品版.能力契約 import 能力文脈
from minidora.採否 import 実行状態


def 構造を作る(本文, 対象="保管具", *, 詳細="標準"):
    対象群 = [対象] if isinstance(対象, str) else list(対象)
    要求 = {"版": "HDS一般会話要求-v2", "対象": [], "主題": 対象群,
            "操作": ["説明"], "形式": "文章", "範囲": "自動", "最大文字数": 24000,
            "問い": "と".join(対象群) + "とは何ですか", "比較対象": [], "観点": [], "詳細": 詳細,
            "提示本文": "", "関係焦点": ["定義"], "肯否": "未指定"}
    return 資料意味を選ぶ({"有限原資料": 能力結果(True, 本文)}, 要求)


def 文脈を作る(構造):
    return 能力文脈("原要求から内容を構成する", "有限内容不足",
                   補助={"合成入力": [{"結果": _結果辞書(能力結果(True, "", データ=構造))}],
                       "合成設定": {}})


class 資料内容不足試験(unittest.TestCase):
    def 診断を得る(self, 構造):
        with self.assertRaises(資料内容不足) as 捕捉:
            回答意味を構成(構造)
        return 捕捉.exception.診断

    def test_所属一つでも原支持と要求と確認を保持(self):
        本文 = "保管具は器具の一種である。"
        構造 = 構造を作る(本文)
        診断 = self.診断を得る(構造)
        self.assertEqual(診断["版"], 資料内容不足版)
        self.assertEqual(診断["意味版"], 資料回答版)
        self.assertEqual(診断["要求"], 構造["要求"])
        self.assertEqual(診断["対象"], ["保管具"])
        self.assertEqual(診断["不足役割"][0]["種別"], "識別的内容")
        self.assertTrue(診断["必要確認"])
        self.assertEqual(len(診断["読解済み内容"]), 1)
        for 支持 in 診断["実支持"]:
            対応 = 支持["対応"]
            self.assertEqual(本文[対応["開始"]:対応["終了"]], 対応["原文"])
        self.assertEqual(資料内容不足を読む(診断, 構造), 診断)

    def test_複数所属でも文数で要求充足へ変えない(self):
        診断 = self.診断を得る(構造を作る("保管具は器具の一種である。保管具は道具の一つである。"))
        self.assertEqual(len(診断["読解済み内容"]), 2)
        self.assertEqual(len(診断["実支持"]), 2)
        self.assertEqual(診断["不足役割"][0]["種別"], "識別的内容")

    def test_具体的定義まで一律に不足としない(self):
        意味 = 回答意味を構成(構造を作る("加工機とは金属を削る機械である。", "加工機"))
        self.assertIn("金属を削る", 意味["意味"]["命題"][0]["本文"])

    def test_同じ具体的連体事象は直接定義と成員定義で保持(self):
        for 述部 in ("金属を削る機械", "金属を削る機械の一つ"):
            with self.subTest(述部=述部):
                意味 = 回答意味を構成(構造を作る("加工機とは" + 述部 + "である。", "加工機"))
                self.assertIn(述部, 意味["意味"]["命題"][0]["本文"])
                定義 = 意味["記載関係"][0]["関係"]["定義"]
                self.assertEqual(定義["連体型証拠"]["原文"], "金属を削る機械")
                if 定義.get("成員関係"):
                    寄与 = next(項 for 項 in 意味["演算"] if 項["種別"] == "成員定義の内容寄与")
                    self.assertIsNone(寄与["読解"]["内部事象"][0]["明示主体"])
                    self.assertEqual(寄与["読解"]["内部事象"][0]["主体状態"], "未明示")
                    self.assertEqual(寄与["読解"]["成員関係"], 定義["成員関係"])

    def test_領域や名称の修飾だけで作用を構成済みにしない(self):
        for 述部 in ("架空領域における区分の一つ", "伝承活動である催事Bの一分野（催事Bの活動A）",
                     "情報を移動するための、装置B（B）が持つ機能の一つ"):
            with self.subTest(述部=述部):
                診断 = self.診断を得る(構造を作る("保管具は" + 述部 + "である。"))
                self.assertEqual(診断["不足役割"][0]["種別"], "定義修飾の役割")
                self.assertIn(述部, 診断["読解済み内容"][0]["本文"])
                self.assertNotIn("示せたのは資料の種別・所属関係", 診断["不足役割"][0]["説明"])

    def test_母集団修飾の明示別主体を成員の動作へ変えない(self):
        診断 = self.診断を得る(構造を作る("加工機とは作業者が金属を削る機械の一つである。", "加工機"))
        self.assertEqual(診断["不足役割"][0]["種別"], "定義修飾の役割")
        self.assertIn("作業者が金属を削る", 診断["読解済み内容"][0]["本文"])

    def test_他対象の定義や補足で不足対象を完成扱いしない(self):
        for 本文 in (
            "加工機とは金属を削る機械である。保管具は器具の一種である。",
            "加工機は機械の一つである。加工機の素材は金属です。保管具は器具の一種である。",
            "加工機とは金属を削る機械である。保管具は地域における器具の一種である。",
        ):
            with self.subTest(本文=本文):
                診断 = self.診断を得る(構造を作る(本文, ["加工機", "保管具"]))
                self.assertEqual(診断["不足役割"][0]["対象"], ["保管具"])
                self.assertTrue(any("加工機" in 項["本文"] for 項 in 診断["読解済み内容"]))
                self.assertTrue(any("保管具" in 項["本文"] for 項 in 診断["読解済み内容"]))

    def test_両対象の具体的成員定義を各主体に保持(self):
        意味 = 回答意味を構成(構造を作る(
            "加工機は金属を削る機械の一つである。保管具は資料を保管する器具の一つである。",
            ["加工機", "保管具"]))
        寄与 = [項 for 項 in 意味["演算"] if 項["種別"] == "成員定義の内容寄与"]
        self.assertEqual({項["対象"] for 項 in 寄与}, {"加工機", "保管具"})

    def test_正常な資料限定留保と内容不足を分ける(self):
        意味 = 回答意味を構成(構造を作る(
            "保管具とは収納用の容器である。保管具の素材は樹脂です。別器具は運転可能です。ただし高温の場合に限ります。"))
        self.assertTrue(意味["意味"]["留保"])
        self.assertTrue(any("樹脂" in 項["本文"] for 項 in 意味["意味"]["命題"]))

    def test_診断の根拠区間要求確認本文改変は通常不正(self):
        構造 = 構造を作る("保管具は器具の一種である。")
        原 = self.診断を得る(構造)
        for 種別 in ("記載ID", "原区間", "要求", "確認", "本文"):
            診断 = deepcopy(原)
            if 種別 == "記載ID": 診断["実支持"][0]["記載ID"] = "存在しない支持"
            elif 種別 == "原区間": 診断["実支持"][0]["対応"]["開始"] += 1
            elif 種別 == "要求": 診断["要求"]["主題"] = ["別対象"]
            elif 種別 == "確認": 診断["必要確認"] = []
            else: 診断["読解済み内容"][0]["本文"] = "未確認の結論"
            with self.subTest(種別=種別), self.assertRaises(ValueError) as 捕捉:
                資料内容不足を読む(診断, 構造)
            self.assertNotIsInstance(捕捉.exception, 資料内容不足)

    def test_能力接続は専用診断を保留成果として返す(self):
        構造 = 構造を作る("保管具は器具の一種である。保管具は道具の一つである。")
        結果 = 一般資料能力("資料内容構成").実行(文脈を作る(構造))
        self.assertFalse(結果.成立)
        self.assertEqual(結果.状態, 実行状態.保留)
        self.assertEqual(結果.データ["版"], 資料内容不足版)
        self.assertEqual(結果.データ["診断"], self.診断を得る(構造))
        self.assertIn("読めた範囲", 結果.保留理由)
        self.assertIn("必要な確認", 結果.保留理由)
        self.assertNotIn("記載がない", 結果.保留理由)

    def test_原構造の不正を内容不足診断へ変えない(self):
        構造 = 構造を作る("保管具は器具の一種である。")
        構造["資料順"] = ["存在しない資料"]
        結果 = 一般資料能力("資料内容構成").実行(文脈を作る(構造))
        self.assertFalse(結果.成立)
        self.assertNotEqual(結果.データ.get("版"), 資料内容不足版)


if __name__ == "__main__":
    unittest.main()
