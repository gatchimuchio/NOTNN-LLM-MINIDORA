        辺 = tuple(_関係(名, 始, 終, 種) for 名, 始, 終, 種 in (
            ("原適用1", "保持句1", "目的1", "条件適用"), ("原適用2", "保持句2", "目的1", "条件適用"),
            ("型適用1", "型保持1", "目的1", "表現適用"), ("型適用2", "型保持2", "目的1", "表現適用"),
            ("対応1", "保持句1", "型保持1", "保持対応"), ("対応2", "保持句2", "型保持2", "保持対応")))
