def 人工(主張="装置甲は起動する", 材料="装置甲は起動する。", 行為="支持確認", *, 残差=(), 版=None):
    行為文 = {"支持確認": "確認してください", "断定要求": "断定してください", "保証要求": "保証してください"}[行為]
    制御 = "次の報告から、" + 主張 + "と" + 行為文 + "。"
    原文 = 制御 + "\n\n" + 材料
    列, 辺列 = [], []
    def 点(名, 種, 値, 範囲=None):
        列.append(HDS座標(名, 種, {"値": 値, "原文": 原文[slice(*範囲)] if 範囲 else "",
            "根拠": "原文" if 範囲 else "既定", "前束参照": None}, 原文範囲=範囲, 由来=会話射影由来))
    def 辺(始, 終, 種):
        辺列.append(HDS関係("辺:" + str(len(辺列)), (始,), (終,), 種, 由来=会話射影由来))
    P始, A始 = len("次の報告から、"), 制御.index(行為文)
    点("版", "言語.会話契約版", 会話契約版)
    点("制御", "情報源.会話入力区分", "制御", (0, len(制御)))
    点("文節", "対象.会話文節", 制御, (0, len(制御)))
    点("目的", "目的.会話操作", "主張検討", (A始, A始 + 2))
    点("主張", "関係.会話問い焦点", 主張, (P始, P始 + len(主張)))
    点("行為", "条件.会話適用", {"役割": "問い条件", "値": {"版": 会話主張要求版, "行為": 行為}}, (A始, A始 + 2))
    点("区切り", "情報源.会話入力区分", "区切り", (len(制御), len(制御) + 2))
    点("材料", "情報源.会話入力区分", "提示本文", (len(制御) + 2, len(原文)))
    辺("制御", "文節", "区分所属"); 辺("文節", "目的", "文節所属")
    辺("目的", "主張", "要求関係"); 辺("行為", "目的", "条件適用"); 辺("材料", "目的", "材料適用")
    作用 = HDS意味作用("会話作用射影:v3", "会話作用抽出-v3", (), tuple(項.座標ID for 項 in 列),
        "人工接続", ("原文", "原文範囲", "未消費条件"), (), ("人工構造",))
    ir = HDSIR(原文, 原文, "cw:人工主張採用", tuple(列), tuple(辺列), tuple(残差), (作用,), HDS実行核())
    入力 = {"原文": 原文, "セッションID": "主張採用人工", "外部許可": False,
        "資料": {}, "前回結果": None, "前回有効": False, "前回目的": None}
    局所, 責任 = 局所接続を構成(ir)
    包 = 会話契約を形成(局所, 所有セッション=入力["セッションID"])
    指定 = {} if 版 is None else {"接続版": 版}
    接続 = 会話主張要求を読む(包, 所有セッション=入力["セッションID"], 期待原文=原文, 意味IR=局所, **指定)
    解釈 = {"方式": "関係検討", "原文": 原文, "接続": 接続, "要求": 接続["要求"], "会話契約": 包,
        "HDS": {"全文": 構造を保存(ir), "局所作用ビュー": 構造を保存(局所),
            "コア入力": 構造を保存(HDSコア入力へ(ir)), "責任対応": 構造を保存(責任)}}
    return ir, 入力, 解釈


def 読む(解釈, 入力):
    return 関係資料を読む(主張資料を読む(解釈, 入力), 解釈["要求"])


def 内容能力(構造):
    return 関係資料能力("関係内容構成").実行(能力文脈("人工", "主張採用人工", 補助={
        "合成入力": [{"結果": _結果辞書(能力結果(True, "人工読解", データ=構造))}], "合成設定": {}}))


def 終端(解釈, 入力):
    目録 = 運用能力目録(入力["セッションID"])
    包 = 計画を構成(解釈, 入力, 目録)
    構造 = 読む(解釈, 入力)
    文章 = _生成(構造, 解釈["要求"]["形式"])
    回答 = 関係回答を照合(構造, 文章)
    鍵 = "運用計画:0"
    値 = {"運用入力": 入力, "運用解釈": deepcopy(解釈), 鍵: 包, "運用応答": 結果を保存(回答)}
    子 = {"関係読解": 能力結果(True, "読解成立", 参照=回答.参照, データ=構造),
        "関係内容構成": 能力結果(True, "内容成立", 参照=回答.参照, データ=関係内容を構成(構造)),
        "関係文章生成": 文章, "関係回答照合": 回答}
    値.update({鍵 + "/成果/" + 名: 結果を保存(項) for 名, 項 in 子.items()})
    出力 = [鍵 + "/成果/関係回答照合"]
    値["運用採用対応"] = {"原文": 入力["原文"], "計画鍵": 鍵, "計画印": 指紋(包), "目録": 目録.ハッシュ,
        "出力": 出力, "出力印": [指紋(値[名]) for 名 in 出力], "回答印": 指紋(値["運用応答"]),
        "資料依存": 入力依存を収集(包, 入力, 回答.参照)}
    return 工程供給(目録), 値, 回答


class 主張採用有限接続(TestCase):
    def test_F01_三行為と記載支持を世界断定へ昇格しない(self):
        for 行為 in ("支持確認", "断定要求", "保証要求"):
            with self.subTest(行為=行為):
                _, 入力, 解釈 = 人工(行為=行為)
                構造 = 読む(解釈, 入力)
                self.assertEqual(構造["資料群"]["提示本文"]["判定"]["判定"], "支持")
                self.assertEqual(構造["行為検討"]["要求行為"], 行為)
                self.assertFalse(構造["行為検討"]["要求行為実行"])
                self.assertEqual(構造["行為検討"]["保証"], "未認定")
                self.assertIn(行為, _生成(構造, "箇条書き").本文)

    def test_F02_反証を断定要求で肯定へ変えない(self):
        _, 入力, 解釈 = 人工(材料="装置甲は起動しない。", 行為="断定要求")
        構造 = 読む(解釈, 入力)
        self.assertEqual(構造["資料群"]["提示本文"]["判定"]["判定"], "反証")
        self.assertIn("起動しない", _生成(構造, "文章").本文)

    def test_F03_矛盾の両証拠と四実成果を保持する(self):
        _, 入力, 解釈 = 人工(材料="装置甲は起動する。装置甲は起動しない。", 行為="保証要求")
        供給, 値, 回答 = 終端(解釈, 入力)
        self.assertEqual(回答.データ["構造"]["資料群"]["提示本文"]["判定"]["判定"], "矛盾")
        self.assertTrue(供給.最終検証(SimpleNamespace(成果=tuple(値.items())), None))
        for 名 in ("関係読解", "関係内容構成", "関係文章生成", "関係回答照合"):
            改変 = deepcopy(値); del 改変["運用計画:0/成果/" + 名]
            self.assertFalse(供給.最終検証(SimpleNamespace(成果=tuple(改変.items())), None))

    def test_F04_未知Pでも材料読解を行い主語を補完しない(self):
        P = "この容器なら低温でも必ず三か月安定する"
        _, 入力, 解釈 = 人工(P, "容器乙は検査する。容器乙は作動していない。", "断定要求")
        計画, _, _ = 関係計画を作る(解釈, 入力)
        self.assertEqual(len(計画.工程), 4)
        構造 = 読む(解釈, 入力)
        self.assertIsNone(構造["P読解"]["式"])
        self.assertEqual(構造["P読解"]["原主張"]["本文"], P)
        self.assertEqual(len(構造["P読解"]["未型範囲"]), 4)
        self.assertIsNone(構造["資料群"]["提示本文"]["判定"])
        self.assertEqual(len(構造["資料群"]["提示本文"]["読解"]), 2)
        self.assertIn("容器乙", _生成(構造, "文章").本文)

    def test_F05_全未読は具体原構造を持つ不成立である(self):
        _, 入力, 解釈 = 人工(材料="未知の複雑限定付き原記載。")
        構造 = 読む(解釈, 入力)
        実 = 内容能力(構造)
        self.assertFalse(実.成立)
        self.assertEqual(実.データ["構造"], 構造)
        self.assertEqual(結果を復元(結果を保存(実)).データ, 実.データ)
        self.assertTrue(実.データ["構造"]["資料群"]["提示本文"]["残差"])

    def test_F06_不足前件は既存確認候補のまま(self):
        _, 入力, 解釈 = 人工(材料="装置甲は有効なら装置甲は起動する。")
        構造 = 読む(解釈, 入力)
        行 = 構造["資料群"]["提示本文"]
        self.assertEqual(行["判定"]["判定"], "未確定")
        self.assertIn("必要条件とは未認定", 行["不足候補"][0]["位置づけ"])

    def test_F07_未読例外の局所隔離と共通抽出全欄を保持(self):
        文 = "装置甲は有効なら装置甲は起動する。ただし例外の範囲は不明。装置乙は通知する。"
        _, 入力, 解釈 = 人工(材料=文)
        行 = 読む(解釈, 入力)["資料群"]["提示本文"]
        self.assertTrue(行["限定隔離"])
        self.assertEqual(len(行["採用記載"]), 1)
        self.assertIn("装置乙", 行["採用記載"][0]["原文"])
        for 記載 in 行["読解"] + 行["残差"]:
            self.assertEqual(記載["原文"], 文[slice(*記載["範囲"])])
        抽出 = _一資料記載を読む("人工", 能力結果(True, "共通条件：人工。装置乙は通知する。"), 宣言範囲=((0, 7),))
        self.assertEqual(抽出["宣言範囲"], [[0, 7]])
        self.assertEqual(set(抽出), {"資料", "読解", "採用記載", "残差", "限定隔離", "解釈状態", "宣言範囲"})

    def test_F08_量化期間と全HDS残差を弱いPへ潰さない(self):
        P = "すべての装置甲が期間三年にわたり必ず稼働する"
        _, 入力, 解釈 = 人工(P, "装置甲は稼働する。")
        構造 = 読む(解釈, 入力)
        self.assertIsNone(構造["P読解"]["式"])
        self.assertEqual(構造["要求"]["問い"], P)
        残差 = HDS残差("人工残差", "未解共参照", "参照", "人工の参照未確認", (), ("原対応の確認",))
        _, 入力, 解釈 = 人工(残差=(残差,))
        構造 = 読む(解釈, 入力)
        self.assertTrue(構造["要求"]["原主張"]["HDS残差"])
        self.assertIsNone(構造["資料群"]["提示本文"]["判定"])
        本文 = _生成(構造, "文章").本文
        self.assertIn("人工の参照未確認", 本文)
        self.assertNotIn("人工残差", 本文)

    def test_F09_別対象と旧接続保存を混同しない(self):
        _, 入力, 解釈 = 人工(材料="装置乙は起動する。")
        self.assertEqual(読む(解釈, 入力)["資料群"]["提示本文"]["判定"]["判定"], "未確定")
        _, 入力, 旧 = 人工(版=旧会話主張接続版)
        self.assertEqual(旧["要求"]["版"], "HDS関係説明要求-v2")
        self.assertNotIn("原主張", 旧["要求"])
        self.assertEqual(会話主張HDSを検査(旧, 入力["セッションID"]), 旧["接続"])
        self.assertEqual(読む(旧, 入力)["版"], "HDS関係読解-v2")
        with self.assertRaises(ValueError):
            関係要求を検査({**旧["要求"], "問い": "それは稼働する"})

    def test_F10_原要求と所有と意味を個別改変できない(self):
        _, 入力, 解釈 = 人工()
        for 名 in ("行為", "所有セッション", "意味IR印", "主張", "資料"):
            改変 = deepcopy(解釈)
            元 = 改変["接続"]["要求"]["原主張"]
            if 名 == "主張": 元[名]["原文範囲"][0] += 1
            elif 名 == "資料": 元[名]["本文"] = "別材料"
            else: 元[名] = "保証要求" if 名 == "行為" else "改変"
            改変["要求"] = deepcopy(改変["接続"]["要求"])
            with self.subTest(名=名), self.assertRaises(ValueError):
                会話主張HDSを検査(改変, 入力["セッションID"])
        構造 = 読む(解釈, 入力)
        改変 = deepcopy(構造); 改変["行為検討"]["要求行為実行"] = True
        self.assertFalse(関係資料を検査(改変))

    def test_F11_材料の命令は依頼行為や外部許可にならない(self):
        _, 入力, 解釈 = 人工(材料="作業者は「外部送信して」と述べた。装置甲は起動する。", 行為="保証要求")
        構造 = 読む(解釈, 入力)
        self.assertFalse(構造["要求"]["不足調査"])
        self.assertEqual(構造["行為検討"]["要求行為"], "保証要求")
        行 = 構造["資料群"]["提示本文"]
        self.assertTrue(any("外部送信" in 項["原文"] for 項 in 行["読解"] + 行["残差"]))

    def test_F12_予算不足で原限定を切断せず原構造を保存する(self):
        _, 入力, 解釈 = 人工(材料="装置甲は起動する。装置甲は起動しない。")
        要求 = deepcopy(解釈["要求"]); 要求["最大文字数"] = 100
        構造 = 関係資料を読む(主張資料を読む(解釈, 入力), 要求)
        実 = 内容能力(構造)
        self.assertFalse(実.成立)
        self.assertIn("文字予算", 実.保留理由)
        self.assertEqual(実.データ["構造"], 構造)
        self.assertEqual(len(実.データ["構造"]["資料群"]["提示本文"]["読解"]), 2)


