    def test_W01_元理由に同じ結果の二端支持を必須とする(self):
        原文 = "職員はなぜ帳票を整理するの？その理由を、帳票との関係で説明してください。"
        成果, 意味 = self.正常(原文, {"資料A": "教師が教材を確認するため、職員は帳票を整理する。"}, 操作="理由")
        要求 = 成果.データ["構造"]["要求"]
        self.assertIn("帳票を整理する", 要求["関係焦点"])
        self.assertEqual(要求["関係要求"][0]["焦点"]["値"], "関係")
        self.assertTrue(any(項["種別"] == "記載理由関係" for 項 in 意味["演算"]))
        証拠 = [項 for 項 in 意味["演算"] if 項.get("版") == "原資料明示二端照合-v1"][0]
        self.双端を検査(証拠, "職員", "帳票", "整理", "する")
        self.assertIn("教師が教材を確認する", 成果.本文)
        self.assertIn("職員は帳票を整理する", 成果.本文)
        self.assertTrue(資料文章を検査(成果))

