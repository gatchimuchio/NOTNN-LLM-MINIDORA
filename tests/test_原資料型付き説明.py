def _形成(原文, *, 所有="人工型付き説明"):
    元 = HDSIR(原文, 原文, "人工読取世界", (), (), (), (), HDS実行核())
    ir = HDS会話文節を形成(元)
    if ir is None:
        raise AssertionError("事前固定した問いの会話型が未形成です")
    包 = 会話契約を形成(ir, 所有セッション=所有)
    行 = 会話目的を読む(包, 所有セッション=所有, 期待原文=原文, 意味IR=ir)
    return ir, 包, 行


def _要求(原文, *, 操作="説明", 種別="関係要求"):
    _, _, 行 = _形成(原文)
    候補 = [項["要求"] for 項 in 行
           if 項["要求"]["操作"] == [操作] and 項["要求"].get(種別)]
    if len(候補) != 1:
        raise AssertionError("事前固定した必須型の要求が一意に形成されていません")
    return 候補[0]


def _構造(原文, 資料, *, 操作="説明", 種別="関係要求"):
    要求 = _要求(原文, 操作=操作, 種別=種別)
    原資料 = {名: 能力結果(True, 本文, データ={"版": "人工原資料-v1"})
              for 名, 本文 in 資料.items()}
    return 資料意味を選ぶ(原資料, 要求)


class 原資料型付き説明有限(TestCase):
    def 正常(self, 原文, 資料, *, 操作="説明", 種別="関係要求"):
        構造 = _構造(原文, 資料, 操作=操作, 種別=種別)
        成果 = 資料文章を照合(構造, _文章(構造))
        self.assertTrue(成果.成立)
        意味 = 資料回答意味を読む(成果.データ["意味成果"], 意味版=資料回答版)
        self.assertTrue(意味["意味"]["命題"])
        self.assertTrue(all(項["本文"].strip() and 項["根拠"] for 項 in 意味["意味"]["命題"]))
        self.assertEqual(成果.データ["構造"]["要求"]["版"], "HDS一般会話要求-v3")
        self.assertEqual(成果.データ["構造"]["要求"][種別], 構造["要求"][種別])
        return 成果, 意味

    def 不足(self, 原文, 資料, *, 操作="説明", 種別="関係要求"):
        構造 = _構造(原文, 資料, 操作=操作, 種別=種別)
        with self.assertRaises(資料内容不足) as 失敗:
            回答意味を構成(構造)
        診断 = 失敗.exception.診断
        self.assertEqual(診断["実支持"], [])
        self.assertEqual(診断["読解済み内容"], [])
        self.assertTrue(診断["必要確認"])
        self.assertEqual(診断["要求"], 構造["要求"])
        self.assertTrue(診断["資料作用成果"])
        self.assertEqual(失敗.exception.構造, 構造)
        return 診断

    def 双端を検査(self, 証拠, 主体, 対象物, 動作, 活用):
        self.assertEqual(証拠["版"], "原資料明示二端照合-v1")
        self.assertEqual({項["格"] for 項 in 証拠["双端対応"]}, {"行為者", "対象物"})
        枠 = 証拠["同作用"]
        for 名, 値 in (("行為者", 主体), ("対象物", 対象物), ("動作", 動作), ("活用", 活用)):
            役割 = 枠["役割"][名]
            self.assertEqual(役割["原文"], 値)
            対応 = 証拠["対応"]
            self.assertEqual(対応["原文"][役割["開始"] - 対応["開始"]:
                                          役割["終了"] - 対応["開始"]], 値)
        self.assertEqual(証拠["格関係"]["終点"], [枠["座標ID"]])
        self.assertEqual(証拠["支持式"], 証拠["原主述表現"]["支持式"])
        self.assertTrue(証拠["明示型"])

    def test_L01_同一作用の両端と全源保存を結ぶ(self):
        成果, 意味 = self.正常("職員と帳票の関係を説明してください。", {"資料A": "職員は帳票を整理する。"})
        証拠 = [項 for 項 in 意味["演算"] if 項.get("版") == "原資料明示二端照合-v1"]
        self.assertEqual(len(証拠), 1)
        self.双端を検査(証拠[0], "職員", "帳票", "整理", "する")
        self.assertIn("職員", 成果.本文)
        self.assertIn("帳票", 成果.本文)
        self.assertIn("整理する", 成果.本文)
        self.assertTrue(資料文章を検査(成果))
        改変 = deepcopy(成果)
        改変.データ["構造"]["資料群"]["資料A"]["資料"]["本文"] = "職員は教材を整理する。"
        self.assertFalse(資料文章を検査(改変))
        改変 = deepcopy(成果)
        改変.データ["意味成果"] = deepcopy(意味)
        改変.データ["意味成果"]["演算"][0]["双端対応"][0]["格"] = "別格"
        self.assertFalse(資料文章を検査(改変))

    def test_L02_逆順の問いでも原方向と過去否定を保つ(self):
        成果, 意味 = self.正常("教材と教師の関係を説明してください。", {"資料A": "教師は教材を配布しなかった。"})
        証拠 = [項 for 項 in 意味["演算"] if 項.get("版") == "原資料明示二端照合-v1"][0]
        self.双端を検査(証拠, "教師", "教材", "配布", "しなかった")
        self.assertEqual(証拠["支持式"]["種別"], "否定")
        self.assertEqual([項["格"] for 項 in 証拠["双端対応"]], ["対象物", "行為者"])
        self.assertIn("配布しなかった", 成果.本文)

