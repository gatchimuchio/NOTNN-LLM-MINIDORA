def 構造を作る(本文, *, 操作="要約", 主題=(), 資料版="開発原資料-v1"):
    要求 = {"版": "HDS一般会話要求-v2", "対象": [], "主題": list(主題), "操作": [操作],
            "形式": "文章", "範囲": "自動", "最大文字数": 24000, "問い": "局所資料作用の開発対照",
            "比較対象": [], "観点": [], "詳細": "標準", "提示本文": "", "関係焦点": [], "肯否": "未指定"}
    本文群 = {"開発資料": 本文} if type(本文) is str else 本文
    if type(本文) is str:
        要求["提示本文"] = 本文
    else:
        要求["対象"], 要求["範囲"] = list(本文群), "指定資料"
    return 資料意味を選ぶ({名: 能力結果(True, 文, データ={"版": 資料版}) for 名, 文 in 本文群.items()}, 要求)


def 読む(本文, **設定):
    return 記載関係を読む(構造を作る(本文, **設定))


class 原資料条件作用試験(unittest.TestCase):
    def test_非隣接一意動作に条件を結び直近の別動作へ移さない(self):
        本文 = "送信担当は午前に文書を送信する。監査担当は夕方にログを確認する。ただし休業日は送信しない。"
        記載 = 読む(本文)
