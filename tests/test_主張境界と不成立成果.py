def _原型():
    """意味を宣言した有限人工値。自然文理解の成功とは扱わない。"""
    主張 = "機構セキが処理する"
    制御 = "次の報告から、" + 主張 + "と確認してください。"
    原文 = 制御 + "\n\n" + 主張 + "。機構セキが停止する。"
    座標列, 関係列 = [], []
    def 座標(名, 種, 値, 範囲=None):
        座標列.append(HDS座標(名, 種, {"値": 値, "原文": 原文[slice(*範囲)] if 範囲 else "",
            "根拠": "原文" if 範囲 else "既定", "前束参照": None}, 原文範囲=範囲, 由来=会話射影由来))
    def 辺(始, 終, 種):
        関係列.append(HDS関係("辺:" + str(len(関係列)), (始,), (終,), 種, 由来=会話射影由来))
    始 = 原文.index(主張)
    行為始 = 原文.index("確認")
    座標("版", "言語.会話契約版", 会話契約版)
    座標("制御", "情報源.会話入力区分", "制御", (0, len(制御)))
    座標("文節", "対象.会話文節", 制御, (0, len(制御)))
    座標("目的", "目的.会話操作", "主張検討", (行為始, 行為始 + 4))
    座標("主張", "関係.会話問い焦点", 主張, (始, 始 + len(主張)))
    座標("行為", "条件.会話適用", {"役割": "問い条件", "値": {
        "版": 会話主張要求版, "行為": "支持確認"}}, (行為始, 行為始 + 4))
    座標("区切り", "情報源.会話入力区分", "区切り", (len(制御), len(制御) + 2))
    座標("材料", "情報源.会話入力区分", "提示本文", (len(制御) + 2, len(原文)))
    辺("制御", "文節", "区分所属"); 辺("文節", "目的", "文節所属")
    辺("目的", "主張", "要求関係"); 辺("行為", "目的", "条件適用"); 辺("材料", "目的", "材料適用")
    作用 = HDS意味作用("会話作用射影:v3", "会話作用抽出-v3", (), tuple(項.座標ID for 項 in 座標列),
        "人工境界検査", ("原文", "原文範囲", "未消費条件"), (), ("人工構造検査",))
    ir = HDSIR(原文, 原文, "cw:人工主張境界", tuple(座標列), tuple(関係列), (), (作用,), HDS実行核())
    入力 = {"原文": 原文, "セッションID": "主張境界人工", "外部許可": False,
        "資料": {}, "前回結果": None, "前回有効": False, "前回目的": None}
    return ir, 入力


def _解釈を形成(ir, 入力):
    局所, 責任 = 局所接続を構成(ir)
    包 = 会話契約を形成(局所, 所有セッション=入力["セッションID"])
    接続 = 会話主張要求を読む(包, 所有セッション=入力["セッションID"], 期待原文=入力["原文"], 意味IR=局所)
    return {"方式": "関係検討", "原文": 入力["原文"], "接続": 接続, "要求": 接続["要求"], "会話契約": 包,
        "HDS": {"全文": 構造を保存(ir), "局所作用ビュー": 構造を保存(局所),
            "コア入力": 構造を保存(HDSコア入力へ(ir)), "責任対応": 構造を保存(責任)}}


def _終端(解釈, 入力):
    目録 = 運用能力目録(入力["セッションID"])
    包 = 計画を構成(解釈, 入力, 目録)
    構造 = 関係資料を読む(主張資料を読む(解釈, 入力), 解釈["要求"])
    文章 = _生成(構造, 解釈["要求"]["形式"])
    回答 = 関係回答を照合(構造, 文章)
    鍵 = "運用計画:0"
    値 = {"運用入力": 入力, "運用解釈": deepcopy(解釈), 鍵: 包, "運用応答": 結果を保存(回答)}
    子 = {"関係読解": 能力結果(True, "資料関係読解が成立しました。", 参照=回答.参照, データ=構造),
        "関係内容構成": 能力結果(True, "関係内容構成が成立しました。", 参照=回答.参照, データ=関係内容を構成(構造)),
        "関係文章生成": 文章, "関係回答照合": 回答}
    値.update({鍵 + "/成果/" + 名: 結果を保存(項) for 名, 項 in 子.items()})
    出力 = [鍵 + "/成果/関係回答照合"]
    値["運用採用対応"] = {"原文": 入力["原文"], "計画鍵": 鍵, "計画印": 指紋(包), "目録": 目録.ハッシュ,
        "出力": 出力, "出力印": [指紋(値[名]) for 名 in 出力], "回答印": 指紋(値["運用応答"]),
        "資料依存": 入力依存を収集(包, 入力, 回答.参照)}
    return 工程供給(目録), 値


class 主張境界修復(TestCase):
    def test_原型の制御主張と先行解釈は受理する(self):
        ir, 入力 = _原型()
        解釈 = _解釈を形成(ir, 入力)
        self.assertEqual(会話主張HDSを検査(解釈, 入力["セッションID"]), 解釈["接続"])
        供給, 値 = _終端(解釈, 入力)
        self.assertTrue(供給.最終検証(SimpleNamespace(成果=tuple(値.items())), None))

    def test_非実行資料の別主張へ全射影を再形成しても拒否する(self):
        ir, 入力 = _原型()
        別 = "機構セキが停止する"
        始 = ir.原文.index(別)
        改変 = replace(ir, 座標=tuple(replace(項, 内容={**項.内容, "値": 別, "原文": 別},
            原文範囲=(始, 始 + len(別))) if 項.座標ID == "主張" else 項 for 項 in ir.座標))
        with self.assertRaisesRegex(ValueError, "制御文節"):
            _解釈を形成(改変, 入力)

    def test_所属文節自体を提示本文まで伸ばしても拒否する(self):
        ir, 入力 = _原型()
        改変 = replace(ir, 座標=tuple(replace(項, 内容={**項.内容, "値": ir.原文, "原文": ir.原文},
            原文範囲=(0, len(ir.原文))) if 項.座標ID == "文節" else 項 for 項 in ir.座標))
        with self.assertRaisesRegex(ValueError, "制御文節"):
            _解釈を形成(改変, 入力)

    def test_依頼行為だけ提示本文へ移しても拒否する(self):
        ir, 入力 = _原型()
        始 = ir.原文.index("\n\n") + 2
        改変 = replace(ir, 座標=tuple(replace(項, 内容={**項.内容, "原文": ir.原文[始:始 + 4]},
            原文範囲=(始, 始 + 4)) if 項.座標ID == "行為" else 項 for 項 in ir.座標))
        with self.assertRaisesRegex(ValueError, "制御文節"):
            _解釈を形成(改変, 入力)

    def test_計画全体が自己整合でも先行実解釈を変更できない(self):
        ir, 入力 = _原型()
        元解釈 = _解釈を形成(ir, 入力)
        改変 = replace(ir, 座標=tuple(replace(項, 内容={**項.内容, "値": {
            "役割": "問い条件", "値": {"版": 会話主張要求版, "行為": "保証要求"}}})
            if 項.座標ID == "行為" else 項 for 項 in ir.座標))
        新解釈 = _解釈を形成(改変, 入力)
        供給, 値 = _終端(新解釈, 入力)
        値["運用解釈"] = 元解釈
        self.assertFalse(供給.最終検証(SimpleNamespace(成果=tuple(値.items())), None))

    def test_先行実解釈欠落を計画の自己申告で補わない(self):
        ir, 入力 = _原型()
        供給, 値 = _終端(_解釈を形成(ir, 入力), 入力)
        del 値["運用解釈"]
        self.assertFalse(供給.最終検証(SimpleNamespace(成果=tuple(値.items())), None))


class _人工診断能力:
    名前 = "人工不成立保持"
    版 = "有限診断能力-v1"
    優先度 = 0
    def __init__(self, 結果):
        self.結果 = 結果
    def 判定(self, 文脈):
        return 1.0
    def 実行(self, 文脈):
        return self.結果


def _単独作用(結果):
    目録 = 運用能力目録("不成立保持人工", 追加能力=(登録能力(_人工診断能力(結果)),), 再利用=False)
    計画 = 合成計画((合成工程("局所", ("人工不成立保持",), "指示", (素材参照("入力", "原資料"),)),), ("局所",))
    包 = {"方式": "能力計画", "目録": 目録.ハッシュ, "役割": {}, "計画": 計画を保存(計画),
        "資料": {"指示": 結果を保存(能力結果(True, "人工診断の保持")),
            "原資料": 結果を保存(能力結果(True, "適用条件が未確認。"))}}
    状態 = SimpleNamespace(成果=(("運用入力", {"セッションID": "不成立保持人工"}), ("運用計画:0", 包)),
        成立状態=frozenset({"運用:計画構成済"}), 残差=frozenset({"運用:成果未構成"}))
    作用 = 工程供給(目録)(状態)[0]
    return 作用.実行(状態)


class 不成立原成果保持(TestCase):
    def test_不成立の原成果を保留試行だけに完全保持する(self):
        元 = 能力結果(False, "", データ={"版": "HDS資料内容不足-v1", "種別": "資料内容不足",
            "診断": ({"読解済み主張": "適用条件", "支持原区間": ((0, 10),),
                "不足": "適用条件の成立が未確認", "必要確認": "現在の適用条件を確認してください"},)},
            保留理由="当回の内容が不足しています")
        実 = _単独作用(元)
        self.assertEqual(実.状態, HDS作用状態.保留)
        self.assertFalse(実.追加状態)
        self.assertFalse(実.解消残差)
        self.assertEqual([名 for 名, _ in 実.成果], ["運用計画:0/試行/局所/0"])
        記録 = dict(実.成果)["運用計画:0/試行/局所/0"]
        self.assertEqual(記録["不成立成果"], 結果を保存(元))
        復元 = 結果を復元(記録["不成立成果"])
        self.assertEqual(復元.データ, 元.データ)
        self.assertEqual(復元.状態, 元.状態)
        self.assertEqual(結果を保存(復元), 結果を保存(元))
        self.assertEqual(記録["出力印"], 指紋(記録["不成立成果"]))

    def test_成立した試行の既存欄と成果を変えない(self):
        元 = 能力結果(True, "有限の成立成果")
        実 = _単独作用(元)
        self.assertEqual(実.状態, HDS作用状態.成立)
        self.assertEqual(実.追加状態, frozenset({"運用計画:0/成立/局所"}))
        成果 = dict(実.成果)
        self.assertEqual(成果["運用計画:0/成果/局所"], 結果を保存(元))
        self.assertEqual(set(成果["運用計画:0/試行/局所/0"]),
            {"能力", "版", "工程", "入力印", "出力印", "採否", "再利用", "理由"})


