"""定義標識と直後説明の原格・条件・支持閉包を有限対照で確認する。"""
from copy import deepcopy
import unittest

from minidora.HDS運用.資料作用射影 import 定義標識を読む, 定義説明を読む, 資料作用成果
from minidora.HDS運用.資料回答 import 記載関係を読む
from minidora.HDS運用.意味資料 import 資料意味を選ぶ
from minidora.HDS運用.内容構成 import _文章, 資料文章を照合, 資料文章を検査
from minidora.製品版.型 import 能力結果


def 要求(対象):
    return {"版": "HDS一般会話要求-v2", "対象": [], "主題": [対象], "操作": ["説明"],
            "形式": "文章", "範囲": "自動", "最大文字数": 24000, "問い": 対象 + "は何か。",
            "比較対象": [], "観点": [], "詳細": "標準", "提示本文": "",
            "関係焦点": ["定義"], "肯否": "未指定"}


def 構造(本文, 対象="記録業務"):
    return 資料意味を選ぶ({"人工資料": 能力結果(True, 本文)}, 要求(対象))


def 成果(本文, 対象="記録業務"):
    読み = 構造(本文, 対象)
    return 資料文章を照合(読み, _文章(読み))


class 定義標識説明試験(unittest.TestCase):
    def test_定義対象と説明内部の明示主体を分けて二記載を支持にする(self):
        本文 = "記録業務とは\n担当者が紙を保存します。"
        出力 = 成果(本文)
        self.assertIn("担当者が紙を保存します。", 出力.本文)
        self.assertNotIn("記録業務は担当者", 出力.本文)
        self.assertTrue(資料文章を検査(出力))
        行 = next(行 for 行 in 記載関係を読む(構造(本文)) if 行["関係"]["定義"])
        説明 = 行["関係"]["定義"]["見出し定義"]["説明"]
        self.assertEqual(説明["内部事象"][0]["明示主体"]["原文"], "担当者")
        self.assertFalse(説明["世界実行認定"])
        self.assertEqual(len(出力.データ["意味成果"]["意味"]["命題"][0]["根拠"]), 2)

    def test_省略主体を定義対象へ補完しない(self):
        出力 = 成果("記録業務とは\n紙を保存します。")
        self.assertTrue(資料文章を検査(出力))
        行 = next(行 for 行 in 出力.データ["意味成果"]["記載関係"] if 行["関係"]["定義"])
        事象 = 行["関係"]["定義"]["見出し定義"]["説明"]["内部事象"][0]
        self.assertIsNone(事象["明示主体"])
        self.assertFalse(事象["定義対象への主体補完"])
        self.assertTrue(any(項["種別"] == "定義説明内部主体未明示" for 項 in 行["資料作用"]["残差"]))

    def test_連用条件と可能連体と括弧注記と原動詞を保持する(self):
        本文 = "負荷が高く、環境の改善による効果が多く 期待できる利用者に対して、担当者（技師、職員など）が作業を見直すサポートをします。"
        読み = 定義説明を読む(本文, 41)
        self.assertIsNotNone(読み)
        事象 = 読み["内部事象"][0]
        self.assertEqual(set(事象["明示格"]), {"に", "が", "を"})
        self.assertEqual(事象["用言原文"], "します")
        self.assertEqual(事象["明示格"]["に"]["標識"], "に対して")
        self.assertEqual(len(事象["明示格"]["に"]["名詞構造"]["修飾"]), 2)
        self.assertEqual(事象["明示格"]["が"]["名詞構造"]["注記"]["終端"]["原文"], "など")
        for 項 in 事象["明示格"].values():
            self.assertEqual(本文[項["開始"] - 41:項["終了"] - 41], 項["原文"])
        出力 = 成果("支援業務とは\n" + 本文, "支援業務")
        self.assertIn(本文, 出力.本文)
        self.assertTrue(資料文章を検査(出力))

    def test_否定形容の連用条件を肯定へ変えない(self):
        読み = 定義説明を読む("必要がなく、効果が期待できる利用者に対して、担当者が紙を保存します。", 0)
        self.assertIsNotNone(読み)
        前提 = 読み["内部事象"][0]["明示格"]["に"]["名詞構造"]["修飾"][0]
        self.assertEqual(前提["肯否"], "否定")

    def test_未知用言と引用報告条件と属性だけを標識から採用しない(self):
        for 本文 in ("担当者が紙をフナリします。", "担当者が紙を保存するとされる。",
                     "「担当者が紙を保存する」と説明する。", "雨の場合に担当者が紙を保存する。",
                     "担当者が強い。", "担当者（雨の場合）が紙を保存する。"):
            with self.subTest(本文=本文):
                self.assertIsNone(定義説明を読む(本文, 0))
                行 = 記載関係を読む(構造("記録業務とは\n" + 本文))
                self.assertFalse(any((項["関係"]["定義"] or {}).get("見出し定義") for 項 in 行))

    def test_標識は裸の名詞句に限定する(self):
        self.assertEqual(定義標識を読む("記録業務とは"), "記録業務")
        for 文 in ("記録業務とは何か。", "仮定の記録業務とは", "誤りの記録業務とは", "「記録業務とは」"):
            self.assertIsNone(定義標識を読む(文))

    def test_別記載又は別節を越えて標識を継承しない(self):
        for 本文 in ("記録業務とは\n資料の案内\n担当者が紙を保存する。",
                     "記録業務とは\n## 別の説明\n担当者が紙を保存する。"):
            self.assertFalse(any((行["関係"]["定義"] or {}).get("見出し定義") for 行 in 記載関係を読む(構造(本文))))

    def test_コード領域の標識を資料の定義へ昇格しない(self):
        for 囲い in ("```", "~~~~"):
            for 中行 in ("", "説明。" + 囲い + "\n"):
                本文 = 囲い + "\n" + 中行 + "記録業務とは\n担当者が紙を保存する。\n" + 囲い
                self.assertFalse(any((行["関係"]["定義"] or {}).get("見出し定義") for 行 in 記載関係を読む(構造(本文))))

    def test_定義説明を後続の原因前文へ転写しない(self):
        本文 = "記録業務とは\n担当者が紙を保存する。\nそのため、利用者が紙を確認する。"
        行 = 記載関係を読む(構造(本文))
        self.assertIsNone(行[-1]["関係"]["理由"])

    def test_同一定義説明の肯否競合を拒否する(self):
        本文 = "記録業務とは\n担当者が紙を保存する。\n記録業務とは\n担当者が紙を保存しない。"
        with self.assertRaisesRegex(ValueError, "定義説明の肯定・否定が競合"):
            成果(本文)

    def test_別条件がある資料も非動作として無条件採用しない(self):
        本文 = "記録業務とは\n担当者が紙を保存する。\nただし、雨天の場合には担当者が紙を保存しない。"
        行 = 記載関係を読む(構造(本文))
        # 条件との適合が未確定でも、型の欄欠落で停止してはならない。
        資料作用成果(行)
        try:
            出力 = 成果(本文)
        except ValueError:
            return
        self.assertIn("雨天", 出力.本文)

    def test_主体と原範囲と帰属関係の改変を再導出で拒否する(self):
        出力 = 成果("記録業務とは\n担当者が紙を保存する。")
        for 改変種 in ("主体", "範囲", "帰属"):
            改変 = deepcopy(出力)
            行 = next(行 for 行 in 改変.データ["意味成果"]["記載関係"] if 行["関係"]["定義"])
            if 改変種 == "主体":
                行["関係"]["定義"]["見出し定義"]["説明"]["内部事象"][0]["明示主体"]["原文"] = "記録業務"
            elif 改変種 == "範囲":
                行["関係"]["定義"]["見出し定義"]["説明"]["開始"] += 1
            else:
                行["資料作用"]["関係"][0]["始点"][0] = "不在の標識"
            self.assertFalse(資料文章を検査(改変))


if __name__ == "__main__":
    unittest.main()
