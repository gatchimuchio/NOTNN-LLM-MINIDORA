"""既存Kernelの意味入力と実行契約を共通の目的座標へ接続する。

原文の再解析はしない。未記述の動機・法則・制約は作らない。機械接続は
実際に宣言されたノード・評価器から構成し、解釈不能な必須条件を残す。
"""
from __future__ import annotations
from dataclasses import replace
from ..コア.値 import 署名, 正規化
from ..コア.指示関係 import (HDS指示関係, HDS指示座標, HDS指示条件, HDS帰還先,
    座標状態, 九座標を用意, コア入力を指示へ射影)
from ..コア.座標展開 import 指示を座標場へ
from .計画 import ノードを検査

座標成果名 = "HDS操作座標場"
接続台帳名 = "HDS入力接続台帳"


def _実ノード(値):
    if not isinstance(値, str): return None
    try: return ノードを検査(値)
    except ValueError: return None


def 全入力を座標へ(状態, *, 原文, 作用群=(), 検証器=(), 成果対応=(), 評価対応=(), 構造入力厳格=False):
    """自由文・Kernel入力・構造化入力に共通する実行前射影。

    成果対応は信頼された入力適合器の論理名→実ノードの対応。外部参照本文
    からこの対応や実行権限を供給してはならない。
    """
    from ..HDS実行主体 import HDS実行状態
    if not isinstance(状態, HDS実行状態): raise TypeError("実行状態が必要")
    if 状態.版 != 0: raise ValueError("新規の入力だけを座標化する。再開は旧目的を継承する")
    成果 = dict(状態.成果)
    if 状態.指示関係 is not None:
        # 既に手動接続された契約を自動契約で上書きしない。
        return replace(状態, 操作座標=状態.操作座標 or 指示を座標場へ(状態.指示関係))
    入力 = 成果.get("HDSコア入力")
    if 入力 is not None:
        if 入力.原文 != 原文: raise ValueError("入力の原文が不一致")
        指示 = コア入力を指示へ射影(入力)
        # 全座標は保持するが、候補や不足位置など説明用座標を
        # 「未接続だから開始禁止」の条件へ昇格させない。
        非阻害 = {
            "目的/" + x.ID for x in 入力.目的
            if x.種別 in ("候補", "不足位置", "要求型")
        }
        必須候補 = tuple(x for x in 指示.要接続座標 if x not in 非阻害)
        # 明示された構造化入力だけ、未解釈の評価規則・制約を開始阻害として残す。
        # 通常自由文でCompilerが説明用に抽出した座標を、旧APIの完了条件へ勝手に追加しない。
        指示 = replace(指示, 要接続座標=必須候補 if 構造入力厳格 else ())
    else:
        # 既存の構造化関係入力を、新しい自然文解釈で置き換えない。
        指示 = HDS指示関係(原文, "実行入力:" + 署名((原文, 状態.目的))[:24], 九座標を用意())
    座標 = list(指示.座標)
    由来 = ("実行APIの明示契約",)
    座標.extend((
        HDS指示座標("実行/対象", "対象", "実行対象", 署名((原文, 入力)), 座標状態.確定値, 由来, 親="対象/実体"),
        HDS指示座標("実行/作用", "手段", "契約作用", "作用契約から目的経路を構成", 座標状態.確定値, 由来, 親="手段/作用"),
    ))
    対応 = dict(成果対応)
    if len(対応) != len(tuple(成果対応)): raise ValueError("成果対応が重複")
    for 論理名, ノード in 対応.items():
        if not 論理名 or _実ノード(ノード) is None: raise ValueError("成果対応が不正")
    条件, 帰還, 台帳 = [], [], []
    # 採用理由は到達の由来。未知の評価規則を状態ラベルへ代理させない。
    元目的 = tuple("目的/" + x.ID for x in 入力.目的
                   if x.種別 == "必要性" or (x.種別 == "到達状態" and isinstance(x.内容, str)
                       and x.内容 in 状態.要求状態)) if 入力 is not None else ()
    def 加える(ID, 座標ID, ノード, *, 判定="有効", 期待値=None, 段階="達成", 参照=()):
        条件.append(HDS指示条件(ID, 座標ID, ノード, 判定, 期待値, 段階, 参照座標=tuple(参照)))
        台帳.append((座標ID, ノード, 段階, "明示実行契約"))
    for 名前 in sorted(状態.要求状態):
        加える("実行到達:" + 名前, "目的/到達状態", "状態:" + 名前, 参照=元目的)
    for 名前 in sorted(状態.要求認識):
        加える("認識到達:" + 名前, "目的/到達状態", "認識:" + 名前, 参照=元目的)
    if 入力 is not None:
        for 名前 in 入力.要求成果:
            ノード = 対応.get(名前, _実ノード(名前) or "成果:" + 名前)
            加える("要求成果:" + 名前, "要求成果", ノード, 参照=元目的)
            帰還.append(HDS帰還先("要求成果", ノード, 名前))
        # 評価規則が構造化済みなら、完了ラベルではなく実値を判定する。
        for 項 in 入力.目的:
            if 項.種別 == "評価規則" and isinstance(項.内容, tuple) and len(項.内容) == 3:
                ノード, 判定, 期待値 = 項.内容
                if _実ノード(ノード) and 判定 in ("一致", "不一致", "有効"):
                    加える("目的評価:" + 項.ID, "目的/" + 項.ID, ノード, 判定=判定, 期待値=期待値)
        for 項 in 入力.条件:
            if len(項.適用先) == 1 and _実ノード(項.適用先[0]) and 項.種別 in ("一致", "不一致", "有効"):
                加える("入力条件:" + 項.ID, "条件/" + 項.ID, 項.適用先[0], 判定=項.種別,
                    期待値=None if 項.種別 == "有効" else 項.内容, 段階="維持")
        for 項 in 入力.作用要求:
            if 項.要求成果:
                for 名前 in 項.要求成果:
                    ノード = 対応.get(名前, _実ノード(名前) or "成果:" + 名前)
                    加える("作用成果:" + 項.ID + ":" + 名前, "作用要求/" + 項.ID, ノード)
        # 検証器の存在だけで合格にしない。既存の最終検証が実際に実行する。
        検証名 = {x.ID for x in 検証器}
        for 項 in 入力.検証要求:
            if 項.ID in 検証名:
                for 番号, ノード in enumerate(sorted({x.ノード for x in 条件 if x.段階 == "達成"})):
                    加える("検証接続:" + 項.ID + ":" + str(番号), "検証要求/" + 項.ID, ノード, 段階="返却")
    # 残差だけが到達条件の場合も、元の全残差を明示的に判定する。
    if not any(x.段階 == "達成" for x in 条件):
        for 名 in sorted(状態.残差): 加える("残差解消:" + 名, "目的/評価規則", "残差:" + 名)
    for 項 in 評価対応:
        if not isinstance(項, HDS指示条件): raise TypeError("評価対応は指示条件型が必要")
        if 項.ID in {x.ID for x in 条件}: raise ValueError("評価対応IDが重複")
        条件.append(項)
        台帳.append((項.座標ID, 項.ノード, 項.段階, "選択入力適合器の実結果検査"))
    # 実体/状態/関係/目的/手段の横断リンク。原文の個別関係は削除しない。
    関係 = (*指示.関係,
        ("対象/現在状態", "目的/到達状態", "現在と到達の差"),
        ("目的/必要性", "目的/到達状態", "要求の採用理由"),
        ("目的/到達状態", "目的/評価規則", "成立を照合"),
        ("手段/作用", "目的/到達状態", "作用の寄与先"),
        ("手段/境界", "手段/作用", "適用条件"),
        ("手段/検証・帰還", "対象/現在状態", "結果を戻す"))
    # 座標は全保持する。明示構造入力の未接続必須座標は、接続できるまで残す。
    指示 = replace(指示, 座標=tuple(座標), 関係=tuple(関係), 条件=tuple(条件), 帰還先=tuple(帰還),
                   検証契約=tuple((x.ID, x.版) for x in 検証器), 自動作用接続=True)
    未接続 = 指示.未接続座標
    台帳.extend((ID, "", "未接続", "原入力の必須条件に実行対応がない") for ID in 未接続)
    成果[接続台帳名] = tuple(台帳)
    return replace(状態, 指示関係=指示, 操作座標=指示を座標場へ(指示), 成果=tuple(sorted(成果.items())))