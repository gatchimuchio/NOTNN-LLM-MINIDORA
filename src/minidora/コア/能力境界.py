_名前索引 = {x.名前: x for x in 標準能力境界}
if len(_名前索引) != len(標準能力境界):
    raise RuntimeError("標準能力境界に重複名がある")

def 能力境界を取得(名前: str) -> 能力境界契約:
    try:
        return _名前索引[名前]
    except KeyError as exc:
        raise ValueError("未分類能力:" + str(名前)) from exc

def 標準能力境界を照合(登録名群, *, 完全集合=True) -> tuple[能力境界契約, ...]:
    登録名列 = tuple(str(x) for x in 登録名群)
    if len(登録名列) != len(set(登録名列)):
        raise ValueError("能力登録名が重複")
    未分類 = sorted(set(登録名列) - set(_名前索引))
    if 未分類:
        raise ValueError("境界未分類の能力:" + ",".join(未分類))
    if 完全集合:
        欠落 = sorted(set(_名前索引) - set(登録名列))
        if 欠落:
            raise ValueError("標準能力入口が欠落:" + ",".join(欠落))
    return tuple(_名前索引[x] for x in 登録名列)



def 標準能力登録を閉包(標準登録名群, 拡張登録名群=()) -> tuple[能力境界契約, ...]:
    """組込標準能力は台帳と完全一致させ、拡張能力だけを明示的に境界外へ分離する。

    標準登録を既知名で先にfilterしない。将来の組込入口が台帳未登録なら必ず失敗する。
    拡張能力は標準名を上書きできず、ここでは標準能力へ自動昇格しない。
    """
    標準名列 = tuple(str(x) for x in 標準登録名群)
    extension = tuple(str(x) for x in 拡張登録名群)
    if len(extension) != len(set(extension)):
        raise ValueError("拡張能力登録名が重複")
    collision = sorted(set(extension) & set(_名前索引))
    if collision:
        raise ValueError("拡張能力が標準入口を上書き:" + ",".join(collision))
    return 標準能力境界を照合(標準名列, 完全集合=True)

def 能力分類集計():
    集計 = {}
    for 境界 in 標準能力境界:
        集計[境界.主分類] = 集計.get(境界.主分類, 0) + 1
    return tuple(sorted(集計.items()))

def 責任境界集計():
    return {
        "入力変換責任あり": sum(bool(x.入力変換責任) for x in 標準能力境界),
        "コア責任あり": sum(bool(x.コア責任) for x in 標準能力境界),
        "局所部品責任あり": sum(bool(x.局所部品責任) for x in 標準能力境界),
        "外部読取": sum(x.外部読取 for x in 標準能力境界),
    }


