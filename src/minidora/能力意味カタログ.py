@dataclass(frozen=True, slots=True)
class 計画作用:
    識別子: str
    能力: str
    入力状態: tuple[str, ...]
    出力状態: str
    固定設定JSON: str = '{}'
    引数写像: tuple[tuple[str, str], ...] = ()

    def 設定(self, 引数: dict) -> dict:
        value = json.loads(self.固定設定JSON)
        for path, key in self.引数写像:
            if key not in 引数:
                raise ValueError('不足引数:' + key)
            target = value
            parts = path.split('.')
            for name in parts[:-1]:
                target = target.setdefault(name, {})
            target[parts[-1]] = 引数[key]
        return value


def _作用(name, module, inputs, output, fixed=None, bindings=()):
    return 計画作用(name, module, inputs, output,
        json.dumps(fixed or {}, ensure_ascii=False, sort_keys=True), bindings)

