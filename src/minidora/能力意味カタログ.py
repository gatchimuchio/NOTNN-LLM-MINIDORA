class 能力意味カタログ:
    def __init__(self, 登録一覧):
        if type(登録一覧) not in (list, tuple) or any(type(r) is not dict
                or set(r) != {'名前', '版', '外部読取'} or type(r['名前']) is not str
                or type(r['版']) is not str or type(r['外部読取']) is not bool for r in 登録一覧):
            raise ValueError('能力一覧の型不正')
        self.記述 = tuple(能力意味記述(*row) for row in _記述)
        actual = {r['名前']: (r['版'], r['外部読取']) for r in 登録一覧}
        expected = {r.名前: (r.版, r.外部読取) for r in self.記述}
        if len(actual) != len(登録一覧) or actual != expected:
            raise ValueError('能力一覧・版・外部作用と意味記述が不一致')
        self.作用 = 標準計画作用()
        if any(rule.能力 not in actual or actual[rule.能力][1] for rule in self.作用):
            raise ValueError('未登録能力又は外部読取の自動接続')
        self.ハッシュ = sha256(json.dumps([_記述, [
            (r.識別子, r.能力, r.入力状態, r.出力状態, r.固定設定JSON, r.引数写像)
            for r in self.作用]], ensure_ascii=False).encode()).hexdigest()
