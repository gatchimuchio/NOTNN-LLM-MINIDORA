def _欄(値, 必須, 名):
    if type(値) is not dict or set(値) != 必須:
        raise ValueError(名 + "の欄が一致しません")


def _文(値, 名, *, 空=False, 上限=256):
    if type(値) is not str or (not 空 and not 値) or len(値) > 上限:
        raise ValueError(名 + "の文字列が不正です")


def _印(値, 名):
    _文(値, 名, 上限=64)
    if len(値) != 64 or any(字 not in "0123456789abcdef" for 字 in 値):
        raise ValueError(名 + "のSHA256が不正です")


def _列(値, 名, 上限, *, 一意=False, 文字=True):
    if type(値) is not list or len(値) > 上限:
        raise ValueError(名 + "の列が不正です")
    if 文字:
        for 項 in 値:
            _文(項, 名)
        if 一意 and len(set(値)) != len(値):
            raise ValueError(名 + "の参照が重複しています")


def _JSON予算(値):
    待ち = [(値, 0)]
    件数 = 0
    while 待ち:
        項, 深さ = 待ち.pop()
        件数 += 1
        if 件数 > 20000 or 深さ > 16:
            raise ValueError("会話契約のJSON予算を超えました")
        if type(項) is dict:
            for 鍵, 子 in 項.items():
                _文(鍵, "JSON鍵")
                待ち.append((子, 深さ + 1))
        elif type(項) is list:
            待ち.extend((子, 深さ + 1) for 子 in 項)
        elif type(項) is str:
            _文(項, "JSON文字列", 空=True, 上限=8000000)
        elif 項 is not None and type(項) is not int:
            raise ValueError("会話契約に非対応のJSON値があります")
        elif type(項) is int and 項.bit_length() > 64:
            raise ValueError("会話契約の整数予算を超えました")


def _正準(値):
    _JSON予算(値)
    return json.dumps(値, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _指紋(値):
    return hashlib.sha256(_正準(値).encode("utf-8")).hexdigest()


def _重複欄を拒否(組):
    結果 = {}
    for 鍵, 値 in 組:
        if 鍵 in 結果:
            raise ValueError("証明JSONの欄が重複しています")
        結果[鍵] = 値
    return 結果


def _証明を読む(文):
    _文(文, "証明正準JSON", 上限=8000000)
    if len(文.encode("utf-8")) > 8000000:
        raise ValueError("会話証明のbyte予算を超えました")
    try:
        値 = json.loads(文, object_pairs_hook=_重複欄を拒否)
    except (RecursionError, json.JSONDecodeError) as 例外:
        raise ValueError("会話証明JSONが不正です") from 例外
    if _正準(値) != 文:
        raise ValueError("会話証明JSONが正準ではありません")
    return 値


def _直列化(項, 型, 欄):
    if type(項) is not 型:
        raise ValueError("会話参照元のHDS型が一致しません")
    結果 = {}
    for 名 in 欄:
        値 = getattr(項, 名)
        if 名 == "値状態":
            if type(値) is not 値状態:
                raise ValueError("会話参照元の値状態型が不正です")
            値 = 値.value
        elif 名 in {"始点", "終点", "条件", "再開放条件", "影響座標", "解消条件",
                    "入力参照", "出力参照", "保持構造", "損失", "検証"}:
            if type(値) is not tuple:
                raise ValueError("会話参照元の列型が不正です")
            値 = list(値)
        elif 名 == "原文範囲" and 値 is not None:
            if type(値) is not tuple:
                raise ValueError("会話参照元の原文範囲型が不正です")
            値 = list(値)
        _JSON予算(値)
        結果[名] = deepcopy(値)
    return 結果


def _IR参照(意味IR):
    if type(意味IR) is not HDSIR:
        raise ValueError("会話契約には同一HDSIRが必要です")
    for 群 in (意味IR.座標, 意味IR.関係, 意味IR.残差, 意味IR.意味作用履歴):
        if type(群) is not tuple:
            raise ValueError("HDSIRの参照列型が不正です")
    for 群, 型 in ((意味IR.座標, HDS座標), (意味IR.関係, HDS関係),
                  (意味IR.残差, HDS残差), (意味IR.意味作用履歴, HDS意味作用)):
        if any(type(項) is not 型 for 項 in 群):
            raise ValueError("HDSIRの参照要素型が不正です")
    座標 = [_直列化(項, HDS座標, _座標欄) for 項 in 意味IR.座標 if 項.由来 == 会話射影由来]
    関係 = [_直列化(項, HDS関係, _関係欄) for 項 in 意味IR.関係 if 項.由来 == 会話射影由来]
    残差 = [_直列化(項, HDS残差, _残差欄) for 項 in 意味IR.残差]
    作用 = [項 for 項 in 意味IR.意味作用履歴 if 項.作用ID == "会話作用射影:v3"]
    if len(作用) != 1 or 作用[0].種別 != "会話作用抽出-v3":
        raise ValueError("明示v3会話意味作用が必要です。旧版は昇格しません")
    for 項 in 座標:
        _文(項["座標ID"], "参照元座標ID")
    for 項 in 残差:
        _文(項["種別"], "参照元残差種別", 上限=8000000)
        _列(項["影響座標"], "参照元残差影響座標", 256, 一意=True)
    識別子 = {項["座標ID"] for 項 in 座標}
    if any(sum(元.座標ID == 名 for 元 in 意味IR.座標) != 1 for 名 in 識別子):
        raise ValueError("会話座標IDが元IRで一意ではありません")
    return {"版": 会話証明版, "原文": 意味IR.原文, "認知世界ID": 意味IR.認知世界ID,
            "座標": 座標, "関係": 関係, "残差": 残差,
            "会話残差ID": [項["残差ID"] for 項 in 残差 if 項["種別"].startswith("会話") or set(項["影響座標"]) & 識別子],
            "意味作用": _直列化(作用[0], HDS意味作用, _作用欄)}


def _範囲(値, 原文):
    if 値 is None:
        return
    if type(値) is not list or len(値) != 2 or any(type(項) is not int for 項 in 値):
        raise ValueError("原文範囲の型が不正です")
    始, 終 = 値
    if not 0 <= 始 < 終 <= len(原文):
        raise ValueError("原文範囲が原文内にありません")


def _原動作目的の原役割を検査(内, 原文):
    """形成済み原役割の範囲と固定格の隣接を照合する。動作は実行しない。"""
    def 原役割(項, 欄):
        _欄(項, {欄, "原文範囲"}, "原動作目的役割")
        _文(項[欄], "原動作目的原値", 上限=4096)
        if 項["原文範囲"] is None: raise ValueError("原動作目的の原文範囲が欠落しています")
        _範囲(項["原文範囲"], 原文)
        if 原文[slice(*項["原文範囲"])] != 項[欄]:
            raise ValueError("原動作目的の値と原文範囲が不一致です")
        return 項["原文範囲"]
    外 = 原役割(内["原語句"], "原文")
    述 = 原役割(内["原述部"], "原文")
    主 = 原役割(内["主要部"], "値")
    if 内["主要部"]["値"] != "目的" or not 外[0] <= 述[0] < 述[1] <= 主[0] < 主[1] == 外[1]:
        raise ValueError("原動作目的の連体述部又は主要部対応が不正です")
    if 原文[述[1]:主[0]].strip() or any(字 in 内["原語句"]["原文"] for 字 in "「」『』。!?！？;；"):
        raise ValueError("原動作目的の原句境界が不正です")
    内範 = {名: None if 内[名] is None else 原役割(内[名], "値") for 名 in ("主体", "対象物")}
    from .会話字句 import 会話字句を観測
    # 保存された原述部と目的主要部の局所型だけを照合する。全文は再解釈しない。
    字 = [項 for 項 in 会話字句を観測(原文[述[0]:主[1]]) if not 項.表層.isspace()]
    動 = 字[:-1]
    if (not 字 or 字[-1].表層 != "目的" or 字[-1].未知語 or not 動
            or 動[-1].品詞[0] != "動詞" or 動[-1].未知語 or "連体形" not in 動[-1].活用形
            or not (len(動) == 1 or len(動) == 2 and 動[-1].辞書形 == "する"
                    and 動[0].品詞[0] == "名詞" and 動[0].品詞[2] == "サ変可能" and not 動[0].未知語)):
        raise ValueError("原動作目的の既知連体述部の型証拠が不正です")
    次 = 外[0]
    for 名, 格 in (("主体", "が"), ("対象物", "を")):
        範 = 内範[名]
        if 範 is None: continue
        if 範[0] != 次 or not 外[0] <= 範[0] < 範[1] < 述[0]:
            raise ValueError("原動作目的の内部原格範囲が不正です")
        後 = 内範["対象物"][0] if 名 == "主体" and 内範["対象物"] is not None else 述[0]
        if 原文[範[1]:後].strip() != 格:
            raise ValueError("原動作目的の主体又は対象格が実原句にありません")
        次 = 後
    if 次 != 述[0]:
        raise ValueError("原動作目的に未対応の内部原句があります")
    return 外


def _値を検査(種, 値):
    if 種 == _条件:
        _欄(値, {"役割", "値"}, "条件値")
        _文(値["役割"], "条件役割")
        if 値["役割"] not in {"資料条件", "問い条件", "出力保持", "作用禁止", "取得時期", "同発話対応", "関係要求", "動作目的要求"}:
            raise ValueError("条件の役割が不正です")
        if 値["役割"] == "動作目的要求":
            内 = 値["値"]
            _欄(内, {"版", "型", "焦点ID", "原語句", "主体", "対象物", "原述部", "主要部"}, "原動作目的値")
            if 内["版"] != 会話原動作目的版 or 内["型"] != "原動作目的":
                raise ValueError("原動作目的の版又は型が不正です")
            _文(内["焦点ID"], "動作目的焦点ID")
        elif 値["役割"] == "関係要求":
            内 = 値["値"]
            _欄(内, {"版", "型", "両端ID", "焦点ID", "原語句範囲"}, "関係要求値")
            if 内["版"] != 会話関係要求版 or 内["型"] != "明示二端関係":
                raise ValueError("関係要求の版又は型が不正です")
            _列(内["両端ID"], "関係両端ID", 2, 一意=True)
            if len(内["両端ID"]) != 2: raise ValueError("関係要求は二つの明示端点が必要です")
            _文(内["焦点ID"], "関係焦点ID")
        elif 値["役割"] == "同発話対応":
            内 = 値["値"]
            _欄(内, {"版", "方式", "元目的ID", "補足目的ID", "元対象ID", "対応対象ID", "観点ID", "標識範囲"}, "同発話対応値")
            if 内["版"] != 会話同発話対応版 or 内["方式"] not in {"比較観点補足", "包含補足", "関係端点補足", "理由参照関係補足", "包含比較補足"}:
                raise ValueError("同発話対応の版又は方式が不正です")
            for 名 in ("元目的ID", "補足目的ID"):
                _文(内[名], 名)
            for 名 in ("元対象ID", "対応対象ID", "観点ID"):
                _列(内[名], 名, 4, 一意=True)
        elif 値["役割"] == "取得時期":
            _欄(値["値"], {"版", "作用", "基準"}, "取得時期値")
            if 値["値"] != {"版": 会話取得時期版, "作用": "外部読取", "基準": "要求時点"}:
                raise ValueError("取得時期値の版・作用・基準が不正です")
        elif 値["役割"] == "作用禁止" and type(値["値"]) is dict:
            _欄(値["値"], {"版", "作用"}, "作用禁止値")
            if 値["値"] != {"版": 会話作用禁止版, "作用": "外部読取"}:
                raise ValueError("作用禁止値の版又は作用が不正です")
        elif 値["役割"] == "問い条件" and type(値["値"]) is dict:
            内 = 値["値"]
            if 内.get("版") == 会話主張変更版:
                _欄(内, {"版", "行為", "取消指定", "書換指定"}, "主張変更要求値")
                if 内["行為"] != "変更照合" or 内["取消指定"] is None and 内["書換指定"] is None:
                    raise ValueError("主張変更の行為又は指定が不正です")
                取消, 書換 = 内["取消指定"], 内["書換指定"]
                if 取消 is not None:
                    _欄(取消, {"操作範囲", "選択範囲", "選択方式", "明示識別子"}, "取消指定")
                    if 取消["選択方式"] == "原句指定":
                        if 取消["明示識別子"] is not None:
                            raise ValueError("原句指定へ条件識別子を補完できません")
                    elif 取消["選択方式"] == "条件ID指定":
                        _文(取消["明示識別子"], "原文明示条件識別子")
                    else:
                        raise ValueError("取消の選択方式が不正です")
                if 書換 is not None:
                    _欄(書換, {"操作範囲", "主張座標ID"}, "書換指定")
                    _文(書換["主張座標ID"], "書換主張座標ID")
            else:
                _欄(内, {"版", "行為"}, "主張要求値")
                if (内["版"] != 会話主張要求版
                        or 内["行為"] not in {"支持確認", "断定要求", "保証要求"}):
                    raise ValueError("主張要求値の版又は行為が不正です")
        else:
            _文(値["値"], "条件値", 上限=8000000)
    elif 種 == _変更:
        _欄(値, {"役割", "対象役割"}, "変更値")
        _文(値["役割"], "変更役割")
        _文(値["対象役割"], "変更対象役割")
        if 値["役割"] not in {"添加", "訂正", "再表現"} or 値["対象役割"] not in _変更役割種:
            raise ValueError("変更の役割が不正です")
    elif 種 in _前束種:
        _欄(値, {"前束印", "座標ID", "役割", "値印"}, "前束参照値")
        _印(値["前束印"], "前束印")
        _印(値["値印"], "値印")
        _文(値["座標ID"], "前束座標ID")
        _文(値["役割"], "前束役割")
        if 値["役割"] not in _変更役割種:
            raise ValueError("前束の参照役割が不正です")
    elif 種 == "表現.会話数量":
        _欄(値, {"単位", "関係", "数"}, "表現数量")
        _文(値["単位"], "数量単位")
        _文(値["関係"], "数量関係")
        if 値["単位"] not in {"文字", "文", "項目"} or 値["関係"] not in {"一致", "以内"}:
            raise ValueError("表現数量の単位又は関係が不正です")
        if type(値["数"]) is not int or not 1 <= 値["数"] <= 24000:
            raise ValueError("表現数量の数が不正です")
    elif 種 == "表現.会話文字上限":
        if type(値) is not int or not 1 <= 値 <= 256000:
            raise ValueError("文字上限が不正です")
    else:
        _文(値, "会話座標値", 上限=8000000)
        if 種 == _区分 and 値 not in {"制御", "区切り", "提示本文"}:
            raise ValueError("入力区分の役割が不正です")
        if 種 == _版座標 and 値 != 会話契約版:
            raise ValueError("会話契約座標の版が一致しません")


def _証明構造(証明):
    _JSON予算(証明)
    _欄(証明, _証明欄, "会話証明")
    if 証明["版"] != 会話証明版:
        raise ValueError("会話参照証明版が一致しません")
    原文 = 証明["原文"]
    _文(原文, "原文", 上限=8000000)
    if len(原文.encode("utf-8")) > 8000000:
        raise ValueError("原文byte予算を超えました")
    _文(証明["認知世界ID"], "認知世界ID")
    for 名, 予算 in (("座標", 256), ("関係", 512), ("残差", 256)):
        _列(証明[名], 名, 予算, 文字=False)
    座標 = {}
    全ID = set()
    def 登録(値):
        _文(値, "識別子")
        if 値 in 全ID:
            raise ValueError("会話参照IDが重複しています")
        全ID.add(値)
    for 項 in 証明["座標"]:
        _欄(項, _座標欄, "座標")
        登録(項["座標ID"])
        _文(項["種別"], "座標種別")
        _文(項["値状態"], "座標値状態")
        if 項["種別"] not in _種別 or 項["由来"] != 会話射影由来 or 項["値状態"] not in _状態:
            raise ValueError("会話座標の種別・由来・状態が不正です")
        _文(項["暫定性"], "暫定性")
        _列(項["再開放条件"], "再開放条件", 64)
        _範囲(項["原文範囲"], 原文)
        内容 = 項["内容"]
        _欄(内容, _内容欄, "座標内容")
        _値を検査(項["種別"], 内容["値"])
        _文(内容["原文"], "座標原文", 空=True, 上限=8000000)
        範囲 = 項["原文範囲"]
        if 内容["原文"] != ("" if 範囲 is None else 原文[範囲[0]:範囲[1]]):
            raise ValueError("座標原文が原文の実sliceと一致しません")
        根拠 = 内容["根拠"]
        _文(根拠, "座標根拠")
        if 根拠 not in {"原文", "既定", "前束"}:
            raise ValueError("座標の根拠種別が不正です")
        if 根拠 == "原文" and 範囲 is None or 根拠 == "既定" and 範囲 is not None:
            raise ValueError("座標根拠と原文範囲が一致しません")
        if 根拠 != "前束" and 内容["前束参照"] is not None:
            raise ValueError("原文又は既定座標に前束参照があります")
        if 根拠 == "前束" and 項["種別"] not in _前束種:
            _文(内容["前束参照"], "前束参照ID")
        if 項["種別"] in _前束種 and (根拠 != "前束" or 内容["前束参照"] is not None):
            raise ValueError("文脈参照自身の根拠が不正です")
        if 項["種別"] in {_区分, _文節} and 根拠 != "原文":
            raise ValueError("区分と文節は実原文が必要です")
        if 項["種別"] in {_目的, _条件, _変更} and 根拠 == "既定":
            raise ValueError("目的・条件・変更を既定値にはできません")
        if 項["種別"] == _版座標 and 根拠 != "既定":
            raise ValueError("版座標は既定値が必要です")
        if 項["種別"] == _文節 and 内容["値"] != 内容["原文"]:
            raise ValueError("文節値が実sliceと一致しません")
        座標[項["座標ID"]] = 項
    版座標 = [項 for 項 in 座標.values() if 項["種別"] == _版座標]
    目的ID = [名 for 名, 項 in 座標.items() if 項["種別"] == _目的]
    if len(版座標) != 1 or not 1 <= len(目的ID) <= 4:
        raise ValueError("版座標又は目的数が不正です")
    関係 = []
    同型関係 = set()
    for 項 in 証明["関係"]:
        _欄(項, _関係欄, "関係")
        登録(項["関係ID"])
        _文(項["種別"], "関係種別")
        _文(項["値状態"], "関係値状態")
        if 項["種別"] not in _関係端 or 項["由来"] != 会話射影由来 or 項["値状態"] not in _状態:
            raise ValueError("会話関係の種別・由来・状態が不正です")
        _文(項["暫定性"], "関係暫定性")
        for 名 in ("始点", "終点", "条件"):
            _列(項[名], 名, 1)
        if len(項["始点"]) != 1 or len(項["終点"]) != 1 or 項["条件"]:
            raise ValueError("関係は単一端点・条件IDの別関係が必要です")
        始, 終, 種 = 項["始点"][0], 項["終点"][0], 項["種別"]
        if 始 not in 座標 or 終 not in 座標 or 座標[始]["種別"] not in _関係端[種][0] or 座標[終]["種別"] not in _関係端[種][1]:
            raise ValueError("会話関係の端点又は役割が不正です")
        if 始 == 終 or (始, 終, 種) in 同型関係:
            raise ValueError("自己関係又は重複関係があります")
        同型関係.add((始, 終, 種))
        関係.append((始, 終, 種))
    残差ID = []
    for 項 in 証明["残差"]:
        _欄(項, _残差欄, "残差")
        登録(項["残差ID"])
        for 名 in ("種別", "原文", "理由"):
            _文(項[名], "残差" + 名, 空=名 == "原文", 上限=8000000)
        for 名 in ("影響座標", "解消条件"):
            _列(項[名], "残差" + 名, 256, 一意=名 == "影響座標")
        if 項["種別"].startswith("会話") and not set(項["影響座標"]) <= set(座標):
            raise ValueError("会話残差の影響座標が欠落しています")
        if 項["種別"].startswith("会話") or set(項["影響座標"]) & set(座標):
            残差ID.append(項["残差ID"])
    _列(証明["会話残差ID"], "会話残差ID", 256, 一意=True)
    if 証明["会話残差ID"] != 残差ID:
        raise ValueError("会話残差が完全に保持されていません")
    作用 = 証明["意味作用"]
    _欄(作用, _作用欄, "意味作用")
    登録(作用["作用ID"])
    if 作用["作用ID"] != "会話作用射影:v3" or 作用["種別"] != "会話作用抽出-v3":
        raise ValueError("明示v3の会話意味作用が必要です")
    _文(作用["変換"], "意味作用変換", 上限=8000000)
    for 名 in ("入力参照", "出力参照", "保持構造", "損失", "検証"):
        _列(作用[名], 名, 256, 一意=名 in {"入力参照", "出力参照"})
    if 作用["入力参照"] or set(作用["出力参照"]) != set(座標) or not {"原文", "原文範囲", "未消費条件"} <= set(作用["保持構造"]):
        raise ValueError("会話作用参照が会話ビューを完全被覆していません")
    _接続を検査(座標, 関係, 原文)
    return 座標, 関係, 目的ID


def _全区間(範囲群, 始, 終, 名):
    現在 = 始
    for 範囲 in sorted(範囲群):
        if 範囲[0] != 現在:
            raise ValueError(名 + "の原文被覆に隙間又は重なりがあります")
        現在 = 範囲[1]
    if 現在 != 終:
        raise ValueError(名 + "の原文被覆が不足しています")


def _接続を検査(座標, 関係, 原文):
    def 先(名, 種):
        return [終 for 始, 終, 関係種 in 関係 if 始 == 名 and 関係種 == 種]
    def 元(名, 種):
        return [始 for 始, 終, 関係種 in 関係 if 終 == 名 and 関係種 == 種]
    def 包含(外, 内):
        範囲 = 座標[内]["原文範囲"]
        外範囲 = 座標[外]["原文範囲"]
        if 範囲 is not None and not 外範囲[0] <= 範囲[0] < 範囲[1] <= 外範囲[1]:
            raise ValueError("文節又は区分の範囲外参照です")
    区分 = [名 for 名, 項 in 座標.items() if 項["種別"] == _区分]
    _全区間([座標[名]["原文範囲"] for 名 in 区分], 0, len(原文), "入力区分")
    区分順 = sorted(区分, key=lambda 名: 座標[名]["原文範囲"][0])
    制御数 = 0
    使用前束 = set()
    for 名, 項 in 座標.items():
        種, 内容 = 項["種別"], 項["内容"]
        if 種 == _区分:
            子 = 先(名, "区分所属")
            if 内容["値"] == "制御":
                制御数 += 1
                _全区間([座標[項名]["原文範囲"] for 項名 in 子], *項["原文範囲"], "制御文節")
                if 先(名, "材料適用"):
                    raise ValueError("制御区分を提示材料にはできません")
            elif 内容["値"] == "提示本文":
                if 子 or not 先(名, "材料適用"):
                    raise ValueError("提示本文の実行昇格又は材料適用欠落です")
            else:
                位置 = 区分順.index(名)
                if (内容["原文"].strip() or any(名 in (始, 終) for 始, 終, _ in 関係)
                        or not 0 < 位置 < len(区分順) - 1
                        or 座標[区分順[位置 - 1]]["内容"]["値"] != "制御"
                        or 座標[区分順[位置 + 1]]["内容"]["値"] != "提示本文"):
                    raise ValueError("区切りは制御と提示本文間の非実行空白区間である必要があります")
        elif 種 == _文節:
            所属 = 元(名, "区分所属")
            if len(所属) != 1 or 座標[所属[0]]["内容"]["値"] != "制御":
                raise ValueError("文節は一つの制御区分へ所属する必要があります")
            包含(所属[0], 名)
        elif 種 in {_目的, _変更}:
            所属 = 元(名, "文節所属")
            if len(所属) != 1:
                raise ValueError("目的又は変更の文節所属が一意ではありません")
            包含(所属[0], 名)
            if 種 == _目的:
                前目的 = 元(名, "目的継承") + 元(名, "命令再実行")
                if len(前目的) > 1 or any(座標[参照]["内容"]["値"]["役割"] != _目的 for 参照 in 前目的):
                    raise ValueError("目的継承の元目的又は一意性が不正です")
                使用前束.update(前目的)
        elif 種 in _役割種:
            if not any(名 in (始, 終) and 関係種 in _役割関係 for 始, 終, 関係種 in 関係):
                raise ValueError("役割座標の目的束縛がありません")
        if 種 == _条件 and 内容["値"]["役割"] == "動作目的要求" and 内容["根拠"] != "前束":
            内 = 内容["値"]["値"]
            外 = _原動作目的の原役割を検査(内, 原文)
            適用 = 先(名, "条件適用")
            if (len(適用) != 1 or 座標[適用[0]]["内容"]["値"] != "説明"
                    or 項["原文範囲"] != 外 or 内容["根拠"] != "原文"
                    or 内["焦点ID"] not in 先(適用[0], "要求関係")):
                raise ValueError("原動作目的の同目的原役割が不正です")
            文節 = 元(適用[0], "文節所属")
            if len(文節) != 1: raise ValueError("原動作目的の文節が一意ではありません")
            制御 = 元(文節[0], "区分所属")[0]
            包含(制御, 名); 包含(文節[0], 名)
            焦点 = 座標[内["焦点ID"]]
            if (焦点["内容"]["根拠"] != "原文" or 焦点["原文範囲"] != 外
                    or 焦点["内容"]["値"] != 内["原語句"]["原文"]):
                raise ValueError("原動作目的の焦点と原句が不一致です")
        if 種 == _条件 and 内容["値"]["役割"] == "関係要求" and 内容["根拠"] != "前束":
            内 = 内容["値"]["値"]
            _範囲(内["原語句範囲"], 原文)
            適用 = 先(名, "条件適用")
            if (len(適用) != 1 or 座標[適用[0]]["内容"]["値"] != "説明"
                    or 項["原文範囲"] != 内["原語句範囲"] or 内容["根拠"] != "原文"
                    or not set(内["両端ID"]) <= set(先(適用[0], "要求対象"))
                    or 内["焦点ID"] not in 先(適用[0], "要求関係")):
                raise ValueError("関係要求の同目的原役割が不正です")
            文節 = 元(適用[0], "文節所属")
            if len(文節) != 1: raise ValueError("関係要求の文節が一意ではありません")
            制御 = 元(文節[0], "区分所属")[0]
            包含(制御, 名)
            焦点 = 座標[内["焦点ID"]]
            if 焦点["内容"]["値"] != "関係" or 焦点["内容"]["原文"] != "関係":
                raise ValueError("未知の関係焦点を具体述語へ補完できません")
            包含(名, 内["焦点ID"])
            for 参照 in 内["両端ID"]:
                端 = 座標[参照]
                if 端["種別"] != "対象.会話主題" or 端["内容"]["根拠"] != "原文":
                    raise ValueError("関係端点は当回の明示主題が必要です")
                包含(制御, 参照)
                原句 = 端["内容"]["原文"]
                原値 = 原句[1:-1] if len(原句) >= 2 and (原句[0], 原句[-1]) in {("「", "」"), ("『", "』")} else 原句
                if 端["内容"]["値"] != 原値:
                    raise ValueError("関係端点の値が原句と一致しません")
            if 座標[内["両端ID"][0]]["内容"]["値"] == 座標[内["両端ID"][1]]["内容"]["値"]:
                raise ValueError("同名の関係端点を二対象へ増殖できません")
            外側 = [参照 for 参照 in 内["両端ID"] if not (座標[文節[0]]["原文範囲"][0] <= 座標[参照]["原文範囲"][0] < 座標[参照]["原文範囲"][1] <= 座標[文節[0]]["原文範囲"][1])]
            対応 = [座標[参照]["内容"]["値"]["値"] for 参照 in 元(適用[0], "条件適用")
                    if 座標[参照]["内容"]["値"]["役割"] == "同発話対応"]
            if any(not any(参照 in 条件["対応対象ID"] for 条件 in 対応) for 参照 in 外側):
                raise ValueError("関係端点の子文外参照に当回の対応証明がありません")
        if 種 == _条件 and 内容["値"]["役割"] == "同発話対応" and 内容["根拠"] != "前束":
            内 = 内容["値"]["値"]
            _範囲(内["標識範囲"], 原文)
            元目的, 補足目的 = 内["元目的ID"], 内["補足目的ID"]
            if (元目的 not in 座標 or 補足目的 not in 座標
                    or 座標[元目的]["種別"] != _目的 or 座標[補足目的]["種別"] != _目的
                    or 先(名, "条件適用") != [補足目的] or 項["原文範囲"] != 内["標識範囲"]
                    or 内容["根拠"] != "原文"):
                raise ValueError("同発話対応の目的又は原標識が不正です")
            元節, 補足節 = 元(元目的, "文節所属"), 元(補足目的, "文節所属")
            if (len(元節) != 1 or len(補足節) != 1
                    or 元(元節[0], "区分所属") != 元(補足節[0], "区分所属")):
                raise ValueError("同発話対応を別の制御区分へ移植できません")
            制御 = 元(元節[0], "区分所属")[0]
            for 参照 in (名, 元目的, 補足目的, *内["元対象ID"], *内["対応対象ID"], *内["観点ID"]):
                if 参照 not in 座標 or 座標[参照]["内容"]["根拠"] != "原文":
                    raise ValueError("同発話対応の原文役割が欠落しています")
                包含(制御, 参照)
                if 参照 in 内["元対象ID"] + 内["対応対象ID"] + 内["観点ID"]:
                    実原句 = 座標[参照]["内容"]["原文"]
                    原値 = 実原句[1:-1] if len(実原句) >= 2 and (実原句[0], 実原句[-1]) in {("「", "」"), ("『", "』")} else 実原句
                    if 座標[参照]["内容"]["値"] != 原値:
                        raise ValueError("同発話対応の原役割値が実原句と一致しません")
            元対象 = 先(元目的, "要求対象")
            補対象 = 先(補足目的, "要求対象")
            if (not 元対象 or 内["元対象ID"] != 元対象 or len(内["対応対象ID"]) != len(元対象)
                    or not set(内["対応対象ID"]) <= set(補対象)):
                raise ValueError("同発話対応の原対象が完全ではありません")
            for 前, 後 in zip(元対象, 内["対応対象ID"]):
                種対応 = 座標[前]["種別"] == 座標[後]["種別"] or (内["方式"] == "包含比較補足"
                      and 座標[前]["種別"] == "対象.会話主題" and 座標[後]["種別"] == "対象.会話比較")
                if (not 種対応
                        or 座標[前]["内容"]["値"] != 座標[後]["内容"]["値"]
                        or 座標[前]["原文範囲"] != 座標[後]["原文範囲"]):
                    raise ValueError("同発話対応の原対象と対応対象が一致しません")
            標識 = 原文[slice(*内["標識範囲"])]
            if 内["方式"] == "比較観点補足":
                from .会話字句 import 会話字句を観測
                字 = 会話字句を観測(標識)
                if (元目的 != 補足目的 or 座標[元目的]["内容"]["値"] != "対照" or len(元対象) < 2
                        or not 内["観点ID"] or not 字 or 字[0].辞書形 not in {"比較", "対照", "比べる"}
                        or not any(子.表層 == "て" or 子.辞書形 == "くださる" for 子 in 字)):
                    raise ValueError("比較観点の当回補足標識が不正です")
            else:
                if (元目的 == 補足目的 or len(元対象) != 1
                        or 座標[元節[0]]["原文範囲"][1] > 座標[補足節[0]]["原文範囲"][0]):
                    raise ValueError("省略対象の当回元目的が一意ではありません")
                同元補足 = {行["内容"]["値"]["値"]["補足目的ID"] for 行 in 座標.values()
                          if 行["種別"] == _条件 and 行["内容"]["値"]["役割"] == "同発話対応"
                          and 行["内容"]["値"]["値"]["元目的ID"] == 元目的}
                先行 = [候補 for 候補, 行 in 座標.items() if 行["種別"] == _目的 and 候補 not in 同元補足
                      and len(元(候補, "文節所属")) == 1
                      and 座標[元(候補, "文節所属")[0]]["原文範囲"][1] <= 座標[補足節[0]]["原文範囲"][0]]
                if 先行 != [元目的]: raise ValueError("同発話の元目的が一意ではありません")
                if 内["方式"] in {"包含補足", "包含比較補足"}:
                    焦点 = 先(元目的, "要求関係")
                    if (標識 not in {"も含めて", "を含めて"} or len(焦点) != 1
                            or 座標[焦点[0]]["内容"]["値"] != "定義"):
                        raise ValueError("定義の包含補足標識が不正です")
                    if 内["方式"] == "包含比較補足" and (座標[補足目的]["内容"]["値"] != "対照" or len(補対象) != 2):
                        raise ValueError("包含比較の原二端と対照作用が不正です")
                    if 内["方式"] == "包含比較補足":
                        別端 = next(参照 for 参照 in 補対象 if 参照 not in 内["対応対象ID"])
                        原終 = 座標[別端]["原文範囲"][1]
                        軸 = sorted((座標[参照]["原文範囲"] for 参照 in 内["観点ID"]), key=lambda 範: 範[0])
                        原観点 = 原文[軸[0][0]:軸[-1][1]] + "の" if 軸 else ""
                        実後 = 原文[原終:内["標識範囲"][0]]
                        if 実後 not in {"との" + 原観点 + "違い", "との" + 原観点 + "相違"}:
                            raise ValueError("包含比較の原端点・観点・違い主要部が不一致です")
                elif 内["方式"] == "理由参照関係補足":
                    前理由 = [候補 for 候補, 行 in 座標.items() if 行["種別"] == _目的 and 行["内容"]["値"] == "理由"
                            and len(元(候補, "文節所属")) == 1
                            and 座標[元(候補, "文節所属")[0]]["原文範囲"][1] <= 座標[補足節[0]]["原文範囲"][0]]
                    if (前理由 != [元目的] or not 標識.lstrip("。？? \r\n\t").startswith("その理由を、")
                            or not 標識.endswith("との") or len(補対象) != 2 or len(内["観点ID"]) != 1):
                        raise ValueError("理由参照の当回元目的又は原標識が不正です")
                elif 標識 != "との" or len(補対象) != 2 or len(内["観点ID"]) != 1:
                    raise ValueError("関係端点の当回補足標識が不正です")
            for 参照 in 内["観点ID"]:
                if 座標[参照]["種別"] != "条件.会話観点" or not any(参照 in 先(目的, "要求観点") for 目的 in {元目的, 補足目的}):
                    raise ValueError("同発話観点の目的対応が不正です")
            if 内["方式"] in {"関係端点補足", "理由参照関係補足"}:
                端点 = next(参照 for 参照 in 補対象 if 参照 not in 内["対応対象ID"])
                観点 = 内["観点ID"][0]
                if (座標[端点]["内容"]["値"] != 座標[観点]["内容"]["値"]
                        or 座標[端点]["原文範囲"] != 座標[観点]["原文範囲"]):
                    raise ValueError("検索観点は明示関係端点の実原句だけが対象です")
        if 種 == _条件 and 内容["値"]["役割"] == "取得時期":
            適用 = 先(名, "条件適用")
            範囲 = 先(適用[0], "要求範囲") if len(適用) == 1 else []
            所属 = 元(適用[0], "文節所属") if len(適用) == 1 else []
            if (内容["根拠"] != "原文" or 項["原文範囲"] is None or len(適用) != 1
                    or len(範囲) != 1 or 座標[範囲[0]]["内容"]["値"] != "公開取得" or len(所属) != 1):
                raise ValueError("取得時期は当回原句と同目的の一意公開取得範囲が必要です")
            同時期 = [始 for 始, 終, 関係種 in 関係 if 終 == 適用[0] and 関係種 == "条件適用"
                   and 座標[始]["内容"]["値"]["役割"] == "取得時期"]
            if len(同時期) != 1:
                raise ValueError("同目的の取得時期が一意ではありません")
            包含(所属[0], 名)
        if (種 == _条件 and 内容["値"]["役割"] == "問い条件"
                and type(内容["値"]["値"]) is dict and 内容["値"]["値"].get("版") == 会話主張変更版):
            内 = 内容["値"]["値"]
            適用 = 先(名, "条件適用")
            所属 = 元(適用[0], "文節所属") if len(適用) == 1 else []
            材料 = 元(適用[0], "材料適用") if len(適用) == 1 else []
            同行為 = [始 for 始, 終, 関係種 in 関係 if len(適用) == 1 and 終 == 適用[0] and 関係種 == "条件適用"
                   and 座標[始]["内容"]["値"]["役割"] == "問い条件"]
            if (内容["根拠"] != "原文" or 項["原文範囲"] is None or len(適用) != 1
                    or 座標[適用[0]]["内容"]["値"] != "主張検討" or len(所属) != 1
                    or len(同行為) != 1 or len(材料) != 1 or 座標[材料[0]]["内容"]["値"] != "提示本文"):
                raise ValueError("主張変更には同目的の原句・行為・提示資料束縛が必要です")
            包含(所属[0], 名)
            外 = 座標[所属[0]]["原文範囲"]
            操作範囲 = []
            for 指定 in (内["取消指定"], 内["書換指定"]):
                if 指定 is None: continue
                範囲 = 指定["操作範囲"]
                _範囲(範囲, 原文)
                if 範囲 is None or not 外[0] <= 範囲[0] < 範囲[1] <= 外[1]:
                    raise ValueError("主張変更の操作範囲が所属制御文節にありません")
                操作範囲.append(範囲)
            if len(操作範囲) == 2 and not (操作範囲[0][1] <= 操作範囲[1][0] or 操作範囲[1][1] <= 操作範囲[0][0]):
                raise ValueError("取消と書換の操作範囲が重複しています")
            取消, 書換 = 内["取消指定"], 内["書換指定"]
            if 取消 is not None:
                選択 = 取消["選択範囲"]
                _範囲(選択, 原文)
                if 選択 is None or not 外[0] <= 選択[0] < 選択[1] <= 取消["操作範囲"][0]:
                    raise ValueError("取消の選択範囲が原操作の前にありません")
                if (取消["選択方式"] == "条件ID指定"
                        and 原文[slice(*選択)] != "条件ID「" + 取消["明示識別子"] + "」"):
                    raise ValueError("条件ID指定が原文明示句と一致しません")
            焦点 = 先(適用[0], "要求関係")
            if 書換 is None:
                if 焦点: raise ValueError("取消のみの依頼に架空主張を追加できません")
            else:
                名詞 = 書換["主張座標ID"]
                if 名詞 not in 座標 or 座標[名詞]["種別"] != "関係.会話問い焦点" or 焦点 != [名詞]:
                    raise ValueError("書換主張が同目的の一意焦点ではありません")
                包含(所属[0], 名詞)
                主張範囲 = 座標[名詞]["原文範囲"]
                if 主張範囲 is None or 主張範囲[1] > 書換["操作範囲"][0]:
                    raise ValueError("書換主張の原範囲が操作の前にありません")
        if 内容["根拠"] == "前束" and 種 not in _前束種:
            if (種 == _条件 and 内容["値"]["役割"] in {"動作目的要求", "関係要求", "同発話対応"}
                    and (項["原文範囲"] is not None or 内容["原文"] != "")):
                raise ValueError("型付き前条件に当回原範囲又は当回原句を付加できません")
            参照 = 内容["前束参照"]
            if 参照 not in 座標 or 座標[参照]["種別"] not in _前束種:
                raise ValueError("継承した役割の前束参照が欠落しています")
            元値 = 座標[参照]["内容"]["値"]
            if 元値["役割"] != 種 or 元値["値印"] != _指紋(内容["値"]):
                raise ValueError("前束の役割又は値が継承座標と一致しません")
            使用前束.add(参照)
        if 種 == _変更:
            対象, 前, 後 = 先(名, "変更対象"), 先(名, "変更前"), 先(名, "変更後")
            if len(対象) != 1 or len(後) != 1 or len(前) > 1 or 内容["値"]["役割"] != "添加" and len(前) != 1:
                raise ValueError("変更の前後又は目的対象が不正です")
            対象役割 = 内容["値"]["対象役割"]
            for 参照 in 前 + 後:
                参照種 = 座標[参照]["種別"]
                if 参照種 == _前束:
                    使用前束.add(参照)
                    参照種 = 座標[参照]["内容"]["値"]["役割"]
                if 参照種 != 対象役割:
                    raise ValueError("変更前後の役割が置換対象と一致しません")
            if 後[0] != 対象[0] and not any(関係種 in _役割関係 and {始, 終} == {後[0], 対象[0]} for 始, 終, 関係種 in 関係):
                raise ValueError("変更後役割が変更目的に束縛されていません")
    if not 制御数:
        raise ValueError("会話制御区分がありません")
    前束ID = {名 for 名, 項 in 座標.items() if 項["種別"] in _前束種}
    if 前束ID != 使用前束:
        raise ValueError("余剰又は未接続の前束座標があります")
    保持辺 = [(始, 終) for 始, 終, 種 in 関係 if 種 == "保持対応"]
    対応目的 = set()
    for 始, 終 in 保持辺:
        if 座標[始]["内容"]["値"]["役割"] != "出力保持":
            raise ValueError("型保持の原条件役割が不正です")
        条件目的, 表現目的 = 先(始, "条件適用"), 先(終, "表現適用")
        if len(条件目的) != 1 or 条件目的 != 表現目的:
            raise ValueError("型保持と原保持句の目的が一致しません")
        if len(元(終, "保持対応")) != 1:
            raise ValueError("型保持と原保持句の対応が一意ではありません")
        対応目的.update(条件目的)
    # 旧包の辺無し形は変換しない。新しい対応を使う目的内では一部だけを省けない。
    for 目的ID in 対応目的:
        原条件 = [名 for 名 in 元(目的ID, "条件適用")
               if 座標[名]["内容"]["値"]["役割"] == "出力保持"]
        型表現 = [名 for 名 in 元(目的ID, "表現適用") if 座標[名]["種別"] == "表現.会話保持"]
        if any(not 先(名, "保持対応") for 名 in 原条件) or any(len(元(名, "保持対応")) != 1 for 名 in 型表現):
            raise ValueError("型保持と原保持句の対応が完全に被覆されていません")
    数量範囲 = {}
    for 始, 終, 種 in 関係:
        if 種 == "表現適用" and 座標[始]["種別"] == "表現.会話数量":
            値 = 座標[始]["内容"]["値"]
            鍵 = (終, 値["単位"])
            下限, 上限 = 数量範囲.get(鍵, (1, 24000))
            下限 = max(下限, 値["数"] if 値["関係"] == "一致" else 1)
            上限 = min(上限, 値["数"])
            if 下限 > 上限:
                raise ValueError("同一目的・単位の表現数量が競合しています")
            数量範囲[鍵] = (下限, 上限)
    子群 = {名: 先(名, "文節従属") for 名, 項 in 座標.items() if 項["種別"] == _文節}
    完了 = set()
    def 辿る(名, 経路):
        if 名 in 経路:
            raise ValueError("文節従属に循環があります")
        if 名 not in 完了:
            for 子 in 子群[名]:
                辿る(子, 経路 | {名})
            完了.add(名)
    for 名 in 子群:
        辿る(名, set())


def _文脈を検査(群, 所有, *, 命令=False):
    if type(群) not in {list, tuple} or len(群) > 4:
        raise ValueError("文脈束数が不正です")
    結果 = {}
    for 元 in 群:
        欄 = {"前束印", "所有セッション", "原記録ID", "依存版", "参照"}
        _欄(元, 欄 | {"版", "用途", "原要求印"} if 命令 else 欄, "文脈束縛")
        if 命令 and (元["版"] != 会話命令証明版 or 元["用途"] != "命令再実行"):
            raise ValueError("命令履歴証明の版又は用途が不正です")
        if 命令:
            _印(元["原要求印"], "命令原要求印")
        _印(元["前束印"], "前束印")
        _文(元["所有セッション"], "前束所有")
        _文(元["原記録ID"], "前束原記録ID")
        if 元["所有セッション"] != 所有 or 元["前束印"] in 結果:
            raise ValueError("文脈の所有又は一意性が不正です")
        if type(元["依存版"]) is not dict or len(元["依存版"]) > 64:
            raise ValueError("前束依存版が不正です")
        for 名, 版 in 元["依存版"].items():
            _文(名, "依存名")
            _印(版, "依存版")
        _列(元["参照"], "前束参照列", 64, 文字=False)
        既参照 = set()
        for 参照 in 元["参照"]:
            _欄(参照, {"座標ID", "役割", "値印"}, "前束参照")
            _文(参照["座標ID"], "前束座標ID")
            _印(参照["値印"], "前束値印")
            _文(参照["役割"], "前束参照役割")
            if 参照["役割"] not in _変更役割種 or 参照["座標ID"] in 既参照:
                raise ValueError("前束参照役割又は一意性が不正です")
            既参照.add(参照["座標ID"])
        結果[元["前束印"]] = deepcopy(元)
    return 結果


def _文脈束縛(座標, 証明群, 所有, 命令証明=()):
    候補 = _文脈を検査(証明群, 所有)
    命令候補 = _文脈を検査(命令証明, 所有, 命令=True)
    if len(証明群) + len(命令証明) > 4:
        raise ValueError("2種の会話証明の全体予算が4を超えています")
    必要 = {}
    for 項 in 座標.values():
        if 項["種別"] not in _前束種:
            continue
        値 = 項["内容"]["値"]
        種 = 項["種別"]
        元 = (命令候補 if 種 == _命令前束 else 候補).get(値["前束印"])
        参照 = {名: 値[名] for 名 in ("座標ID", "役割", "値印")}
        if 元 is None or 参照 not in 元["参照"]:
            raise ValueError("前束参照が呼出元の実文脈証明と一致しません")
        必要.setdefault((種, 値["前束印"]), []).append(参照)
    結果 = []
    for (種, 印), 参照群 in 必要.items():
        元 = deepcopy((命令候補 if 種 == _命令前束 else 候補)[印])
        元["参照"] = [参照 for 参照 in 元["参照"] if 参照 in 参照群]
        結果.append(元)
    return 結果


def _残差対応(証明, 座標, 関係, 目的ID):
    経路 = {名: set() for 名 in 座標}
    for 始, 終, 種 in 関係:
        if 種 in {"要求対象", "要求観点", "要求関係", "問い方向", "要求範囲", "変更前", "変更後"}:
            経路[終].add(始)
        else:
            経路[始].add(終)
    for 名, 項 in 座標.items():
        if 項["内容"]["根拠"] == "前束" and 項["種別"] not in _前束種:
            経路[項["内容"]["前束参照"]].add(名)
    def 到達(始):
        残り, 到達済 = [始], set()
        while 残り:
            名 = 残り.pop()
            if 名 in 到達済:
                continue
            到達済.add(名)
            残り.extend(経路.get(名, ()))
        return set(目的ID) & 到達済
    結果 = []
    for 残差 in 証明["残差"]:
        if 残差["残差ID"] not in 証明["会話残差ID"]:
            continue
        対象 = set()
        for 名 in 残差["影響座標"]:
            対象 |= 到達(名) or set(目的ID)
        if not 対象:
            対象 = set(目的ID)
        結果.append({"残差ID": 残差["残差ID"], "目的ID": [名 for 名 in 目的ID if 名 in 対象]})
    return 結果


def _導出欄(証明, 座標, 関係, 目的ID, 文脈証明, 所有, 命令証明=()):
    return {"区分参照": [名 for 名, 項 in 座標.items() if 項["種別"] == _区分],
            "目的参照": 目的ID,
            "条件参照": [名 for 名, 項 in 座標.items() if 項["種別"] in _条件種],
            "表現参照": [名 for 名, 項 in 座標.items() if 項["種別"] in _表現種],
            "変更参照": [名 for 名, 項 in 座標.items() if 項["種別"] == _変更],
            "残差対応": _残差対応(証明, 座標, 関係, 目的ID),
            "文脈束縛": _文脈束縛(座標, 文脈証明, 所有, 命令証明)}


def 会話契約を形成(意味IR: HDSIR, *, 所有セッション: str, 文脈証明=(), 命令証明=()) -> dict:
    """同一Kernelの明示v3参照を保存包へ降ろす。解釈の追加はしない。"""
    _文(所有セッション, "所有セッション")
    証明 = _IR参照(意味IR)
    座標, 関係, 目的ID = _証明構造(証明)
    文 = _正準(証明)
    包 = {"版": 会話契約版, "証明範囲": _証明範囲, "所有セッション": 所有セッション,
          "原文印": hashlib.sha256(証明["原文"].encode("utf-8")).hexdigest(),
          "意味束印": hashlib.sha256(文.encode("utf-8")).hexdigest(), "証明正準JSON": 文,
          **_導出欄(証明, 座標, 関係, 目的ID, 文脈証明, 所有セッション, 命令証明)}
    会話契約を検査(包, 所有セッション=所有セッション, 意味IR=意味IR, 文脈証明=文脈証明, 命令証明=命令証明)
    return 包


def 会話契約を検査(包: dict, *, 所有セッション: str, 期待原文: str | None = None,
            意味IR: HDSIR | None = None, 文脈証明=(), 命令証明=()) -> dict:
    """保存された局所ビューを検査して返す。採用・原記録所有は呼出元責任。"""
    _文(所有セッション, "所有セッション")
    _欄(包, _包欄, "会話契約包")
    if len(_正準(包).encode("utf-8")) > 16000000:
        raise ValueError("会話包byte予算を超えました")
    if 包["版"] != 会話契約版 or 包["証明範囲"] != _証明範囲 or 包["所有セッション"] != 所有セッション:
        raise ValueError("会話契約の版・範囲・所有が一致しません")
    for 名 in ("原文印", "意味束印"):
        _印(包[名], 名)
    文 = 包["証明正準JSON"]
    証明 = _証明を読む(文)
    座標, 関係, 目的ID = _証明構造(証明)
    if 包["意味束印"] != hashlib.sha256(文.encode("utf-8")).hexdigest() or 包["原文印"] != hashlib.sha256(証明["原文"].encode("utf-8")).hexdigest():
        raise ValueError("会話参照の正準印が一致しません")
    if 期待原文 is not None:
        _文(期待原文, "期待原文", 上限=8000000)
        if 期待原文 != 証明["原文"]:
            raise ValueError("呼出元の原文と会話証明が一致しません")
    if 意味IR is not None and _正準(_IR参照(意味IR)) != 文:
        raise ValueError("呼出元の同一HDSIRと会話参照ビューが一致しません")
    # 当該旧包へのcaller実履歴証明がある場合だけ、旧祖先の5欄を検査する。
    # 新包形成にはこの適合を使わず、保存包も現行成果証明も書き換えない。
    命令群 = _文脈を検査(命令証明, 所有セッション, 命令=True)
    _文脈を検査(文脈証明, 所有セッション)
    検査文脈 = list(文脈証明)
    if 包["意味束印"] in 命令群:
        if 命令群[包["意味束印"]]["原要求印"] != 包["原文印"]:
            raise ValueError("命令履歴証明の原要求印が旧包全文と一致しません")
        必要印 = {項["内容"]["値"]["前束印"] for 項 in 座標.values() if 項["種別"] == _前束}
        現行印 = {項["前束印"] for 項 in 検査文脈}
        for 印 in 必要印 - 現行印:
            if 印 in 命令群:
                検査文脈.append({名: deepcopy(値) for 名, 値 in 命令群[印].items() if 名 not in {"版", "用途", "原要求印"}})
    # 検査用適合ビューは同じ証明の予算を重複計上しない。
    検査命令 = [項 for 項 in 命令証明 if 項["前束印"] not in {項["前束印"] for 項 in 検査文脈}
            or any(座標項["種別"] == _命令前束 and 座標項["内容"]["値"]["前束印"] == 項["前束印"] for 座標項 in 座標.values())]
    if len(文脈証明) + len(命令証明) > 4:
        raise ValueError("2種の会話証明の全体予算が4を超えています")
    for 名, 値 in _導出欄(証明, 座標, 関係, 目的ID, 検査文脈, 所有セッション, 検査命令).items():
        if type(包[名]) is not list or 包[名] != 値:
            raise ValueError("会話契約の" + 名 + "が同一ビューの導出と一致しません")
    return deepcopy(証明)
