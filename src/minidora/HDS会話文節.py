def _旧単目的で保持できる(列, 操作, 問い, 本文):
    """旧有限構文の表現可能性。目的数だけで新しい格・補助句を捨てない。"""
    if len(操作) != 1 or any(句.get("構造") or 句.get("同発話") for 句 in 問い):
        return False
    if 問い and 本文.startswith(("別の話", "話題を変えて", "次の話題")):
        return True  # 旧話題変更の作用と残差検査を保つ。
    頭始 = 操作[0][0]
    if any(not 項.引用 and (位置 < 頭始 and 項.表層 in {"、", ",", ";", "；", "\n"}
                          or 項.辞書形 == "ほしい") for 位置, 項 in enumerate(列)):
        return False
    if any(列[位置].表層 in {"を", "は"}
           and _引用資料指示(列, _NP前(列, 位置, set()), 位置)
           for 位置 in range(頭始)):
        return False
    if 問い:
        # 有効な単一問いと、旧型で保持できる連体主題の定義に限る。
        return len(問い) == 1 and (問い[0]["理由"] is None
               or 操作[0][2] == "疑問:説明" and "とは" in 本文)
    return 操作[0][2] in {"説明", "解説", "要約", "比較", "対照", "まとめる", "比べる", "教える"}


def _補助末(列, 終):
    while 終 < len(列) and (列[終].辞書形 in _補助 or 列[終].表層.isspace()):
        終 += 1
    return 終


def _依頼未確定(列, 始, 終, *, 後続操作):
    末 = _補助末(列, 終)
    補助 = [項 for 項 in 列[終:末] if not 項.表層.isspace()]
    if any(項.辞書形 == "た" for 項 in 補助):
        return "過去の行為報告を今回の依頼へ昇格できません"
    if "命令形" in 列[終 - 1].活用形:
        return None
    if 補助 and 補助[0].辞書形 in {"て", "で", "くださる"}:
        return None
    if 後続操作 and "連用形" in 列[終 - 1].活用形:
        return None
    return "操作語の時制又は依頼形が未確定です"


def _数(文):
    try:
        return int(文)
    except ValueError:
        pass
    if not 文 or any(字 not in _数字.keys() | _位.keys() for 字 in 文):
        return None
    合計, 部分, 数 = 0, 0, 0
    前位 = 10000
    for 字 in 文:
        if 字 in _数字:
            数 = 数 * 10 + _数字[字]
        else:
            位 = _位[字]
            if 位 != 10000 and 位 >= 前位:
                return None
            if 位 == 10000:
                合計 += (部分 + 数 or 1) * 位
                部分, 数, 前位 = 0, 0, 10000
            else:
                部分 += (数 or 1) * 位
                数, 前位 = 0, 位
    return 合計 + 部分 + 数


def _助数詞句(列, 位置):
    """『つ』の係り先候補。世界の個数を出力項目へ置換しない。"""
    if (列[位置].引用 or 列[位置].詳細 != "数詞" or 位置 + 1 >= len(列)
            or 列[位置 + 1].表層 != "つ" or 列[位置 + 1].品詞 != "接尾辞"):
        return None
    終, 比較 = 位置 + 2, "一致"
    if 終 < len(列) and 列[終].表層 == "目":
        return ("世界", 終 + 1, 比較, None)
    if 終 < len(列) and 列[終].表層 in {"以内", "以下"}:
        終, 比較 = 終 + 1, "以内"
    if 終 < len(列) and 列[終].表層 == "の":
        if (終 + 2 < len(列) and 列[終 + 1].表層 == "箇条書き"
                and 列[終 + 1].品詞 == "名詞" and 列[終 + 2].表層 in {"で", "に"}):
            末 = 終 + 3
            # 箇条書きに「ある」記載などは文書側の個数であり表現形式ではない。
            if 末 < len(列) and 列[末].品詞 == "動詞" and 列[末].辞書形 not in _動詞:
                return ("世界", 末, 比較, None)
            if 末 < len(列) and 列[末].表層 == "は":
                return ("未確定", 末, 比較, None)
            return ("箇条書き", 末, 比較, None)
        return ("世界", 終, 比較, None)
    if 終 < len(列) and 列[終].表層 in {"を", "は", "も"}:
        return ("世界", 終, 比較, None)
    if 終 < len(列) and 列[終].表層 in {"で", "に"}:
        終 += 1
    要点格 = (位置 - 1 if 位置 >= 2 and 列[位置 - 1].表層 == "を"
            and 列[位置 - 2].表層 == "要点" and 列[位置 - 2].品詞 == "名詞" else None)
    return ("要点" if 要点格 is not None else "未確定", 終, 比較, 要点格)


def _単位数量句(列, 位置):
    """数量の属格対象と出力形式を格・係り先で分ける。"""
    if (列[位置].引用 or 列[位置].詳細 != "数詞" or 位置 + 1 >= len(列)
            or 列[位置 + 1].表層 not in {"文字", "文", "項目"}):
        return None
    終, 比較 = 位置 + 2, "一致"
    if 終 < len(列) and 列[終].表層 in {"以内", "以下"}:
        終, 比較 = 終 + 1, "以内"
    if 終 < len(列) and 列[終].表層 == "の":
        if (列[位置 + 1].表層 == "項目" and 終 + 2 < len(列)
                and 列[終 + 1].表層 == "箇条書き" and 列[終 + 1].品詞 == "名詞"
                and 列[終 + 2].表層 in {"で", "に"}):
            末 = 終 + 3
            if 末 < len(列) and (列[末].表層 == "は" or 列[末].品詞 == "動詞"
                    and 列[末].辞書形 not in _動詞.keys() | {"する"}):
                return ("世界", 末, 比較)
            return ("箇条書き", 末, 比較)
        return ("世界", 終, 比較)
    if 終 < len(列) and 列[終].表層 in {"を", "は", "が", "も"}:
        return ("世界", 終, 比較)
    if 終 < len(列) and 列[終].表層 in {"で", "に"}:
        終 += 1
    return ("出力", 終, 比較)


def _NP字(項, 次=None):
    # 既知の形状詞一般は、原文で名詞へ直接連接する場合だけNP内部の修飾とする。
    # 単独、空白越し、助動詞・副詞句・条件節はこの字句判定で名詞へ変えない。
    return (項.引用 or 項.品詞 in {"名詞", "連体詞", "接頭辞", "接尾辞"}
            or 項.品詞 == "代名詞" and 項.表層 in _前束語
            or 項.品詞 == "形容詞" and "連体形" in 項.活用形
            or (項.品詞 == "形状詞" and 項.詳細 == "一般" and not 項.未知語
                and 項.活用形 == "*" and 次 is not None and 項.終 == 次.始
                and 次.品詞 == "名詞")
            or 項.品詞 == "助詞" and 項.表層 in {"の", "と", "や"}
            or 項.表層 in {"及び", "および"})


def _NP前(列, 位置, 消費):
    始 = 位置
    while 始 and 始 - 1 not in 消費 and (
            _NP字(列[始 - 1], 列[始] if 始 < 位置 else None) or 列[始 - 1].表層.isspace()):
        始 -= 1
    # 「引用」という名詞の連体句は引用を動作へ昇格せず名詞句として保つ。
    if 始 >= 3 and 列[始 - 1].辞書形 in {"いう", "言う"} and 列[始 - 2].表層 == "と" and 列[始 - 3].引用:
        始 -= 3
    while 始 < 位置 and 列[始].表層.isspace():
        始 += 1
    return 始


def _引用資料指示(列, 始, 終):
    """引用名に外側の文書主要部が付く未形成参照。引用内を実行しない。"""
    return (終 - 始 > 1 and 列[終 - 1].辞書形 in 文書指示名詞
            and any(項.引用 for 項 in 列[始:終 - 1]))


def _名詞群(列, 始, 終, 本文, 複数):
    範囲, 現在 = [], 始
    for 番号 in range(始, 終):
        if 複数 and not 列[番号].引用 and 列[番号].表層 in {"と", "や", "及び", "および"}:
            範囲.append((現在, 番号)); 現在 = 番号 + 1
    範囲.append((現在, 終))
    結果 = []
    for 左, 右 in 範囲:
        while 左 < 右 and 列[左].表層.isspace(): 左 += 1
        while 左 < 右 and 列[右 - 1].表層.isspace(): 右 -= 1
        if 左 == 右 or not any(項.引用 or 項.品詞 in {"名詞", "代名詞"} for 項 in 列[左:右]):
            return []
        始点, 終点 = 列[左].始, 列[右 - 1].終
        名 = 列[左].辞書形 if 右 == 左 + 1 and 列[左].引用 else 本文[始点:終点].strip()
        if not 名 or len(名) > 128:
            return []
        結果.append((名, 始点, 終点))
    return 結果 if len(結果) <= 4 else []


def _前入力(文脈, 前採用包, 文脈証明, 前命令包=None, 命令証明=(), *, 再実行=False):
    if 前採用包 is not None and 前命令包 is not None:
        raise ValueError("前採用包と前命令包の元源を混合できません")
    焦点 = getattr(文脈, "現在焦点", None)
    # 候補の供与は採用ではない。当前の字句作用が選んだ一用途だけを読む。
    前 = 焦点.get("前採用会話") if type(焦点) is dict and not 再実行 else None
    if 前 is not None:
        if type(前) is not dict or set(前) not in ({"契約包", "文脈証明"}, {"契約包", "文脈証明", "命令証明"}):
            raise ValueError("前採用会話の呼出側欄が不正です")
        if 前採用包 is not None and 前採用包 != 前["契約包"] or 文脈証明 and 文脈証明 != 前["文脈証明"]:
            raise ValueError("前採用会話の明示引数と文脈が競合しています")
        前採用包, 文脈証明 = 前["契約包"], 前["文脈証明"]
        if "命令証明" in 前:
            if 命令証明 and 命令証明 != 前["命令証明"]:
                raise ValueError("前採用会話の命令祖先証明が競合しています")
            命令証明 = 前["命令証明"]
    命令 = 焦点.get("前命令候補") if type(焦点) is dict and 再実行 else None
    if 命令 is not None:
        if type(命令) is not dict or set(命令) != {"契約包", "文脈証明", "命令証明"}:
            raise ValueError("前命令候補の呼出側欄が不正です")
        if (前命令包 is not None and 前命令包 != 命令["契約包"] or 文脈証明 and 文脈証明 != 命令["文脈証明"]
                or 命令証明 and 命令証明 != 命令["命令証明"]):
            raise ValueError("前命令候補の明示引数と文脈が競合しています")
        前命令包, 文脈証明, 命令証明 = 命令["契約包"], 命令["文脈証明"], 命令["命令証明"]
    if 前採用包 is not None and 前命令包 is not None:
        raise ValueError("前採用包と前命令包の元源を混合できません")
    return 前採用包, 文脈証明, 前命令包, 命令証明


def _値印(値):
    文 = json.dumps(値, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(文.encode("utf-8")).hexdigest()


def _前を読む(前採用包, 文脈証明, 命令証明=(), *, 命令=False):
    証明群 = 命令証明 if 命令 else 文脈証明
    if type(前採用包) is not dict or not 証明群:
        raise ValueError("前採用包と呼出側の文脈証明が必要です")
    所有 = 前採用包.get("所有セッション")
    前 = 会話契約を検査(前採用包, 所有セッション=所有, 文脈証明=文脈証明, 命令証明=命令証明)
    if 前["会話残差ID"] or 前["意味作用"]["損失"]:
        raise ValueError("未解決の前採用会話を継承できません")
    if any(項["値状態"] != "確定" or 項["暫定性"] != "原則暫定" or 項.get("再開放条件")
           for 項 in 前["座標"] + 前["関係"]):
        raise ValueError("未確定の前採用役割を継承できません")
    証明 = [項 for 項 in 証明群 if 項["前束印"] == 前採用包["意味束印"]]
    if len(証明) != 1 or 証明[0]["所有セッション"] != 所有:
        raise ValueError("前採用包への独立した呼出側証明がありません")
    if 命令 and 証明[0]["原要求印"] != 前採用包["原文印"]:
        raise ValueError("命令履歴と元包の原要求印が一致しません")
    return 前, 証明[0], 所有


def _実行字を読む(列, 本文):
    位置群 = {}
    結果 = set()
    for 番号, 項 in enumerate(列):
        if 項.引用 or not 1 <= len(項.表層) <= 256:
            continue
        if 項.表層 not in 位置群:
            位置群[項.表層] = {位置 for 位置, _ in 最上位位置(本文, (項.表層,))}
        if 項.始 in 位置群[項.表層]:
            結果.add(番号)
    return 結果


def _表現名詞句(列, 始):
    """既存形式語彙と完全一致する連続既知名詞句。字句の全体結合は行わない。"""
    文字, 前終 = "", None
    for 位置 in range(始, min(len(列), 始 + max(map(len, _表現形式)))):
        項 = 列[位置]
        品詞 = 項.品詞 if type(項.品詞) is str else 項.品詞[0]
        左, 右 = (項.始, 項.終) if isinstance(項, _句字) else (項.開始, 項.終了)
        if (品詞 not in {"名詞", "接尾辞"} or 項.未知語 or getattr(項, "引用", False)
                or 前終 is not None and 左 != 前終):
            return None
        文字 += 項.表層; 前終 = 右
        if 文字 in _表現形式: return _表現形式[文字], 位置 + 1
        if not any(語.startswith(文字) for 語 in _表現形式): return None
    return None


def _再表現頭(列, 実行字):
    結果 = []
    for 位置, 項 in enumerate(列):
        if 位置 not in 実行字 or 項.品詞 != "動詞" or 項.辞書形 != "する" or 位置 < 2 or 列[位置 - 1].表層 != "に":
            continue
        前 = 列[位置 - 2]
        形式 = any((句 := _表現名詞句(列, 始)) is not None and 句[1] == 位置 - 1 for 始 in range(max(0, 位置 - 1 - max(map(len, _表現形式))), 位置 - 1))
        if 形式 or 前.表層 in {"文", "項目", "文字", "以内", "以下"}:
            結果.append((位置, 位置 + 1, "再表現"))
    return 結果


def _再実行頭(列, 実行字):
    """最上位の依頼活用と反復副詞。引用・過去・余剰節は命令へ昇格しない。"""
    頭, 反復 = [], []
    for 位置 in sorted(実行字):
        項 = 列[位置]
        if (項.品詞 == "名詞" and 項.辞書形 == "再計算" and 位置 + 1 in 実行字
                and 列[位置 + 1].品詞 == "動詞" and 列[位置 + 1].辞書形 == "する"):
            頭.append((位置, 位置 + 2))
        elif 項.品詞 == "動詞" and 項.辞書形 == "続ける":
            頭.append((位置, 位置 + 1))
        elif (項.品詞 == "副詞" and 項.辞書形 == "もう" and 位置 + 1 in 実行字
                and 列[位置 + 1].品詞 == "名詞" and 列[位置 + 1].辞書形 == "一度"):
            反復.append((位置, 位置 + 2))
    if not 頭 and not 反復:
        return None
    消費 = {位置 for 位置, 項 in enumerate(列) if 項.表層.isspace() or 項.品詞 == "補助記号"}
    理由 = None
    if len(頭) > 1 or len(反復) > 1:
        理由 = "再実行の命令作用が一意ではありません"
    for 始, 終 in 頭:
        理由 = 理由 or _依頼未確定(列, 始, 終, 後続操作=False)
        消費.update(range(始, _補助末(列, 終)))
    for 始, 終 in 反復:
        消費.update(range(始, 終))
    if any(位置 not in 消費 for 位置 in range(len(列))):
        理由 = 理由 or "再実行命令に未解釈の対象又は条件があります"
    始 = min(項[0] for 項 in 頭 + 反復)
    終 = max(項[1] for 項 in 頭 + 反復)
    return 始, 終, 消費, 理由


def _訂正句(列, 実行字, 本文):
    """格付きの明示置換を保存する。旧役割の採否は前包の実適用辺と照合する。"""
    結果 = []
    明示役割 = {"観点": "条件.会話観点", "主題": "対象.会話主題", "資料": "対象.会話資料"}
    for 位置 in sorted(実行字):
        if (列[位置].表層 != "で" or 位置 + 2 not in 実行字 or 列[位置 + 1].表層 != "は"
                or 列[位置 + 2].辞書形 != "ない" or "連用形" not in 列[位置 + 2].活用形):
            continue
        始 = _NP前(列, 位置, set())
        旧 = _名詞群(列, 始, 位置, 本文, False)
        新始, 新終 = 位置 + 3, 位置 + 3
        while (新終 < len(列) and (新終 in 実行字 or 列[新終].引用)
               and _NP字(列[新終], 列[新終 + 1] if 新終 + 1 < len(列) else None)):
            新終 += 1
        新 = _名詞群(列, 新始, 新終, 本文, False)
        if not 旧 or not 新:
            continue
        格 = 列[新終].表層 if 新終 < len(列) else ""
        if 格 not in {"を", "で", "に"} and 格 and 列[新終].品詞 != "補助記号":
            continue
        役割 = None
        if 始 >= 2 and 列[始 - 1].表層 == "を" and 列[始 - 2].表層 in 明示役割:
            役割 = 明示役割[列[始 - 2].表層]
            始 -= 2
        結果.append({"旧値": 旧[0][0], "新値": 新[0][0], "新範囲": (新[0][1], 新[0][2]),
                  "役割": 役割, "始": 始, "終": 新終 + (格 in {"を", "で", "に"}), "格": 格})
    return 結果


def _訂正元を選ぶ(句, 前, 元目的=None):
    if 前 is None:
        return None, None, "訂正の現行成果と所有証明が未接続です"
    座標 = {項["座標ID"]: 項 for 項 in 前["座標"]}
    許容 = {"対象.会話主題", "対象.会話資料", "対象.会話比較", "条件.会話観点"}
    候補 = []
    for 辺 in 前["関係"]:
        if 辺["種別"] not in {"要求対象", "要求観点"}:
            continue
        目的ID, 役割ID = 辺["始点"][0], 辺["終点"][0]
        役割 = 座標[役割ID]
        if (役割["種別"] not in 許容 or 役割["内容"]["値"] != 句["旧値"]
                or 句["役割"] is not None and 役割["種別"] != 句["役割"]
                or 元目的 is not None and 目的ID != 元目的["座標ID"]):
            continue
        候補.append((座標[目的ID], 役割))
    if len(候補) != 1:
        return None, None, "訂正前の目的と役割が一意ではありません"
    return *候補[0], None


def _前目的を選ぶ(列, 節, 前, 実行字):
    指示 = [項 for 項 in 節 if 項 in 実行字 and 列[項].表層 in _前束語]
    if not 指示:
        return None, None
    if 前 is None:
        return None, "前束の所有証明が未接続の照応です"
    目的 = [項 for 項 in 前["座標"] if 項["種別"] == "目的.会話操作"]
    選択 = []
    for 位置 in 指示:
        語 = 列[位置].表層
        if 語 in {"前者", "一つ目"} and len(目的) == 2:
            選択.append(目的[0])
        elif 語 in {"後者", "二つ目"} and len(目的) == 2:
            選択.append(目的[1])
        elif 語 in {"それ", "これ", "前回"} and len(目的) == 1:
            選択.append(目的[0])
        else:
            return None, "前束の指示対象が一意ではありません"
    if len({項["座標ID"] for 項 in 選択}) != 1:
        return None, "一目的内の複数前目的又は訂正scopeが未接続です"
    return 選択[0], None


def HDS会話文節を形成(ir: HDSIR, *, 文脈=None, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()) -> HDSIR | None:
    """新しい局所scopeが必要な入力だけを同じIRへ射影する。Noneは旧経路。"""
    if type(ir) is not HDSIR or type(ir.原文) is not str or not ir.原文:
        raise ValueError("会話文節には空でない同一HDSIRが必要です")
    if ir.実行核.作用 not in (None, "参照"):
        return None
    if any(項.由来 == 会話射影由来 for 項 in ir.座標):
        raise ValueError("既存会話射影の無言v3変換は行いません")
    区分 = _入力区分(ir)
    制御区分 = next(項 for 項 in 区分 if 項[0] == "制御")
    _, 制御始, 制御終 = 制御区分
    制御 = ir.原文[制御始:制御終]
    元字句 = 会話字句を観測(制御)
    焦点 = getattr(文脈, "現在焦点", None)
    前供与 = 前採用包 is not None or type(焦点) is dict and 焦点.get("前採用会話") is not None
    # 字句上の候補さえない別Kernel入力へ、会話引用・予算を適用しない。
    from .HDS会話意味射影 import 会話依頼末を読む
    材料依頼 = any(項[0] == "提示本文" for 項 in 区分) and 会話依頼末を読む(制御)
    候補 = 材料依頼 or any(項.品詞[0] == "動詞" and 項.辞書形 in _動詞.keys() | _保持動詞 | _資料変更動詞.keys() | {"調べる", "読む", "答える"}
              or 項.品詞[0] == "名詞" and 項.辞書形 in _サ変.keys() | _保持サ変 | _主張サ変.keys() | _資料変更サ変.keys()
              and 番号 + 1 < len(元字句) and 元字句[番号 + 1].辞書形 == "する"
              or 項.品詞[1] == "数詞" and 番号 + 1 < len(元字句)
              and 元字句[番号 + 1].表層 in {"文字", "文", "項目", "つ"}
              or 前供与 and 項.品詞[0] == "動詞" and 項.辞書形 == "する"
              and 番号 >= 2 and 元字句[番号 - 1].表層 == "に"
               and any((句 := _表現名詞句(元字句, 始)) is not None and 句[1] == 番号 - 1
                       for 始 in range(max(0, 番号 - 1 - max(map(len, _表現形式))), 番号 - 1))
              or 項.辞書形 in {"再計算", "続ける", "もう", "なぜ", "どう", "何", "なに", "違い", "違う", "異なる", "関係"}
              or 前供与 and 項.辞書形 == "ない" and "連用形" in 項.活用形
              for 番号, 項 in enumerate(元字句))
    if not 候補:
        return None
    列 = _字句(制御, 元字句)
    実行字 = _実行字を読む(列, 制御)
    再実行句 = _再実行頭(列, 実行字)
    再実行 = 再実行句 is not None
    前採用包, 文脈証明, 前命令包, 命令証明 = _前入力(
        文脈, 前採用包, 文脈証明, 前命令包, 命令証明, 再実行=再実行)
    if 再実行 and 前命令包 is None:
        if 前採用包 is None:
            return None  # 歴史候補が無い旧継続要求は既存Kernel責任を維持する。
        raise ValueError("明示再実行には採用命令履歴の専用証明が必要です")
    訂正候補 = _訂正句(列, 実行字, 制御) if 前採用包 is not None else []
    頭 = _頭(列, 制御)
    主張 = _主張節(列, 制御, 実行字, 頭)
    主張対応 = {項["頭"]: 項 for 項 in 主張}
    資料変更 = _資料変更節(列, 制御, 実行字, 頭)
    資料変更対応 = {項["頭"]: 項 for 項 in 資料変更}
    疑問 = [項 for 項 in _疑問節(列, 制御, 実行字)
          if not any(句["左"] <= 項["頭"][0] < 句["右"] for 句 in 主張 + 資料変更)]
    取得句, 禁止句, 補問い = _取得付属を読む(列, 制御, 実行字, 頭)
    疑問.extend(補問い)
    補足, 補足頭 = _同発話補足(列, 制御, 実行字, 頭, 疑問)
    疑問.extend(補足)
    問い対応 = {項["頭"]: 項 for 項 in 疑問}
    操作 = [項 for 項 in 頭 if (項[2] in _サ変 or 項[2] in _動詞)
          and 項 not in 補足頭
          and not any(句["左"] <= 項[0] < 句["右"] for 句 in 疑問 + 主張 + 資料変更)]
    操作.extend(項["頭"] for 項 in 疑問)
    操作.extend(項["頭"] for 項 in 主張)
    操作.extend(項["頭"] for 項 in 資料変更)
    再表現 = _再表現頭(列, 実行字) if 前採用包 is not None else []
    操作 = sorted(操作 + 再表現)
    if 訂正候補 and not 操作:
        操作 = [(番号, 番号 + 1, "訂正") for 番号 in 実行字
              if 列[番号].品詞 == "動詞" and 列[番号].辞書形 == "する"]
        if not 操作:
            操作 = [(句["始"], 句["終"], "訂正") for 句 in 訂正候補]
    前ビュー, 前証明, 所有 = None, None, "構文化局所検査"
    if 前命令包 is not None and not 再実行:
        raise ValueError("命令履歴だけでは一般照応を解決できません")
    if 前採用包 is not None or 再実行:
        前ビュー, 前証明, 所有 = _前を読む(前命令包 if 再実行 else 前採用包, 文脈証明, 命令証明, 命令=再実行)
    命令目的 = [項 for 項 in 前ビュー["座標"] if 項["種別"] == "目的.会話操作"] if 再実行 else []
    if 再実行:
        操作 = [(再実行句[0], 再実行句[1], "再実行") for _ in 命令目的]
    前候補 = 前採用包 is not None and (再表現 or 訂正候補 or any(列[番号].表層 in _前束語 for 番号 in 実行字))
    単位候補 = {位置: 句 for 位置 in 実行字 if (句 := _単位数量句(列, 位置)) is not None}
    数量候補 = any(句[0] != "世界" for 句 in 単位候補.values())
    助数候補 = {位置: 句 for 位置 in 実行字 if (句 := _助数詞句(列, 位置)) is not None}
    # 裸助数詞自体を読解目的にしない。原文中の世界名詞の個数も旧責任へ残す。
    if 操作 and any(句[0] != "世界" for 句 in 助数候補.values()):
        数量候補 = True
    保持候補 = [項 for 項 in 頭 if 項[2] in _保持サ変 or 項[2] in _保持動詞]
    取得語候補 = any(位置 in 実行字 and 項.辞書形 in {"調べる", "読む", "答える"}
                 for 位置, 項 in enumerate(列))
    if (not 主張 and not 資料変更 and not 数量候補 and not 保持候補 and not 前候補 and not 再実行 and not 取得句 and not 禁止句
            and not (取得語候補 and 操作)
            and not (材料依頼 and not 操作)
            and (not 操作 or _旧単目的で保持できる(列, 操作, 疑問, 制御))):
        return None
    if len(制御) > 4096:
        raise ValueError("会話文節の制御prompt上限は4096文字です")
    if len(操作) > 4:
        raise ValueError("会話文節の目的数上限は4です")
    if not 操作:
        # 数量/保持だけの未解釈入力を旧要求へ無言降格しない。
        操作 = [(0, len(列), "未解釈")]
