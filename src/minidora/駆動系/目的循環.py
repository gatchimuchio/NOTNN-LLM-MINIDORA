"""不足関係の構成・観測・再評価を、既存の通常循環の作用として供給する。

別の採否主体や実行ループを置かない。原要求を保持し、新しい観測は作業用の
証拠集合にだけ加える。観測の再実行ではなく、純粋な変換証明から学習する。
"""
from __future__ import annotations
from dataclasses import dataclass, replace
from .契約 import 関係要求, 関係証拠, 関係保証, 関係出力束
from .取得 import 関係を取得
from .変換 import 関係を変換
from .射影 import 関係結果を射影
from .学習 import 有効形成を取得, 実行経験を形成
from .目的不足 import 不足関係を構成
from ..HDS実行主体 import HDS関数作用, HDS作用結果, HDS作用状態
from ..統合駆動_v2.計画 import HDS作用仕様, HDS探索契約
from ..統合駆動_v2.政策 import HDS阻害, 停止理由
from ..統合駆動_v2.座標接続 import 座標成果名
from ..コア.値 import 署名

要求成果 = '関係駆動/要求'
作業要求成果 = '関係駆動/作業要求'
取得成果 = '関係駆動/取得'
変換成果 = '関係駆動/変換'
出力成果 = '関係駆動/出力'
学習成果 = '関係駆動/学習更新'
不足成果 = '関係駆動/不足計画'
観測済成果 = '関係駆動/観測済み'
観測履歴成果 = '関係駆動/観測履歴'
照合消費成果 = '関係駆動/照合消費'
取得済 = '関係駆動/取得済'
変換済 = '関係駆動/変換済'
回答済 = '関係駆動/回答成立'


@dataclass(frozen=True, slots=True)
class 関係観測依頼:
    原要求: 関係要求
    作業要求署名: str
    不足: tuple
    利用先: str


def 目的作用を構成(原要求, 学習状態, *, 停止要求=None, 観測器=None, 最大観測作用=32):
    if not isinstance(原要求, 関係要求): raise TypeError('関係要求が必要')
    if 観測器 is not None and not callable(観測器): raise TypeError('関係観測器は登録済みcallable')
    if type(最大観測作用) is not int or 最大観測作用 < 1: raise ValueError('観測作用上限が必要')
    追加契約 = 有効形成を取得(学習状態, 原要求.変換)
    原署名 = 原要求.署名

    def 読む(状態):
        値 = dict(状態.成果)
        原 = 値[要求成果]
        作業 = 値.get(作業要求成果, 原)
        if 原.署名 != 原署名 or replace(作業, 証拠=原.証拠) != 原:
            raise ValueError('原要求の目的・規則・境界が無断変更された')
        return 値, 作業

    def 取得(状態):
        値, 作業 = 読む(状態)
        成果 = 関係を取得(作業, 追加契約)
        return HDS作用結果(HDS作用状態.成立, 追加状態=frozenset({取得済}),
            成果=((取得成果, 成果),))

    def 変換(状態):
        値, 作業 = 読む(状態)
        累積 = int(dict(状態.主体状態).get(照合消費成果, 0))
        残り = 原要求.資源.最大照合 - 累積
        if 残り <= 0:
            return HDS作用結果(HDS作用状態.保留, 停止要求=True,
                阻害=HDS阻害(停止理由.予算枯渇, '関係駆動/変換', '全観測世代の関係照合予算を消費'))
        # 要求署名を変えないまま、共有予算の残量を停止コールバックで制御する。
        確認回数 = 0
        def 消費境界():
            nonlocal 確認回数
            if 停止要求 is not None and 停止要求(): return True
            確認回数 += 1
            return 確認回数 > 残り
        成果 = 関係を変換(作業, 値[取得成果], 停止要求=消費境界)
        return HDS作用結果(HDS作用状態.成立, 追加状態=frozenset({変換済}),
            成果=((変換成果, 成果),), 主体状態差分=((照合消費成果, 累積 + 成果.照合数),))

    def 射影(状態):
        値, 作業 = 読む(状態)
        変換結果 = 値[変換成果]
        出力 = 関係結果を射影(作業, 変換結果, 追加契約)
        学習 = 実行経験を形成(学習状態, 作業, 変換結果, 出力)
        成果 = [(出力成果, 出力), (学習成果, 学習)]
        if 出力.状態 == '成立':
            return HDS作用結果(HDS作用状態.成立, 追加状態=frozenset({回答済}), 成果=tuple(成果),
                理由=('目的に必要な関係の導出証明を実値で確認',))
        if 出力.状態 == '未観測':
            不足 = 不足関係を構成(作業, 追加契約, 利用先=('状態:' + 回答済,), 停止要求=停止要求)
            成果.append((不足成果, 不足))
            場 = 状態.操作座標
            if 場 is not None and 不足.不足:
                場 = 場.展開('目的/到達状態/変換', 理由='到達関係の不足を具体化',
                    利用先=('状態:' + 回答済,), 内容群=(
                        ('取得', tuple(x.ID for x in 不足.不足)),
                        ('変換', tuple(x.経路 for x in 不足.不足)),
                        ('射影', ('状態:' + 回答済,))))

            if 観測器 is not None and 不足.完了 and 不足.不足:
                return HDS作用結果(HDS作用状態.成立, 成果=tuple(成果), 座標更新=場,
                    理由=('不足する中間関係と次の利用先を構成し観測作用へ渡す',))
        理由 = {'競合':停止理由.証拠競合, '予算枯渇':停止理由.予算枯渇,
                '停止':停止理由.明示停止}.get(出力.状態, 停止理由.観測不足)
        return HDS作用結果(HDS作用状態.保留, 成果=tuple(成果), 停止要求=True,
            阻害=HDS阻害(理由, '関係駆動/射影', ';'.join(出力.未充足)), 理由=出力.未充足)

    共通 = dict(純粋=True, 版='目的関係接続v2')
    作用 = [
        HDS関数作用('関係駆動/取得', 取得,
            計画仕様=HDS作用仕様('関係駆動/取得', 読取成果=(要求成果, 作業要求成果),
                生成成果=(取得成果,), 追加状態=frozenset({取得済}), **共通)),
        HDS関数作用('関係駆動/変換', 変換,
            計画仕様=HDS作用仕様('関係駆動/変換', 読取成果=(作業要求成果, 取得成果),
                観測入力=('主体:' + 照合消費成果,), 生成成果=(変換成果,),
                追加状態=frozenset({変換済}), **共通)),
        HDS関数作用('関係駆動/射影', 射影,
            計画仕様=HDS作用仕様('関係駆動/射影', 読取成果=(作業要求成果, 変換成果),
                生成成果=(出力成果, 学習成果, 不足成果), 追加状態=frozenset({回答済}), **共通)),
    ]
    if 観測器 is None: return tuple(作用)

    def 未観測(状態):
        値, 作業 = 読む(状態)
        計画 = 値.get(不足成果)
        if 計画 is None or 計画.要求署名 != 作業.署名: return ()
        消費 = frozenset(値.get(観測済成果, ()))
        # 要求内容・作用先・観測済み証拠が変わらなければ同じ空振りを反復しない。
        return tuple(x for x in 計画.不足 if 署名((x.対象, x.利用先)) not in 消費)

    def 観測(状態):
        値, 作業 = 読む(状態)
        不足 = 未観測(状態)
        if not 不足: raise ValueError('観測の必要関係がない')
        依頼 = 関係観測依頼(原要求, 作業.署名, 不足, '状態:' + 回答済)
        新証拠 = 観測器(依頼)
        if not isinstance(新証拠, tuple) or any(not isinstance(x, 関係証拠) or x.保証 != 関係保証.観測 for x in 新証拠):
            raise TypeError('関係観測は由来付きの観測証拠tupleを返す必要がある')
        証拠辞書 = {x.ID: x for x in 作業.証拠}
        for 項 in 新証拠:
            if 項.ID in 証拠辞書 and 証拠辞書[項.ID] != 項:
                raise ValueError('同一証拠IDの無言改訂。新しい版のIDが必要')
            証拠辞書[項.ID] = 項
        新要求 = replace(作業, 証拠=tuple(証拠辞書[k] for k in sorted(証拠辞書)))
        消費 = tuple(sorted(set(値.get(観測済成果, ())) | {署名((x.対象, x.利用先)) for x in 不足}))
        履歴 = (*値.get(観測履歴成果, ()), (依頼, 新証拠))
        return HDS作用結果(HDS作用状態.成立,
            成果=((作業要求成果, 新要求), (観測済成果, 消費), (観測履歴成果, 履歴)),
            理由=('目的由来の不足関係を観測し、後続変換の入力を更新',))

    仕様 = HDS作用仕様('関係駆動/不足観測', 読取成果=(要求成果, 作業要求成果),
        観測入力=('成果:' + 不足成果,), 生成成果=(作業要求成果, 観測済成果, 観測履歴成果),
        観測専用=True, 版='目的関係観測v1', 探索=HDS探索契約(
            '関係駆動/観測枠', '目的に必要な中間関係の不足', ('成果:' + 作業要求成果,),
            ('状態:' + 回答済,), 最大試行=最大観測作用, 最大資源=最大観測作用, 再観測=True))
    作用.append(HDS関数作用('関係駆動/不足観測', 観測, 計画仕様=仕様,
        機会判定=lambda 状態: bool(未観測(状態)),
        入力署名=lambda 状態: 署名(tuple(x.署名 for x in 未観測(状態)))))
    return tuple(作用)