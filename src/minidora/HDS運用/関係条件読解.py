"""v6資料読解。例外付き規則の採用条件と、実際の導出を分けて保存する。"""
from __future__ import annotations
from dataclasses import asdict
from ..命題句 import 構成句を分ける
from ..命題構造 import 命題記載
from ..命題推論 import 命題推論器, 推論上限
from ..導出説明 import 導出説明を構成
from ..製品版.型 import 能力結果
from .値 import 結果を保存
from .関係構文化 import 関係文を構成

_限定語 = ("ただし", "除く", "除き", "限り", "例外", "のみ")


def 関係条件資料を読む(名前, 資料, 問い):
    if not isinstance(資料, 能力結果) or not 資料.成立 or not 0 < len(資料.本文) <= 16000:
        raise ValueError("関係読解の資料型・成立・文字上限")
    区間 = list(構成句を分ける(資料.本文))
    if len(区間) > 64:
        raise ValueError("関係資料の記載数上限")
    記載, 読解, 残差, 例外群 = [], [], [], {}
    先行, 限定 = None, False
    for 番号, (開始, 終了) in enumerate(区間):
        原文 = 資料.本文[開始:終了]
        if 原文.strip().startswith("#"):
            先行 = None
            限定 |= any(語 in 原文 for 語 in _限定語)
            残差.append({"範囲": [開始, 終了], "原文": 原文, "理由": "見出し（参照範囲を再開）"})
            continue
        try:
            式, 先行, 変換, 例外 = 関係文を構成(原文, 先行主体=先行)
            識別子 = "記載" + str(番号)
            記載.append(命題記載(識別子, 式, 名前, 原文, (開始, 終了)))
            読解.append({"識別子": 識別子, "範囲": [開始, 終了], "原文": 原文,
                         "式": 式.辞書(), "変換": 変換, "例外": None if 例外 is None else 例外.辞書()})
            if 例外 is not None:
                例外群[識別子] = 例外
        except ValueError as 問題:
            先行 = None
            限定 |= any(語 in 原文 for 語 in _限定語)
            残差.append({"範囲": [開始, 終了], "原文": 原文, "理由": str(問題)})
    if len(例外群) > 8:
        raise ValueError("明示例外規則は一資料八件まで")
    総操作 = 0
    器群, 判定庫 = {}, {}

    def 判定する(採用, 式):
        nonlocal 総操作
        対象 = tuple(行.識別子 for 行 in 採用)
        鍵 = (対象, 式.鍵())
        if 鍵 not in 判定庫:
            if not 採用:
                結果 = {"判定": "未確定", "問い": 式.辞書(), "支持": None, "反証": None, "導出": {}, "操作数": 0,
                        "解釈境界": "採用可能な記載がないため推論を行っていない。問いの否定ではない。"}
            else:
                if 対象 not in 器群:
                    器群[対象] = 命題推論器(tuple(採用), 上限=推論上限(操作数=12000, 事実数=256, 項数=48, 根拠数=1024))
                結果 = 器群[対象].判定(式)
                総操作 += 結果["操作数"]
                if 総操作 > 100000:
                    raise ValueError("関係資料の総推論操作予算超過。途中結果を採用しない")
            判定庫[鍵] = 結果
        return 判定庫[鍵]

    # 例外不成立の初期根拠は、例外付き規則自身や他の例外付き規則から得ない。
    基点 = tuple(行 for 行 in 記載 if 行.識別子 not in 例外群) if not 限定 else ()
    独立 = {識別子: 判定する(基点, 式) for 識別子, 式 in 例外群.items()}
    有効 = {識別子 for 識別子, 結果 in 独立.items() if 結果["判定"] == "反証"} if not 限定 else set()
    棄却 = set()
    撤回判定 = {}

    def 採用列():
        return tuple(行 for 行 in 記載 if 行.識別子 not in 例外群 or 行.識別子 in 有効) if not 限定 else ()

    # 規則採用で例外が成立・矛盾になれば撤回する。撤回済み規則を同じ循環で
    # 再採用しないため自己／相互阻害で振動しない。最大で例外件数+1回。
    for _ in range(len(有効) + 1):
        採用 = 採用列()
        取消 = {識別子 for 識別子 in sorted(有効) if 判定する(採用, 例外群[識別子])["判定"] != "反証"}
        if not 取消:
            break
        for 識別子 in sorted(取消):
            撤回判定[識別子] = {"採用記載": [行.識別子 for 行 in 採用],
                                   "判定": 判定する(採用, 例外群[識別子])}
        有効 -= 取消
        棄却 |= 取消
    else:
        raise ValueError("例外採用の収束検査不成立")
    採用 = 採用列()
    監査 = []
    for 識別子, 式 in 例外群.items():
        最終 = 判定する(採用, 式)
        理由 = ("作用域未確定の限定があるため資料全体を隔離" if 限定 else
               "採用後に例外が支持・矛盾となった。自己又は相互阻害の規則を再採用しない" if 識別子 in 棄却 else
               "例外でないことを他の通常記載から独立に支持し、採用後にも例外の支持がない" if 識別子 in 有効 else
               "例外でないことの独立した支持のみを得ていない。未記載を否定に変えない")
        監査.append({"規則記載": 識別子, "例外": 式.辞書(), "独立判定": 独立[識別子],
                     "最終判定": 最終, "撤回判定": 撤回判定.get(識別子), "採用": 識別子 in 有効, "理由": 理由})
    判定 = 判定する(採用, 問い)
    説明 = 導出説明を構成(判定, [asdict(行) for 行 in 採用])
    不足 = []
    if 判定["判定"] != "支持" and not 限定:
        for 行 in 記載:
            if 行.式.種別 != "含意" or 行.式.子[1].鍵() != 問い.鍵():
                continue
            前件 = 行.式.子[0]
            前判定 = 判定する(採用, 前件)
            if 前判定["判定"] != "支持":
                不足.append({"規則記載": 行.識別子, "前件": 前件.辞書(), "判定": 前判定["判定"],
                             "位置づけ": "この導出経路を使う場合の確認候補。事実・必要条件とは未認定"})
    return {"資料": 結果を保存(資料), "読解": 読解, "残差": 残差,
            "限定隔離": 限定, "判定": 判定, "説明": 説明, "不足候補": 不足,
            "解釈状態": "限定作用域の確認待ち" if 限定 else "部分解釈" if 残差 else "対応文法内の解釈成立",
            "例外監査": 監査, "採用記載": [行.識別子 for 行 in 採用], "総推論操作数": 総操作}
