"""依頼・記載被覆から文章内容を構成し、既存文章作成器へ渡す。自由創作とは区別する。"""
from __future__ import annotations
from copy import deepcopy
from dataclasses import asdict
from ..能力合成 import _結果辞書, _参照結合
from ..文章作成 import 文章仕様, 文章単位, 文章断片, 文章を作る, 文章仕様を復元
from ..能力結果復元 import 能力結果を復元
from ..製品版.型 import 能力結果
from .値 import 正準, 指紋, 結果を保存, 結果を復元
from .意味資料 import 意味資料を検査

資料文章版 = "HDS資料文章-v1"


def 内容仕様を構成(構造, *, 形式=None):
    if not 意味資料を検査(構造):
        raise ValueError("文章の入力意味構造が不整合")
    要求, 記録 = 構造["要求"], 構造["資料群"]
    形式 = 要求["形式"] if 形式 is None else 形式
    if 形式 not in ("文章", "箇条書き", "引用"):
        raise ValueError("資料文章の表現形式が未対応")
    名前群 = 要求["対象"] if 要求["範囲"] == "指定資料" else sorted(記録)
    素材, 単位群, 順序 = {}, [], []
    def 表記(本文, 種別="段落"):
        番号 = str(len(単位群))
        素材名, 単位名 = "表記" + 番号, "単位" + 番号
        素材[素材名] = 能力結果(True, 本文)
        単位群.append(文章単位(単位名, 種別, (文章断片(素材名, 0, len(本文)),), 必須=True, 保護=True))
        順序.append(単位名)
    操作名 = {"要約": "抽出要約", "説明": "資料に基づく説明", "対照": "観点別の記載対照", "確認提案": "追加確認の提案"}
    表記("・".join(操作名[項] for 項 in 要求["操作"]), "見出し")
    表記("資料の記載を根拠として構成しています。記載の真偽、同名対象の同一性、比較条件の同等性は未検証です。", "留保")
    if 要求["主題"]:
        表記("対象主題: " + " / ".join(要求["主題"]))
    if 構造["取得記録"] is not None:
        表記("公開取得資料の保存本文を使用しています。再表現は再取得ではなく、情報の最新性を保証しません。", "留保")
    不足 = [行 for 行 in 構造["被覆"] if not 行["記載一致"]]
    if "対照" in 要求["操作"]:
        表記("観点ごとの対応", "見出し")
        for 主題 in 要求["主題"]:
            対応 = [行 for 行 in 構造["被覆"] if 行["主題"] == 主題]
            表記(主題 + ": " + " / ".join(行["資料"] + ("＝記載一致" if 行["記載一致"] else "＝未特定") for 行 in 対応))
        表記("記載一致は意味や条件の同値ではありません。数値の優劣・矛盾・因果は、この対照から自動確定しません。", "留保")
    表記("原文と同伴文脈", "見出し")
    for 番号, 名前 in enumerate(名前群):
        行 = 記録[名前]
        if not 行["選択"]:
            continue
        素材名 = "原資料" + str(番号)
        資料 = 結果を復元(行["資料"])
        素材[素材名] = 資料
        for 節番 in 行["選択"]:
            節 = 行["節"][節番]
            道 = " > ".join(階["見出し"] for 階 in 節["階層"])
            表記("資料「" + 名前 + "」" + (" / " + 道 if 道 else "") +
                 " [" + str(節["開始"]) + ":" + str(節["終了"]) + "]" +
                 ("（条件・前文の同伴）" if 節番 in 行["同伴節"] else ""))
            単位名 = "単位" + str(len(単位群))
            種別 = {"文章": "段落", "箇条書き": "箇条書き", "引用": "引用"}[形式]
            単位群.append(文章単位(単位名, 種別, (文章断片(素材名, 節["開始"], 節["終了"]),), 必須=True, 保護=True))
            順序.append(単位名)
    if 不足:
        表記("記載を特定できなかった範囲", "見出し")
        for 行 in 不足:
            表記("資料「" + 行["資料"] + "」の「" + 行["主題"] + "」。未特定は不存在の証明ではありません。", "留保")
    if "確認提案" in 要求["操作"]:
        表記("次に確認する内容（提案）", "見出し")
        for 行 in 不足:
            表記("資料「" + 行["資料"] + "」について、「" + 行["主題"] + "」の用語対応と根拠資料を確認する。", "番号付き")
        表記("採用前に、各記載の対象・時点・適用条件と例外が今回の目的に一致するか確認する。", "番号付き")
        if "対照" in 要求["操作"]:
            表記("条件の異なる値を直接比較せず、共通条件を明示して追加の資料又は計算を求める。", "番号付き")
    未選択数 = sum(len(行["未選択"]) for 行 in 記録.values())
    if 未選択数:
        表記("非選択の" + str(未選択数) + "節は原文とともに結果内へ保持しています。選択外の含意まで解釈したとは扱いません。", "留保")
    if len(単位群) > 128:
        raise ValueError("文章単位数上限。条件を削らず資料範囲を絞ってください")
    return 正準({"素材": {名前: _結果辞書(値) for 名前, 値 in 素材.items()},
                 "仕様": asdict(文章仕様(tuple(単位群), tuple(順序), 要求["最大文字数"]))})


def _文章(構造, *, 形式=None):
    仕様 = 内容仕様を構成(構造, 形式=形式)
    文章 = 文章を作る({名: 能力結果を復元(値) for 名, 値 in 仕様["素材"].items()}, 文章仕様を復元(仕様["仕様"]))
    if not 文章.成立:
        raise ValueError("文章生成が不成立:" + 文章.保留理由 + ":" + str(文章.データ.get("診断", "")))
    return 文章


def 資料文章を照合(構造, 文章, *, 形式=None):
    形式 = 構造["要求"]["形式"] if 形式 is None else 形式
    再構成 = _文章(構造, 形式=形式)
    if 指紋(_結果辞書(文章)) != 指紋(_結果辞書(再構成)):
        raise ValueError("内容仕様と生成文章の原文対応が不一致")
    参照 = _参照結合(参照 for 行 in 構造["資料群"].values() for 参照 in 結果を復元(行["資料"]).参照)
    記録 = {"版": 資料文章版, "種別": "資料文章回答", "構造": 正準(構造), "表示形式": 形式,
            "文章": 結果を保存(結果を復元(結果を保存(文章))), "照合": "依頼・原文区間・内容仕様・文章再生成一致"}
    return 能力結果(True, 文章.本文, 参照=参照, データ=記録)


def 資料文章を検査(成果):
    try:
        if (not isinstance(成果, 能力結果) or not 成果.成立 or type(成果.データ) is not dict
                or 成果.データ.get("版") != 資料文章版 or 成果.データ.get("種別") != "資料文章回答"):
            return False
        再 = 資料文章を照合(成果.データ["構造"], 結果を復元(成果.データ["文章"]), 形式=成果.データ["表示形式"])
        return 指紋(結果を保存(成果)) == 指紋(結果を保存(再))
    except (ValueError, TypeError, KeyError, AttributeError, RecursionError):
        return False


def 資料文章を再表現(成果, 形式):
    if not 資料文章を検査(成果) or 形式 not in ("文章", "箇条書き", "引用"):
        raise ValueError("再表現の起点・形式が不正")
    構造 = deepcopy(成果.データ["構造"])
    return 資料文章を照合(構造, _文章(構造, 形式=形式), 形式=形式)
