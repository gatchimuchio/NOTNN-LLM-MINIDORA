数量生成版 = "HDS数量生成-v1"


def 数量コード仕様(構造):
    構造を検査(構造)
    手順, 定数 = [], {}
    def 参照(名): return {"種別":"参照", "名前":名}
    def 演算(種, 左, 右): return {"種別":"算術", "演算":種, "左":左, "右":右}
    def 代入(名, 式): 手順.append({"種別":"代入", "名前":名, "式":式})
    for 節 in 構造["節点"]:
        鍵 = 節["識別子"]
        if 節["種別"] == "数値":
            数 = Fraction(節["値"])
            for 部, 値 in (("分子",数.numerator), ("分母",数.denominator)):
                定数[鍵+部] = 値
                代入(鍵+部, {"種別":"定数参照", "キー":鍵+部})
        else:
            左子, 左母 = 参照(節["左"]+"分子"), 参照(節["左"]+"分母")
            右子, 右母 = 参照(節["右"]+"分子"), 参照(節["右"]+"分母")
            if 節["演算"] in ("加算", "減算"):
                子 = 演算(節["演算"], 演算("乗算",左子,右母), 演算("乗算",右子,左母))
                母 = 演算("乗算",左母,右母)
            elif 節["演算"] == "乗算":
                子, 母 = 演算("乗算",左子,右子), 演算("乗算",左母,右母)
            else:
                子, 母 = 演算("乗算",左子,右母), 演算("乗算",左母,右子)
            代入(鍵+"分子", 子); 代入(鍵+"分母", 母)
    手順.append({"種別":"返却", "式":{"種別":"リスト", "要素":[
        {"種別":"リスト", "要素":[参照(行["節点"]+"分子"), 参照(行["節点"]+"分母")]}
        for 行 in 構造["出力"]]}})
    return {"仕様":{"名前":"数量を検算", "引数":[], "手順":手順}, "定数":定数}


def 数量コード実行(構造, ソース):
    仕様 = 数量コード仕様(構造)
    期待 = 関数を生成(仕様["仕様"], 仕様["定数"])
    if not 期待.成立:
        raise ValueError("数量コード生成の既存境界を超えた:" + 期待.保留理由)
    if ソース != 期待.本文:
        raise ValueError("数量コードと原構造が不一致")
    評価 = コードを評価(ソース, {"定数":仕様["定数"]}, 最大手数=50000)
    if not 評価.成立:
        raise ValueError("数量コードの評価不成立:" + 評価.保留理由)
    return {"版":数量生成版, "構造印":指紋(構造), "ソース":ソース,
            "定数":仕様["定数"], "評価":評価.データ}


def 数量を照合(構造, 計算, 検算):
    if 数量を評価(構造) != 計算:
        raise ValueError("数量計算と原構造の再評価が不一致")
    if (type(検算) is not dict or 検算.get("構造印") != 指紋(構造)
            or 検算 != 数量コード実行(構造, 検算["ソース"])):
        raise ValueError("数量検算の原構造・再実行不一致")
    数群 = 検算["評価"]["値"]
    if type(数群) is not list or len(数群) != len(計算["結果"]):
        raise ValueError("数量検算の出力数が不一致")
    for 数, 行 in zip(数群, 計算["結果"]):
        if (type(数) is not list or len(数) != 2 or any(type(x) is not int for x in 数)
                or 数[1] == 0 or Fraction(*数) != Fraction(行["値"])):
            raise ValueError("数量の有理数演算と生成コードが不一致")
    return {"版":数量生成版, "構造印":指紋(構造), "計算印":指紋(計算), "検算印":指紋(検算),
            "一致":True, "範囲":"同じ意味構造に対する有理数演算と限定Pythonの実行一致。原文解釈・現実の妥当性の独立証明ではない"}


def 単位表記(単位):
    分子, 分母 = [], []
    for 名, 冪 in sorted(単位.items()):
        (分子 if 冪 > 0 else 分母).append(名 + ("^"+str(abs(冪)) if abs(冪) != 1 else ""))
    上 = "*".join(分子)
    下 = "*".join(分母)
    if len(分母) > 1:
        下 = "(" + 下 + ")"
    return (上 or "1") + "/" + 下 if 分母 else 上


def 数表記(値):
    値 = Fraction(値)
    return str(値.numerator) if 値.denominator == 1 else str(値)


def 数量を説明(構造, 計算, 検算, 照合, *, 表示=None):
    表示 = deepcopy(構造["要求"]["表示"] if 表示 is None else 表示)
    要求 = deepcopy(構造["要求"])
    要求["表示"] = 表示
    from .数量構造 import 要求を検査
    要求を検査(要求)
    期待 = 数量を照合(構造, 計算, 検算)
    if 照合 != 期待:
        raise ValueError("数量説明の照合根拠不一致")
    単位 = 単位表記(計算["結果"][0]["単位"])
    題 = 構造["要求"]["数量"]
    節 = []
    if 表示["形式"] == "表":
        節.extend([f"| 資料 | {題} |", "|---|---:|"])
        節.extend(f'| {行["資料"]} | {数表記(行["値"])}{単位表記(行["単位"])} |' for 行 in 計算["結果"])
    else:
        節.extend(f'資料「{行["資料"]}」の{題}は{数表記(行["値"])}{単位表記(行["単位"])}です。' for 行 in 計算["結果"])
    for 名, 結果 in 計算["集計"].items():
        if 名 == "比較":
            for 行 in 結果:
                差 = Fraction(行["差"])
                節.append(f'「{行["右"]}」と「{行["左"]}」は同じ値です。' if not 差 else
                    f'「{行["右"]}」は「{行["左"]}」より{数表記(abs(差))}{単位}{"大きい" if 差>0 else "小さい"}です。')
        else:
            節.append(f'{題}の{名}は{数表記(結果)}{単位}です。')
    for 条件 in 構造["要求"]["条件変更"]:
        節.append(f'今回の条件：{条件["資料"]}の{条件["数量"]}を{条件["値"]}として計算。原資料は変更していません。')
    if 表示["詳細"]:
        値群 = {行["節点"]:行 for 行 in 計算["演算"]}
        節群 = {行["識別子"]:行 for 行 in 構造["節点"]}
        記号 = {"加算":"+", "減算":"−", "乗算":"×", "除算":"÷"}
        def 展開(鍵):
            行 = 節群[鍵]
            if 行["種別"] == "数値": return 数表記(行["値"])+単位表記(行["単位"])
            def 値表記(参照):
                項 = 値群[参照]
                return 数表記(項["値"])+単位表記(項["単位"])
            # DAGを文章の木へ指数的に展開しない。直前の実結果を代入して示す。
            return "("+値表記(行["左"])+" "+記号[行["演算"]]+" "+値表記(行["右"])+")"
        節.append("計算根拠：")
        for 行 in 計算["結果"]:
            節.append(f'{行["資料"]}：{展開(行["節点"])} = {数表記(行["値"])}{単位表記(行["単位"])}')
        節.append("原文対応：")
        for 行 in 構造["束縛"]:
            節.append(f'{行["対象"]}/{行["数量"]} ← {行["資料"]}[{行["範囲"][0]}:{行["範囲"][1]}]「{行["原文"]}」')
    if 表示["コード"]:
        節.extend(["検算コード（入力値は定数辞書で分離）：", "```python", 検算["ソース"].rstrip(),
                   "", "定数 = " + repr(検算["定数"]), "print(数量を検算(定数))", "```",
                   "返却値は対象順の[分子, 分母]です。単位の整合は数量構造側で検査しています。"])
    技術 = 表示["読者"] == "技術者"
    節.append("検算：有理数演算とPython AST評価の結果が一致。" if 技術 else "検算用コードの計算結果も一致しています。")
    節.append("資料内の定義と明示条件に基づく結果です。現実の妥当性・異なる資料の条件同一性は認定していません。")
    if 構造["未使用記載"]:
        節.append(f'問いに用いない定義は{len(構造["未使用記載"])}件あり、原資料と記録に保持しています：' + "、".join(行["資料"]+"/"+行["数量"] for 行 in 構造["未使用記載"]))
    本文 = "\n".join(節)
    if len(本文) > 40000:
        raise ValueError("数量説明の文字数上限。途中切断しない")
    記録 = 正準({"版":数量生成版, "種別":"数量言語回答", "構造":構造, "計算":計算,
                 "検算":検算, "照合":照合, "表示":表示, "本文":本文})
    return 本文, 記録


def 数量回答を検査(値):
    try:
        資料 = 値.データ
        if 資料.get("種別") != "数量言語回答" or not 値.成立:
            return False
        本文, 記録 = 数量を説明(資料["構造"], 資料["計算"], 資料["検算"], 資料["照合"], 表示=資料["表示"])
        return 本文 == 値.本文 and 記録 == 資料
    except (ValueError, KeyError, TypeError, RecursionError, ZeroDivisionError):
        return False
