def _文数(本文):
    """引用・括弧内の句点を外側の完結文数へ足さない。未完結は保留。"""
    if '"' in 本文:
        raise ValueError("会話束の文数量:ASCII引用の文帰属は未対応です")
    位置群 = list(最上位位置(本文.translate(str.maketrans({"（": "(", "）": ")"})), ("。", "！", "？")))
    開始, 区間 = 0, []
    for 位置, _ in 位置群:
        if 位置 == 開始 and 区間:
            区間[-1][1] = 位置 + 1
        elif 本文[開始:位置].strip():
            区間.append([開始, 位置 + 1])
        else:
            raise ValueError("会話束の文数量:句読点だけを文として数えられません")
        開始 = 位置 + 1
    if 本文[開始:].strip():
        raise ValueError("会話束の文数量:完結文として数えられない記載が残ります")
    return len(区間), 区間


def _実数量(子, 単位):
    if 単位 == "文字":
        return {"数": len(子.本文), "根拠": "実本文のUnicode codepoint数", "区間": [[0, len(子.本文)]]}
    if 単位 == "文":
        数, 区間 = _文数(子.本文)
        return {"数": 数, "根拠": "実本文の引用外の完結文", "区間": 区間}
    if 単位 == "項目":
        文章 = 結果を復元(子.データ["文章"])
        区間 = []
        for 項 in 文章.データ["初期単位位置"]:
            if 項["種別"] not in ("箇条書き", "番号付き"):
                continue
            左, 右 = 項["開始"], 項["終了"]
            表記 = 子.本文[左:右]
            if not re.match(r"(?:- |[1-9][0-9]*\. )", 表記):
                raise ValueError("会話束の項目数量:実本文の項目表記が不一致です")
            区間.append([左, 右])
        return {"数": len(区間), "根拠": "既存writerの実箇条書き又は番号付き単位", "区間": 区間}
    raise ValueError("会話束の数量単位が未対応です:" + str(単位))


def _数量を照合(行, 子):
    記録 = []
    for 条件 in 行["数量"]:
        if (type(条件) is not dict or set(条件) != {"単位", "関係", "数"}
                or 条件["関係"] not in ("一致", "以内") or type(条件["数"]) is not int
                or not 1 <= 条件["数"] <= 24000):
            raise ValueError("会話束の数量条件が不正です")
        実測 = _実数量(子, 条件["単位"])
        成立 = 実測["数"] == 条件["数"] if 条件["関係"] == "一致" else 1 <= 実測["数"] <= 条件["数"]
        if not 成立:
            raise ValueError("会話束の目的数量が未成立:" + 行["目的ID"] + ":" + 条件["単位"] +
                             ":要求" + str(条件["数"]) + 条件["関係"] + ":実測" + str(実測["数"]))
        記録.append({"条件": 条件, "実測": 実測})
    return 記録


def _否定を含む(式):
    return bool(式 and (式.get("種別") == "否定" or any(_否定を含む(子) for 子 in 式.get("子", ()))))


def _数詞候補(原行):
    対応 = 原行["対応"]
    候補 = []
    for 語 in 会話字句を観測(対応["原文"]):
        左, 右 = 対応["開始"] + 語.開始, 対応["開始"] + 語.終了
        if 語.品詞[:2] == ("名詞", "数詞") and not any(
                項["開始"] <= 左 < 右 <= 項["終了"] for 項 in 原行["脚注"]):
            候補.append({"原文": 語.表層, "開始": 左, "終了": 右, "品詞": list(語.品詞),
                         "辞書版": 語.辞書版, "処理器版": 語.処理器版})
    return 候補


def _保持閉包を読む(意味):
    """既存の採用・支持・原区間依存に限定を同伴させる。問いを再解釈しない。"""
    記載 = 意味["記載関係"]
    原行群 = {行["ID"]: 行 for 行 in 記載}
    留保群 = {行["記載ID"]: 行 for 行 in 意味["未確定限定"]}
    命題支持 = {名 for 項 in 意味["意味"]["命題"] for 名 in 項["根拠"]}
    使用 = set(意味["使用記載"])
    閉包 = 使用 | 命題支持 | set(留保群)
    if not 閉包 <= 原行群.keys() | 留保群.keys():
        raise ValueError("会話束の意味保持閉包に実在しない記載IDがあります")
    依存, 同伴記録 = [], []
    部分依存 = {}
    # 子の実原資料・意味・文章は呼出元で全再導出済み。この版付き演算の
    # 手段表現だけを同じ所有記載へ接続し、他の部分区間へは一般化しない。
    for 番号, 証拠 in enumerate(意味["演算"]):
        if type(証拠) is not dict or 証拠.get("版") != "原資料目的手段二端照合-v1":
            continue
        候補 = [行 for 行 in 記載 if 行["ID"] == 証拠["記載ID"] and 行["対応"] == 証拠["対応"]]
        if len(候補) != 1 or 証拠["種別"] != "原資料目的手段の明示二端関係":
            raise ValueError("会話束の目的手段の所有記載が一意に対応しません")
        原行 = 候補[0]
        全文, 目的 = 原行["対応"], 原行["関係"]["目的"]
        所有 = 原行["資料作用"]["原資料"]
        二端 = 証拠["双端照合"]
        表現 = 二端["原主述表現"]
        if (not 目的 or 原行["関係"]["理由"] or 目的.get("接続") == "連体用途"
                or 証拠["原目的関係"] != 目的 or 証拠["原資料"] != 所有
                or 所有["資料ID"] != 全文["資料"] or 原行["ID"] not in 所有["全記載ID"]
                or 二端["版"] != "原資料明示二端照合-v1" or 二端["種別"] != "原資料明示二端関係"
                or 二端["記載ID"] != 原行["ID"] or 二端["対応"] != 全文 or 二端["原資料"] != 所有
                or 二端["同作用"] != 原行["資料作用"]["作用"]
                or 二端["元要求印"] != 証拠["元要求印"] or 二端["関係要求"] != 証拠["関係要求"]
                or 表現["記載ID"] != 原行["ID"] or 表現["種別"] != "原主述終止表現" or 表現["態"] != "能動"):
            raise ValueError("会話束の目的手段の二端証拠が同じ原記載に束縛されません")
        手段 = 目的["手段"]
        if type(手段) is not str or not 手段 or 全文["原文"].count(手段) != 1:
            raise ValueError("会話束の目的手段の原区間が一意ではありません")
        起点 = 全文["原文"].find(手段)
        対応 = {"資料": 全文["資料"], "開始": 全文["開始"] + 起点,
                "終了": 全文["開始"] + 起点 + len(手段), "原文": 手段}
        範囲 = 証拠["手段範囲"]
        if (type(範囲) is not list or any(type(値) is not int for 値 in 範囲)
                or 範囲 != [対応["開始"], 対応["終了"]] or 表現["対応"] != 対応):
            raise ValueError("会話束の目的手段の部分対応が原文と一致しません")
        部分依存["採用演算." + str(番号) + ".双端照合.原主述表現.対応"] = {
            "記載ID": 原行["ID"], "対応": 対応}

    def 依存を読む(値, 由来):
        # 原資料区間と既存の根拠IDだけを読む。語・近接から新しい依存を作らない。
        if 由来 in 部分依存:
            局所 = 部分依存[由来]
            if type(値) is not dict or 値 != 局所["対応"]:
                raise ValueError("会話束の目的手段の局所依存が不一致です")
            閉包.add(局所["記載ID"])
            依存.append({"由来": 由来, **局所})
            return
        if type(値) is dict:
            if {"資料", "開始", "終了", "原文"} <= 値.keys():
                対応 = {鍵: 値[鍵] for 鍵 in ("資料", "開始", "終了", "原文")}
                候補 = [行 for 行 in 記載 if 行["対応"] == 対応]
                if len(候補) != 1:
                    raise ValueError("会話束の意味依存原区間が全記載へ一意に対応しません")
                閉包.add(候補[0]["ID"])
                依存.append({"由来": 由来, "記載ID": 候補[0]["ID"], "対応": 対応})
                return
            for 鍵, 子 in 値.items():
                if 鍵 in ("記載ID", "根拠ID") and type(子) is str:
                    if 子 not in 原行群:
                        raise ValueError("会話束の意味依存に実在しない根拠IDがあります")
                    閉包.add(子)
                    依存.append({"由来": 由来 + "." + 鍵, "記載ID": 子, "対応": 原行群[子]["対応"]})
                else:
                    依存を読む(子, 由来 + "." + 鍵)
        elif type(値) in (list, tuple):
            for 番号, 子 in enumerate(値):
                依存を読む(子, 由来 + "." + str(番号))

    依存を読む(意味["演算"], "採用演算")
    未確定 = {}
    読んだ依存 = set()
    while True:
        前 = set(閉包)
        for 名 in sorted((閉包 & 原行群.keys()) - 読んだ依存):
            依存を読む(原行群[名]["関係"], 名 + ".関係")
            読んだ依存.add(名)
        同伴 = _条件を結ぶ(記載, 閉包, 未確定=未確定)
        for 元, 条件群 in 同伴.items():
            for 条件 in 条件群:
                閉包.add(条件["ID"])
                辺 = {"元記載ID": 元, "条件記載ID": 条件["ID"], "対応": 条件["対応"]}
                if 辺 not in 同伴記録:
                    同伴記録.append(辺)
        if 前 == 閉包:
            break
    # 読めない同主題の限定は、既存の限定回答が原行と理由を保存した時だけ留保として残す。
    for 名, 項 in 未確定.items():
        if 名 not in 留保群 or 留保群[名]["対応"] != 項["対応"] or 留保群[名]["理由"] != 項["理由"]:
            raise ValueError("会話束の資料意味不足:適用未確定の限定が保存留保から欠落しています:" + 名 + ":" + 項["理由"])
        閉包.add(名)
    return {"起点": {"使用記載": sorted(使用), "命題支持": sorted(命題支持), "限定留保": sorted(留保群)},
            "記載ID": sorted(閉包), "意味依存": 依存, "条件同伴": 同伴記録,
            "未確定作用域": list(未確定.values()),
            "閉包外記載": sorted(原行群.keys() - 閉包),
            "範囲": "既存採用意味の支持と原区間依存及び同Kernelの限定同伴。閉包外の事実性・必要性を再判定しない"}


def _保持を照合(行, 子):
    意味 = 資料回答意味を読む(子.データ["意味成果"], 意味版=資料回答版)
    採用 = set(意味["使用記載"])
    命題 = 意味["意味"]["命題"]
    留保 = 意味["未確定限定"]
    閉包 = _保持閉包を読む(意味)
    閉包ID = set(閉包["記載ID"])
    保持 = _必須保持 | set(行["保持"])
    結果 = []
    for 原行 in 意味["記載関係"]:
        if 原行["ID"] not in 閉包ID:
            continue
        射影 = 原行["資料作用"]
        枠 = 射影["条件"]["帰結"] if 射影["条件"] else 射影["作用"]
        属性 = 原行["関係"]["属性"]
        主語 = (枠["役割"].get("行為者", {}).get("原文") if 枠 else None) or (
            属性["対象"] if 属性 else 原行["明示主語"])
        時点 = (枠["役割"].get("時点", {}).get("原文") if 枠 else None) or (
            属性.get("時点") if 属性 else None)
        型 = set()
        if 射影["条件候補"] or (原行["限定"] and not 射影["作用"]):
            型.add("条件")
        if 射影["条件"] and 射影["条件"]["例外談話"]:
            型.add("例外")
        if _否定を含む(原行["命題"]) or 枠 and 枠["肯否"] == "否定":
            型.add("否定")
        数値 = 数値記載文.fullmatch(原行["対応"]["原文"])
        数詞 = _数詞候補(原行)
        if 数値 or 数詞:
            型.add("数値")
        if 主語:
            型.add("主語")
        if 時点:
            型.add("時点")
        対象型 = 型 & 保持
        if not 対象型:
            continue
        支持 = [番号 for 番号, 項 in enumerate(命題) if 原行["ID"] in 項["根拠"]]
        保留支持 = [番号 for 番号, 項 in enumerate(留保) if 項["記載ID"] == 原行["ID"]]
        if 原行["ID"] not in 採用 or not 支持 and not 保留支持:
            raise ValueError("会話束の資料意味不足:採用意味の原資料保持が未成立:" + 行["目的ID"] + ":" +
                             "・".join(sorted(対象型)) + ":" + 原行["ID"])
        条件表記 = 属性.get("条件") if 属性 and 属性.get("条件") else 原行["対応"]["原文"]
        if "条件" in 対象型 and 条件表記 not in 子.本文:
            raise ValueError("会話束の条件原文が実本文から欠落しています:" + 原行["ID"])
        if "主語" in 対象型 and 主語 not in 子.本文:
            raise ValueError("会話束の要求主語保持を実本文で証明できません:" + 原行["ID"])
        if "時点" in 対象型 and 時点 not in 子.本文:
            raise ValueError("会話束の要求時点保持を実本文で証明できません:" + 原行["ID"])
        支持本文 = [命題[番号]["本文"] for 番号 in 支持] + [子.本文 if 保留支持 else ""]
        if "数値" in 対象型 and not 数値 and any(
                not any(語["原文"] in 文 for 文 in 支持本文) for 語 in 数詞):
            raise ValueError("会話束の未読解数詞保持を支持本文で証明できません:" + 原行["ID"])
        結果.append({"記載ID": 原行["ID"], "保持型": sorted(対象型), "原資料区間": 原行["対応"],
                     "役割表記": {"主語": 主語, "時点": 時点},
                     "数詞候補": 数詞, "数値読解": "既存数量器の再照合" if 数値 else "原数詞表記を支持本文へ保持",
                     "命題番号": 支持, "未確定限定番号": 保留支持,
                     "証明": "既存資料意味/文章再照合の支持と子本文全文保護。世界の事実性は認定しない"})
    return {"要求保持": 行["保持"], "必須保持": sorted(_必須保持), "保持閉包": 閉包, "原区間被覆": 結果}


def _文脈を正準化(前採用包, 文脈証明, 前命令包=None, 命令証明=()):
    for 名, 包 in (("前採用包", 前採用包), ("前命令包", 前命令包)):
        if 包 is not None and type(包) is not dict:
            raise ValueError("会話束の" + 名 + "は契約包又はNoneが必要です")
    if 前採用包 is not None and 前命令包 is not None:
        raise ValueError("会話束の当前源の前採用包と前命令包を混合できません")
    for 名, 群 in (("文脈証明", 文脈証明), ("命令証明", 命令証明)):
        if type(群) not in (list, tuple) or any(type(項) is not dict for 項 in 群):
            raise ValueError("会話束の" + 名 + "は証明辞書列が必要です")
    if len(文脈証明) + len(命令証明) > 4:
        raise ValueError("会話束の文脈・命令証明の合計が4を超えています")
    return 正準({"前採用包": 前採用包, "文脈証明": list(文脈証明),
                "前命令包": 前命令包, "命令証明": list(命令証明)})


def _保存文脈を選ぶ(文脈):
    # 通常継続にも命令祖先の独立証明が必要な場合がある。poolの混在は用途混合ではない。
    if 文脈["前命令包"] is not None or 文脈["命令証明"]:
        return 会話束文脈回答版, 文脈
    return 会話束回答版, {鍵: 文脈[鍵] for 鍵 in ("前採用包", "文脈証明")}


def _子を検査(子成果列, 契約包, 所有セッション, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    文脈 = _文脈を正準化(前採用包, 文脈証明, 前命令包, 命令証明)
    try:
        目的群 = 会話目的を読む(契約包, 所有セッション=所有セッション, **文脈)
    except TypeError as 例外:
        raise ValueError("会話束のreader前文脈検査が未成立:" + str(例外)) from 例外
    if type(子成果列) not in (list, tuple) or len(子成果列) != len(目的群):
        raise ValueError("会話束の目的と子成果の件数が不一致です")
    照合 = []
    for 行, 対応 in zip(目的群, 子成果列):
        if type(対応) is not dict or set(対応) != {"目的ID", "成果"} or 対応["目的ID"] != 行["目的ID"]:
            raise ValueError("会話束の目的ID・順序・子成果対応が不一致です")
        子 = 対応["成果"]
        if not isinstance(子, 能力結果) or not 子.成立:
            raise ValueError("会話束の未成立子成果を採用できません:" + 行["目的ID"])
        結果を保存(子)
        資料 = 子.データ
        if 資料.get("版") != 資料文章版 or 資料.get("種別") != "資料文章回答":
            raise ValueError("会話束の子成果版が失効しています。原保存を保って再計算してください")
        資料回答意味を読む(資料.get("意味成果"), 意味版=資料回答版)
        if 指紋(資料["構造"]["要求"]) != 指紋(行["要求"]):
            raise ValueError("会話束の目的要求と子成果要求が完全一致しません:" + 行["目的ID"])
        if 資料["表示形式"] != 行["要求"]["形式"] or not 資料文章を検査(子):
            raise ValueError("会話束の子成果内容・原資料・文章の照合が不成立です:" + 行["目的ID"])
        if not 1 <= len(子.本文) <= 行["要求"]["最大文字数"]:
            raise ValueError("会話束の子成果が目的文字予算を超えています:" + 行["目的ID"])
        照合.append({**行, "子成果": 結果を保存(子),
                    "照合": {"要求完全一致": True, "実原資料と意味と文章": True,
                            "数量": _数量を照合(行, 子), "保持": _保持を照合(行, 子)}})
    return 照合


def _内容仕様(群):
    素材, 単位 = {}, []
    for 番号, 行 in enumerate(群):
        名 = "目的本文" + str(番号)
        子 = 結果を復元(行["子成果"])
        # 束のwriter原本には全文と参照を渡し、膨大な子IRの複製は最終保存へ分離する。
        素材[名] = _結果辞書(能力結果(True, 子.本文, 根拠=子.根拠, 参照=子.参照))
        単位.append(文章単位(名, "段落", (文章断片(名, 0, len(子.本文)),), 必須=True, 保護=True))
    総文字数 = sum(len(素材[名]["本文"]) for 名 in 素材) + 2 * (len(単位) - 1)
    if 総文字数 > 24000:
        raise ValueError("会話束の総文字予算24000が不足しています。保持内容は削除しません")
    return 正準({"素材": 素材, "仕様": asdict(文章仕様(tuple(単位), tuple(項.識別子 for 項 in 単位), 24000))})


def 会話束内容仕様を構成(子成果列, 契約包, *, 所有セッション, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    return _内容仕様(_子を検査(子成果列, 契約包, 所有セッション, 前採用包, 文脈証明, 前命令包, 命令証明))


def _文章を作る(内容仕様):
    文章 = 文章を作る({名: 能力結果を復元(値) for 名, 値 in 内容仕様["素材"].items()},
                   文章仕様を復元(内容仕様["仕様"]))
    if not 文章.成立:
        raise ValueError("会話束の文章作成が不成立:" + 文章.保留理由 + ":" + str(文章.データ.get("診断", "")))
    return 文章


def _文章を保存(文章):
    # 既存資料文章と同じ交換境界。JSON鍵順とtuple位置の列挙順を保存後に固定する。
    return 結果を保存(結果を復元(結果を保存(文章)))


def 会話束回答を照合(子成果列, 契約包, 文章, *, 所有セッション, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    文脈 = _文脈を正準化(前採用包, 文脈証明, 前命令包, 命令証明)
    版, 保存文脈 = _保存文脈を選ぶ(文脈)
    群 = _子を検査(子成果列, 契約包, 所有セッション, **文脈)
    仕様 = _内容仕様(群)
    再 = _文章を作る(仕様)
    if 指紋(_文章を保存(文章)) != 指紋(_文章を保存(再)):
        raise ValueError("会話束の要求・全子本文・保護範囲と実文章が不一致です")
    記録 = 正準({"版": 版, "種別": "会話目的束回答", "契約包": 契約包,
                  "所有セッション": 所有セッション, **保存文脈, "目的成果": 群, "内容仕様": 仕様,
                  "文章": _文章を保存(文章),
                  "照合": {"全子全文保持": True, "目的数": len(群), "実文字数": len(文章.本文),
                          "総文字予算": 24000, "束文字対応": 文章.データ["対応"],
                          "範囲": "要求・原資料・意味・数量・保持・既存writer再生成一致。COMMIT/資料依存/世界事実は呼出元責任"}})
    return 能力結果(True, 文章.本文, 根拠=tuple(行["目的ID"] for 行 in 群),
                   参照=_参照結合(参照 for 対応 in 子成果列 for 参照 in 対応["成果"].参照), データ=記録)


def 会話束回答を検査(成果, *, 所有セッション, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    try:
        if (not isinstance(成果, 能力結果) or not 成果.成立 or type(成果.データ) is not dict
                or 成果.データ.get("種別") != "会話目的束回答"
                or 成果.データ.get("所有セッション") != 所有セッション):
            return False
        資料 = 成果.データ
        文脈 = _文脈を正準化(前採用包, 文脈証明, 前命令包, 命令証明)
        版, 保存文脈 = _保存文脈を選ぶ(文脈)
        # 保存自身から文脈を再発行しない。旧v3への欄追加や新版への無言変換も先に拒否する。
        if (資料.get("版") != 版 or set(資料) != _回答基本欄 | set(保存文脈)
                or 指紋({鍵: 資料[鍵] for 鍵 in 保存文脈}) != 指紋(保存文脈)):
            return False
        列 = [{"目的ID": 行["目的ID"], "成果": 結果を復元(行["子成果"])} for 行 in 資料["目的成果"]]
        再 = 会話束回答を照合(列, 資料["契約包"], 結果を復元(資料["文章"]), 所有セッション=所有セッション, **文脈)
        return 指紋(結果を保存(成果)) == 指紋(結果を保存(再))
    except (ValueError, TypeError, KeyError, AttributeError, RecursionError):
        return False
