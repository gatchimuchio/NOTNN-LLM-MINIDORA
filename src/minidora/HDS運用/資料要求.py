"""既存の資料読解・命題・仮説・介入能力を共通HDS運用へ接続する純粋な要求構成。"""
from __future__ import annotations
from copy import deepcopy
from dataclasses import asdict

from ..監査改善会話解釈 import 改善発話を解釈
from ..依頼表現 import 検討依頼を読む
from ..監査改善計画 import 改善目的を計画
from ..製品版.型 import 能力結果
from .契約 import 成果を保存, 成果を復元, 名前を検査


def 資料要求を構成(構成器, 入力, 基礎):
    原文 = 入力['原文']
    前回 = 入力.get('前回') or {}
    前要求 = 前回.get('資料要求')
    登録 = 原文.startswith(('本文資料', '命題資料', '仮説資料', '介入資料'))
    表現 = 検討依頼を読む(原文)
    継続 = bool(前要求) and (原文 in ('短く説明して', '詳しく説明して', 'もう一度', '続けて')
        or 原文.startswith(('観測を', '候補を', '介入を', '問いを', '述語別名を', '照応距離を')))
    # 元の文書・比較・数学入口を、別の部分一致で横取りしない。
    if not 登録 and 表現 is None and not 継続:
        return None
    発話 = 表現 if 表現 is not None else 改善発話を解釈(原文)
    資料 = {k: 成果を復元(v) for k, v in 入力['資料'].items()}
    if 発話['行為'] in ('登録', '更新'):
        名 = 名前を検査(発話['資料'])
        if (発話['行為'] == '登録') == (名 in 資料):
            raise ValueError('資料の登録・更新と既存資料の有無が不一致')
        素材 = 能力結果(True, 発話['本文'], 根拠=('利用者が提供した資料。世界の事実性は未認定',),
            データ={'HDS資料種別': 発話['種類'], '構造': 発話['データ'], '原文対応': 発話['原文対応']})
        return {**基礎, '種別': 発話['行為'], '資料名': 名, '本文': 発話['本文'],
                '資料成果': 成果を保存(素材), '意味': None}
    再表現 = 発話['行為'] == '再表現'
    if 発話['行為'] == '検討':
        要求 = deepcopy(発話)
    elif 前要求 and 発話['行為'] in ('訂正', '再表現', '再実行', '継続'):
        要求 = deepcopy(前要求)
        if 発話['行為'] == '訂正':
            要求['変更'] = {**要求.get('変更', {}), **deepcopy(発話['変更'])}
    else:
        raise ValueError('この資料要求の継続方法は未対応')
    名, 種類 = 要求['資料'], 要求['種類']
    if 名 not in 資料:
        raise ValueError('参照する提供資料がない:' + 名)
    素材 = 資料[名]
    元種類 = 素材.データ.get('HDS資料種別', '本文')
    if 種類 in ('命題', '読解'):
        if 元種類 not in ('本文', '命題'):
            raise ValueError('構造化された仮説・介入資料を通常本文と同一視しない')
        内容 = {'資料': [{'名前': 名, '本文': 素材.本文}]}
    else:
        if 元種類 != 種類:
            raise ValueError('目的と資料種別の不一致')
        内容 = deepcopy(素材.データ['構造'])
    許可欄 = {'命題': {'問い', '問い候補', '資料候補', '照応距離', '述語別名'},
             '仮説': {'観測', '仮説候補'}, '介入': {'介入'}, '読解': {'問い', '述語別名'}}[種類]
    if not set(要求.get('変更', {})) <= 許可欄:
        raise ValueError('検討目的に適用できない訂正')
    内容.update(deepcopy(要求.get('変更', {})))
    原要求 = 能力結果(True, '', 参照=素材.参照, 根拠=素材.根拠, データ=内容)
    詳細 = bool(発話.get('詳細', True))
    元報告 = None
    if 再表現:
        from .契約 import 内容署名
        if any(k not in 入力['資料'] or 内容署名(入力['資料'][k]) != h for k, h in 前回['依存資料'].items()):
            raise ValueError('資料更新後の旧報告は再表現しない。依頼の再実行が必要')
        元報告 = 成果を復元(前回['内容成果'][0][1])
    計画 = 改善目的を計画(種類, 原要求, 構成器.目録.一覧(), 詳細=詳細, 元報告=元報告)
    内容出力 = tuple(x.識別子 for x in 計画.計画.工程
                    if x.能力候補[0] in ('拡張命題検討', '有限仮説検討', '有限介入比較', '資料読解'))
    案 = 構成器._計画案(基礎, 計画.計画, 計画.資料, None, (名,), 入力, 内容出力,
                       前回=前回 if 再表現 else None)
    案['資料要求'] = 要求
    return 案
