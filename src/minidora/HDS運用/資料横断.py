"""明示された識別体系・対象・時点・適用条件だけを資料間の接続前提にする。

宣言の一致は世界の同一性の保証ではない。対象名の字面、検索一致、取得成功で
接続しない。引用内・量化の作用域は本増分では書き換えない。
"""
from __future__ import annotations
from dataclasses import asdict, replace
import re
import unicodedata
from ..命題句 import 構成句を分ける
from ..命題構造 import 命題項, 命題記載, 命題を復元
from .値 import 正準, 指紋
from .関係言語 import 関係文を読む, 関係式を表現

横断版 = "HDS資料横断-v1"
_範囲欄 = ("識別体系", "時点", "適用条件")
_値 = r'([^「」\n]{1,64})'
_宣言 = re.compile(r'(識別体系|時点|適用条件)は「' + _値 + r'」(?:である|です)\Z')
_対象 = re.compile(r'対象「' + _値 + r'」の識別子は「' + _値 + r'」(?:である|です)\Z')


def _文字(値):
    if (type(値) is not str or not 0 < len(値) <= 64 or 値 != 値.strip()
            or any(unicodedata.category(字).startswith("C") for 字 in 値)):
        raise ValueError("宣言値の型・空白・制御文字・文字上限不正")
    return 値


def 横断要求を検査(要求):
    from .関係読解 import 関係要求を検査, 関係要求版
    if type(要求) is not dict or 要求.get("版") != "HDS資料横断要求-v1" or set(要求) != {"版", "対象", "範囲", "問い", "形式", "不足調査", "最大文字数", "照会資料"}:
        raise ValueError("資料横断要求の欄不一致")
    共通 = {鍵: 値 for 鍵, 値 in 要求.items() if 鍵 != "照会資料"}
    共通["版"] = 関係要求版
    関係要求を検査(共通)
    if (要求["範囲"] != "指定資料" or len(要求["対象"]) < 2
            or type(要求["照会資料"]) is not str or 要求["照会資料"] not in 要求["対象"]):
        raise ValueError("資料横断には2〜8件の指定資料と、その中の照会資料が必要")
    return 正準(要求)


def 資料宣言を読む(本文):
    if type(本文) is not str or not 0 < len(本文) <= 16000:
        raise ValueError("資料横断の本文型・文字上限")
    範囲, 対象, 記録, 区間, 不整合 = {}, {}, [], [], []
    宣言終了, 直前宣言 = False, False
    for 開始, 終了 in 構成句を分ける(本文):
        文 = 本文[開始:終了].strip().removesuffix("。")
        欄, 名 = _宣言.fullmatch(文), _対象.fullmatch(文)
        if not 欄 and not 名 and not (文.startswith(tuple(語 + "は" for 語 in _範囲欄))
                                     or 文.startswith('対象「')):
            if 直前宣言 and 文.startswith(("ただし", "但し", "例外", "ただ", "しかし")):
                不整合.append({"範囲": [開始, 終了], "原文": 本文[開始:終了], "理由": "接続宣言への留保・例外が未解釈"})
            if not 文.startswith("#"):
                宣言終了 = True
            直前宣言 = False
            continue
        区間.append([開始, 終了])
        原 = {"範囲": [開始, 終了], "原文": 本文[開始:終了]}
        直前宣言 = True
        try:
            if 宣言終了:
                raise ValueError("本文後の接続宣言は作用域未対応。先頭に明示してください")
            if 欄:
                鍵, 値 = 欄[1], _文字(欄[2])
                if 鍵 in 範囲 and 範囲[鍵] != 値:
                    raise ValueError("競合する" + 鍵 + "宣言")
                範囲[鍵] = 値
                記録.append({**原, "種類": 鍵, "値": 値})
            elif 名:
                名前, 識別子 = _文字(名[1]), _文字(名[2])
                式, 主体, _ = 関係文を読む(名前 + "は有効である")
                if 主体 != 名前 or 式.項[0].名前 != 名前:
                    raise ValueError("対象宣言の名前が一意でない")
                if 名前 in 対象 and 対象[名前] != 識別子:
                    raise ValueError("同じ表記に異なる識別子")
                対象[名前] = 識別子
                if len(対象) > 32:
                    raise ValueError("資料横断の対象宣言数上限")
                記録.append({**原, "種類": "対象", "対象": 名前, "値": 識別子})
            else:
                raise ValueError("識別体系・対象・時点・適用条件の宣言構文が未対応")
        except ValueError as 例外:
            不整合.append({**原, "理由": str(例外)})
    不足 = [語 for 語 in _範囲欄 if 語 not in 範囲]
    if not 対象:
        不足.append("対象識別子")
    return 正準({"範囲": 区間, "共通範囲": 範囲, "対象": 対象, "記録": 記録,
                 "不整合": 不整合, "不足": 不足, "成立": not 不整合 and not 不足})


def _接続式(式, 宣言):
    """命題を直接変換する。原文の文字列置換や字面による同一化はしない。"""
    if 式.種別 in ("帰属", "全称", "存在"):
        raise ValueError("引用・発言・量化を含む記載は横断接続の対象外")
    if 式.種別 == "原子":
        if not 式.項:
            raise ValueError("対象を持たない命題は横断しない")
        if 式.時点 not in ("未指定", 宣言["共通範囲"]["時点"]):
            raise ValueError("命題の明示時点と資料の時点宣言が異なる")
        新項 = []
        for 項 in 式.項:
            if 項.種別 != "定数" or 項.名前 not in 宣言["対象"]:
                raise ValueError("対象識別子が未宣言:" + 項.名前)
            新項.append(命題項("対象:" + 指紋([宣言["共通範囲"]["識別体系"], 宣言["対象"][項.名前]])))
        # 時点・様相は一切上書きしない。資料スコープと式内スコープの両方を照合する。
        return replace(式, 項=tuple(新項))
    return replace(式, 子=tuple(_接続式(子, 宣言) for 子 in 式.子))


def 横断式を表現(式辞書, 対応):
    def 表示(式):
        return replace(式, 項=tuple(命題項(対応[項.名前]["識別子"], 項.種別)
                       if 項.名前 in 対応 else 項 for 項 in 式.項), 子=tuple(表示(子) for 子 in 式.子))
    return 関係式を表現(表示(命題を復元(式辞書, 内部許可=True)))


def 資料を結び付ける(資料群, 宣言群, 要求, 問い):
    """採用済み記載を宣言で再束縛し、原記載ID・位置と実導出を一緒に返す。"""
    from .関係読解 import 記載を判定
    要求 = 横断要求を検査(要求)
    照会 = 要求["照会資料"]
    起点 = 宣言群[照会]
    保留, 記載, 対応, 採用資料 = [], [], {}, []

    def 残す(資料, 理由, 識別子="", 範囲=None):
        保留.append({"資料": 資料, "記載": 識別子, "範囲": 範囲, "理由": 理由})

    for 名, 宣言 in sorted(宣言群.items()):
        for 不整合 in 宣言["不整合"]:
            残す(名, 不整合["理由"], 範囲=不整合["範囲"])
        if 宣言["不足"]:
            残す(名, "接続宣言が不足:" + "、".join(宣言["不足"]))
    新問い, 接続可 = 問い, 起点["成立"]
    if 接続可:
        try:
            新問い = _接続式(問い, 起点)
        except ValueError as 例外:
            残す(照会, "照会命題を接続できない:" + str(例外))
            接続可 = False
    if 接続可:
        for 番号, (名, 行) in enumerate(sorted(資料群.items())):
            宣言 = 宣言群[名]
            if not 宣言["成立"]:
                continue
            if 宣言["共通範囲"] != 起点["共通範囲"]:
                差 = [鍵 for 鍵 in _範囲欄 if 宣言["共通範囲"][鍵] != 起点["共通範囲"][鍵]]
                残す(名, "接続範囲が不一致:" + "、".join(差))
                continue
            for 元 in 行["採用記載"]:
                try:
                    式 = _接続式(命題を復元(元["式"]), 宣言)
                    式.検査()
                except ValueError as 例外:
                    残す(名, str(例外), 元["識別子"], 元["範囲"])
                    continue
                if len(記載) >= 128:
                    raise ValueError("横断採用記載数上限。原文を切り捨てず資料範囲を絞ってください")
                記載.append(命題記載("資料" + str(番号) + "/" + 元["識別子"], 式, 名, 元["原文"], tuple(元["範囲"])))
                if 名 not in 採用資料:
                    採用資料.append(名)
            if 名 in 採用資料 or 名 == 照会:
                for 名前, 識別子 in sorted(宣言["対象"].items()):
                    鍵 = "対象:" + 指紋([宣言["共通範囲"]["識別体系"], 識別子])
                    要素 = 対応.setdefault(鍵, {"識別子": 識別子, "表記": []})
                    要素["表記"].append({"資料": 名, "対象": 名前})
        共有 = any(len({行["資料"] for 行 in 値["表記"]}) >= 2 for 値 in 対応.values())
        if len(採用資料) < 2 or not 共有:
            残す(照会, "接続可能な2資料と共有識別子が揃っていない")
            接続可 = False
    判定, 説明, 不足 = 記載を判定(tuple(記載) if 接続可 else (), 新問い)
    使用資料 = sorted({行.資料 for 行 in 記載 if 行.識別子 in 説明["使用記載"]})
    return 正準({"版": 横断版, "宣言": 宣言群, "共通範囲": 起点["共通範囲"],
                 "状態": "宣言条件内の横断判定" if 接続可 else "接続保留", "保留": 保留,
                 "問い式": 新問い.辞書(), "対象対応": 対応, "接続候補資料": 採用資料,
                 "採用記載": [asdict(項) for 項 in 記載] if 接続可 else [],
                 "判定": 判定, "説明": 説明, "不足候補": 不足, "使用資料": 使用資料,
                 "境界": "利用者が指定した登録資料の明示宣言を前提とする条件付き導出です。識別体系・対象識別子・時点・適用条件の宣言一致は、世界の対象同一性や資料の信頼性の検証ではありません。導出中の対象は共有識別子で表示します。公開取得資料は自動接続しません。"})
