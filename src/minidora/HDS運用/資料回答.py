def 回答意味を構成(構造):
    要求, 記載 = 構造["要求"], 記載関係を読む(構造)
    対象群 = 要求["比較対象"] or 要求["主題"]
    観点群 = 要求["観点"]
    定義要求 = "定義" in 要求.get("関係焦点", ())
    関係焦点 = [項 for 項 in 要求.get("関係焦点", ()) if 項 != "定義"]
    肯否 = 要求.get("肯否", "未指定")
    # 問いの中核が読めている単一対象の定義だけに限定する。
    # 条件・肯否・理由・比較を問われた際の未解釈を限定回答で置き換えない。
    限定回答可 = (要求["操作"] == ["説明"] and 要求.get("関係焦点") == ["定義"]
                   and len(対象群) == 1 and not 要求["比較対象"] and not 観点群 and 肯否 == "未指定")
    未確定限定 = {} if 限定回答可 else None
    簡潔 = 要求["詳細"] == "簡潔"
    条件前置き = "条件：" if 簡潔 else "原資料の適用条件："
    命題, 使用, 演算, 属性表記, 内容不足 = [], set(), [], {}, []
    def 採用(種別, 本文, 根拠群, *, 条件=()):
        根拠群 = tuple(根拠群)
        if not 本文.strip() or not 根拠群:
            raise ValueError("内容のない命題・根拠なしの確定は不可")
        命題.append(回答命題(種別, 本文, tuple(行["ID"] for 行 in 根拠群), tuple(条件)))
        使用.update(行["ID"] for 行 in 根拠群)
    def 理由を採用(行):
        本文 = _記載理由の本文(行, 簡潔=簡潔)
        if 本文 is None:
            return False
        関係 = 行["関係"]["理由"] or 行["関係"]["目的"]
        根拠群 = (行,)
        if 関係.get("前文"):
            前 = tuple(項 for 項 in 記載 if 項["対応"] == 関係["前文"])
            if len(前) != 1:
                raise ValueError("理由の前文根拠が一意ではありません")
            根拠群 = 前 + 根拠群
        採用("記載理由", 本文, 根拠群)
        演算.append({"種別": "記載理由関係", "関係": 関係})
        return True

    for 操作 in 要求["操作"]:
        if 操作 == "対照":
            if len(対象群) != 2:
                raise ValueError("比較対象を二つ明示してください")
            軸群 = list(観点群)
            if not 軸群:
                対応軸 = [{行["関係"]["属性"]["観点"] for 行 in 記載 if 行["関係"]["属性"] and _照合語(行["関係"]["属性"]["対象"]) == _照合語(対象)} for 対象 in 対象群]
                軸群 = sorted(set.intersection(*対応軸))
            if 軸群:
                for 軸 in 軸群:
                    群 = [[行 for 行 in 記載 if 行["関係"]["属性"] and _照合語(行["関係"]["属性"]["観点"]) == _照合語(軸) and _照合語(行["関係"]["属性"]["対象"]) == _照合語(対象)] for 対象 in 対象群]
                    if any(len(値) != 1 for 値 in 群):
                        raise ValueError("比較の属性値が不足又は競合:" + 軸)
                    a, b = 群[0][0], 群[1][0]
                    数 = _量比較(構造, 軸, 対象群)
                    if 数:
                        採用("数量比較", 数[0], (a, b)); 演算.append({"種別": "既存数量比較", "成果": 数[1], "原資料区間": 数[2]})
                    else:
                        左, 右 = a["関係"]["属性"]["値"], b["関係"]["属性"]["値"]
                        # 未解析の数値・時点条件を質的文字比較へ迂回させない。
                        限定を除く値 = re.sub(r"できない|しない", "", 左 + 右)
                        if re.search(r"[0-9０-９]", 左 + 右) or _限定.search(限定を除く値):
                            raise ValueError("数値・条件付き属性の比較が未解釈です。共通条件と単位を明示してください")
                        本文, 証拠 = _属性を対照(a, b, 軸)
                        採用("属性対照", 本文, (a, b))
                        演算.append(証拠)
            else:
                対照 = _明示場所を対照(記載, 対象群) or _定義を対照(記載, 対象群)
                for 文, 根拠群, 証拠 in 対照:
                    採用("定義対照", 文, 根拠群)
                    演算.append(証拠)
        elif 操作 == "理由":
            候補 = []
            for 行 in 記載:
                理由, 目的 = 行["関係"]["理由"], 行["関係"]["目的"]
                現象 = 理由["結果"] if 理由 else 目的["手段"] if 目的 else ""
                対象作用 = 理由.get("対象作用") if 理由 else None
                照合 = (_問いの式を照合(命題を復元(対象作用), 対象群, 関係焦点, 肯否) if 対象作用
                        else bool(現象) and any(_照合語(対象) in _照合語(現象) for 対象 in 対象群)
                        and _現象を照合(現象, 対象群, 関係焦点, 肯否))
                if 照合 and (not 観点群 or all(_照合語(軸) in _照合語(現象) for 軸 in 観点群)):
                    候補.append(行)
            if not 候補:
                raise ValueError("この問いを支持する原因・目的と主体・作用の関係を、HDSで安全に束縛できません。"
                                 "原資料に理由が存在しないとは認定していません。対象・作用・条件を明示した記載が必要です")
            if len(候補) > 8:
                raise ValueError("理由の候補が多すぎます。現象と条件を明示してください")
            for 行 in 候補:
                if not 理由を採用(行):
                    raise ValueError("理由標識の作用域が未確定です")
        elif 操作 in ("説明", "要約"):
            候補 = [行 for 行 in 記載 if not 対象群 or any(_説明対象一致(行, 対象) for 対象 in 対象群)]
            if 観点群:
                候補 = [行 for 行 in 候補 if any(_観点一致(行, 軸) for 軸 in 観点群)]
            if 関係焦点:
                属性候補 = [行 for 行 in 候補 if 行["関係"]["属性"] and
                            any(_照合語(項) == _照合語(行["関係"]["属性"]["観点"]) for 項 in 関係焦点)]
                候補 = 属性候補 if 属性候補 else [行 for 行 in 候補 if
                            行["命題"] and _現象を照合(行["対応"]["原文"], 対象群, 関係焦点, 肯否)]
            if 定義要求:
                定義候補 = [行 for 行 in 候補 if 行["関係"]["定義"] and
                        any(_照合語(対象) == _照合語(行["関係"]["定義"]["対象"]) for 対象 in 対象群)]
                if not 定義候補:
                    raise ValueError("対象の定義・種別関係が未確認です。一属性の記載を定義へ変えません")
                # 定義を中核とし、明示された同一主体の読解済み記載だけを補足する。
                # 引用診断付きの経路は従来の単一定義の限定契約を保つ。
                診断あり = any(項.get("全体構文診断") for 項 in 構造["資料群"].values())
                補足 = [] if 診断あり else [
                    行 for 行 in 候補 if 行 not in 定義候補 and
                    any(_対象一致(行, 対象) for 対象 in 対象群) and
                    (行["関係"]["属性"] or 行["関係"]["叙述"]) and
                    _補足の文脈を束縛(行, 定義候補, 記載)]
                候補 = 定義候補 + 補足
            if not 候補:
                raise ValueError("問われた対象・観点を説明する記載がありません")
            # 冒頭位置で選ばず、定義・具体属性・理由を優先する。採用されない全文も構造へ保存する。
            順 = sorted(候補, key=lambda 行: (not bool(行["関係"]["定義"]), not bool(行["関係"]["属性"]), not bool(行["関係"]["理由"]), 行["対応"]["開始"]))
            上限 = {"簡潔": 2, "標準": 4, "詳細": 8}[要求["詳細"]]
            選択 = 順[:上限]
            # 数値・否定・適用条件を持つ対象記載は短文化でも切り捨てない。
            選択 += [行 for 行 in 候補 if 行 not in 選択 and (行["限定"] or re.search(r"\d", 行["対応"]["原文"]))]
            条件対応 = _条件を結ぶ(記載, {行["ID"] for 行 in 候補}, 未確定=未確定限定)
            for 行 in 候補:
                if 行["ID"] in 条件対応:
                    for 同伴 in (行, *条件対応[行["ID"]]):
                        if 同伴 not in 選択:
                            選択.append(同伴)
            if len(選択) > 24:
                raise ValueError("数値・条件を保持した説明が長すぎます。対象・観点を絞ってください")
            for 行 in 選択:
                関係 = 行["関係"]
                # 定義を問われた場合は、名詞述部に修飾された手段・用途も含む定義全体を保つ。
                # 定義内の「によって」を単独の結果文へ切り出して主体を補完しない。
                if not 定義要求 and (関係["理由"] or 関係["目的"]) and 理由を採用(行):
                    continue
                if 関係["定義"] and not (関係["属性"] and not 定義要求):
                    本文 = _述文(関係["定義"])
                    採用("定義", 本文, (行,))
                elif 関係["属性"]:
                    属性 = 関係["属性"]
                    数値 = 数値記載文.fullmatch(行["対応"]["原文"])
                    if 数値 and 数値["単位"] in _単位:
                        try:
                            数量, 区間 = _数値を読む(構造, 属性["対象"], 属性["観点"], 数値["単位"])
                        except 会話処理不成立 as 例外:
                            raise ValueError("説明する数値が未確定:" + 例外.理由) from 例外
                        値 = 数量.データ
                        表示 = 値["表示値"] + 値["表示単位"]
                        文 = "資料の記載では、" + 属性["対象"] + "の" + 属性["観点"] + "は" + 表示 + "。"
                        if 値["条件"] is not None:
                            文 = "条件「" + 値["条件"] + "」では、" + 文
                        if 値["時点"] is not None:
                            文 = "時点「" + 値["時点"] + "」の記載：" + 文
                        採用("数量記載", 文, (行,)); 演算.append({"種別": "既存数量採用", "成果": 結果を保存用(数量), "原資料区間": 区間})
                        属性表記[行["ID"]] = {"対象": 属性["対象"], "観点": 属性["観点"], "値": 表示,
                                              "数量": True, "数量正準": (値["値"], 値["単位"]),
                                              "条件": 値["条件"], "時点": 値["時点"]}
                    else:
                        採用("属性", "資料が示す" + 属性["対象"] + "の" + 属性["観点"] + "：" + 属性["値"].rstrip("。") + "。", (行,))
                        属性表記[行["ID"]] = {"対象": 属性["対象"], "観点": 属性["観点"], "値": 属性["値"].rstrip("。"),
                                              "数量": False, "条件": None, "時点": None}
                elif 関係["叙述"]:
                    採用("主述記載", _述文(関係["叙述"]), (行,))
                elif 行["命題"]:
                    from ..命題解釈 import 命題を表現
                    採用("主述記載", 命題を表現(命題を復元(行["命題"])) + "。", (行,))
                else:
                    if 行["限定"]:
                        採用("限定記載", 行["対応"]["原文"], (行,))
            if not any(項.種別 != "限定記載" for 項 in 命題):
                raise ValueError("説明に必要な定義・属性・主述関係が未読解です。原文抜粋だけでは問いの成立にしません")
            中核 = [項 for 項 in 命題 if 項.種別 != "限定記載"]
            分類不足 = False
            if 定義要求 and len(中核) == 1 and 中核[0].種別 == "定義":
                使用定義 = [行["関係"]["定義"] for 行 in 定義候補 if 行["ID"] in 使用]
                if 使用定義 and all(項.get("成員関係") for 項 in 使用定義):
                    分類不足 = True
                    内容不足.append("示せたのは資料の種別・所属関係です。対象を区別する特徴・仕組みの説明は、"
                                    "今回の読解では十分に構成できていません。同じ対象の特徴を明示した記載の確認が必要です。")
            if not 分類不足 and 要求["詳細"] == "詳細" and len({_照合語(項.本文) for 項 in 中核}) < 2:
                内容不足.append("今回構成できた説明は、この一つの記載・関係に限られます。"
                                "詳しい説明に必要な追加の内容を、この資料から安全に読解できていません。"
                                "仕組み・具体例・条件を明示する追加資料又は確認が必要です。")
        elif 操作 == "確認提案":
            if not 命題:
                raise ValueError("確認する対象の説明根拠が不足しています")
        else:
            raise ValueError("未対応の回答操作:" + 操作)

    if 要求["操作"] == ["要約"]:
        命題, 統合 = _要約属性を統合(命題, 記載, 属性表記)
        演算.append({"種別": "同観点の記載要約", "統合": 統合})
    _競合を検査(構造, 記載, 対象群, 使用)
    同伴 = _条件を結ぶ(記載, 使用, 未確定=未確定限定)
    for 番号, 項 in enumerate(命題):
        条件群 = {行["ID"]: 行 for 根拠 in 項.根拠 for 行 in 同伴.get(根拠, ())}
        if 条件群:
            命題[番号] = replace(項, 条件=tuple(dict.fromkeys((*項.条件,
                                *(条件前置き + 行["対応"]["原文"] for 行 in 条件群.values())))),
                                根拠=tuple(dict.fromkeys((*項.根拠, *条件群))))
    条件群 = {行["ID"]: 行 for 群 in 同伴.values() for 行 in 群}
    for 行 in 条件群.values():
        if 行["ID"] not in 使用:
            採用("限定記載", 条件前置き + 行["対応"]["原文"], (行,))
    使用.update(条件群)
    if not 命題:
        raise ValueError("問いに対する内容が構成できませんでした")
    構文留保 = _構文診断を留保(構造, 記載, 使用, 対象群, 限定回答可=限定回答可)
    if 構文留保 and (not any(項.種別 == "定義" for 項 in 命題) or any(
            項.種別 not in ("定義", "限定記載") for 項 in 命題)):
        raise ValueError("構文診断付きの限定回答は、意味読解済みの定義と厳密な適用条件が必要です")
    for 項 in 構文留保:
        未確定限定[項["記載ID"]] = 項
    留保 = ()
    if 未確定限定:
        if not any(項.種別 == "定義" for 項 in 命題):
            raise ValueError("限定回答に必要な定義の意味が未読解です")
        命題 = [replace(項, 本文="資料の定義としては、" + 項.本文) if 項.種別 == "定義" else 項
                for 項 in 命題]
        条件留保 = [項 for 項 in 未確定限定.values() if 項.get("種別") != "構文診断"]
        留保 = ("この回答は資料で読解できた定義・同じ対象の記載に限ります。次の記載が各主張へ適用されるかは未確定です。",) + tuple(
            "原資料の未確定記載：" + 項["対応"]["原文"] + "\n" + 項["理由"] + "。" + 項["必要資料"]
            for 項 in 条件留保)
        if 構文留保:
            留保 += ("次の原資料の引用不整合について、定義との依存・適用範囲は未確定です。原行を訂正せず示します。",)
            for 項 in 構文留保:
                項["留保番号"] = len(留保)
                留保 += ("".join(_診断留保の部分(項)),)
        使用.update(未確定限定)
    留保 += tuple(dict.fromkeys(内容不足))
    計画 = 内容計画(tuple(内容単位(項.種別, 項.本文, 項.根拠, 項.条件) for 項 in 命題), 留保)
    if not 内容計画を検査(計画, 許可根拠={行["ID"] for 行 in 記載}):
        raise ValueError("回答内容と実在する資料区間が不整合")
    意味 = 回答意味IR(tuple(命題), 留保, tuple(構造["資料順"]))
    return 正準({"版": 資料回答版, "意味": asdict(意味), "内容計画": asdict(計画),
                 "記載関係": 記載, "演算": 演算, "使用記載": sorted(使用),
                 "未確定限定": list((未確定限定 or {}).values()),
                 "未使用記載": [行["ID"] for 行 in 記載 if 行["ID"] not in 使用]})


def 会話内容仕様を構成(構造, *, 形式=None):
    from .意味資料 import 資料を区分
    成果 = 回答意味を構成(構造)
    要求 = 構造["要求"]
    形式 = 要求["形式"] if 形式 is None else 形式
    if 形式 not in ("文章", "箇条書き", "引用"):
        raise ValueError("会話回答形式が未対応")
    素材, 単位群 = {}, []
    for 番号, 命題 in enumerate(成果["意味"]["命題"]):
        資料を区分(命題["本文"], 会話本文=True)
        名前 = "内容" + str(番号)
        素材[名前] = 能力結果(True, 命題["本文"], 根拠=tuple(命題["根拠"]))
        単位群.append(文章単位(名前, {"文章": "段落", "箇条書き": "箇条書き", "引用": "引用"}[形式],
                     (文章断片(名前, 0, len(命題["本文"])),), 必須=True, 保護=True))
    原行留保 = {項["留保番号"]: 項 for 項 in 成果["未確定限定"] if 項.get("種別") == "構文診断"}
    for 番号, 本文 in enumerate(成果["意味"]["留保"]):
        名前 = "留保" + str(番号)
        if 番号 in 原行留保:
            項 = 原行留保[番号]
            前, 原文, 後 = _診断留保の部分(項)
            if 本文 != 前 + 原文 + 後:
                raise ValueError("構文診断の留保と原行断片が不一致")
            原本 = 結果を復元(構造["資料群"][項["対応"]["資料"]]["資料"]).本文
            if 原本[項["対応"]["開始"]:項["対応"]["終了"]] != 原文:
                raise ValueError("診断原行と元座標が不一致")
            資料を区分(前, 会話本文=True)
            資料を区分(後, 会話本文=True)
            先ID, 原ID, 後ID = "診断説明" + str(番号), "診断原行" + str(番号), "追加確認" + str(番号)
            素材[先ID] = 能力結果(True, 前)
            素材[後ID] = 能力結果(True, 後)
            素材[原ID] = 能力結果(True, 原文, 根拠=(項["記載ID"],), データ={
                "種別": "原資料構文診断片", "資料": 項["対応"]["資料"],
                "本文SHA256": 項["本文SHA256"], "元開始": 項["対応"]["開始"], "元終了": 項["対応"]["終了"]})
            断片 = tuple(文章断片(ID, 0, len(素材[ID].本文)) for ID in (先ID, 原ID, 後ID))
            単位群.append(文章単位(名前, "留保", 断片, 必須=True, 保護=True))
        else:
            資料を区分(本文, 会話本文=True)
            素材[名前] = 能力結果(True, 本文, 根拠=tuple(項["記載ID"] for 項 in 成果["未確定限定"]))
            単位群.append(文章単位(名前, "留保", (文章断片(名前, 0, len(本文)),), 必須=True, 保護=True))
    return 正準({"素材": {名: _結果辞書(値) for 名, 値 in 素材.items()},
                 "仕様": asdict(文章仕様(tuple(単位群), tuple(項.識別子 for 項 in 単位群), 要求["最大文字数"]))})
