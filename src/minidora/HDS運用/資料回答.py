def _数量区間を選ぶ(構造, 対象, 属性):
    """数値器に渡す実区間と原本への対応。別属性の有効な記載は改変せず保全。"""
    記載 = 記載関係を読む(構造)
    数値ID = {行["ID"] for 行 in 記載 if (数値 := 数値記載文.fullmatch(行["対応"]["原文"])) and
              数値["対象"] == 対象 and 数値["属性"] == 属性}
    条件対応 = _条件を結ぶ(記載, {行["ID"] for 行 in 記載})
    数値条件 = {条件["ID"] for 番号 in 数値ID for 条件 in 条件対応.get(番号, ())}
    非数値条件 = {条件["ID"] for 番号, 群 in 条件対応.items() if 番号 not in 数値ID for 条件 in 群}
    参照群, 対応群 = [], []
    for 行 in 記載:
        文 = 行["対応"]["原文"]
        数値, 記載属性 = 数値記載文.fullmatch(文), 行["関係"]["属性"]
        if 数値:
            必要 = 数値["対象"] == 対象 and 数値["属性"] == 属性
        elif 行["限定"]:
            # 未読解の条件・年度・例外を抜いて数値だけを成立させない。
            必要 = 行["ID"] in 数値条件 or 行["ID"] not in 非数値条件
        elif 記載属性:
            必要 = 記載属性["対象"] == 対象 and 記載属性["観点"] == 属性
        elif 行["命題"] or 行["関係"]["定義"] or 行["関係"]["叙述"]:
            必要 = False
        else:
            必要 = True
        if not 必要:
            continue
        名前 = 行["対応"]["資料"]
        元 = 結果を復元(構造["資料群"][名前]["資料"])
        開始, 終了 = 行["対応"]["開始"], 行["対応"]["終了"]
        if 元.本文[開始:終了] != 文:
            raise ValueError("数値原文区間の対応不一致")
        元参照 = next((項 for 項 in 元.参照 if 項.本文 == 元.本文), None)
        元ID = 元参照.識別子 if 元参照 else "提示:" + 名前
        区間ID = 元ID + "@原文区間:" + str(開始) + ":" + str(終了)
        参照群.append(参照資料(区間ID, 元参照.題名 if 元参照 else 名前,
                              "原文区間:" + (元参照.出典 if 元参照 else "利用者提示"),
                              URL=元参照.URL if 元参照 else "", 公開時刻=元参照.公開時刻 if 元参照 else None, 本文=文))
        対応群.append({"参照ID": 区間ID, "原資料": 名前, "元参照ID": 元ID,
                       "開始": 開始, "終了": 終了, "原文": 文, "原本文印": 指紋(元.本文)})
    if not 参照群:
        raise ValueError("対象・属性の実数値区間がありません")
    return 能力結果(True, "", 参照=tuple(参照群)), 対応群


def _数値を読む(構造, 対象, 属性, 単位):
    区間資料, 対応 = _数量区間を選ぶ(構造, 対象, 属性)
    return 記載数量を読む(区間資料, {"対象": 対象, "属性": 属性, "単位": 単位}), 対応


