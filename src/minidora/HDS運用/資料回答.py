def _記載理由の本文(行, *, 簡潔=False):
    理由, 目的 = 行["関係"]["理由"], 行["関係"]["目的"]
    if not (理由 or 目的):
        return None
    関係 = 理由 or 目的
    if 関係.get("前文") is None:
        # 引用や括弧の内部にある標識を、外側の因果・用途へ移さない。
        標識 = ("ため", "ので", "から", "により", "によって") if 理由 else ("ために", "ための", "ことを目的として", "ことを目的に")
        try:
            位置群 = _最上位(行["対応"]["原文"], 標識)
        except ValueError:
            return None
        if not 位置群:
            return None
    現象 = 関係.get("結果", 関係.get("手段", ""))
    if _結果式を読む(関係) is None:
        raise ValueError("説明に使う理由・手段の主述が未読解です:" + 現象[:160])
    if 理由:
        前文 = ("資料が扱う事象範囲は「" + 関係["事象範囲"]["対応"]["原文"].rstrip("。") + "」です。この範囲で、"
                if 関係.get("事象範囲") else
                "前文には「" + 関係["前文"]["原文"].rstrip("。") + "」と記載されています。"
                if 関係.get("作用結果参照") else "")
        if 簡潔:
            return 前文 + "資料の理由は「" + 関係["理由"].rstrip("。") + "」。結果は「" + 関係["結果"].rstrip("。") + "」。"
        return 前文 + "資料が示す理由は「" + 関係["理由"].rstrip("。") + "」で、結果は「" + 関係["結果"].rstrip("。") + "」です。"
    if 関係.get("接続") == "連体用途":
        return "資料に記された" + 関係["用途原対象"] + "（" + 関係["種別"] + "）の用途は「" + 関係["目的"] + "」です。その用途の手段は「" + 関係["手段"] + "」と記載されています。"
    if 簡潔:
        return "資料の目的は「" + 関係["目的"].rstrip("。") + "」。手段は「" + 関係["手段"].rstrip("。") + "」。"
    return "目的は「" + 関係["目的"].rstrip("。") + "」です。そのための手段として「" + 関係["手段"].rstrip("。") + "」が記載されています。"


def _要約属性を統合(命題, 記載, 属性表記):
    """同じ属性・実条件の記載を統合。値や様相を短い別の事実へ置き換えない。"""
    条件対応 = _条件を結ぶ(記載, {根拠 for 項 in 命題 for 根拠 in 項.根拠})
    群, 順 = {}, []
    for 番号, 項 in enumerate(命題):
        表記 = 属性表記.get(項.根拠[0]) if len(項.根拠) == 1 else None
        if 表記:
            条件 = tuple(sorted((条件["対応"]["原文"],
                                  条件["資料作用"]["原資料"]["保存指紋"],
                                  条件["資料作用"]["条件"]["座標ID"] if 条件["資料作用"]["条件"] else "")
                                 for 条件 in 条件対応.get(項.根拠[0], ())))
            鍵 = ("属性", 表記["観点"], 表記["数量"], 表記["条件"], 表記["時点"], 条件)
        else:
            鍵 = ("単独", 番号)
        if 鍵 not in 群:
            群[鍵] = []
            順.append(鍵)
        群[鍵].append((項, 表記))
    結果, 統合記録 = [], []
    for 鍵 in 順:
        行群 = 群[鍵]
        if 鍵[0] != "属性":
            結果.extend(項 for 項, _ in 行群)
            continue
        表示, 対象値, 表示済み = [], {}, set()
        for 項, 表記 in 行群:
            対象 = 表記["対象"]
            # 数量は既存器の正準値・単位で照合し、表示上の単位差で不等にしない。
            意味値 = tuple(表記["数量正準"]) if 表記["数量"] else _照合語(表記["値"])
            if 対象 in 対象値 and 対象値[対象] != 意味値:
                raise ValueError("同じ対象・属性・条件の要約値が競合しています:" + 対象)
            対象値[対象] = 意味値
            表現 = 対象 + ("" if 表記["数量"] else "が") + 表記["値"]
            if (対象, 意味値) not in 表示済み:
                表示.append(表現)
                表示済み.add((対象, 意味値))
        根拠 = tuple(dict.fromkeys(根拠 for 項, _ in 行群 for 根拠 in 項.根拠))
        本文 = 鍵[1] + "は" + "、".join(表示) + "。"
        if 鍵[3] is not None:
            本文 = "条件「" + 鍵[3] + "」では、" + 本文
        if 鍵[4] is not None:
            本文 = "時点「" + 鍵[4] + "」の記載：" + 本文
        結果.append(回答命題("属性要約", 本文, 根拠))
        統合記録.append({"観点": 鍵[1], "原命題": [asdict(項) for 項, _ in 行群], "根拠": 根拠,
                        "表記": [表記 for _, 表記 in 行群], "条件": 鍵[5]})
    if 結果:
        結果[0] = replace(結果[0], 本文="資料では、" + 結果[0].本文)
    return 結果, 統合記録


def _構文診断を留保(構造, 記載, 使用, 対象群, *, 限定回答可):
    診断資料 = [(名, 行["全体構文診断"]) for 名, 行 in 構造["資料群"].items()
                if "全体構文診断" in 行]
    if not 診断資料:
        return []
    from .意味資料 import 意味資料を検査, 資料を区分
    if not 限定回答可 or not 意味資料を検査(構造):
        raise ValueError("構文診断のある資料は、原本検査済みの単一対象の定義だけを限定して扱います")
    採用 = [行 for 行 in 記載 if 行["ID"] in 使用]
    for 行 in 採用:
        資料を区分(行["対応"]["原文"], 会話本文=True)
    結果, 済み = [], set()
    for 名前, 注記 in 診断資料:
        for 診断 in 注記["診断"]:
            左, 右 = 診断["開始"], 診断["終了"]
            鍵 = (名前, 左, 右)
            if 鍵 in 済み:
                continue
            済み.add(鍵)
            交差 = [行 for 行 in 記載 if 行["対応"]["資料"] == 名前 and
                    行["対応"]["開始"] < 右 and 左 < 行["対応"]["終了"]]
            if any(行["ID"] in 使用 for 行 in 交差):
                raise ValueError("定義・条件・前文の根拠閉包が構文不整合行と交差しています")
            原文 = 診断["原文"]
            # 未読の否定/撤回/条件を単なる書誌へ格下げしない。
            条件文 = re.sub(r"[0-9]{4}年", "", 原文)
            if _限定.search(条件文) or _指示.match(原文.strip()) or any(
                    any(_対象一致(行, 対象) or 行["明示主語"] and _主体対応(行["明示主語"], 対象)
                        for 対象 in 対象群) for 行 in 交差):
                raise ValueError("構文不整合行の否定・撤回・条件又は同対象記載を未確定書誌へ変えられません")
            for 対象 in 対象群:
                if any(_照合語(対象 + 助詞) in _照合語(原文) for 助詞 in ("は", "が", "とは")):
                    raise ValueError("構文不整合行に同じ対象の未読主述があります")
            使用脚注 = {脚注["原文"] for 行 in 採用 if 行["対応"]["資料"] == 名前 for 脚注 in 行["脚注"]}
            if 使用脚注.intersection(項[0] for 項 in re.finditer(r"\[[0-9]+\]", 原文)):
                raise ValueError("使用した脚注の明示参照が構文不整合行と交差しています")
            結果.append({"種別": "構文診断", "記載ID": 名前 + ":構文診断:" + str(左) + ":" + str(右),
                         "対応": {"資料": 名前, "開始": 左, "終了": 右, "原文": 原文},
                         "本文SHA256": 注記["本文SHA256"], "理由": 診断["理由"],
                         "作用域": 診断["作用域"], "必要資料": 診断["必要資料"]})
    return 結果


