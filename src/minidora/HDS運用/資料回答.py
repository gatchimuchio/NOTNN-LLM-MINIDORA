def _修飾命題を読む(行):
    定義 = 行["関係"]["定義"]
    修飾 = 定義.get("修飾") if 定義 else None
    if not 修飾 or 定義.get("成員関係"):
        return None
    条件, 内部修飾 = [], ""
    読む修飾 = 修飾
    譲歩 = re.fullmatch(r"(?P<条件>[^はが、,。\n]{1,80}が[一-龥々ァ-ヴーA-Za-z・]{1,40}しても)(?P<後節>.+)", 修飾)
    同伴 = re.fullmatch(r"(?P<条件>[^はが、,。\n]{1,80}と(?:とも|共)に(?:[一-龥々ァ-ヴー]{1,24}的に)?)(?P<後節>.+)", 修飾)
    if 譲歩 or 同伴:
        条件.append((譲歩 or 同伴)["条件"])
        読む修飾 = (譲歩 or 同伴)["後節"]
    try:
        主格 = next(最上位位置(読む修飾, ("は", "が")), None)
        文 = 読む修飾 if 主格 else 定義["対象"] + "は" + 読む修飾
        式, _, 履歴 = 関係文を読む(文)
    except ValueError:
        return None
    原子式 = 式.子[0] if 式.種別 == "否定" else 式
    if 原子式.種別 != "原子":
        return None
    項役割 = []
    for 項 in 原子式.項:
        if 項.名前 == 定義["対象"]:
            項役割.append((項.種別, ("焦点",)))
        else:
            名詞 = re.fullmatch(r"(?P<修飾>.+?[ぁ-ん]る)(?P<主要部>[一-龥々ァ-ヴーA-Za-z・]{1,24})", 項.名前)
            項役割.append((項.種別, ("内部項", 名詞["主要部"] if 名詞 else 項.名前)))
            if 名詞:
                内部修飾 = 名詞["修飾"]
    return {"式": 式, "原子": 原子式, "履歴": 履歴, "修飾原文": 修飾,
            "局所条件": 条件, "項役割": tuple(項役割), "内部修飾": 内部修飾}


def _属性の動作を読む(行):
    """属性を修飾する用言を読む。方式の記載を外側主体の実行へ変えない。"""
    属性 = 行["関係"]["属性"]
    値 = re.sub(r"(?:である|です)$", "", 属性["値"].strip().rstrip("。"))
    名詞 = _種別を読む(値)
    if not 名詞 or 名詞.get("成員関係") or 名詞.get("後置注記"):
        return None
    # 有限の一般用言修飾。主題・動作名の辞書や二値の共通部分推測は持たない。
    一致 = re.fullmatch(
        r"(?:(?P<対象物>[^はがを、,。\n「」『』（）()]{1,80})を)?"
        r"(?P<修飾>個別|一括|順次|一斉|[一-龥々]{1,12}的に)?"
        r"(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})"
        r"(?P<活用>できない|できる|しない|する)", 名詞["修飾"])
    if not 一致 or _限定.search(一致["対象物"] or "") or _限定.search(一致["動作"]):
        return None
    活用 = 一致["活用"]
    修飾, 対象物 = 一致["修飾"] or "", 一致["対象物"]
    # 原子の項は外側対象・属性・被修飾名詞・明示ヲ格。省略した対象物は補わない。
    項 = (属性["対象"], 属性["観点"], 名詞["種別"])
    if 対象物:
        項 += (対象物,)
    原子式 = 原子(修飾 + 一致["動作"] + "する", *項,
                  様相="可能" if 活用.startswith("でき") else "記載")
    式 = 反対(原子式) if 活用 in ("できない", "しない") else 原子式
    根拠 = 命題記載(行["ID"], 式, 行["対応"]["資料"], 行["対応"]["原文"],
                    (行["対応"]["開始"], 行["対応"]["終了"]))
    判定 = 命題推論器((根拠,)).判定(原子式)
    if 判定["判定"] not in ("支持", "反証"):
        return None
    return {"動作": 一致["動作"], "修飾": 修飾, "対象物": 対象物,
            "活用": 活用, "種別": 名詞["種別"], "式": 式.辞書(), "判定": 判定,
            "作用域": "外側対象の属性を修飾する記載。対象自身の実行事実ではない"}


def _名詞区分を読む(行):
    """明示された分類属性の裸名詞。未知の名称を動作・仕組みへ変えない。"""
    属性 = 行["関係"]["属性"]
    if not re.search(r"(?:方式|方法|手順|種類|種別|区分|分類)$", 属性["観点"]):
        return None
    値 = re.sub(r"(?:である|です)$", "", 属性["値"].strip().rstrip("。"))
    if not re.fullmatch(r"[一-龥々ァ-ヴーA-Za-z・]{1,60}", 値) or _限定.search(値):
        return None
    修飾 = next((語 for 語 in ("個別", "一括", "順次", "一斉") if 値.startswith(語) and len(値) > len(語)), "")
    名称 = 値[len(修飾):]
    式 = 原子("記載の名詞区分", 属性["対象"], 属性["観点"], 値)
    return {"値": 値, "修飾": 修飾, "中心名詞": 名称, "式": 式.辞書(),
            "作用域": "資料が明示する分類属性の名詞区分。実行・機構・同義又は排他性は未判定"}


def _名詞区分を対照(左, 右, 軸):
    読解 = [_名詞区分を読む(行) for 行 in (左, 右)]
    if any(項 is None for 項 in 読解):
        return None
    部分 = [行["関係"]["属性"]["対象"] + "の区分は「" + 項["値"] + "」" for 行, 項 in zip((左, 右), 読解)]
    本文 = "資料が明示する「" + 軸 + "」の名詞区分として、" + "、".join(部分) + "です。"
    if 読解[0]["中心名詞"] == 読解[1]["中心名詞"]:
        本文 += "中心名詞「" + 読解[0]["中心名詞"] + "」は共通し、修飾は「" + (読解[0]["修飾"] or "未記載") + "」と「" + (読解[1]["修飾"] or "未記載") + "」です。"
    else:
        本文 += "中心名詞の区分は「" + 読解[0]["中心名詞"] + "」と「" + 読解[1]["中心名詞"] + "」です。異なる名称が同義かどうかは未確定です。"
    本文 += "比較は資料内の名詞区分に限り、未知の名称から仕組み・実行・優劣を補っていません。"
    return 本文, {"種別": "明示属性枠の名詞区分対照", "共通軸": 軸,
                  "対象別": [{"対応": 行["対応"], "読解": 項} for 行, 項 in zip((左, 右), 読解)]}


def _属性を対照(左, 右, 軸):
    読解 = [_属性の動作を読む(行) for 行 in (左, 右)]
    if any(項 is None for 項 in 読解):
        名詞対照 = _名詞区分を対照(左, 右, 軸)
        if 名詞対照:
            return 名詞対照
        raise ValueError("属性の動作・活用又は明示名詞区分の意味軸を安全に読解できません。二記載の文字差だけでは比較できません")
    if len({(項["動作"], 項["種別"]) for 項 in 読解}) != 1:
        raise ValueError("属性に共通の動作・被修飾名詞の意味軸がありません")
    動作 = 読解[0]["動作"]
    部分 = []
    for 行, 項 in zip((左, 右), 読解):
        対象 = 行["関係"]["属性"]["対象"]
        修飾 = "修飾「" + 項["修飾"] + "」で、" if 項["修飾"] else "動作の修飾は未記載で、"
        語態 = {"できる": "可能", "できない": "可能の否定",
                "する": "動作", "しない": "動作の否定"}[項["活用"]]
        対象物 = "作用対象は「" + 項["対象物"] + "」" if 項["対象物"] else "作用対象は未記載"
        部分.append(対象 + "は" + 修飾 + "「" + 動作 + 項["活用"] + "」という" + 語態 +
                    "を記した" + 項["種別"] + "です。" + 対象物 + "です。")
    相違 = [欄 for 欄 in ("修飾", "活用", "対象物") if 読解[0][欄] != 読解[1][欄]]
    表示 = {"修飾": "動作の修飾", "活用": "可能・動作と肯否の記載", "対象物": "作用対象の記載"}
    結論 = "、".join(表示[欄] for 欄 in 相違) + "が異なります。" if 相違 else "この動作・修飾・活用・対象物の記載は共通しています。"
    本文 = 軸 + "は、共通する動作「" + 動作 + "」の" + 読解[0]["種別"] + "として対照できます。" + "".join(部分) + 結論
    本文 += "比較は属性を修飾する記載に限り、外側対象の実行や優劣を確定していません。"
    return 本文, {"種別": "属性の共通動作対照", "共通軸": {"動作": 動作, "被修飾名詞": 読解[0]["種別"]},
                 "対象別": [{"対応": 行["対応"], "読解": 項} for 行, 項 in zip((左, 右), 読解)],
                 "相違欄": 相違}


def _定義を対照(記載, 対象群):
    定義群 = [[行 for 行 in 記載 if 行["関係"]["定義"] and
               _照合語(行["関係"]["定義"]["対象"]) == _照合語(対象)] for 対象 in 対象群]
    if any(not 群 for 群 in 定義群):
        raise ValueError("比較する共通属性又は対象の定義が不足しています")
    定義ID = {行["ID"] for 群 in 定義群 for 行 in 群}
    条件対応 = _条件を結ぶ(記載, 定義ID)
    明示対比 = [行 for 群 in 定義群 for 行 in 群 if (対比 := 行["関係"]["定義"].get("明示対比"))
                 and {_照合語(対比["対象"]), _照合語(行["関係"]["定義"]["対象"])} == set(map(_照合語, 対象群))]
    対象別 = []
    for 対象, 群 in zip(対象群, 定義群):
        候補 = []
        for 行 in 群:
            読解 = _修飾命題を読む(行)
            if not 読解:
                continue
            原子式 = 読解["原子"]
            条件 = tuple(sorted(_照合語(項["対応"]["原文"]) for 項 in 条件対応.get(行["ID"], ())
                                if 項["ID"] not in 定義ID))
            原対象 = 行["関係"]["定義"]["対象"]
            if 明示対比:
                # 源資料自身の明示対比に限り、名詞修飾の主要部を項役割の共通軸へ使う。
                # 実命題の項・内部修飾・各記載の条件は別々に残す。同一個体や条件同値は導かない。
                軸項, 軸条件 = 読解["項役割"], ()
            else:
                軸項 = tuple((項.種別, ("焦点",) if 項.名前 == 原対象 else ("実項", 項.名前)) for 項 in 原子式.項)
                軸条件 = 条件 + tuple(読解["局所条件"])
            軸 = (原子式.述語, 軸項, 原子式.時点, 原子式.様相, 軸条件)
            候補.append((軸, 行, 読解))
        # 外側定義ごとに独立の文脈を作る。内部主語の同名を別定義へ混ぜない。
        根拠 = [命題記載(行["ID"], 読解["式"], 行["対応"]["資料"], 行["対応"]["原文"],
                          (行["対応"]["開始"], 行["対応"]["終了"])) for _, 行, 読解 in 候補]
        for 行 in 記載:
            式 = _根拠主述(行)
            if 式 and 対象 in _式の対象(式) and 行["ID"] not in 定義ID:
                根拠.append(命題記載(行["ID"], 式, 行["対応"]["資料"], 行["対応"]["原文"],
                                     (行["対応"]["開始"], 行["対応"]["終了"])))
        推論 = 命題推論器(tuple(根拠)) if 根拠 else None
        if 推論 and any(推論.判定(読解["原子"])["判定"] == "矛盾" for _, _, 読解 in 候補):
            raise ValueError("同一対象の定義修飾の肯定・否定が競合しています")
        対象別.append((候補, 推論))
    共通 = set.intersection(*(set(項[0] for 項 in 候補) for 候補, _ in 対象別))
    if not 共通:
        raise ValueError("定義に共通の主述・条件の意味軸が未形成です。二定義の並置だけでは比較できません")
    if len(共通) > 8:
        raise ValueError("定義の共通意味軸が多すぎます。比較観点を明示してください")
    成果 = []
    for 軸 in sorted(共通):
        判定群, 根拠群, 説明群 = [], [], []
        for 対象, (候補, 推論) in zip(対象群, 対象別):
            軸候補 = [(行, 読解) for 鍵, 行, 読解 in 候補 if 鍵 == 軸]
            問い = 軸候補[0][1]["原子"]
            判定 = 推論.判定(問い)
            if 判定["判定"] not in ("支持", "反証"):
                raise ValueError("定義の共通主述が未確定又は矛盾しています")
            方向 = 判定["判定"] == "支持"
            表示 = next(読解["修飾原文"] for _, 読解 in 軸候補
                        if (読解["式"].種別 != "否定") == 方向)
            説明群.append(対象 + "の定義は「" + 表示 + "」")
            根拠群.extend(行 for 行, _ in 軸候補)
            判定群.append({"外側対象": 対象, "問い": 問い.辞書(), "判定": 判定,
                           "射影": [{"記載ID": 行["ID"], "修飾原文": 読解["修飾原文"],
                                    "実命題": 読解["式"].辞書(), "履歴": 読解["履歴"],
                                    "局所条件": 読解["局所条件"], "内部修飾": 読解["内部修飾"]} for 行, 読解 in 軸候補]})
        同方向 = 判定群[0]["判定"]["判定"] == 判定群[1]["判定"]["判定"]
        本文 = "共通の主述軸「" + 軸[0] + "」では、" + "、".join(説明群) + "です。"
        本文 += "この軸の記載は共通しています。" if 同方向 else "この軸の明示された肯否が異なります。"
        if 明示対比:
            根拠群.extend(明示対比)
            本文 = "資料自身が示す対比に限ると、" + 本文 + "各定義の修飾・条件の範囲は別々に保持し、同一の項・同一条件での一般法則とは扱いません。"
        成果.append((本文, 根拠群, {"種別": "既存命題による定義対照", "共通軸": 軸,
                                    "対象別": 判定群, "明示対比": [行["対応"] for 行 in 明示対比],
                                    "限界": "当該主述の記載に限る。その他の性質・項・条件の同一性は未判定"}))
    return 成果


def _明示場所を対照(記載, 対象群):
    if len(対象群) != 2:
        return []
    候補 = [行 for 行 in 記載 if 行.get("明示場所対照") and
            {_照合語(項["対象"]) for 項 in 行["明示場所対照"]["対象別"]} == set(map(_照合語, 対象群))]
    if not 候補:
        return []
    値群 = {tuple((項["対象"], 項["場所"], 項["限定"], 項["述部"]) for 項 in 行["明示場所対照"]["対象別"]) for 行 in 候補}
    if len(値群) != 1:
        raise ValueError("同じ対象の明示対比に複数の場所・作用・条件があり、範囲を確定できません")
    行, 読み = 候補[0], 候補[0]["明示場所対照"]
    左, 右 = 読み["対象別"]
    if any(問いの否定を読む(項["作用"].rstrip("。")) or _撤回.search(項["述部"]) for 項 in (左, 右)):
        raise ValueError("否定・撤回された主述を場所の肯定記載へ変えられません")
    本文 = "資料が明示する対比の軸は、各主述の場所です。"
    本文 += 左["対象"] + "については「" + 左["述部"].rstrip("。") + "」、"
    本文 += 右["対象"] + "については「" + 右["述部"].rstrip("。") + "」と記載されています。"
    本文 += "場所格に対応する記載は「" + 左["場所"] + "」と「" + 右["場所"] + "」です。"
    本文 += "この場所の記載は一致しています。" if _照合語(左["場所"]) == _照合語(右["場所"]) else "この場所の記載が異なります。"
    return [(本文, tuple(候補), {"種別": "原資料の明示対比と場所格", "読解": 読み,
                                    "原資料区間": [項["対応"] for 項 in 候補]})]


def _記載理由の本文(行, *, 簡潔=False):
    理由, 目的 = 行["関係"]["理由"], 行["関係"]["目的"]
    if not (理由 or 目的):
        return None
    関係 = 理由 or 目的
    if 関係.get("前文") is None:
        # 引用や括弧の内部にある標識を、外側の因果・用途へ移さない。
        標識 = ("ため", "ので", "から", "により", "によって") if 理由 else ("ために", "ための", "ことを目的として", "ことを目的に")
        try:
            位置群 = _最上位(行["対応"]["原文"], 標識)
        except ValueError:
            return None
        if not 位置群:
            return None
    現象 = 関係.get("結果", 関係.get("手段", ""))
    if _結果式を読む(関係) is None:
        raise ValueError("説明に使う理由・手段の主述が未読解です:" + 現象[:160])
    if 理由:
        前文 = ("資料が扱う事象範囲は「" + 関係["事象範囲"]["対応"]["原文"].rstrip("。") + "」です。この範囲で、"
                if 関係.get("事象範囲") else
                "前文には「" + 関係["前文"]["原文"].rstrip("。") + "」と記載されています。"
                if 関係.get("作用結果参照") else "")
        if 簡潔:
            return 前文 + "資料の理由は「" + 関係["理由"].rstrip("。") + "」。結果は「" + 関係["結果"].rstrip("。") + "」。"
        return 前文 + "資料が示す理由は「" + 関係["理由"].rstrip("。") + "」で、結果は「" + 関係["結果"].rstrip("。") + "」です。"
    if 関係.get("接続") == "連体用途":
        return "資料に記された" + 関係["用途原対象"] + "（" + 関係["種別"] + "）の用途は「" + 関係["目的"] + "」です。その用途の手段は「" + 関係["手段"] + "」と記載されています。"
    if 簡潔:
        return "資料の目的は「" + 関係["目的"].rstrip("。") + "」。手段は「" + 関係["手段"].rstrip("。") + "」。"
    return "目的は「" + 関係["目的"].rstrip("。") + "」です。そのための手段として「" + 関係["手段"].rstrip("。") + "」が記載されています。"


def _要約属性を統合(命題, 記載, 属性表記):
    """同じ属性・実条件の記載を統合。値や様相を短い別の事実へ置き換えない。"""
    条件対応 = _条件を結ぶ(記載, {根拠 for 項 in 命題 for 根拠 in 項.根拠})
    群, 順 = {}, []
    for 番号, 項 in enumerate(命題):
        表記 = 属性表記.get(項.根拠[0]) if len(項.根拠) == 1 else None
        if 表記:
            条件 = tuple(sorted(条件["対応"]["原文"] for 条件 in 条件対応.get(項.根拠[0], ())))
            鍵 = ("属性", 表記["観点"], 表記["数量"], 表記["条件"], 表記["時点"], 条件)
        else:
            鍵 = ("単独", 番号)
        if 鍵 not in 群:
            群[鍵] = []
            順.append(鍵)
        群[鍵].append((項, 表記))
    結果, 統合記録 = [], []
    for 鍵 in 順:
        行群 = 群[鍵]
        if 鍵[0] != "属性":
            結果.extend(項 for 項, _ in 行群)
            continue
        表示, 対象値, 表示済み = [], {}, set()
        for 項, 表記 in 行群:
            対象 = 表記["対象"]
            # 数量は既存器の正準値・単位で照合し、表示上の単位差で不等にしない。
            意味値 = tuple(表記["数量正準"]) if 表記["数量"] else _照合語(表記["値"])
            if 対象 in 対象値 and 対象値[対象] != 意味値:
                raise ValueError("同じ対象・属性・条件の要約値が競合しています:" + 対象)
            対象値[対象] = 意味値
            表現 = 対象 + ("" if 表記["数量"] else "が") + 表記["値"]
            if (対象, 意味値) not in 表示済み:
                表示.append(表現)
                表示済み.add((対象, 意味値))
        根拠 = tuple(dict.fromkeys(根拠 for 項, _ in 行群 for 根拠 in 項.根拠))
        本文 = 鍵[1] + "は" + "、".join(表示) + "。"
        if 鍵[3] is not None:
            本文 = "条件「" + 鍵[3] + "」では、" + 本文
        if 鍵[4] is not None:
            本文 = "時点「" + 鍵[4] + "」の記載：" + 本文
        結果.append(回答命題("属性要約", 本文, 根拠))
        統合記録.append({"観点": 鍵[1], "原命題": [asdict(項) for 項, _ in 行群], "根拠": 根拠,
                        "表記": [表記 for _, 表記 in 行群], "条件": 鍵[5]})
    if 結果:
        結果[0] = replace(結果[0], 本文="資料では、" + 結果[0].本文)
    return 結果, 統合記録


def _構文診断を留保(構造, 記載, 使用, 対象群, *, 限定回答可):
    診断資料 = [(名, 行["全体構文診断"]) for 名, 行 in 構造["資料群"].items()
                if "全体構文診断" in 行]
    if not 診断資料:
        return []
    from .意味資料 import 意味資料を検査, 資料を区分
    if not 限定回答可 or not 意味資料を検査(構造):
        raise ValueError("構文診断のある資料は、原本検査済みの単一対象の定義だけを限定して扱います")
    採用 = [行 for 行 in 記載 if 行["ID"] in 使用]
    for 行 in 採用:
        資料を区分(行["対応"]["原文"], 会話本文=True)
    結果, 済み = [], set()
    for 名前, 注記 in 診断資料:
        for 診断 in 注記["診断"]:
            左, 右 = 診断["開始"], 診断["終了"]
            鍵 = (名前, 左, 右)
            if 鍵 in 済み:
                continue
            済み.add(鍵)
            交差 = [行 for 行 in 記載 if 行["対応"]["資料"] == 名前 and
                    行["対応"]["開始"] < 右 and 左 < 行["対応"]["終了"]]
            if any(行["ID"] in 使用 for 行 in 交差):
                raise ValueError("定義・条件・前文の根拠閉包が構文不整合行と交差しています")
            原文 = 診断["原文"]
            # 未読の否定/撤回/条件を単なる書誌へ格下げしない。
            条件文 = re.sub(r"[0-9]{4}年", "", 原文)
            if _限定.search(条件文) or _指示.match(原文.strip()) or any(
                    any(_対象一致(行, 対象) or 行["明示主語"] and _主体対応(行["明示主語"], 対象)
                        for 対象 in 対象群) for 行 in 交差):
                raise ValueError("構文不整合行の否定・撤回・条件又は同対象記載を未確定書誌へ変えられません")
            for 対象 in 対象群:
                if any(_照合語(対象 + 助詞) in _照合語(原文) for 助詞 in ("は", "が", "とは")):
                    raise ValueError("構文不整合行に同じ対象の未読主述があります")
            使用脚注 = {脚注["原文"] for 行 in 採用 if 行["対応"]["資料"] == 名前 for 脚注 in 行["脚注"]}
            if 使用脚注.intersection(項[0] for 項 in re.finditer(r"\[[0-9]+\]", 原文)):
                raise ValueError("使用した脚注の明示参照が構文不整合行と交差しています")
            結果.append({"種別": "構文診断", "記載ID": 名前 + ":構文診断:" + str(左) + ":" + str(右),
                         "対応": {"資料": 名前, "開始": 左, "終了": 右, "原文": 原文},
                         "本文SHA256": 注記["本文SHA256"], "理由": 診断["理由"],
                         "作用域": 診断["作用域"], "必要資料": 診断["必要資料"]})
    return 結果


