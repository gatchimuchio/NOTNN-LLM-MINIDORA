def _最上位(文, 標識):
    return tuple(最上位位置(文.translate(str.maketrans({"（": "(", "）": ")"})), 標識))


def _作用を読む(文):
    """明示主語・ヲ格・任意サ変を読む。受動の行為者は原文にある時だけ。"""
    文 = re.sub(r"(?:\[[0-9]+\])+$", "", 文.strip().rstrip("。"))
    能動 = re.fullmatch(r"(?P<対象>[^はが、,。\n]{1,80})(?:は|が)(?P<対象物>[^はがを、,。\n]{1,80})を(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})(?P<活用>する|します|した|しました|しない|しません|しなかった)", 文)
    受動 = re.fullmatch(r"(?P<対象物>[^はがを、,。\n]{1,80})(?:は|が)(?P<対象>[^はがを、,。\n]{1,80})(?:によって|により)(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})(?P<活用>される|されます|された|されました|されない|されません|されなかった)", 文)
    一致 = 能動 or 受動
    if not 一致 or any(_指示.match(一致[欄]) or re.search(r"[「」『』（）()]|ため|場合|なら|とき", 一致[欄])
                        for 欄 in ("対象", "対象物")):
        return None
    活用 = 一致["活用"]
    過去 = 活用.endswith(("した", "しました", "しなかった", "された", "されました", "されなかった"))
    否定 = 活用.endswith(("しない", "しません", "しなかった", "されない", "されません", "されなかった"))
    述語 = 一致["対象物"] + "を" + 一致["動作"] + ("した" if 過去 else "する")
    式 = 原子(述語, 一致["対象"])
    return {"対象": 一致["対象"], "対象物": 一致["対象物"], "動作": 一致["動作"],
            "式": 反対(式) if 否定 else 式, "原文": 文,
            "読み": "明示行為者付き受動" if 受動 else "明示主語・ヲ格・サ変"}


def _因果を読む(文):
    """最上位の接続位置で因果を分け、引用内の標識を外側へ使わない。"""
    try:
        位置群 = _最上位(文, ("ため", "ので", "から", "により", "によって"))
    except ValueError:
        return None
    候補 = []
    for 位置, 接続 in 位置群:
        前, 後 = 文[:位置], 文[位置 + len(接続):]
        if 接続 in ("により", "によって"):
            # 明示行為者の受動は原因節ではなく、一つの主述である。
            区切り = [項[0] for 項 in _最上位(文, ("、", ",")) if 項[0] < 位置]
            受動節 = 文[区切り[-1] + 1:] if 区切り else 文
            if _作用を読む(受動節):
                continue
            後 = 後.lstrip("、, ")
        else:
            一致 = re.fullmatch(r"(?:に|で|だ|です|である)?[、,]\s*(.+)", 後, re.S)
            if not 一致:
                continue
            後 = 一致[1]
            if 接続 == "から" and not re.search(r"(?:する|した|ない|である|です|だ)$", 前):
                continue
        if 前.strip() and 後.strip():
            候補.append({"理由": 前.strip(), "結果": 後.strip(), "接続": 接続,
                         "接続位置": 位置})
    return 候補[0] if len(候補) == 1 else None


def _連体用途を読む(定義):
    """同じ連体用途に明示されたサ変手段だけを用途へ結ぶ。"""
    if not 定義 or not 定義.get("種別"):
        return None
    述部 = 定義["述部"]
    try:
        位置群 = _最上位(述部, ("ための",))
    except ValueError:
        return None
    if len(位置群) != 1:
        return None
    位置 = 位置群[0][0]
    一致 = re.fullmatch(r"(?P<対象物>[^はがを、,。\n]{1,80})を(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})して[、,]?\s*(?P<目的>.+?する)", 述部[:位置])
    if not 一致 or re.search(r"場合|なら|とき|[「」『』]", 一致["対象物"]):
        return None
    手段 = 定義["対象"] + "は" + 一致["対象物"] + "を" + 一致["動作"] + "する"
    if _作用を読む(手段) is None:
        return None
    return {"目的": 一致["目的"], "手段": 手段, "接続": "連体用途",
            "原手段": 一致["対象物"] + "を" + 一致["動作"] + "して",
            "用途対象": 定義["対象"], "用途原対象": 定義["原対象"], "種別": 定義["種別"]}


def _明示式(文):
    """既存の関係読解が確定できる主述だけを使用する。未知を原子へ包まない。"""
    文 = 文.strip().rstrip("。！？")
    if _指示.match(文) or re.match(r"(?:ただし|但し|なお|例外)", 文):
        return None
    文 = re.sub(r"ではないです$", "ではない", 文)
    作用 = _作用を読む(文)
    if 作用:
        return 作用["式"]
    try:
        式, _, _ = 関係文を読む(文)
        if 式.種別 not in ("原子", "否定", "連言"):
            return None
        if any(項.種別 not in ("原子", "否定", "連言") for 項 in _式列(式)):
            return None
        return 式
    except ValueError:
        # 既存有限文法にないヲ格を含む単純述部を、原文のまま単一原子へ接続。
        # 主体の省略・別主体・条件・引用・並列の係りは補完しない。
        一致 = re.fullmatch(r"(?P<対象>[^、,。はが\n]{1,80}?)(?:は|が)(?P<述部>[^、,。\n]{1,80})", 文)
        if not 一致 or _指示.match(一致["対象"]):
            return None
        述部 = 一致["述部"]
        限定検査文 = re.sub(r"(?:しない|できない|しません|できません|しなかった|しませんでした)$", "", 述部)
        if re.search(r"は|が|ではなく|でなく|なら|場合|とき|ため|ので|かつ|および|または|[「」『』（）()]", 述部) or _限定.search(限定検査文):
            return None
        否定 = 問いの否定を読む(述部)
        for 尾, 正形 in (("しませんでした", "した"), ("しなかった", "した"), ("しました", "した"),
                         ("できません", "できる"), ("できない", "できる"), ("できます", "できる"),
                         ("しません", "する"), ("しない", "する"), ("します", "する")):
            if 述部.endswith(尾):
                述部 = 述部[:-len(尾)] + 正形
                break
        else:
            if 否定:
                return None
        式 = 原子(述部, 一致["対象"])
        return 反対(式) if 否定 else 式


def _式列(式):
    yield 式
    for 子 in 式.子:
        yield from _式列(子)


def _式の対象(式):
    return {項.名前 for 原子式 in 原子群(式) for 項 in 原子式.項 if 項.種別 == "定数"}


def _定義明示(一致):
    # 「Xは青い/安全です」の主述記載を概念定義へ変えない。
    # 定義接続か、原文で明示された種別・呼称関係だけを扱う。
    return (一致["接続"] != "は" or 一致["終止"].startswith("を")
            or bool(re.search(r"の(?:一種|総称|こと|名称)", 一致["述部"]))
            or _種別を読む(一致["述部"]) is not None)


def _種別を読む(述部):
    # 連体節・用途・性質の修飾を受けた末尾名詞を種別役割として保持する。
    # 裸の「安全/青い」を任意の名詞種別と推測せず、題材の概念辞書も持たない。
    照合 = 述部.lstrip("、, ").rstrip()
    注記 = re.search(r"[（(][^（）()]*[）)]$", 照合)
    if 注記:
        照合 = 照合[:注記.start()].rstrip()
    所属 = re.fullmatch(r"(?P<母集団>.+)の(?P<成員>一つ|ひとつ|一種|一種類|一分野|一部分|一員)", 照合)
    if 所属:
        # 「Xは群の一つ」の成員関係は、コピュラの有無に依存しない。
        # 母集団の原記載と実際の末尾名詞を保ち、単なる性質から種別を補わない。
        名詞 = re.search(r"[一-龥々ァ-ヴーA-Za-z・]{1,24}$", 所属["母集団"])
        if not 名詞 or _限定.search(名詞[0]):
            return None
        return {"修飾": 所属["母集団"][:名詞.start()], "種別": 名詞[0],
                "成員関係": 所属.groupdict(), "後置注記": 注記[0] if 注記 else ""}
    一致 = re.fullmatch(r"(?P<修飾>.+?(?:[ぁ-ん]る|する|した|している|である|となる|ための|用の|向けの|という|[ぁ-ん]い|な|の))(?P<種別>[一-龥々ァ-ヴーA-Za-z・]{1,24}(?:や[一-龥々ァ-ヴーA-Za-z・]{1,24}){0,3}|もの|こと)", 照合)
    if not 一致 or _限定.search(一致["種別"]):
        return None
    return {**一致.groupdict(), "後置注記": 注記[0] if 注記 else ""}


def _定義文を読む(文):
    前置範囲, 読む文 = "", 文
    範囲 = re.match(r"^([^、,。\n]{1,80}において[、,])\s*(.+)$", 文, re.S)
    if 範囲:
        前置範囲, 読む文 = 範囲[1], 範囲[2]
    try:
        # 照合用の一文字対一文字の丸括弧表記。原文と位置は変更しない。
        主格 = next(最上位位置(読む文.translate(str.maketrans({"（": "(", "）": ")"})), ("とは", "というのは", "は")), None)
    except ValueError:
        return None
    if 主格 is None or 主格[0] == 0:
        return None
    位置, 接続 = 主格
    主語, 内容 = 読む文[:位置], 読む文[位置 + len(接続):]
    同格 = re.match(r"^[、, ]*(?P<名称>「[^「」]{1,80}」|[一-龥々ァ-ヴーA-Za-z0-9_-]{1,80})で[、,]\s*(?P<内容>.+)$", 内容, re.S)
    補足 = {"前置範囲": 前置範囲} if 前置範囲 else {}
    if 同格 and 主語.startswith("対比されている"):
        補足.update({"同格主語": 主語, "同格接続": "で、"})
        主語, 内容 = 同格["名称"], 同格["内容"]
    終止 = re.fullmatch(r"(?P<述部>.+?)(?P<終止>のことである|のことです|のこと|である|です|だ|をいう|を指す|を意味する)(?:\[[0-9]+\])*[。]?$", 内容, re.S)
    if not 終止:
        名詞止め = re.fullmatch(r"(?P<述部>.+?)(?:\[[0-9]+\])*。", 内容, re.S)
        if not 名詞止め or _種別を読む(名詞止め["述部"]) is None:
            return None
        return {"主語": 主語, "接続": 接続, "述部": 名詞止め["述部"], "終止": "", **補足}
    return {"主語": 主語, "接続": 接続, **終止.groupdict(), **補足}


def _明示主語(文):
    # 意味上の範囲句は主体ではない。対比文の最後の明示主格も原文に残して読む。
    末節 = re.split(r"[、,]", 文)[-1]
    候補文 = re.sub(r"^(?:狭義|広義|一般|通常|厳密)(?:では|には|は)[、,]?", "", 末節)
    if 候補文.startswith(("ただし", "但し", "なお", "例外")):
        return None
    try:
        主格 = next(最上位位置(候補文.translate(str.maketrans({"（": "(", "）": ")"})), ("は", "が")), None)
    except ValueError:
        return None
    if not 主格 or not 0 < 主格[0] <= 128:
        return None
    主語 = re.sub(r"[（(].*?[）)]", "", 候補文[:主格[0]]).strip()
    if _指示.match(主語) or re.search(r"[、,。\n]|場合|条件|時点|では|なら", 主語):
        return None
    return 主語


def _主体対応(源, 対象):
    if _照合語(源.strip("「」")) == _照合語(対象):
        return True
    if 源.startswith("「"):
        return False
    群 = re.split(r"および|及び|と", 源)
    return 1 < len(群) <= 4 and any(_照合語(項) == _照合語(対象) for 項 in 群)


def _照合語(文):
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", 文)).casefold()


def _文群(本文):
    """句点・改行の原位置を保持。括弧・引用の途中で分割しない。"""
    群, 開始, 引用 = [], 0, []
    開閉 = {"「": "」", "『": "』", "（": ")", "(": ")", "[": "]"}
    for 位置, 字 in enumerate(本文):
        if 字 in 開閉:
            引用.append(開閉[字])
        elif 引用 and (")" if 字 in (")", "）") else 字) == 引用[-1]:
            引用.pop()
        if not 引用 and 字 in "。！？\n":
            if 本文[開始:位置 + 1].strip():
                左 = 開始 + len(本文[開始:位置 + 1]) - len(本文[開始:位置 + 1].lstrip())
                右 = 位置 + 1 - (len(本文[開始:位置 + 1]) - len(本文[開始:位置 + 1].rstrip()))
                群.append((左, 右))
            開始 = 位置 + 1
    if 本文[開始:].strip():
        群.append((開始 + len(本文[開始:]) - len(本文[開始:].lstrip()), len(本文.rstrip())))
    if 引用:
        raise ValueError("資料の引用・括弧が閉じていません")
    if len(群) > 2048:
        raise ValueError("資料の記載文数上限")
    return 群


def _明示場所対照を読む(文):
    """原資料の対比標識と二つの明示主格を、同じ場所格へ結ぶ。"""
    try:
        接続 = _最上位(文, ("のに対し、", "のに対して、"))
    except ValueError:
        return None
    if len(接続) != 1:
        return None
    位置, 標識 = 接続[0]
    部分 = []
    for 節 in (文[:位置], 文[位置 + len(標識):]):
        try:
            主格 = _最上位(節, ("は", "が"))
        except ValueError:
            return None
        if not 主格 or not 0 < 主格[0][0] <= 80:
            return None
        対象 = 節[:主格[0][0]].strip()
        述部 = 節[主格[0][0] + len(主格[0][1]):]
        if _指示.match(対象) or re.search(r"[、,。\n「」『』（）()]|場合|条件", 対象):
            return None
        場所 = re.fullmatch(r"(?P<限定>主に|主として)?(?P<場所>[^にでをはが、,。\n]{1,80})(?P<格>を場として|で|に)(?P<作用>.+)", 述部, re.S)
        if not 場所 or re.search(r"[「」『』（）()]|場合|なら|とき", 場所["場所"]) or not re.search(r"る|し|された|した", 場所["作用"]):
            return None
        部分.append({"対象": 対象, "述部": 述部, "場所": 場所["場所"],
                     "格": 場所["格"], "限定": 場所["限定"] or "", "作用": 場所["作用"]})
    if _照合語(部分[0]["対象"]) == _照合語(部分[1]["対象"]):
        return None
    return {"軸": "明示された主述の場所", "標識": 標識, "対象別": 部分,
            "限界": "原資料が対比した主述の場所格に限る。次元・用途・行為者の世界知識は補わない"}


def 記載関係を読む(構造):
    記載 = []
    for 名前 in 構造["資料順"]:
        本文 = 結果を復元(構造["資料群"][名前]["資料"]).本文
        先行, 節番号 = None, 0
        for 開始, 終了 in _文群(本文):
            文 = 本文[開始:終了]
            if re.fullmatch(r"#{1,6}\s+.*", 文):
                先行 = None
                節番号 += 1
                continue
            定義, 属性, 因果, 目的 = _定義文を読む(文), _属性.fullmatch(文), _因果を読む(文), _目的.fullmatch(文)
            if 属性 and re.search(r"を|について|ながら|なら|ため|ので", 属性["対象"] + 属性["観点"]):
                属性 = None
            if 文.startswith(("ただし", "但し", "なお", "例外")) or _指示.match(文):
                定義 = 属性 = None
            主語, 原対象, 述部 = "", "", ""
            if 定義:
                原対象, 述部 = 定義["主語"].strip(), 定義["述部"].strip()
                # 読み・外国語名の括弧は原文側に残し、対象照合では外側の名称を使う。
                主語 = re.sub(r"[（(].*?[）)]", "", 原対象).strip().strip("「」")
            elif 属性:
                主語 = 属性["対象"].strip()
            対応 = {"資料": 名前, "開始": 開始, "終了": 終了, "原文": 文}
            関係 = {"定義": None, "叙述": None, "属性": None, "理由": None, "目的": None}
            if 定義 and 主語 and not _指示.match(主語) and len(主語) <= 128:
                項 = {"対象": 主語, "原対象": 原対象, "述部": 述部.lstrip("、, "), "終止": 定義["終止"]}
                項.update({鍵: 定義[鍵] for 鍵 in ("前置範囲", "同格主語", "同格接続") if 鍵 in 定義})
                if 定義.get("同格主語", "").startswith("対比されている") and 記載:
                    先行定義 = [前 for 前 in 記載 if 前["関係"]["定義"] and 前["対応"]["資料"] == 名前
                                and 前["節"] == 節番号 and 前["段落"] == 本文.count("\n", 0, 開始) - 1]
                    if len(先行定義) == 1:
                        前 = 先行定義[0]
                        項["明示対比"] = {"対象": 前["関係"]["定義"]["対象"], "対応": 前["対応"],
                                           "標識": 定義["同格主語"]}
                種別 = _種別を読む(項["述部"])
                if 種別:
                    項.update(種別)
                関係["定義" if _定義明示(定義) else "叙述"] = 項
                先行 = 主語
            if 属性 and not _指示.match(属性["対象"]):
                関係["属性"] = {"対象": 属性["対象"].strip(), "観点": 属性["観点"].strip(), "値": 属性["値"].strip()}
                先行 = 属性["対象"].strip()
            elif not 定義:
                主格 = re.match(r"^([^、。\n]{1,128}?)(?:は|が)", 文)
                if 主格 and not _指示.match(主格[1]) and not 主格[1].startswith(("ただし", "但し", "なお")):
                    先行 = re.sub(r"[（(].*?[）)]", "", 主格[1]).strip()
            数値 = 数値記載文.fullmatch(文)
            if 数値:
                関係["属性"] = {"対象": 数値["対象"], "観点": 数値["属性"],
                               "値": 数値["数"] + 数値["単位"] + (数値["比較"] or "") + (数値["終止"] or ""),
                               "条件": 数値["条件"], "時点": 数値["時点"]}
                先行 = 数値["対象"]
            if 因果:
                関係["理由"] = 因果
            if 目的:
                関係["目的"] = {"目的": 目的["前"].strip(), "手段": 目的["後"].strip()}
            elif not 因果:
                関係["目的"] = _連体用途を読む(関係["定義"])
            # 「そのため」の前文参照は明示された連続二文に限り保持する。
            if 文.startswith(("そのため、", "このため、", "したがって、")) and 記載 and 記載[-1]["対応"]["資料"] == 名前:
                前 = 記載[-1]
                if not 前["限定"] and not _指示.match(前["対応"]["原文"]):
                    関係["理由"] = {"理由": 前["対応"]["原文"].rstrip("。"), "結果": 文.split("、", 1)[1], "接続": "前文参照", "前文": 前["対応"]}
            式 = _明示式(文)
            行 = {"ID": 名前 + ":" + str(開始) + ":" + str(終了), "対応": 対応,
                         "関係": 関係, "限定": bool(_限定.search(文)), "先行主語": 先行,
                         "明示主語": _明示主語(文),
                         "節": 節番号, "段落": 本文.count("\n", 0, 開始), "命題": 式.辞書() if 式 else None,
                         "脚注": [{"原文": 項[0], "開始": 開始 + 項.start(), "終了": 開始 + 項.end(),
                                    "検証": "原資料の参照表記位置。参照先の正確性は未検証"}
                                   for 項 in re.finditer(r"\[[0-9]+\]", 文)]}
            場所対照 = _明示場所対照を読む(文)
            if 場所対照:
                行["明示場所対照"] = 場所対照
            if 関係["理由"]:
                _作用結果を結ぶ(行, 記載)
            記載.append(行)
    return 記載


def _作用結果を結ぶ(行, 先行記載):
    """直前の一意な作用結果への明示修飾参照。記事名から主体を補わない。"""
    理由 = 行["関係"]["理由"]
    _事象範囲を結ぶ(行, 先行記載)
    一致 = re.match(r"^この(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})された(?P<対象物>[^はが、,。\n]{1,80})(?:は|が)", 理由["理由"])
    if not 一致 or not 先行記載:
        return
    同段落 = [前 for 前 in 先行記載 if (前["対応"]["資料"], 前["節"], 前["段落"]) ==
               (行["対応"]["資料"], 行["節"], 行["段落"])]
    候補 = [(前, 作用) for 前 in 同段落 if (作用 := _作用を読む(前["対応"]["原文"]))
            and (作用["対象物"], 作用["動作"]) == (一致["対象物"], 一致["動作"])]
    if len(候補) != 1 or 候補[0][0] != 先行記載[-1] or 候補[0][1]["式"].種別 == "否定":
        return
    前, 作用 = 候補[0]
    理由.update({"前文": 前["対応"], "対象作用": 作用["式"].辞書(),
                 "作用結果参照": {"原文": 一致[0], "対象物": 一致["対象物"], "動作": 一致["動作"],
                                "根拠ID": 前["ID"], "読み": 作用["読み"]}})


def _事象範囲を結ぶ(行, 先行記載):
    """明示事象の供給源→同じ受取先→この供給物の原因を資料内で結ぶ。

    事象と結果の異なる動詞を世界同義にせず、明示事象の範囲を残す。
    """
    理由 = 行["関係"]["理由"]
    if 理由["接続"] not in ("により", "によって"):
        return
    結果式 = _明示式(理由["結果"])
    if 結果式 is None or len(_式の対象(結果式)) != 1:
        return
    受取先 = next(iter(_式の対象(結果式)))
    同段落 = [前 for 前 in 先行記載 if (前["対応"]["資料"], 前["節"], 前["段落"]) ==
               (行["対応"]["資料"], 行["節"], 行["段落"])]
    候補 = []
    for 前 in 同段落:
        文 = 前["対応"]["原文"]
        一致 = re.fullmatch(r"(?P<前置>.*?)(?P<主体句>[^、,はが。\n]{1,80})が(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})して(?P<同伴動作>[^は、,。\n]{1,40})ときの(?P<供給物>[一-龥々ァ-ヴーA-Za-z・]{1,40})源は(?P<供給元>.+)", 文)
        if not 一致 or re.search(r"[「」『』（）()]", 一致["前置"] + 一致["主体句"]):
            continue
        主体句 = 一致["主体句"]
        # 受取先が後節でも明示される場合だけ、前置の格句を範囲として残す。
        if 主体句 != 受取先 and not re.fullmatch(r".+(?:に|で)" + re.escape(受取先), 主体句):
            continue
        供給物 = 一致["供給物"]
        供給 = re.fullmatch(r"(?P<供給>.+" + re.escape(供給物) + r")が(?P<形態>[^、,。\n]{1,40})として" +
                          re.escape(受取先) + r"に与えられ[、,]\s*この" + re.escape(供給物), 理由["理由"])
        if not 供給:
            continue
        # 別の供給源についての原因を事象へ移さない。名詞の列挙は原資料のまま。
        名前群 = re.split(r"や|、|,|そして|および|及び|と", 一致["供給元"].removesuffix("である。").removesuffix("です。"))
        実供給元 = 供給["供給"][:-len(供給物)].removesuffix("の")
        実名前群 = re.split(r"や|、|,|および|及び|と", 実供給元)
        名前群 = [名.strip() for 名 in 名前群 if 名.strip()]
        実名前群 = [名.strip() for 名 in 実名前群 if 名.strip()]
        名称対応 = []
        if not 0 < len(名前群) == len(実名前群) <= 4:
            continue
        for 名 in 実名前群:
            一致名 = [元 for 元 in 名前群 if _照合語(元) == _照合語(名)]
            if not 一致名 and "の" not in 名:
                # 同じ局所記載の一意な裸名再出現。元の修飾・所有者は原文へ残す。
                一致名 = [元 for 元 in 名前群 if _照合語(元.split("の")[-1]) == _照合語(名)]
            if len(一致名) != 1:
                break
            名称対応.append({"元表記": 一致名[0], "再出現": 名})
        if len(名称対応) != len(実名前群) or len({項["元表記"] for 項 in 名称対応}) != len(名前群):
            continue
        式 = 原子(一致["動作"] + "する", 受取先)
        候補.append((前, 式, {"主体": 受取先, "原主体句": 主体句,
                                "動作": 一致["動作"], "同伴動作": 一致["同伴動作"],
                                "供給物": 供給物, "供給元": 一致["供給元"], "供給形態": 供給["形態"],
                                "局所名称対応": 名称対応}))
    if len(候補) == 1:
        前, 式, 読み = 候補[0]
        理由.update({"前文": 前["対応"], "対象作用": 式.辞書(),
                     "事象範囲": {"対応": 前["対応"], "読み": 読み,
                                  "限界": "同じ事象範囲で記された供給と原因。事象と結果を世界同義にしない"}})


def _結果式を読む(関係):
    現象 = 関係.get("結果", 関係.get("手段", ""))
    式 = _明示式(現象)
    if 式 is not None:
        return 式
    if 関係.get("作用結果参照"):
        # 省略行為者を外側主体へ代入せず、可能と記された効果だけを保持。
        可能 = re.fullmatch(r"(?P<作用>[^はが、,。\n]{1,80})ことが可能(?:となる|である|です)(?:\[[0-9]+\])*[。]?", 現象)
        if 可能 and not re.search(r"ため|場合|なら|とき|[「」『』（）()]", 可能["作用"]):
            return 原子(可能["作用"], 様相="可能")
    return None


def _述文(定義):
    述部 = 定義["述部"].rstrip("。")
    前置 = 定義.get("前置範囲", "")
    if re.search(r"[、,]|狭義|広義|場合|条件|のみ", 述部):
        return 前置 + 定義["原対象"] + "の定義・記載：" + 述部 + 定義["終止"] + "。"
    return 前置 + 定義["原対象"] + "は" + 述部 + "です。"


def _対象一致(記載, 対象):
    語 = _照合語(対象)
    関係 = 記載["関係"]
    return any(項 and _照合語(項["対象"]) == 語 for 項 in (関係["定義"], 関係["叙述"], 関係["属性"]))


def _補足の文脈を束縛(行, 定義群, 記載):
    """同じ原段落の先行中核へ結べる補足だけ。別対象の段落を一般化しない。"""
    座標 = (行["対応"]["資料"], 行["節"], 行["段落"])
    候補 = [定義 for 定義 in 定義群 if
            (定義["対応"]["資料"], 定義["節"], 定義["段落"]) == 座標 and
            定義["対応"]["終了"] <= 行["対応"]["開始"]]
    if not 候補:
        return False
    中核 = max(候補, key=lambda 定義: 定義["対応"]["開始"])
    主体 = 中核["関係"]["定義"]["対象"]
    間 = [前 for 前 in 記載 if (前["対応"]["資料"], 前["節"], 前["段落"]) == 座標 and
          中核["対応"]["終了"] <= 前["対応"]["開始"] < 行["対応"]["開始"]]
    # 同名の明示主語でも、別主体の定義・叙述や未読解の文脈を越えて補足しない。
    # 原見出しの語から未知の親子関係を作らず、遠方の段落も同義にしない。
    return all(_対象一致(前, 主体) for 前 in 間)


def _説明対象一致(記載, 対象):
    if _対象一致(記載, 対象):
        return True
    if 記載["命題"]:
        if any(_照合語(項) == _照合語(対象) for 項 in _式の対象(命題を復元(記載["命題"]))):
            return True
    理由 = 記載["関係"]["理由"] or 記載["関係"]["目的"]
    if 理由:
        式 = _明示式(理由.get("結果", 理由.get("手段", "")))
        return 式 is not None and any(_照合語(項) == _照合語(対象) for 項 in _式の対象(式))
    return False


def _観点一致(記載, 観点):
    # 属性が読めている場合、値・条件内の同じ語を属性名へ移さない。
    属性 = 記載["関係"]["属性"]
    if 属性:
        return _照合語(属性["観点"]) == _照合語(観点)
    主述 = 記載["関係"]["定義"] or 記載["関係"]["叙述"]
    if 主述:
        return _照合語(観点) in _照合語(主述["述部"])
    if 記載["命題"]:
        return any(_照合語(観点) in _照合語(項.述語)
                   for 項 in 原子群(命題を復元(記載["命題"])))
    return False


def _現象を照合(本文, 対象群, 焦点群, 肯否):
    """結果節の主語と述語を既存命題の同じ原子で照合。全文の語共存は使わない。"""
    式 = _明示式(本文)
    if 式 is None:
        try:
            主格 = _最上位(本文, ("は", "が"))
        except ValueError:
            主格 = ()
        # 読めない別属性・別主体を質問主体の文字共存だけで候補にしない。
        if 主格 and not any(_主体対応(本文[:主格[0][0]].strip(), 対象) for 対象 in 対象群) and not any(
                _照合語(対象 + 助詞) in _照合語(本文) for 対象 in 対象群 for 助詞 in ("は", "が")):
            return False
        raise ValueError("理由の結果又は手段の主述・否定の係り先が未確定:" + 本文[:160])
    return _問いの式を照合(式, 対象群, 焦点群, 肯否)


def _問いの式を照合(式, 対象群, 焦点群, 肯否):
    if not 対象群:
        raise ValueError("理由を問う主体が未確定です")
    推論 = 命題推論器((命題記載("結果", 式, "結果節", "主述役割の照合", (0, 0)),))
    for 対象 in 対象群:
        実対象 = [項 for 項 in _式の対象(式) if _照合語(項) == _照合語(対象)]
        if len(実対象) != 1:
            continue
        if not 焦点群:
            return True
        for 焦点 in 焦点群:
            問い = _明示式(実対象[0] + "は" + 焦点)
            if 問い is None:
                raise ValueError("問われた関係焦点の主述を照合できません:" + 焦点)
            if 肯否 != "未指定" and 問いの否定を読む(焦点) != (肯否 == "否定"):
                raise ValueError("問いの述部とKernelの肯否が不一致です")
            判定 = 推論.判定(問い)["判定"]
            if 判定 == "矛盾":
                raise ValueError("結果節の肯定・否定が競合しています")
            if 判定 != "支持":
                break
        else:
            return True
    return False


def _実参照資料(構造):
    資料 = []
    for 名前 in 構造["資料順"]:
        値 = 結果を復元(構造["資料群"][名前]["資料"])
        参照 = tuple(r for r in 値.参照 if r.本文 == 値.本文)
        if not 参照:
            参照 = (参照資料("提示:" + 名前, 名前, "利用者提示", 本文=値.本文),)
        資料.extend(参照)
    return 能力結果(True, "", 参照=tuple(資料))


def _数量区間を選ぶ(構造, 対象, 属性):
    """数値器に渡す実区間と原本への対応。別属性の有効な記載は改変せず保全。"""
    記載 = 記載関係を読む(構造)
    数値ID = {行["ID"] for 行 in 記載 if (数値 := 数値記載文.fullmatch(行["対応"]["原文"])) and
              数値["対象"] == 対象 and 数値["属性"] == 属性}
    条件対応 = _条件を結ぶ(記載, {行["ID"] for 行 in 記載})
    数値条件 = {条件["ID"] for 番号 in 数値ID for 条件 in 条件対応.get(番号, ())}
    非数値条件 = {条件["ID"] for 番号, 群 in 条件対応.items() if 番号 not in 数値ID for 条件 in 群}
    参照群, 対応群 = [], []
    for 行 in 記載:
        文 = 行["対応"]["原文"]
        数値, 記載属性 = 数値記載文.fullmatch(文), 行["関係"]["属性"]
        if 数値:
            必要 = 数値["対象"] == 対象 and 数値["属性"] == 属性
        elif 行["限定"]:
            # 未読解の条件・年度・例外を抜いて数値だけを成立させない。
            必要 = 行["ID"] in 数値条件 or 行["ID"] not in 非数値条件
        elif 記載属性:
            必要 = 記載属性["対象"] == 対象 and 記載属性["観点"] == 属性
        elif 行["命題"] or 行["関係"]["定義"] or 行["関係"]["叙述"]:
            必要 = False
        else:
            必要 = True
        if not 必要:
            continue
        名前 = 行["対応"]["資料"]
        元 = 結果を復元(構造["資料群"][名前]["資料"])
        開始, 終了 = 行["対応"]["開始"], 行["対応"]["終了"]
        if 元.本文[開始:終了] != 文:
            raise ValueError("数値原文区間の対応不一致")
        元参照 = next((項 for 項 in 元.参照 if 項.本文 == 元.本文), None)
        元ID = 元参照.識別子 if 元参照 else "提示:" + 名前
        区間ID = 元ID + "@原文区間:" + str(開始) + ":" + str(終了)
        参照群.append(参照資料(区間ID, 元参照.題名 if 元参照 else 名前,
                              "原文区間:" + (元参照.出典 if 元参照 else "利用者提示"),
                              URL=元参照.URL if 元参照 else "", 公開時刻=元参照.公開時刻 if 元参照 else None, 本文=文))
        対応群.append({"参照ID": 区間ID, "原資料": 名前, "元参照ID": 元ID,
                       "開始": 開始, "終了": 終了, "原文": 文, "原本文印": 指紋(元.本文)})
    if not 参照群:
        raise ValueError("対象・属性の実数値区間がありません")
    return 能力結果(True, "", 参照=tuple(参照群)), 対応群


def _数値を読む(構造, 対象, 属性, 単位):
    区間資料, 対応 = _数量区間を選ぶ(構造, 対象, 属性)
    return 記載数量を読む(区間資料, {"対象": 対象, "属性": 属性, "単位": 単位}), 対応


def _根拠主述(行):
    関係 = 行["関係"]["理由"] or 行["関係"]["目的"]
    if 関係:
        if 関係.get("対象作用") and not 関係.get("事象範囲"):
            return 命題を復元(関係["対象作用"])
        return _結果式を読む(関係)
    if 行["命題"]:
        return 命題を復元(行["命題"])
    return None


def _競合を検査(構造, 記載, 対象群, 使用):
    """説明でも既存命題判定・数量採用に戻り、矛盾を並列確定しない。"""
    命題群, 採用命題, 数量欄 = [], [], set()
    for 行 in 記載:
        # 理由採用で確認した同じ結果・手段の主述も競合検査へ渡す。
        # 原因側の主述を、問われた結果の主述に読み替えない。
        式 = _根拠主述(行)
        if 式 is not None:
            if not 対象群 or _式の対象(式).intersection(対象群):
                命題群.append(命題記載(行["ID"], 式, 行["対応"]["資料"], 行["対応"]["原文"],
                                          (行["対応"]["開始"], 行["対応"]["終了"])))
                if 行["ID"] in 使用:
                    採用命題.append(命題群[-1])
        数値 = 数値記載文.fullmatch(行["対応"]["原文"])
        if 数値 and 行["ID"] in 使用:
            if 数値["単位"] not in _単位:
                raise ValueError("数値記載の単位が未対応:" + 数値["単位"])
            数量欄.add((数値["対象"], 数値["属性"], 数値["単位"]))
    if 命題群:
        推論 = 命題推論器(tuple(命題群))
        for 項 in 採用命題:
            if 推論.判定(項.式)["判定"] == "矛盾":
                raise ValueError("同一主述の肯定・否定が競合しています:" + 項.原文)
    if 数量欄:
        for 対象, 属性, 単位 in sorted(数量欄):
            try:
                _数値を読む(構造, 対象, 属性, 単位)
            except 会話処理不成立 as 例外:
                raise ValueError("説明する数値の競合・適用条件が未確定:" + 例外.理由) from 例外
    # 定義の名詞修飾も、読めた同一主述の肯否を既存命題器へ戻す。
    # 内部主語は外側の定義ごとの文脈に残し、別対象の定義へ混ぜない。
    定義対象 = {_照合語(行["関係"]["定義"]["対象"]) for 行 in 記載
                if 行["ID"] in 使用 and 行["関係"]["定義"]}
    for 対象 in 定義対象:
        根拠, 問い = [], []
        for 行 in 記載:
            定義 = 行["関係"]["定義"]
            if 定義 and _照合語(定義["対象"]) == 対象:
                読解 = _修飾命題を読む(行)
                if 読解:
                    根拠.append(命題記載(行["ID"], 読解["式"], 行["対応"]["資料"],
                                           行["対応"]["原文"], (行["対応"]["開始"], 行["対応"]["終了"])))
                    if 行["ID"] in 使用:
                        問い.append(読解["原子"])
            elif not 定義:
                式 = _根拠主述(行)
                if 式 and 対象 in {_照合語(項) for 項 in _式の対象(式)}:
                    根拠.append(命題記載(行["ID"], 式, 行["対応"]["資料"], 行["対応"]["原文"],
                                           (行["対応"]["開始"], 行["対応"]["終了"])))
        if 根拠:
            推論 = 命題推論器(tuple(根拠))
            if any(推論.判定(式)["判定"] == "矛盾" for 式 in 問い):
                raise ValueError("同一対象の定義修飾の肯定・否定が競合しています")


def _条件を結ぶ(記載, 使用, *, 未確定=None):
    """節内の明示広域参照を保持。省略した限定の主体を直近だけへ狭めない。"""
    同伴 = {}
    採用群 = [行 for 行 in 記載 if 行["ID"] in 使用]
    def 作用域を保留(条件, 理由):
        文 = 条件["対応"]["原文"]
        # 誤り・撤回を未知条件へ格下げして、元の定義を採用しない。
        if _撤回.search(文):
            raise ValueError("採用候補に誤り・撤回・訂正の記載があります。訂正版を確認してください:" + 文[:160])
        if 未確定 is None:
            raise ValueError(理由 + ":" + 文[:160])
        未確定[条件["ID"]] = {"記載ID": 条件["ID"], "対応": 条件["対応"], "理由": 理由,
                               "必要資料": "この記載の適用主体・対象・範囲を明示した資料が必要です。"}
    for 番号, 条件 in enumerate(記載):
        if not 条件["限定"]:
            continue
        節群 = [行 for 行 in 記載 if (行["対応"]["資料"], 行["節"]) ==
                                     (条件["対応"]["資料"], 条件["節"])]
        採用節 = [行 for 行 in 採用群 if 行 in 節群]
        if not 採用節:
            continue
        文 = 条件["対応"]["原文"]
        # 文頭の「〜例では、」はその例の閉じた記載範囲である。
        # 同名主体の別の事象範囲へ、別段落の例条件を移さない。
        if re.match(r"^[^、,。\n]{1,160}例では[、,]", 文) and not re.search(
                r"上記|下記|以下|以上|両者|この説明|その説明|全て|すべて|(?:これら|それら)(?:の?(?:説明|記載|関係)|は|が)", 文):
            事象採用 = [行 for 行 in 採用節 if (行["関係"]["理由"] or {}).get("事象範囲")]
            if 事象採用 and all(行["段落"] != 条件["段落"] for 行 in 事象採用):
                continue
        明示主体 = (条件["関係"]["定義"] or 条件["関係"]["叙述"] or 条件["関係"]["属性"] or {}).get("対象")
        主体群 = {項["対象"] for 行 in 節群 for 項 in
                  (行["関係"]["定義"], 行["関係"]["叙述"], 行["関係"]["属性"]) if 項}
        for 行 in 節群:
            主述 = _根拠主述(行)
            if 主述 is not None:
                主体群.update(_式の対象(主述))
        if not 明示主体 and 条件["明示主語"]:
            明示主体 = 条件["明示主語"]
        広域 = bool(re.match(r"(?:上記|下記|以下|以上|これら|それら|両者)(?:の|は|を|に|[、,]|[1-9一二三四五六七八九](?:つ|件|個|行))", 文))
        参照 = bool(_指示.match(文))
        隣接採用 = [行 for 行 in 採用節 if abs(記載.index(行) - 番号) <= 1 or 行["段落"] == 条件["段落"]]
        if 参照 and not (広域 or 明示主体 or 隣接採用):
            # 「それ/この」の未結合な別段落参照を、離れた採用定義へ移さない。
            # 採用主述の直後・同段落にある未知参照は従来どおり確認待ちとする。
            continue
        if not (明示主体 or 広域 or 参照 or 隣接採用):
            # 採用記載への明示的結合のない別区間のcaption/日付/条件は全文へ残す。
            # 遠方記載を、位置だけで回答定義の前提へ変換しない。
            continue
        前 = 記載[番号 - 1] if 番号 and 記載[番号 - 1] in 節群 else None
        限定述部 = re.fullmatch(r"(?:ただし|但し)[、,]?\s*.+?(?:場合|とき)(?:に|は|には)(.+?)[。]?$", 文)
        動作核 = re.search(r"([一-龥々]+)(?:する|した|しない|しません)[。]?$", 限定述部[1]) if 限定述部 else None
        前主述 = _根拠主述(前) if 前 else None
        局所動作 = (前主述 and 動作核 and len(_式の対象(前主述)) == 1
                    and all(動作核[1] in 項.述語 for 項 in 原子群(前主述)))
        if 局所動作:
            # 条件文が同じ明示動作を指す場合だけ直前主述へ結ぶ。別属性へ移さない。
            範囲 = [前] if 前 in 採用節 else []
        elif 広域:
            # 原資料の節という境界を超えない。上記/以下の方向も保持する。
            範囲 = [行 for 行 in 採用節 if abs(行["段落"] - 条件["段落"]) <= 1 and
                    (not 文.startswith(("上記", "以上")) or 行["対応"]["開始"] < 条件["対応"]["開始"]) and
                    (not 文.startswith(("下記", "以下")) or 行["対応"]["開始"] > 条件["対応"]["開始"])]
            個数 = re.match(r"(?:上記|以上|下記|以下)の?([1-9一二三四五六七八九])(?:つ|件|個|行)", 文)
            if 個数:
                数 = int(個数[1]) if 個数[1].isdigit() else "一二三四五六七八九".index(個数[1]) + 1
                前方 = 文.startswith(("上記", "以上"))
                候補 = [行 for 行 in 節群 if 行["対応"]["開始"] != 条件["対応"]["開始"] and
                        (行["対応"]["開始"] < 条件["対応"]["開始"]) == 前方]
                選択 = 候補[-数:] if 前方 else 候補[:数]
                if len(選択) != 数 or any(not (行["命題"] or any(行["関係"].values())) for 行 in 選択):
                    if 隣接採用:
                        作用域を保留(条件, "複数記載への参照数と作用域が未確定です")
                    範囲 = []
                else:
                    範囲 = [行 for 行 in 採用節 if 行 in 選択]
            elif re.search(r"(?:全て|すべて|全部)の?(?:説明|記載)", 文):
                範囲 = [行 for 行 in 採用節 if (行["対応"]["開始"] < 条件["対応"]["開始"]) ==
                        文.startswith(("上記", "以上"))]
        elif 明示主体:
            範囲 = [行 for 行 in 採用節 if any(_主体対応(明示主体, 項["対象"]) for 項 in
                    (行["関係"]["定義"], 行["関係"]["叙述"], 行["関係"]["属性"]) if 項)
                    or 行["先行主語"] and _主体対応(明示主体, 行["先行主語"])
                    or _根拠主述(行) and any(_主体対応(明示主体, 対象) for 対象 in _式の対象(_根拠主述(行)))]
            if 条件["関係"]["属性"]:
                軸 = 条件["関係"]["属性"]["観点"]
                範囲 = [行 for 行 in 範囲 if 行["関係"]["属性"] and 行["関係"]["属性"]["観点"] == 軸]
        elif 参照 or re.match(r"(?:ただし|但し|なお|例外|.+(?:場合|条件).+)", 文):
            if len(主体群) != 1:
                作用域を保留(条件, "限定の対象又は作用域が未確定です。対象を明示してください")
                continue
            範囲 = 採用節
        elif 条件["ID"] in 使用:
            範囲 = [条件]
        else:
            # 年度などの省略記載も未検証の隣接帰属で捨てない。
            if len(主体群) != 1:
                作用域を保留(条件, "条件記載の適用対象が未確定です")
                continue
            範囲 = 採用節
        if 範囲 and _撤回.search(文):
            raise ValueError("採用候補に誤り・撤回・訂正の記載があります。訂正版を確認してください:" + 文[:160])
        for 行 in 範囲:
            if 行["ID"] != 条件["ID"]:
                同伴.setdefault(行["ID"], []).append(条件)
    return 同伴


def _量比較(構造, 軸, 対象群):
    """既存数量・証拠・比較器に戻す。表記を置換した擬似原資料を作らない。"""
    集約 = _実参照資料(構造)
    単位群 = set()
    for 値 in 集約.参照:
        for 文 in re.finditer(r"[^。\n]+。?", 値.本文):
            一致 = 数値記載文.fullmatch(文[0].strip())
            if 一致 and 一致["属性"] == 軸 and 一致["対象"] in 対象群 and 一致["単位"] in _単位:
                単位群.add(一致["単位"])
    if not 単位群:
        return None
    if len({_単位[単位][0] for 単位 in 単位群}) != 1:
        raise ValueError("比較する属性の単位次元が異なります")
    単位 = sorted(単位群)[0]
    try:
        読取 = tuple(_数値を読む(構造, 対象, 軸, 単位) for 対象 in 対象群)
        数量 = tuple(値 for 値, _ in 読取)
        結果 = 数量を比較(*数量, {"時点差": False})
        文 = 回答を構成((結果,)).本文
        return 文, 結果を保存用(結果), [行 for _, 対応 in 読取 for 行 in 対応]
    except 会話処理不成立 as 例外:
        # 数値があるのに比較できない状態は、質的比較へ偽装しない。
        raise ValueError("数値比較の根拠が未確定:" + 例外.理由) from 例外


