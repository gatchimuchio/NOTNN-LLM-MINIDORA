def _旧資料を検査(名前, 資料):
    名前を確認(名前)
    if type(資料) is not dict or set(資料) != {"種類", "本文", "データ", "版", "結果"}:
        raise ValueError("旧資料の欄不一致")
    if (資料["種類"] not in ("資料", "知識", "本文", "命題", "仮説", "介入")
            or type(資料["本文"]) is not str or len(資料["本文"]) > 100000 or type(資料["データ"]) is not dict):
        raise ValueError("旧資料の種類・型・上限不正")
    if 資料["版"] != 指紋({鍵: 資料[鍵] for 鍵 in ("種類", "本文", "データ")}):
        raise ValueError("旧資料の本文・版不一致")
    参照 = 参照資料("運用資料:" + 名前 + ":" + 資料["版"], 名前,
                  "利用者提供" + 資料["種類"], 本文=資料["本文"])
    期待 = 能力結果(True, 資料["本文"], 参照=(参照,), データ=資料["データ"])
    if 指紋(結果を保存(期待)) != 指紋(資料["結果"]):
        raise ValueError("旧資料の本体・結果不一致")


def _旧保存を読む(原本, *, 深さ=0):
    if 深さ > 3:
        raise ValueError("旧保存履歴の入れ子上限")
    if type(原本) is not str:
        raise ValueError("旧保存原本はUTF-8文字列が必要")
    状態 = 開封(JSONを厳格に読む(原本, 最大バイト数=16000000))
    if type(状態) is not dict or 状態.get("版") not in _旧契約:
        raise ValueError("対応する旧保存版はv1・v2・v3・v4・v5・v6・v7です")
    追加 = set() if 状態["版"].endswith("-v1") else _v2欄
    if 状態["版"].endswith(("-v4", "-v5", "-v6", "-v7")):
        追加 = 追加 | {"移行履歴"}
    if set(状態) != _共通欄 | 追加:
        raise ValueError("旧保存の欄不一致")
    if 状態["目録"] != _旧契約[状態["版"]][0]:
        raise ValueError("未確認の旧能力契約です。独自追加能力の自動移行は行いません")
    if type(状態["資料"]) is not dict or len(状態["資料"]) > 32:
        raise ValueError("旧保存資料の型・件数不正")
    if type(状態["旧資料"]) is not list or len(状態["旧資料"]) > 32:
        raise ValueError("旧保存履歴の型・件数不正")
    for 名前, 資料 in 状態["資料"].items():
        _旧資料を検査(名前, 資料)
    for 行 in 状態["旧資料"]:
        if type(行) is not dict or set(行) != {"名前", "種類", "本文", "データ", "版", "結果"}:
            raise ValueError("旧保存履歴の資料構造不正")
        _旧資料を検査(行["名前"], {鍵: 値 for 鍵, 値 in 行.items() if 鍵 != "名前"})
    if 状態["版"].endswith(("-v4", "-v5", "-v6", "-v7")):
        旧番号 = int(状態["版"].rsplit("v", 1)[1])
        許容 = {"HDS-MINIDORA-全体運用-v" + str(番号) for 番号 in range(1, 旧番号)}
        if (type(状態["移行履歴"]) is not list or any(type(行) is not dict or 行.get("旧版") not in 許容
                for 行 in 状態["移行履歴"])):
            raise ValueError(状態["版"].split("-")[-1] + "当時に存在しない移行履歴")
        # v4/v5には移行記録v1、v6にはv1/v2、v7にはv1/v2/v3が存在した。
        記録版 = {"HDS旧保存明示移行-v1"}
        if 旧番号 >= 6:
            記録版.add("HDS旧保存明示移行-v2")
        if 旧番号 == 7:
            記録版.add("HDS旧保存明示移行-v3")
        移行履歴を検査(状態["移行履歴"], 深さ=深さ + 1, 許容版=記録版)
    # 旧形式に未来の横断要求を埋めて現行能力へ流入させない。
    for 鍵 in ("前回目的", "保留目的"):
        目的 = 状態.get(鍵)
        if type(目的) is dict and 目的.get("方式") == "関係資料":
            要求 = 目的.get("要求")
            if (状態["版"].endswith("-v7") and type(要求) is dict
                    and 要求.get("版") == "HDS資料横断要求-v1"):
                # v7当時の公開契約。要求を検査して保全するだけで、横断導出は実行しない。
                from .資料横断 import 横断要求を検査
                横断要求を検査(要求)
                continue
            期待版 = "HDS関係説明要求-v2" if 状態["版"].endswith(("-v6", "-v7")) else "HDS関係説明要求-v1"
            if (not 状態["版"].endswith(("-v5", "-v6", "-v7")) or type(要求) is not dict
                    or set(要求) != {"版", "対象", "範囲", "問い", "形式", "不足調査", "最大文字数"}
                    or 要求.get("版") != 期待版):
                raise ValueError("旧保存当時に存在しない関係要求")
    return 状態


def 移行履歴を検査(履歴, *, 深さ=0, 許容版=None):
    if 深さ > 3:
        raise ValueError("旧保存履歴の入れ子上限")
    if type(履歴) is not list or len(履歴) > 1:
        raise ValueError("移行履歴の型・件数不正")
    許容 = _既知移行版 if 許容版 is None else set(許容版)
    if not 許容 <= _既知移行版:
        raise ValueError("移行履歴の許容版不正")
    for 行 in 履歴:
        if (type(行) is not dict or set(行) != {"版", "旧版", "旧目録", "由来commit", "原本", "原本SHA256", "方針"}
                or 行["版"] not in 許容):
            raise ValueError("移行履歴の欄・版不一致")
        旧 = _旧保存を読む(行["原本"], 深さ=深さ)
        if (行["旧版"] != 旧["版"] or 行["旧目録"] != 旧["目録"]
                or 行["由来commit"] != _旧契約[旧["版"]][1]
                or 行["原本SHA256"] != sha256(行["原本"].encode()).hexdigest()
                or 行["方針"] != _移行方針(旧["版"])):
            raise ValueError("移行履歴の原本・方針が不整合")


def 旧成果履歴を照合(状態, 成果保存):
    """既知v1〜v6原本に一致する失効成果だけを履歴表示用に確認する。採用ではない。"""
    if (type(状態) is not dict or type(成果保存) is not dict
            or 状態.get("焦点有効") is not False
            or 状態.get("前回結果") != 成果保存):
        return False
    履歴 = 状態.get("移行履歴")
    if type(履歴) is not list or len(履歴) != 1:
        return False
    try:
        移行履歴を検査(履歴)
        旧 = _旧保存を読む(履歴[0]["原本"])
        if 旧["版"].endswith("-v7"):
            return False
        if not 旧["版"].endswith("-v1"):
            旧庫 = 運用原記録.復元(旧["原記録"], 旧["セッションID"])
            旧庫.資料を照合(旧["資料"])
            if not any(行["種別"] == "成果" and 原記録成果を復元(行) == 成果保存
                       and 行["内容"]["データ"].get("依存版") == 旧["前回依存"]
                       for 事象 in 旧["原記録"]["庫"]["履歴"] for 行 in 事象["追加"]):
                return False
        return (状態.get("セッションID") == 旧["セッションID"]
                and type(状態.get("外部読取許可")) is bool
                and 状態["外部読取許可"] is 旧["外部読取許可"]
                and 状態.get("前回依存") == 旧["前回依存"]
                and 成果保存 == 旧["前回結果"])
    except (ValueError, TypeError, KeyError):
        return False


def _v7原会話を検査(状態, 庫):
    # 旧成果は採用しないが、元の結果と所有原記録・目的の対応は失効前に確認する。
    if (type(状態["焦点有効"]) is not bool or type(状態["前回依存"]) is not dict
            or type(状態["外部読取許可"]) is not bool or type(状態["手順形成"]) is not bool):
        raise ValueError("旧v7会話状態の型不正")
    for 名, 版 in 状態["前回依存"].items():
        名前を確認(名)
        if type(版) is not str or len(版) != 64 or any(字 not in "0123456789abcdef" for 字 in 版):
            raise ValueError("旧v7依存の版不正")
    for 名 in ("前回目的", "保留目的"):
        目的 = 状態[名]
        if 目的 is not None and (type(目的) is not dict or type(目的.get("方式")) is not str):
            raise ValueError("旧v7目的の型不正")
    if 状態["前回結果"] is None:
        if 状態["焦点有効"]:
            raise ValueError("旧v7の有効焦点に原成果がない")
        return
    成果 = 結果を復元(状態["前回結果"])
    対応 = [行 for 事象 in 状態["原記録"]["庫"]["履歴"] for 行 in 事象["追加"]
            if 行["種別"] == "成果" and 原記録成果を復元(行) == 状態["前回結果"]
            and 行["内容"]["データ"].get("依存版") == 状態["前回依存"]]
    if not 対応 or (状態["焦点有効"] and not any(庫.庫.原記録(行["識別子"])["現行"] for 行 in 対応)):
        raise ValueError("旧v7前回結果と同所有原記録の不一致")
    種別 = 成果.データ.get("種別")
    if 種別 in ("資料文章回答", "関係資料回答", "数量言語回答"):
        目的 = 状態["前回目的"]
        構造 = 成果.データ.get("構造")
        if (type(目的) is not dict or type(構造) is not dict
                or 目的.get("要求") != 構造.get("要求")):
            raise ValueError("旧v7目的と原成果要求の不一致")


def _v1原記録(状態):
    # v1には原記録庫が存在しない。残っている旧版列と現行資料から新設する。
    # 失われた過去や生成時刻は補完しない。元の記録は移行原本に残る。
    庫 = 運用原記録(状態["セッションID"])
    仮資料 = {}
    for 行 in [*状態["旧資料"], *({"名前": 名, **値} for 名, 値 in sorted(状態["資料"].items()))]:
        if type(行) is not dict or set(行) != {"名前", "種類", "本文", "データ", "版", "結果"}:
            raise ValueError("v1旧資料の構造不正")
        名前 = 行["名前"]
        資料 = {鍵: 値 for 鍵, 値 in 行.items() if 鍵 != "名前"}
        庫 = 庫.同期候補({"資料": 仮資料}, {"行為": "更新" if 名前 in 仮資料 else "登録", "名前": 名前, "資料": 資料}, None, {})
        仮資料[名前] = deepcopy(資料)
    庫.資料を照合(状態["資料"])
    return 庫


def 旧保存を移行(原本, *, 外部読取許可=False, 取得器=None):
    """元の文字列を変更せず、新セッションを返す。外部通信・能力実行はしない。"""
    from .セッション import HDS運用セッション
    from .手順形成 import 手順資産を検査
    旧 = _旧保存を読む(原本)
    if 旧["外部読取許可"] is not 外部読取許可:
        raise ValueError("保存データから外部権限を移行しない。呼出側設定との一致が必要")
    新 = deepcopy(旧)
    試用 = HDS運用セッション(旧["セッションID"], 外部読取許可=外部読取許可, 取得器=取得器,
                          最大作用回数=旧["最大作用回数"], 最大発話=旧["最大発話"], 手順形成=旧.get("手順形成", False))
    # 新復元器の資料・回答・履歴検査を先に通すため、v1の欠落欄を明示構成する。
    if 旧["版"].endswith("-v1"):
        庫 = _v1原記録(旧)
        新.update(原記録=庫.保存(), 知識資産={名: 知識を形成(名, 値) for 名, 値 in 旧["資料"].items() if 値["種類"] == "知識"},
                 形成手順={}, 手順形成=False, 前回知識範囲=None)
    else:
        庫 = 運用原記録.復元(旧["原記録"], 旧["セッションID"])
        庫.資料を照合(旧["資料"])
        if 旧["版"].endswith("-v7"):
            _v7原会話を検査(旧, 庫)
        if type(旧["形成手順"]) is not dict or len(旧["形成手順"]) > 64:
            raise ValueError("旧形成手順の型・上限不正")
        # 検証対象は記録契約のみ。旧コードや手順を実行しない。
        from .関係接続 import 関係能力名
        # 旧版ごとに当時存在した能力名だけを検証対象へ残す。v5では関係系、
        # v4以降では資料意味系、v3以降では数量系が既に存在していた。
        除外 = set()
        if not 旧["版"].endswith(("-v5", "-v6", "-v7")):
            除外 |= set(関係能力名)
        if not 旧["版"].endswith(("-v4", "-v5", "-v6", "-v7")):
            除外 |= {"資料意味選択", "取得資料意味選択", "資料内容構成", "資料文章照合", "資料文章再表現"}
        if 旧["版"].endswith("-v2"):
            除外 |= {"数量文構文化", "数量式評価", "数量コード仕様", "数量コード実行", "数量結果照合", "数量回答構成", "数量回答再表現"}
        純粋名 = (試用.目録._純粋 & _v7純粋名) if 旧["版"].endswith("-v7") else 試用.目録._純粋 - 除外
        検証用 = SimpleNamespace(ハッシュ=旧["目録"], _純粋=純粋名, 取得=試用.目録.取得)
        for 鍵, 手順 in 旧["形成手順"].items():
            手順資産を検査(手順, 検証用)
            if 手順["目的鍵"] != 鍵:
                raise ValueError("旧手順の索引不一致")
    失効 = []
    for 事象 in 庫.保存()["庫"]["履歴"]:
        for 行 in 事象["追加"]:
            if 行["種別"] == "成果" and 庫.庫.原記録(行["識別子"])["現行"]:
                失効.append(行["識別子"])
    for 開始 in range(0, len(失効), 128):
        庫.庫.更新(庫.庫.起点(), 失効ID=tuple(失効[開始:開始+128]), 理由="保存移行で能力契約が変更。旧成果は履歴のみ")
    if 旧["版"].endswith(("-v5", "-v6")):
        # v5/v6の旧目的は通常関係要求だけ。新しい横断目的を旧成果から生成しない。
        # 旧結果は採用せず、再計算用の目的だけを現行要求版へ明示的に移す。旧目的・旧結果は原本へ残る。
        for 鍵 in ("前回目的", "保留目的"):
            目的 = 新.get(鍵)
            if type(目的) is dict and 目的.get("方式") == "関係資料" and type(目的.get("要求")) is dict:
                目的["要求"] = deepcopy(目的["要求"])
                目的["要求"]["版"] = "HDS関係説明要求-v2"
        if 新.get("前回結果") is not None:
            旧結果 = 結果を復元(新["前回結果"])
            if 旧結果.データ.get("種別") == "関係資料回答":
                新["前回結果"] = None
    if 旧["版"].endswith("-v7"):
        # 旧作用範囲を新しい要求へ無言変換しない。元の目的/成果は文字列原本に保全する。
        新.update(前回結果=None, 前回目的=None, 保留目的=None)
    新.update(版=運用版, 目録=試用.目録.ハッシュ, 原記録=庫.保存(), 焦点有効=False, 形成手順={})
    新["移行履歴"] = [{"版": _移行記録版(旧["版"]), "旧版": 旧["版"], "旧目録": 旧["目録"], "由来commit": _旧契約[旧["版"]][1],
                       "原本": 原本, "原本SHA256": sha256(原本.encode()).hexdigest(),
                       "方針": _移行方針(旧["版"])}]
    移行履歴を検査(新["移行履歴"])
    文字列 = json.dumps(封緘(新), ensure_ascii=False, allow_nan=False)
    # 全資料・結果・依存・知識資産等は現行復元器でも再検査する。
    return HDS運用セッション.復元(文字列, 外部読取許可=外部読取許可, 取得器=取得器)
