"""格役割、活用、条件の向き、明示例外を原文から構成するv6の有限射影。

v5読解器は変更しない。語彙は言語形の対応であり、世界事実や正解表ではない。
未対応の活用・修飾・指示先を、既知の語へ推測補完しない。
"""
from __future__ import annotations
import re
import unicodedata
from ..命題句 import 最上位位置, 引用を切り出す, 構成句を分ける
from ..命題解釈 import _外側, 命題を表現
from ..命題構造 import 命題式, 命題項, 原子, 結合, 反対, 文脈を付す
from .関係言語 import 関係文を読む as 旧関係文を読む, _対象, _未束縛参照を検査
from .関係言語 import _指示, _未対応指示, _動作根, _制限

関係構文化版 = "HDS関係構文化-v2"
_格順 = ("を", "に", "へ", "から", "まで", "で", "と")
_格境界 = ("から", "まで", "を", "に", "へ", "で", "と")
_形 = {}


def _活用を登録(原形, 未然, 連用, 接続, 過去):
    for 表層, 正形, 否定 in (
        (原形, 原形, False), (連用 + "ます", 原形, False),
        (未然 + "ない", 原形, True), (連用 + "ません", 原形, True),
        (過去, 過去, False), (連用 + "ました", 過去, False),
        (未然 + "なかった", 過去, True), (連用 + "ませんでした", 過去, True),
        (接続 + "いる", 接続 + "いる", False), (接続 + "います", 接続 + "いる", False),
        (接続 + "いない", 接続 + "いる", True), (接続 + "いません", 接続 + "いる", True),
    ):
        値 = (正形, 否定)
        if 表層 in _形 and _形[表層] != 値:
            raise ValueError("活用表の衝突:" + 表層)
        _形[表層] = 値


# 一段と五段の区別を未知語の語尾だけから決めない。語義の同一化もしない。
_五段語 = ("書く", "読む", "送る", "渡す", "受け取る", "動く", "働く", "開く", "閉まる", "止まる",
          "使う", "作る", "選ぶ", "運ぶ", "持つ", "待つ", "話す", "返す", "戻る", "進む", "続く", "買う", "行く")
_五段形 = {"う": ("わ", "い", "って", "った"), "く": ("か", "き", "いて", "いた"),
          "ぐ": ("が", "ぎ", "いで", "いだ"), "す": ("さ", "し", "して", "した"),
          "つ": ("た", "ち", "って", "った"), "ぬ": ("な", "に", "んで", "んだ"),
          "ぶ": ("ば", "び", "んで", "んだ"), "む": ("ま", "み", "んで", "んだ"), "る": ("ら", "り", "って", "った")}
for _語 in _五段語:
    _根 = _語[:-1]
    _未, _連, _接, _過 = _五段形[_語[-1]]
    if _語 == "行く":
        _接, _過 = "って", "った"
    _活用を登録(_語, _根 + _未, _根 + _連, _根 + _接, _根 + _過)
for _語 in ("見る", "調べる", "開ける", "閉じる", "閉める", "止める", "受ける", "届ける", "変える", "増える", "減る"):
    # 「減る」は五段。曖昧な語尾からの類推ではなく下で個別登録する。
    if _語 != "減る":
        _根 = _語[:-1]
        _活用を登録(_語, _根, _根, _根 + "て", _根 + "た")
_活用を登録("減る", "減ら", "減り", "減って", "減った")
_サ変 = (
    ("していません", "している", True), ("していない", "している", True),
    ("しています", "している", False), ("している", "している", False),
    ("しませんでした", "した", True), ("しなかった", "した", True),
    ("しました", "した", False), ("した", "した", False),
    ("できません", "できる", True), ("できない", "できる", True),
    ("できます", "できる", False), ("できる", "できる", False),
    ("しません", "する", True), ("しない", "する", True), ("します", "する", False), ("する", "する", False),
)


def _動作(文字):
    if 文字 in _形:
        return _形[文字]
    for 語尾, 正形, 否定 in _サ変:
        一致 = re.fullmatch("(" + _動作根 + ")" + 語尾, 文字)
        if 一致:
            return 一致[1] + 正形, 否定
    return None


def _参照主体(名前):
    if 名前 in _指示 | _未対応指示:
        raise ValueError("未束縛の照応先を定数にしない:" + 名前)
    return _対象(名前)


def _格項(名前):
    _参照主体(名前)
    # この増分の格項は明示された単純名詞。ひらがな修飾や接続した動詞を
    # 目的物・場所等の名前として飲み込まない。任意の固有名詞分割は未対応。
    if not re.fullmatch(_動作根, 名前) or any(最上位位置(名前, _格境界)) or re.search(r"[\s、,。:：\[\]]", 名前):
        raise ValueError("格項の修飾・並列・境界が未確定:" + 名前[:80])
    return 名前


def _動作文(文, 参照, *, 省略=False):
    主格 = list(最上位位置(文, ("は", "が")))
    if len(主格) == 1:
        位置, 助詞 = 主格[0]
        主体, 述部 = 文[:位置].strip(), 文[位置 + len(助詞):].strip()
        変換 = []
        if 主体 in _指示:
            if 参照 is None:
                raise ValueError("照応先が一意でありません")
            変換.append("照応:" + 主体 + "→" + 参照)
            主体 = 参照
        _参照主体(主体)
    elif not 主格 and 省略 and 参照 is not None:
        主体, 述部, 変換 = _参照主体(参照), 文, ["局所主体補完:" + 参照]
    else:
        return None
    # 活用語尾の「できる」「している」の助詞らしい部分を格境界へしない。
    動作 = _動作(述部)
    格 = {}
    if 動作 is None:
        位置群 = list(最上位位置(述部, _格境界))
        # 各切断候補を検査する。候補が複数成立して異なる意味なら未確定とする。
        候補 = []
        for 終点, 最後の格 in 位置群:
            後 = 述部[終点 + len(最後の格):].strip()
            活用 = _動作(後)
            if 活用 is None:
                continue
            前, 格候補 = 0, {}
            for 位置, 助詞 in 位置群:
                if 位置 > 終点:
                    break
                名 = 述部[前:位置].strip()
                if 助詞 in 格候補:
                    raise ValueError("同じ格の重複・並列は未対応")
                格候補[助詞] = _格項(名)
                前 = 位置 + len(助詞)
            if not 1 <= len(格候補) <= 3:
                raise ValueError("格役割は主語に加え三つまで")
            候補.append((活用, 格候補))
        if not 候補:
            return None
        if len(候補) != 1:
            raise ValueError("動作と格役割の切断が複数")
        動作, 格 = 候補[0]
    _格項(主体)
    正形, 否定 = 動作
    順 = tuple(助詞 for 助詞 in _格順 if 助詞 in 格)
    述語 = "格動作[" + ",".join(順) + "]:" + 正形 if 順 else 正形
    式 = 原子(述語, 主体, *(格[助詞] for 助詞 in 順))
    変換.append("動作活用:" + 述部 + "→" + ("否定:" if 否定 else "") + 正形)
    if 順:
        変換.append("格役割:" + ",".join(順) + "（語順だけを正準化し、役割を交換しない）")
    return (反対(式) if 否定 else 式), 主体, 変換


def _末尾例外(文):
    # 最上位の末尾括弧だけが直前の条件全体に係る。引用内の注記は拾わない。
    閉じ = {"(": ")", "（": "）", "「": "」", "『": "』"}
    積み, 開始 = [], None
    for i, 字 in enumerate(文):
        if 字 in 閉じ:
            if not 積み:
                開始 = i
            積み.append(閉じ[字])
        elif 字 in 閉じ.values():
            if not 積み or 積み.pop() != 字:
                raise ValueError("引用・括弧の対応不正")
            if not 積み and i == len(文) - 1 and 文[開始] in "(（":
                内 = 文[開始 + 1:i]
                一致 = re.fullmatch(r"ただし[、,]?\s*(.+?)(?:の場合|な場合|場合)を除く", 内, re.S)
                if 一致:
                    return 文[:開始].strip(), 一致[1].strip()
    if 積み:
        raise ValueError("引用・括弧が閉じていない")
    return None


def 関係文を構成(原文: str, *, 先行主体: str | None = None):
    """式・主体・変換履歴・明示例外を返す。例外を既定の不成立とはしない。"""
    if type(原文) is not str or not 0 < len(原文) <= 4096:
        raise ValueError("関係文の型・文字上限")
    if any(unicodedata.category(字) in ("Cf", "Cs") or (unicodedata.category(字) == "Cc" and 字 not in "\n\r\t") for 字 in 原文):
        raise ValueError("関係文の不可視制御文字")
    if 先行主体 is not None:
        _対象(先行主体)
    履歴 = []
    展開 = 0

    def 解析(文, 参照=None, 深さ=0, *, 裸=False, 省略=False):
        nonlocal 展開
        展開 += 1
        if 深さ > 12 or 展開 > 256:
            raise ValueError("関係文の構成深さ・展開上限")
        文 = 文.strip()
        if not 文:
            raise ValueError("空の関係節")
        list(最上位位置(文, ("。",)))  # 全ての括弧対応を先に検査する。
        内 = _外側(文)
        if 内 is not None:
            履歴.append("括弧作用域保持")
            return 解析(内, None, 深さ + 1)
        if 文.startswith("否定") and _外側(文[2:].strip()) is not None:
            式, _ = 解析(文[2:].strip(), None, 深さ + 1)
            履歴.append("否定作用域保持")
            return 反対(式), None
        必要 = re.fullmatch(r'「([^「」]+)」は「([^「」]+)」の(必要十分|必要|十分)条件(?:である|です)', 文)
        if 必要:
            a, _ = 解析(必要[1], None, 深さ + 1)
            b, _ = 解析(必要[2], None, 深さ + 1)
            履歴.append("条件方向:" + 必要[3] + "（逆向きは明示された場合のみ）")
            if 必要[3] == "必要":
                return 結合("含意", b, a), None
            if 必要[3] == "十分":
                return 結合("含意", a, b), None
            return 結合("連言", 結合("含意", a, b), 結合("含意", b, a)), None
        必要 = re.fullmatch(r'(.+?)(?:ため)?には[、,]?\s*(.+?)ことが必要(?:である|です)', 文, re.S)
        if 必要:
            b, _ = 解析(必要[1], None, 深さ + 1)
            a, _ = 解析(必要[2], None, 深さ + 1)
            履歴.append("必要条件:BからA（AだけでBを成立させない）")
            return 結合("含意", b, a), None
        if any(語 in 文 for 語 in _制限) or "例外" in 文:
            raise ValueError("未対応の留保・限定作用域")
        時点 = re.fullmatch(r'(?:時点「([^「」]+)」では|([0-9]{4})年では)([（(].*[）)])', 文, re.S)
        if 時点:
            式, 主体 = 解析(時点[3], None, 深さ + 1)
            履歴.append("明示時点保持")
            return 文脈を付す(式, 時点=時点[1] or 時点[2] + "年"), 主体
        様相 = re.fullmatch(r'(可能性として|義務として)([（(].*[）)])', 文, re.S)
        if 様相:
            式, 主体 = 解析(様相[2], None, 深さ + 1)
            履歴.append("明示様相保持")
            return 文脈を付す(式, 様相="可能" if 様相[1] == "可能性として" else "義務"), 主体
        条件 = list(最上位位置(文, ("ならば", "であれば", "な場合には", "な場合は", "な場合", "なときには", "なときは", "なとき", "場合には", "場合は", "場合", "ときには", "ときは", "とき", "なら")))
        if 条件:
            if len(条件) != 1:
                raise ValueError("複数条件の係り先を括弧で指定してください")
            位置, 接続 = 条件[0]
            前 = 文[:位置].removeprefix("もしも").removeprefix("もし").strip()
            後 = 文[位置 + len(接続):].lstrip("、, ")
            a, 主体a = 解析(前, 参照, 深さ + 1, 裸=True, 省略=省略)
            b, 主体b = 解析(後, 主体a, 深さ + 1, 省略=True)
            履歴.append("条件節:" + 接続 + "（前件を事実化しない）")
            return 結合("含意", a, b), 主体a if 主体a == 主体b else None
        接続群 = list(最上位位置(文, ("であり、", "であり,", "かつ", "および", "または")))
        if 接続群:
            種類 = {"選言" if 語 == "または" else "連言" for _, 語 in 接続群}
            if len(種類) != 1 or len(接続群) > 7:
                raise ValueError("連言・選言の作用域または節数が未対応")
            部分, 前 = [], 0
            for 位置, 接続 in 接続群:
                部分.append(文[前:位置] + ("である" if 接続.startswith("であり") else ""))
                前 = 位置 + len(接続)
            部分.append(文[前:])
            式群, 主体群, 現主体 = [], [], 参照
            for 番号, 節 in enumerate(部分):
                式, 主体 = 解析(節, 現主体, 深さ + 1, 省略=省略 or 番号 > 0)
                式群.append(式); 主体群.append(主体)
                現主体 = 主体 if len(set(主体群)) == 1 else None
            履歴.append("接続:" + next(iter(種類)))
            return 結合(next(iter(種類)), *式群), 現主体
        # 引用は独立作用域。外側の主体も事実性も引用内容へ流入させない。
        for 位置, 助詞 in 最上位位置(文, ("は", "が", "によると")):
            開始 = 位置 + len(助詞)
            if 開始 >= len(文) or 文[開始] not in "「『":
                continue
            内, 終了 = 引用を切り出す(文, 開始)
            語尾 = 文[終了:]
            種別 = {"と述べる": "発言", "と述べた": "過去発言", "と考える": "信念", "と考えた": "過去信念"}.get(語尾)
            if 助詞 == "によると" and not 語尾:
                種別 = "伝聞"
            if 種別 is None:
                continue
            主体 = _参照主体(文[:位置])
            区間 = list(構成句を分ける(内))
            if not 1 <= len(区間) <= 8:
                raise ValueError("直接引用の記載数上限")
            式群 = [解析(内[a:b], None, 深さ + 1)[0] for a, b in 区間]
            内容 = 式群[0] if len(式群) == 1 else 結合("連言", *式群)
            履歴.append("帰属と引用内容の分離")
            return 命題式("帰属", 種別, (命題項(主体),), (内容,)), None
        # 否定コピュラの「ではない」の「は」は第二の主格ではない。
        # v5の再現経路は変えず、v6で明示名詞述語の主格だけを接続する。
        主格 = list(最上位位置(文, ("は", "が")))
        if 主格 and 主格[0][1] == "が":
            位置 = 主格[0][0]
            if re.fullmatch(_動作根 + r"(?:ではない|ではありません)", 文[位置 + 1:]):
                文 = 文[:位置] + "は" + 文[位置 + 1:]
                履歴.append("主格が→は（否定述語の作用域を保持）")
        動作 = _動作文(文, 参照, 省略=省略)
        if 動作 is not None:
            式, 主体, 変換 = 動作
            履歴.extend(変換)
            return 式, 主体
        # 旧名詞・量化・関数文法へ戻す。新しい照応や語義を追加しない。
        if 裸:
            主格 = list(最上位位置(文, ("は", "が")))
            if len(主格) == 1 and re.fullmatch(_動作根, 文[主格[0][0] + 1:]):
                文 += "である"
                履歴.append("条件内の名詞述語")
        if 省略 and 参照 is not None and not list(最上位位置(文, ("は", "が"))):
            文 = 参照 + "は" + 文
            履歴.append("局所主体補完:" + 参照)
        式, 主体, 変換 = 旧関係文を読む(文, 先行主体=参照)
        履歴.extend(変換)
        return 式, 主体

    文 = 原文.strip().removesuffix("。")
    注記 = _末尾例外(文)
    例外 = None
    if 注記 is not None:
        規則, 例外文 = 注記
        式, 主体 = 解析(規則, 先行主体)
        if 式.種別 != "含意":
            raise ValueError("明示例外は直前の一つの条件全体へ指定してください")
        例外, _ = 解析(例外文, None, 裸=True)
        def 例外境界を検査(対象):
            if 対象.種別 not in ("原子", "否定", "連言", "選言"):
                raise ValueError("例外は量化・条件・帰属を含まない記載が必要")
            for 子 in 対象.子:
                例外境界を検査(子)
        例外境界を検査(例外)
        式 = 結合("含意", 結合("連言", 式.子[0], 反対(例外)), 式.子[1])
        履歴.append("明示例外:非例外の独立支持を条件に追加（例外から後件否定を導かない）")
        主体 = None
    else:
        式, 主体 = 解析(文, 先行主体)
    式.検査()
    _未束縛参照を検査(式)
    return 式, 主体, 履歴, 例外


def 関係文を読む(原文, *, 先行主体=None):
    式, 主体, 変換, _ = 関係文を構成(原文, 先行主体=先行主体)
    return 式, 主体, 変換


def 関係式を表現(式):
    if 式.時点 == "未指定" and 式.様相 == "記載":
        if 式.種別 == "原子":
            格 = re.fullmatch(r"格動作\[([^\[\]]+)\]:(.+)", 式.述語)
            if 格:
                助詞群 = 格[1].split(",")
                if (tuple(助詞 for 助詞 in _格順 if 助詞 in 助詞群) == tuple(助詞群)
                        and len(式.項) == len(助詞群) + 1 and all(項.種別 == "定数" for 項 in 式.項)):
                    return 式.項[0].名前 + "は" + "".join(項.名前 + 助詞 for 項, 助詞 in zip(式.項[1:], 助詞群)) + 格[2]
            if len(式.項) == 1 and 式.項[0].種別 == "定数" and _動作(式.述語) is not None:
                return 式.項[0].名前 + "は" + 式.述語
        if 式.種別 == "否定":
            return "否定（" + 関係式を表現(式.子[0]) + "）"
        if 式.種別 in ("連言", "選言", "含意"):
            語 = {"連言": "かつ", "選言": "または", "含意": "ならば"}[式.種別]
            return 語.join("（" + 関係式を表現(子) + "）" for 子 in 式.子)
    return 命題を表現(式)
