from .数量言語 import 名前を読む, 式を読む, 参照名
from .値 import 結果を保存, 結果を復元
from ..能力合成 import 合成計画, 合成工程, 素材参照
from ..製品版.型 import 能力結果


def _前回(入力):
    目的 = deepcopy(入力.get("保留目的") or 入力.get("前回目的"))
    if 目的 and 目的.get("方式") == "継続":
        目的 = 目的["目的"]
    return 目的 if 目的 and 目的.get("方式") == "数量言語" else None


def 数量依頼を読む(入力):
    原文 = 入力["原文"]
    文 = 原文.strip().rstrip("。")
    前回 = _前回(入力)
    if 前回:
        変更 = re.fullmatch(r'(?:資料「(?P<資料>[^「」]+)」の)?(?P<数量>「[^「」]+」|[^「」\s]+?)を(?P<値>.+?)に(?:変更|訂正)して', 文)
        返答 = re.fullmatch(r'(?:資料「(?P<資料>[^「」]+)」の)?(?P<数量>「[^「」]+」|[^「」\s]+?)(?:は|=)(?P<値>.+?)(?:です)?', 文)
        一致 = 変更 or 返答
        if 一致:
            対象 = 一致["資料"]
            if 対象 is None:
                if len(前回["要求"]["対象"]) != 1:
                    raise ValueError("数量訂正の対象資料が曖昧です。資料名を指定してください")
                対象 = 前回["要求"]["対象"][0]
            項 = {"資料":対象, "数量":名前を読む(一致["数量"]), "値":一致["値"],
                  "原文":原文, "範囲":[原文.index(文)+一致.start("値"), 原文.index(文)+一致.end("値")]}
            条件 = 前回["要求"]["条件変更"]
            条件[:] = [c for c in 条件 if (c["資料"],c["数量"]) != (項["資料"],項["数量"])]
            条件.append(項)
            要求を検査(前回["要求"])
            前回["原文"] = 原文
            return 前回
        if 文 in ("変更条件を解除して", "元の条件で再計算して"):
            前回["要求"]["条件変更"] = []
            前回["原文"] = 原文
            return 前回
        表示差分 = {"詳しく説明して":{"詳細":True}, "短く説明して":{"詳細":False},
                    "表にして":{"形式":"表"}, "文章にして":{"形式":"文章"},
                    "技術者向けに説明して":{"読者":"技術者", "詳細":True},
                    "専門用語を減らして":{"読者":"一般"},
                    "検算コードを付けて":{"コード":True}, "コードを省いて":{"コード":False}}
        if 文 in 表示差分:
            if not 入力.get("前回有効") or 入力.get("前回結果") is None:
                raise ValueError("再表現する数量成果が失効しています。再計算してください")
            return {"方式":"数量再表現", "原文":原文, "表示差分":表示差分[文]}
    # 同じ語でも比較だけの既存数量入口は維持する。計算/検算を明示した複合要求だけ扱う。
    if not re.search(r'計算|検算', 文):
        return None
    主 = re.fullmatch(r'(?P<資料>(?:資料)?「[^「」]+」(?:と(?:資料)?「[^「」]+」)*)(?:に(?P<規則>(?:資料)?「[^「」]+」(?:と(?:資料)?「[^「」]+」)*)を使って[、,]?\s*|の)(?P<数量>「[^「」]+」|[^「」\s]+?)を(?P<操作>.+)', 文)
    if not 主:
        return None
    対象 = re.findall(r'「([^「」]+)」', 主["資料"])
    規則 = re.findall(r'「([^「」]+)」', 主["規則"] or "")
    操作 = []
    表示 = {"詳細":False, "コード":False, "形式":"文章", "読者":"一般"}
    条項群 = [片.strip() for 片 in re.split(r'[、,。]|してから', 主["操作"]) if 片.strip()]
    for 片 in 条項群:
        if 片 in ("計算して", "計算し", "計算"):
            作用 = "計算"
        elif 片 in ("比較して", "比較し", "比較"):
            作用 = "比較"
        elif 片 in ("合計して", "合計し", "合計を出して"):
            作用 = "合計"
        elif 片 in ("平均して", "平均を出して"):
            作用 = "平均"
        elif 片 in ("最大値を出して", "最大を出して"):
            作用 = "最大"
        elif 片 in ("最小値を出して", "最小を出して"):
            作用 = "最小"
        elif 片 in ("Pythonで検算して", "Pythonで検算し", "Pythonで検算", "検算して", "検算コードを付けて"):
            作用 = "検算"; 表示["コード"] = True
        elif 片 in ("説明して", "詳しく説明して", "技術者向けに説明して", "短く説明して", "表にして", "文章にして"):
            if 片 == "表にして": 表示["形式"] = "表"
            elif 片 == "文章にして": 表示["形式"] = "文章"
            else:
                表示["詳細"] = 片 != "短く説明して"
                if 片 == "技術者向けに説明して": 表示["読者"] = "技術者"
            continue
        else:
            raise ValueError("数量依頼の未対応条件:" + 片)
        if 作用 not in 操作: 操作.append(作用)
    if not ({"計算", "検算"} & set(操作)):
        return None
    要求 = 要求を検査({"対象":対象, "規則":規則, "数量":名前を読む(主["数量"]),
                      "操作":操作, "条件変更":[], "表示":表示})
    return {"方式":"数量言語", "原文":原文, "要求":要求}


def 数量計画を作る(解釈, 入力):
    if 解釈["方式"] == "数量再表現":
        if not 入力.get("前回有効"):
            raise ValueError("数量成果の再表現起点が失効")
        素材 = {"前回":結果を復元(入力["前回結果"]), "指示":能力結果(True,"前回の数量成果を保持して表現を変更する"),
                 "表示":能力結果(True,"", データ=解釈["表示差分"])}
        計画 = 合成計画((合成工程("数量再表現", ("数量回答再表現",), "指示", (素材参照("入力","前回"),), "表示"),), ("数量再表現",))
        return 計画, 素材, "数量回答"
    要求 = 要求を検査(解釈["要求"])
    素材 = {}
    for 名 in 要求["対象"]+要求["規則"]:
        if 名 not in 入力["資料"]:
            raise ValueError("確認待ち:資料不足:" + 名)
        素材[名] = 結果を復元(入力["資料"][名]["結果"])
    素材["数量:設定"] = 能力結果(True,"", データ=要求)
    素材["数量:指示"] = 能力結果(True,"原資料と利用者条件から数量を構成し、計算・生成コード・説明を照合する")
    指示 = "数量:指示"
    def 参照(名): return 素材参照("工程",名)
    計画 = 合成計画((
        合成工程("数量構文化", ("数量文構文化",), 指示,
                 tuple(素材参照("入力", 名) for 名 in 要求["対象"]+要求["規則"]), "数量:設定"),
        合成工程("数量計算", ("数量式評価",), 指示, (参照("数量構文化"),)),
        合成工程("数量コード仕様", ("数量コード仕様",), 指示, (参照("数量構文化"),)),
        合成工程("数量コード生成", ("コード生成",), 指示, (参照("数量コード仕様"),)),
        合成工程("数量コード実行", ("数量コード実行",), 指示, (参照("数量構文化"),参照("数量コード生成"),参照("数量計算"))),
        合成工程("数量照合", ("数量結果照合",), 指示, (参照("数量構文化"),参照("数量計算"),参照("数量コード実行"))),
        合成工程("数量説明", ("数量回答構成",), 指示, (参照("数量構文化"),参照("数量計算"),参照("数量コード実行"),参照("数量照合")))
        ), ("数量説明",))
    return 計画, 素材, "数量回答"
