def _成果鍵(鍵, 工程):
    return 鍵 + "/成果/" + 工程


def _試行鍵(鍵, 工程):
    return 鍵 + "/試行/" + 工程 + "/0"


def _最新資源(成果群):
    """旧取得の資源帳を保持し、後続の別取得へ同じ当回の残量を渡す。"""
    群 = [x.データ.get("資源制御") for x in 成果群]
    if not 群 or any(type(x) is not dict for x in 群):
        return None
    上限名 = {"検索回数": "最大検索回数", "候補数": "最大候補数",
             "本文取得数": "最大本文取得数", "HTTP開始数": "最大HTTP開始数", "総バイト数": "最大総バイト数"}
    for x in 群:
        上限 = 公開取得上限(**x["上限"])
        if (x["版"] != "公開取得資源-v2" or type(x["当回ID"]) is not str or not x["当回ID"]
                or type(x["使用"]) is not dict or set(x["使用"]) != set(上限名)
                or any(type(v) is not int or not 0 <= v <= getattr(上限, 上限名[k])
                       for k, v in x["使用"].items())):
            raise ValueError("資料補充の共有資源の型・使用上限が不一致")
    最新 = max(群, key=lambda x: sum(x["使用"].values()))
    if any(x["当回ID"] != 最新["当回ID"] or x["上限"] != 最新["上限"]
           or any(v > 最新["使用"][k] for k, v in x["使用"].items()) for x in 群):
        raise ValueError("資料補充の共有資源の当回・単調増加が不一致")
    return 最新


def _追加検索(鍵, 包, 計画, 意味, 診断, 取得群, *, 資源成果=()):
    """型付き定義不足の別表現を一度だけ検索する。旧要求・旧成果は置換しない。"""
    if (len(取得群) >= 4 or 診断["要求"]["関係焦点"] != ["定義"]
            or len(診断["対象"]) != 1
            or not any(x["種別"] == "定義・種別関係" for x in 診断["不足役割"])):
        return None
    対象語 = 診断["対象"][0]
    検索語 = 対象語 + " とは"
    if any(要求.検索語 == 検索語 for _, 要求, _, _ in 取得群):
        return None
    元 = next((x for x in 取得群 if x[1].必要語 == (対象語,)), None)
    if 元 is None:
        return None
    資源 = _最新資源([x[2] for x in 取得群] + list(資源成果))
    if 資源 is None or any(資源["使用"][項] >= 資源["上限"][上限] for 項, 上限 in
            (("検索回数", "最大検索回数"), ("候補数", "最大候補数"),
             ("本文取得数", "最大本文取得数"), ("HTTP開始数", "最大HTTP開始数"),
             ("総バイト数", "最大総バイト数"))):
        return None
    旧工程, 原要求, _, _ = 元
    新要求 = replace(原要求, 検索語=検索語, 最大検索回数=1,
                   最大候補数=min(原要求.最大候補数,
                               資源["上限"]["最大候補数"] - 資源["使用"]["候補数"]),
                   最大資料数=1)
    新要求.検証()
    設定名 = "一般:再検索設定:" + 鍵.split(":")[-1]
    工程名 = "一般公開再検索:" + 鍵.split(":")[-1]
    if 設定名 in 包["資料"] or any(x.識別子 == 工程名 for x in 計画.工程):
        raise ValueError("同じ追加検索を反復しません")
    from dataclasses import asdict
    新 = deepcopy(包)
    新["資料"][設定名] = 結果を保存(能力結果(True, "", データ=正準(asdict(新要求))))
    追加工程 = 合成工程(工程名, ("知識取得",), 旧工程.指示参照, (), 設定名)
    工程列 = []
    for x in 計画.工程:
        if x == 意味:
            工程列.append(追加工程)
            x = replace(x, 入力=x.入力 + (素材参照("工程", 工程名),))
        工程列.append(x)
    return 新, 合成計画(tuple(工程列), 計画.出力工程), 旧工程, 設定名, 工程名


def _継続失敗後再検索(鍵, 包, 値, 目録):
    """実不成立を保持し、前prefixの実不足と最新消費から別検索を構成する。"""
    証明 = 包.get("資料補充", {})
    if 証明.get("版") != 資料補充版 or "再検索工程" in 証明:
        return None
    元鍵 = 証明["前計画鍵"]
    if 元鍵 != "運用計画:" + str(int(鍵.split(":")[-1]) - 1):
        raise ValueError("不成立継続の前prefixが不一致")
    元包 = 値[元鍵]
    元再 = 資料補充を構成(元鍵, 元包, 値, 目録)
    if 元再 is None or 指紋(元再) != 指紋(包):
        raise ValueError("不成立継続の元不足・元計画が再導出と不一致")
    失敗鍵 = _試行鍵(鍵, 証明["取得工程"])
    if 失敗鍵 not in 値 or _成果鍵(鍵, 証明["取得工程"]) in 値:
        return None
    試行 = 値[失敗鍵]
    if "不成立成果" not in 試行:
        return None
    不成立 = 結果を復元(試行["不成立成果"])
    if 不成立.保留理由 != "未消費候補がありません":
        return None
    if (試行["能力"] != "知識取得" or 試行["工程"] != 証明["取得工程"]
            or 試行["出力印"] != 指紋(試行["不成立成果"])
            or 試行["採否"] != 不成立.状態.value or 試行["理由"] != 不成立.保留理由):
        raise ValueError("不成立継続の実試行対応が不一致")
    計画 = 計画を復元(元包["計画"])
    工程 = {x.識別子: x for x in 計画.工程}
    意味 = 工程[証明["意味工程"]]
    元意味鍵 = _成果鍵(元鍵, 意味.識別子)
    元不足鍵 = 証明["不足試行鍵"]
    元不足 = 結果を復元(値[元不足鍵]["不成立成果"])
    元意味 = 結果を復元(値[元意味鍵])
    診断 = 資料内容不足を読む(元不足.データ["診断"], 元意味.データ)
    if 指紋(診断["要求"]) != 指紋(元包["解釈"]["要求"]):
        raise ValueError("不成立継続の元要求が不一致")
    取得群, 復帰 = [], {}
    for r in 意味.入力:
        x = 工程[r.識別子]
        if r.領域 != "工程" or x.能力候補 != ("知識取得",):
            raise ValueError("不成立継続の元取得依存が不一致")
        要求 = 知識取得モジュール._要求(能力文脈("", "", 補助={
            "合成設定": 結果を復元(元包["資料"][x.設定参照]).データ}))
        前鍵 = _成果鍵(元鍵, x.識別子)
        前 = 結果を復元(値[前鍵])
        束 = 継続束を読む(前, 要求)
        取得群.append((x, 要求, 前, 束))
        復帰[x.識別子] = 前鍵
        if x.識別子 == 証明["取得工程"]:
            継続不成立を検査(前, 不成立, 要求)
            旧資源, 今資源 = 前.データ.get("資源制御"), 不成立.データ.get("資源制御")
            _最新資源([前, 不成立])
            if (旧資源 is None or 今資源 is None
                    or any(今資源["使用"][k] < v for k, v in 旧資源["使用"].items())
                    or any(今資源["使用"][k] != 旧資源["使用"][k] for k in ("検索回数", "候補数"))
                    or 今資源["使用"]["本文取得数"] - 旧資源["使用"]["本文取得数"] !=
                       不成立.データ["本文取得数"] - 前.データ["本文取得数"]):
                raise ValueError("不成立継続の実消費と共有資源が不一致")
    追加 = _追加検索(鍵, 元包, 計画, 意味, 診断, 取得群, 資源成果=(不成立,))
    if 追加 is None:
        return None
    新, 新計画, 対象, 素材名, 新工程名 = 追加
    再開 = {新工程名, 意味.識別子}
    while True:
        下流 = {x.識別子 for x in 新計画.工程
              if any(r.領域 == "工程" and r.識別子 in 再開 for r in x.入力)} - 再開
        if not 下流:
            break
        再開.update(下流)
    目録.構造検査器._準備(新計画, {k: 結果を復元(v) for k, v in 新["資料"].items()}, 新["外部許可"])
    新["計画"] = 計画を保存(新計画)
    新["資料補充"] = {"版": 資料補充版, "前計画鍵": 鍵, "前計画印": 指紋(包),
        "不足試行鍵": 元不足鍵, "不足印": 指紋(値[元不足鍵]), "意味工程": 意味.識別子,
        "意味印": 指紋(値[元意味鍵]), "取得工程": 対象.識別子,
        "取得印": 指紋(値[復帰[対象.識別子]]), "素材名": 素材名,
        "再開工程": sorted(再開), "再検索工程": 新工程名, "成果復帰": 復帰,
        "取得失敗後再検索": {"元計画鍵": 元鍵, "元計画印": 指紋(元包),
                         "意味成果鍵": 元意味鍵, "不成立試行鍵": 失敗鍵,
                         "不成立試行印": 指紋(試行), "不成立資源印": 指紋(不成立.データ["資源制御"])}}
    return 正準(新)


def 資料補充を構成(鍵, 包, 値, 目録):
    """単独一般資料の型付き内容不足だけを扱う。候補の意味採否は行わない。"""
    if (包.get("解釈", {}).get("方式") != "一般資料"
            or 包.get("回答種別") != "資料文章回答" or 包.get("役割")
            or not 包.get("外部許可") or not 値["運用入力"]["外部許可"]):
        return None
    計画 = 計画を復元(包["計画"])
    工程 = {x.識別子: x for x in 計画.工程}
    内容 = 工程.get("一般内容構成")
    意味 = 工程.get("一般意味選択")
    不足鍵, 意味鍵 = _試行鍵(鍵, "一般内容構成"), _成果鍵(鍵, "一般意味選択")
    if (内容 is None or 内容.能力候補 != ("資料内容構成",)
            or 内容.入力 != (素材参照("工程", "一般意味選択"),)
            or 意味 is None or 意味.能力候補 != ("取得資料意味選択",)
            ):
        return None
    if 不足鍵 not in 値 or 意味鍵 not in 値 or "不成立成果" not in 値[不足鍵]:
        return _継続失敗後再検索(鍵, 包, 値, 目録)
    不足 = 結果を復元(値[不足鍵]["不成立成果"])
    if 不足.成立 or 不足.本文 or 不足.データ.get("版") != 資料内容不足版 or 不足.データ.get("種別") != "資料内容不足":
        return None
    if set(不足.データ) != {"版", "種別", "診断"}:
        raise ValueError("資料補充の不足成果の欄不一致")
    実意味 = 結果を復元(値[意味鍵])
    診断 = 資料内容不足を読む(不足.データ["診断"], 実意味.データ)
    if (不足.参照 != 実意味.参照 or
            指紋(診断["要求"]) != 指紋(包["解釈"]["要求"])):
        raise ValueError("資料補充の不足と原要求・実意味が不一致")
    対象, 取得群 = None, []
    for 参照 in 意味.入力:
        if 参照.領域 != "工程" or 参照.識別子 not in 工程:
            raise ValueError("資料補充の取得依存が未形成")
        候補 = 工程[参照.識別子]
        if 候補.能力候補 != ("知識取得",) or 候補.設定参照 is None:
            raise ValueError("資料補充の取得工程が不一致")
        原設定 = 結果を復元(包["資料"][候補.設定参照]).データ
        要求 = 知識取得モジュール._要求(能力文脈("", "", 補助={"合成設定": 原設定}))
        前 = 結果を復元(値[_成果鍵(鍵, 候補.識別子)])
        束 = 継続束を読む(前, 要求)
        取得群.append((候補, 要求, 前, 束))
        失敗後 = 包.get("資料補充", {}).get("取得失敗後再検索")
        消費済み = (失敗後 is not None and
                 候補.識別子 == 値[失敗後["不成立試行鍵"]]["工程"])
        if (束["消費位置"] < len(束["候補"])
                and not 消費済み
                and 前.データ["本文取得数"] < 要求.最大取得数
                and 前.データ["資料数"] < 要求.最大資料数
                and any(x in 診断["対象"] for x in 要求.必要語)):
            if 対象 is None:
                対象 = 候補
    追加 = None
    if 対象 is None:
        追加 = _追加検索(鍵, 包, 計画, 意味, 診断, 取得群)
        if 追加 is None:
            return None
        新, 新計画, 対象, 素材名, 新工程名 = 追加
        再開 = {新工程名, 意味.識別子}
    else:
        素材名 = "一般:補充元:" + 鍵.split(":")[-1]
        if 素材名 in 包["資料"]:
            raise ValueError("同じ資料補充を反復しません")
        新 = deepcopy(包)
        新["資料"][素材名] = deepcopy(値[_成果鍵(鍵, 対象.識別子)])
        新計画 = 合成計画(tuple(replace(x, 入力=(素材参照("入力", 素材名),)) if x == 対象 else x
                               for x in 計画.工程), 計画.出力工程)
        再開 = {対象.識別子}
    for x in 新計画.工程:
        if any(r.領域 == "工程" and r.識別子 in 再開 for r in x.入力):
            再開.add(x.識別子)
    # 計画は常に依存順で供給される。未閉鎖の依存を取りこぼさない。
    while True:
        追加依存 = {x.識別子 for x in 新計画.工程
                if any(r.領域 == "工程" and r.識別子 in 再開 for r in x.入力)} - 再開
        if not 追加依存:
            break
        再開.update(追加依存)
    if not {"一般意味選択", "一般内容構成", "一般回答照合"} <= 再開:
        raise ValueError("資料補充の意味・内容・照合依存が閉じていません")
    取得鍵 = _成果鍵(鍵, 対象.識別子)
    目録.構造検査器._準備(新計画, {k: 結果を復元(v) for k, v in 新["資料"].items()}, 新["外部許可"])
    新["計画"] = 計画を保存(新計画)
    新["資料補充"] = {"版": 資料補充版, "前計画鍵": 鍵, "前計画印": 指紋(包),
        "不足試行鍵": 不足鍵, "不足印": 指紋(値[不足鍵]), "意味工程": 意味.識別子,
        "意味印": 指紋(値[意味鍵]), "取得工程": 対象.識別子, "取得印": 指紋(値[取得鍵]),
        "素材名": 素材名, "再開工程": sorted(再開)}
    if 追加 is not None:
        新["資料補充"]["再検索工程"] = 新工程名
    return 正準(新)


def 資料補充を検査(鍵, 包, 値, 目録, 最大回復):
    """再封印した差替えも、旧prefixの実成果と再導出した計画に照合する。"""
    数 = int(鍵.split(":")[-1])
    if not 0 <= 数 <= 最大回復:
        raise ValueError("資料補充回数の上限不一致")
    while "資料補充" in 包:
        根拠 = 包["資料補充"]
        前鍵 = "運用計画:" + str(数 - 1)
        if 数 <= 0 or 根拠.get("版") != 資料補充版 or 根拠.get("前計画鍵") != 前鍵:
            raise ValueError("資料補充の前計画対応不一致")
        前包 = 値[前鍵]
        再 = 資料補充を構成(前鍵, 前包, 値, 目録)
        if 再 is None or 指紋(再) != 指紋(包):
            raise ValueError("資料補充の計画・不足・取得原値が再導出と不一致")
        for 工程 in 計画を復元(包["計画"]).工程:
            新鍵, 旧鍵 = _成果鍵(鍵, 工程.識別子), _成果鍵(前鍵, 工程.識別子)
            if 新鍵 not in 値:
                continue
            復帰元 = 根拠.get("成果復帰", {}).get(工程.識別子, 旧鍵)
            if 工程.識別子 not in 根拠["再開工程"] and 指紋(値[新鍵]) != 指紋(値[復帰元]):
                raise ValueError("資料補充の対象外成果が変化しました")
            if 工程.識別子 == 根拠.get("再検索工程"):
                設定 = 結果を復元(包["資料"][工程.設定参照]).データ
                要求 = 知識取得モジュール._要求(能力文脈("", "", 補助={"合成設定": 設定}))
                次 = 結果を復元(値[新鍵])
                新束 = 継続束を読む(次, 要求)
                失敗後 = 根拠.get("取得失敗後再検索")
                取得元鍵 = 失敗後["元計画鍵"] if 失敗後 else 前鍵
                旧群 = [結果を復元(値[_成果鍵(取得元鍵, x.識別子)])
                       for x in 計画を復元(値[取得元鍵]["計画"]).工程 if x.能力候補 == ("知識取得",)]
                旧資料 = [m for x in 旧群 for m in x.データ["資料"]]
                資源群 = 旧群 + ([結果を復元(値[失敗後["不成立試行鍵"]]["不成立成果"])] if 失敗後 else [])
                旧資源, 新資源 = _最新資源(資源群), 次.データ.get("資源制御")
                _最新資源([*資源群, 次])
                if (新束["親記録SHA256"] is not None or 新束["検索済み語"] != [要求.検索語]
                        or 次.データ["資料数"] != 1 or 工程.入力
                        or any(m["本文SHA256"] == n["本文SHA256"] or m["最終URL"] == n["最終URL"]
                               for m in 旧資料 for n in 次.データ["資料"])
                        or type(新資源) is not dict or 旧資源 is None
                        or 新資源["当回ID"] != 旧資源["当回ID"] or 新資源["上限"] != 旧資源["上限"]
                        or any(v > 新資源["使用"][k] for k, v in 旧資源["使用"].items())
                        or 新資源["使用"]["検索回数"] != 旧資源["使用"]["検索回数"] + 1
                        or 新資源["使用"]["本文取得数"] - 旧資源["使用"]["本文取得数"] != 次.データ["本文取得数"]
                        or 新資源["使用"]["候補数"] - 旧資源["使用"]["候補数"] !=
                           len(新束["候補"]) + sum(x.get("作用") == "候補除外" for x in 次.データ["試行"])):
                    raise ValueError("追加検索に同じ当回の新規原本文の進展がありません")
            elif 工程.識別子 == 根拠["取得工程"] and "再検索工程" not in 根拠:
                設定 = 結果を復元(包["資料"][工程.設定参照]).データ
                要求 = 知識取得モジュール._要求(能力文脈("", "", 補助={"合成設定": 設定}))
                継続進展を検査(結果を復元(値[旧鍵]), 結果を復元(値[新鍵]), 要求)
        鍵, 包, 数 = 前鍵, 前包, 数 - 1
    if 数 != 0:
        raise ValueError("資料補充の証明が初期計画まで閉じていません")
    if any(x.能力候補 == ("知識取得",) and x.入力 for x in 計画を復元(包["計画"]).工程):
        raise ValueError("初期計画へ継続入力を偽装できません")
    return True
