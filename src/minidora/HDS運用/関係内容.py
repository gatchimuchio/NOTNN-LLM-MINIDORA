class 資料条件変更内容不足(主張内容不足):
    def __init__(self, 構造, 理由):
        super().__init__(構造, 理由)
        self.診断 = 正準({"版":"HDS資料条件変更内容不足-v1","種別":"資料条件変更内容不足","理由":理由,"構造":構造})


def 資料条件変更内容を構成(構造, *, 形式=None):
    if not 関係資料を検査(構造) or 構造["版"] != 資料条件変更読解版:
        raise ValueError("資料条件変更の全源再導出が不一致")
    照合=構造["原限定保持照合"]
    if 照合["状態"] not in ("原限定保持照合", "明示仮定内の原限定保持照合"):
        raise 資料条件変更内容不足(構造, "書換範囲の具体照合が未形成です。"+"。".join(構造["確認待ち"]))
    要求=構造["要求"];形式=要求["形式"] if 形式 is None else 形式
    if 形式 not in ("文章","箇条書き","引用"): raise ValueError("資料条件変更の形式不正")
    素材,単位,順序={},[],[]
    def 追加(本文,種別=None):
        if len(単位)>=120: raise 資料条件変更内容不足(構造,"原条件を保持する説明の単位上限")
        名="説明"+str(len(単位));素材[名]=_結果辞書(能力結果(True,本文))
        単位.append(文章単位(名,種別 or {"文章":"段落","箇条書き":"箇条書き","引用":"引用"}[形式],
                            (文章断片(名,0,len(本文)),),必須=True,保護=True));順序.append(名)
    追加("原条件を保持した書換検討","見出し")
    追加("書換主張：「"+要求["主張"]["本文"]+"」。資料の記載と主体範囲を照合します。")
    追加(構造["境界"],"留保")
    if 照合["仮定"] is not None:
        追加("書換主張の実対象対応は未形成です。"+照合["仮定"]+"、以下の主体範囲差と限定案を示せます。この仮定を実対象一致へ認定しません。","留保")
    else:
        追加("原資料と書換主張で明示された話題の原表記が一致します。用言の辞書形列・肯否・時制を原範囲で照合しました。対象物の省略補完や世界判断は行っていません。","留保")
    原=照合["原限定"]["読解"]["役割"];差=照合["範囲差"]
    追加("原文は主体の範囲を「"+差["原主体"]["原文"]+差["原限定標識"]["原文"]+"」に限定しています。書換主張は「"+差["書換主体"]["原文"]+
        "」という全称主体範囲です。原主体の限定を残す証明がないため、その限定を消した書換を意味同等とは扱えません。これは現実の誰かの能力・許可の反証ではありません。")
    if "連体前提" in 原:
        追加("主体名詞「"+原["名詞主要部"]["原文"]+"」に付く連体前提「"+原["連体前提"]["原文"]+"」を維持します。未明示の前提主体や前提充足を補完しません。")
    案=[]
    for 行 in 構造["原記載"]:
        読=行["資料作用"]["局所限定"]["読解"];役=読["役割"]
        if 読["種別"]=="主体範囲限定":
            話題=役.get("話題")
            本文=(話題["原文"]+役["話題標識"]["原文"] if 話題 else "")+役["主体NP"]["原文"]+役["限定標識"]["原文"]+役["主体格"]["原文"]+役["用言"]["原文"]+"。"
        elif 読["種別"]=="名詞述部範囲限定と連用否定":
            追加("「"+役["明示主体"]["原文"]+"」について、名詞述部「"+役["限定名詞"]["原文"]+役["限定標識"]["原文"]+
                "」の範囲と、対象「"+役["否定対象物"]["原文"]+"」への「"+役["否定用言"]["原文"]+"」という否定を別々に維持します。名詞の範囲を後続操作の許可へ変えません。")
            本文="".join(役[k]["原文"] for k in ("明示主体","主体標識","限定名詞","限定標識","名詞連用接続","読点","否定対象物","対象格","否定用言"))+"。"
        else: raise 資料条件変更内容不足(構造,"限定案の全原条件型が未対応")
        案.append(本文)
    追加("原限定を維持する具体案："+"".join(案))
    if 照合["仮定"] is not None:
        追加("この案は「"+照合["仮定"]+"」という条件の下での提示です。実対象対応は未形成で、変更適用や利用許可は認定していません。","留保")
    if 要求["取消指定"] is not None:
        追加("取消選択「"+要求["取消指定"]["選択原文"]+"」が指す実条件は未対応です。条件を取り消していません。取消対象の条件の原文を確認してください。","留保")
    else: 追加("取消は求められていません。原条件を変更又は失効させていません。","留保")
    for 確認 in 構造["確認待ち"]:追加(確認,"留保")
    追加("案を提示した段階です。原資料の書換・条件取消は未適用で、世界の主張支持・許可・能力可能・十分条件・存在は未認定です。","留保")
    if sum(len(v["本文"]) for v in 素材.values())>要求["最大文字数"]:
        raise 資料条件変更内容不足(構造,"原限定と仮定を保持する必須内容が文字予算を超えます")
    return 正準({"素材":素材,"仕様":asdict(文章仕様(tuple(単位),tuple(順序),要求["最大文字数"]))})


def 主張採用内容を構成(構造, *, 形式=None):
    if not 関係資料を検査(構造) or 構造["版"] != 主張採用読解版:
        raise ValueError("主張採用内容の構造不整合")
    if not any(行["読解"] or any(記載["必要内容寄与"] is True
                  for 原 in 行["材料局所読解"] for 記載 in 原["読解"])
               for 行 in 構造["資料群"].values()):
        raise 主張内容不足(構造, "材料の読解済み記載がありません。原Pの判定未実施と材料未読を保持します")
    要求, P = 構造["要求"], 構造["P読解"]
    形式 = 要求["形式"] if 形式 is None else 形式
    if 形式 not in ("文章", "箇条書き", "引用"):
        raise ValueError("主張採用回答の形式不正")
    素材, 単位, 順序 = {}, [], []
    def 追加(本文, 種別=None):
        if len(単位) >= 120:
            raise 主張内容不足(構造, "主張採用説明単位の上限。原限定を削らず材料範囲を絞ってください")
        名 = "説明" + str(len(単位))
        素材[名] = _結果辞書(能力結果(True, 本文))
        単位.append(文章単位(名, 種別 or {"文章": "段落", "箇条書き": "箇条書き", "引用": "引用"}[形式],
                          (文章断片(名, 0, len(本文)),), 必須=True, 保護=True))
        順序.append(名)
    元 = 要求["原主張"]
    追加("主張と材料の検討", "見出し")
    追加("原要求行為：" + 元["行為"] + " / 原行為" + str(元["行為範囲"]) + "：" + 元["行為原文"])
    追加("原主張" + str(元["主張"]["原文範囲"]) + "：" + 要求["問い"])
    追加(構造["境界"], "留保")
    追加("原主張の読解：" + P["状態"] + "。要求行為の実行は未認定で、資料記載の説明を行います。", "留保")
    for 診断 in P["診断"]:
        追加("原主張全範囲の読解阻害：" + 診断 + "。対象・条件・期間・量化の個別対応を確定せず、材料の対象へ補完しません。", "留保")
    for 残差 in 元["HDS残差"]:
        追加("原主張に残る未確認原文：" + 残差["原文"] + " / " + 残差["理由"], "留保")
    for 名, 行 in 構造["資料群"].items():
        追加("資料「" + 名 + "」：" + 行["解釈状態"], "見出し")
        採用ID = {項["識別子"] for 項 in 行["採用記載"]}
        for 記載 in 行["読解"]:
            採否 = "推論採用可能" if 記載["識別子"] in 採用ID else "限定作用域未確定のため推論未採用"
            追加("読解済み原記載" + str(記載["範囲"]) + "：" + 記載["原文"] + " / " + 採否
                + " / 記載内容：" + 関係式を表現(命題を復元(記載["式"], 内部許可=True)))
        for 原 in 行["材料局所読解"]:
            for 記載 in 原["読解"]:
                役 = 記載["役割"]
                追加("材料で読めた原記載" + str(記載["範囲"]) + "：「" + 記載["原文"] + "」。")
                if 記載["種別"] == "名詞述部連用":
                    追加("材料では「" + 役["話題NP"]["原名詞句"]["原文"] + "」の値を「"
                        + 役["名詞述部"]["原文"] + "」と記載しています。")
                    if 役["数量原形"] is not None:
                        数 = 役["数量原形"]
                        追加("数詞「" + 数["数詞"]["原文"] + "」と計量名詞「" + 数["計量名詞"]["原文"]
                            + "」をその表記で保持します。別の値・単位や期間へ読み替えていません。", "留保")
                elif 記載["種別"] == "明示格用言記載":
                    格 = 役["明示格"]
                    追加("材料の明示格：" + "、".join("「" + 値["名詞句"]["原名詞句"]["原文"]
                        + "」" + 名 for 名, 値 in 格.items()) + "。用言は「" + 役["用言"]["原文"] + "」です。")
                    if 記載["明示主体"] is None:
                        追加("この用言の実行主体は原記載で明示されていません。前節の対象や値を主体へ補完しません。", "留保")
                elif 記載["種別"] == "話題用言記載":
                    話題型 = 役["話題NP"]
                    述部 = (役["未完了標識"]["原文"] if 役["未完了標識"] else "") + 役["用言"]["原文"]
                    追加("材料は「" + 話題型["原名詞句"]["原文"] + "」について「" + 述部 + "」と記載しています。")
                    if 話題型["連体前提"] is not None:
                        追加("名詞「" + 話題型["名詞主要部"]["原文"] + "」に付く「" + 話題型["連体前提"]["原文"]
                            + "」という前提を保持します。前提の未明示主体を補完せず、前提充足を世界の事実と認定しません。", "留保")
                    追加("話題の名詞と用言の実行主体の対応は未確定です。", "留保")
                    if 役["未完了標識"] is not None:
                        追加("「" + 述部 + "」という未完了の原表現を保持し、完了済みや恒久的な不可能へ変えません。", "留保")
                        追加("確認候補：「" + 話題型["原名詞句"]["原文"] + "」についての実施状況・結果・適用対象と条件を確認してください。"
                            + "原主張の期間・量化に対応する根拠との接続は未形成です。この候補を原主張の必要条件や反証と認定していません。", "留保")
                else:
                    raise 主張内容不足(構造, "材料局所役割の内容型が未対応")
                追加("上記は材料の局所役割の説明です。原主張への支持・反証や世界の保証を採用したものではありません。", "留保")
            for 未読 in 原["残差"]:
                追加("局所役割も未読の原記載" + str(未読["範囲"]) + "：「" + 未読["原文"] + "」 / " + 未読["理由"], "留保")
        if 行["限定隔離"]:
            追加("未確定の例外・限定に関係する記載を局所隔離し、読めた記載と未採用原文を保持します。", "留保")
        if 行["判定"] is None:
            追加("この資料による原主張の支持・反証判定は未実施です。材料不足や反証の判定へ読み替えません。", "留保")
        else:
            追加("読めた記載内の判定：" + 行["判定"]["判定"])
            for 節 in 行["説明"]["節"]:
                本文 = 節["本文"]
                if 節["役割"] == "導出作用":
                    節点 = 行["判定"]["導出"][節["根拠"][0]]
                    本文 = "導出（" + 節点["作用"] + "）：" + 関係式を表現(命題を復元(節点["式"], 内部許可=True))
                追加(本文, "留保" if 節["役割"] == "局所仮定" else None)
            for 候補 in 行["不足候補"]:
                追加("導出経路の確認候補：" + 関係式を表現(命題を復元(候補["前件"]))
                    + " / " + 候補["判定"] + " / " + 候補["位置づけ"], "留保")
        for 残差 in 行["残差"]:
            追加("命題未読・未採用原記載" + str(残差["範囲"]) + "：" + 残差["原文"] + " / " + 残差["理由"], "留保")
        if 行["採用記載"]:
            追加("限定説明案：資料「" + 名 + "」の読解済み原記載" + str([項["範囲"] for 項 in 行["採用記載"]])
                + "について、上記の記載内容と限定を資料内の説明として使用できます。原主張全体の断定・保証は未認定です。", "留保")
        追加("確認範囲：原主張" + str(元["主張"]["原文範囲"]) + "と資料「" + 名
            + "」の上記原記載について、対象・時点・条件・期間・量化の対応と未読箇所の作用域を確認してください。", "留保")
    if sum(len(項["本文"]) for 項 in 素材.values()) > 要求["最大文字数"]:
        raise 主張内容不足(構造, "必須の主張・材料・限定説明が文字予算を超えます。切断せず停止します")
    return 正準({"素材": 素材, "仕様": asdict(文章仕様(tuple(単位), tuple(順序), 要求["最大文字数"]))})


def 関係内容を構成(構造, *, 形式=None):
    if type(構造) is dict and 構造.get("版") == 資料条件変更読解版:
        return 資料条件変更内容を構成(構造, 形式=形式)
    if type(構造) is dict and 構造.get("版") == 主張採用読解版:
        return 主張採用内容を構成(構造, 形式=形式)
    if not 関係資料を検査(構造):
        raise ValueError("関係内容の構造不整合")
    要求 = 構造["要求"]
    if 要求["不足調査"] and 構造["取得状態"] == "必要":
        raise ValueError("要求された不足調査が未実行")
    形式 = 要求["形式"] if 形式 is None else 形式
    if 形式 not in ("文章", "箇条書き", "引用"):
        raise ValueError("関係回答の形式不正")
    素材, 単位, 順序 = {}, [], []
    def 追加(本文, 種別=None):
        if len(単位) >= 120:
            raise ValueError("説明単位の上限。原文や例外を削らず資料範囲を絞ってください")
        名 = "説明" + str(len(単位))
        素材[名] = _結果辞書(能力結果(True, 本文))
        単位.append(文章単位(名, 種別 or {"文章": "段落", "箇条書き": "箇条書き", "引用": "引用"}[形式],
                          (文章断片(名, 0, len(本文)),), 必須=True, 保護=True))
        順序.append(名)
    追加("関係・条件に基づく説明", "見出し")
    追加("問い：" + 要求["問い"])
    追加(構造["境界"], "留保")
    if 要求["不足調査"]:
        追加("不足調査：" + 構造["取得状態"] + "。語の一致や取得成功だけでは問いを解決したと扱いません。", "留保")
        if 構造["取得"] is not None and not 結果を復元(構造["取得"]).成立:
            追加("取得失敗の観測：" + 結果を復元(構造["取得"]).保留理由, "留保")
    if "横断" in 構造:
        from .資料横断 import 横断式を表現
        横断 = 構造["横断"]
        追加("資料を結び付けた判定", "見出し")
        追加(横断["境界"], "留保")
        追加("照会資料：" + 要求["照会資料"] + " / " + 横断["状態"])
        追加("宣言の照合：" + str(横断["共通範囲"]), "留保")
        追加("横断判定：" + 横断["判定"]["判定"] + " / 実根拠の資料：" + "、".join(横断["使用資料"]))
        for 対応 in 横断["対象対応"].values():
            追加("共有識別子「" + 対応["識別子"] + "」：" + " / ".join(
                "資料「" + 行["資料"] + "」の「" + 行["対象"] + "」" for 行 in 対応["表記"]))
        for 節 in 横断["説明"]["節"]:
            本文 = 節["本文"]
            if 節["役割"] == "導出作用":
                節点 = 横断["判定"]["導出"][節["根拠"][0]]
                本文 = "横断導出（" + 節点["作用"] + "）：" + 横断式を表現(節点["式"], 横断["対象対応"])
            追加(本文, "留保" if 節["役割"] == "局所仮定" else None)
        for 候補 in 横断["不足候補"]:
            追加("横断確認候補（" + 候補["規則記載"] + "）：" + 横断式を表現(候補["前件"], 横断["対象対応"]) +
                "。現状：" + 候補["判定"] + "。" + 候補["位置づけ"], "留保")
        for 行 in 横断["保留"]:
            追加("横断未採用：資料「" + 行["資料"] + "」" + 行["記載"] + " / " + 行["理由"], "留保")
    for 区分 in ("資料群", "公開資料群"):
        for 名, 行 in 構造[区分].items():
            追加(("公開資料" if 区分 == "公開資料群" else "資料") + "「" + 名 + "」", "見出し")
            if 区分 == "公開資料群":
                参照 = 結果を復元(行["資料"]).参照
                追加("取得元：" + " / ".join(項.URL for 項 in 参照) + "。保存時の本文を使用し、現在の最新性は保証しません。", "留保")
            追加("読めた記載内の判定：" + 行["判定"]["判定"] + " / " + 行["解釈状態"])
            if 行["限定隔離"]:
                追加("作用域を確定できない例外・限定に関係する記載だけを局所隔離しています。隔離した原文は未採用原文として保持します。", "留保")
            for 節 in 行["説明"]["節"]:
                本文 = 節["本文"]
                if 節["役割"] == "導出作用":
                    節点 = 行["判定"]["導出"][節["根拠"][0]]
                    本文 = "導出（" + 節点["作用"] + "）：" + 関係式を表現(命題を復元(節点["式"], 内部許可=True))
                追加(本文, "留保" if 節["役割"] == "局所仮定" else None)
            if 行["判定"]["判定"] == "未確定":
                追加("支持・反証を導けていません。記載不足・未読解・推論範囲の不足を含み、問いが偽だという意味ではありません。", "留保")
            if 行["判定"]["判定"] == "矛盾":
                追加("支持と反証の両方を保持します。片側の証拠を隠して採用しません。", "留保")
            for 候補 in 行["不足候補"]:
                追加("確認候補（" + 候補["規則記載"] + "）：" + 関係式を表現(命題を復元(候補["前件"])) +
                   "。現状：" + 候補["判定"] + "。" + 候補["位置づけ"], "留保")
            for 残差 in 行["残差"]:
                追加("未採用原文[" + str(残差["範囲"][0]) + ":" + str(残差["範囲"][1]) + "]：" +
                   残差["原文"] + " / " + 残差["理由"], "留保")
    追加("採用判断の前に、資料の対象・時点・適用条件と、残る未解釈箇所が今回の目的に関係するかを確認してください。", "留保")
    return 正準({"素材": 素材, "仕様": asdict(文章仕様(tuple(単位), tuple(順序), 要求["最大文字数"]))})


def _生成(構造, 形式):
    仕様 = 関係内容を構成(構造, 形式=形式)
    結果 = 文章を作る({名: 能力結果を復元(値) for 名, 値 in 仕様["素材"].items()}, 文章仕様を復元(仕様["仕様"]))
    if not 結果.成立:
        raise ValueError("関係文章の生成不成立:" + 結果.保留理由)
    return 結果


def 関係回答を照合(構造, 文章, *, 形式=None):
    形式 = 構造["要求"]["形式"] if 形式 is None else 形式
    再 = _生成(構造, 形式)
    if 指紋(_結果辞書(文章)) != 指紋(_結果辞書(再)):
        raise ValueError("関係内容と生成文章の不一致")
    参照 = _参照結合(項 for 区分 in ("資料群", "公開資料群") for 行 in 構造[区分].values() for 項 in 結果を復元(行["資料"]).参照)
    保存版 = 資料条件変更回答版 if 構造["版"] == 資料条件変更読解版 else 主張採用回答版 if 構造["版"] == 主張採用読解版 else 関係回答版
    return 能力結果(True, 文章.本文, 参照=参照, データ={"版": 保存版, "種別": "関係資料回答",
        "構造": 正準(構造), "表示形式": 形式, "文章": 結果を保存(結果を復元(結果を保存(文章))), "照合": "依頼・原資料・関係導出・内容仕様・文章再生成一致"})


def 関係回答を検査(成果):
    try:
        if not isinstance(成果, 能力結果) or not 成果.成立 or 成果.データ.get("種別") != "関係資料回答":
            return False
        if 成果.データ.get("版") == "HDS主張採用回答-v1":
            return False
        再 = 関係回答を照合(成果.データ["構造"], 結果を復元(成果.データ["文章"]), 形式=成果.データ["表示形式"])
        return 指紋(結果を保存(再)) == 指紋(結果を保存(成果))
    except (ValueError, TypeError, KeyError, AttributeError, RecursionError, OverflowError):
        return False


def 関係回答を再表現(成果, 形式):
    if not 関係回答を検査(成果):
        raise ValueError("関係回答の再表現起点が不整合")
    構造 = 成果.データ["構造"]
    return 関係回答を照合(構造, _生成(構造, 形式), 形式=形式)
