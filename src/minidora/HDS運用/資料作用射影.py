def _局所範囲を読む(文, 起点):
    """条件を含む名詞修飾又は明示報告の引用を、外側の主述へ移さない。"""
    from ..会話字句 import 会話字句を観測, 会話字句不成立

    def 範囲(種別, 左, 右):
        return {"種別": 種別, "原文": 文[左:右], "開始": 起点 + 左, "終了": 起点 + 右}

    # 引用の内容だけでは帰属を確定しない。外側の報告述部と引用格を要する。
    引用 = re.fullmatch(r'(?P<前>[^「」『』。\n]*)(?P<開>「|『)(?P<内>[^「」『』]+)(?P<閉>」|』)'
        r'(?P<格>と)(?P<述部>(?:記載|記述|報告|説明)(?:する|した|している|されている)|述べ(?:る|た|ている))', 文)
    if 引用 and ((引用["開"], 引用["閉"]) in (("「", "」"), ("『", "』"))):
        前 = 引用["前"]
        主格 = re.fullmatch(r"([^はがをにで、,。\n]{1,80})(は|が)", 前) if 前 else None
        if 前 and (not 主格 or not _名詞句(主格[1])):
            return None
        if not re.search(r"ただし|但し|場合|とき|[^はがを、,。\n]+日は", 引用["内"]):
            return None
        部分 = [範囲("引用内容", 引用.start("内"), 引用.end("内")),
                範囲("引用格", 引用.start("格"), 引用.end("格")),
                範囲("外側報告述部", 引用.start("述部"), 引用.end("述部"))]
        if 主格:
            部分.insert(0, 範囲("外側報告主語", 0, len(主格[1])))
        return {"種別": "明示報告内の引用条件", "開始": 起点, "終了": 起点 + len(文),
                "外側述部型": "報告", "外側非動作証明": None, "外側未読解": None,
                "範囲": 部分, "字句": [],
                "読み": "閉じた引用内容と外側の引用格・報告述部"}

    名詞化 = _時間条件名詞化を読む(文, 起点)
    if 名詞化:
        return 名詞化
    時間事象 = _時間事象名詞化を読む(文, 起点)
    if 時間事象:
        return 時間事象

    自己 = _自己述定を読む(文, 起点)
    if 自己:
        return 自己
    if re.match(r"(?:ただし|但し|なお|例外として)", 文) or re.search(r"[「」『』]", 文):
        return None
    try:
        接続 = tuple(最上位位置(文.translate(str.maketrans({"（": "(", "）": ")"})), ("場合", "とき")))
    except ValueError:
        return None
    if len(接続) != 1:
        return None
    左, 語 = 接続[0]
    内部作用 = _句を読む(文[:左], 起点, 省略許可=True)
    if not 内部作用:
        return None
    後開始 = 左 + len(語)
    # 読点で独立した帰結を、名詞の内部へ押し込まない。
    if not 文[後開始:].startswith("に") or 文[後開始 + 1:].startswith(("、", ",")):
        return None
    後開始 += 1
    連体 = re.match(r"(?P<核>[一-龥々ァ-ヴーA-Za-z・]{1,40})(?P<活用>される|された|する|した)", 文[後開始:])
    if not 連体:
        return None
    名詞開始 = 後開始 + 連体.end()
    try:
        外格 = tuple(最上位位置(文[名詞開始:].translate(str.maketrans({"（": "(", "）": ")"})), ("は", "が")))
    except ValueError:
        return None
    if len(外格) != 1:
        return None
    格位置, 格 = 外格[0]
    格位置 += 名詞開始
    名詞 = 文[名詞開始:格位置]
    if not 名詞 or re.search(r"[、,。\n]", re.sub(r"[（(][^（）()]*[）)]", "", 名詞)):
        return None
    # 括弧は名前の注記として局所に保つ。未読の条件・動詞を注記として除去しない。
    注記 = list(re.finditer(r"[（(]([^（）()]*)[）)]", 名詞))
    裸名詞 = re.sub(r"[（(][^（）()]*[）)]", "", 名詞)
    if re.search(r"[（）()]", 裸名詞):
        return None
    try:
        核字句 = 会話字句を観測(連体["核"])
        if not 核字句 or any(項.未知語 for 項 in 核字句) or 核字句[-1].品詞[:3] != ("名詞", "普通名詞", "サ変可能"):
            return None
        for 項 in 注記:
            if re.search(r"ただし|但し|場合|とき|しない|ではない|上記|以下", 項[1]):
                return None
            if any(字.品詞[0] not in ("名詞", "接尾辞", "補助記号", "空白") for 字 in 会話字句を観測(項[1])):
                return None
        名詞字句 = 会話字句を観測(裸名詞)
        if not 名詞字句 or any(項.未知語 or not (項.品詞[:2] == ("名詞", "普通名詞") or
                項.表層 == "の" and 項.品詞[0] == "助詞") for 項 in 名詞字句):
            return None
        if 名詞字句[-1].品詞[:2] != ("名詞", "普通名詞"):
            return None
        外述開始 = 格位置 + len(格)
        外述 = 文[外述開始:].lstrip("、, ")
        外述開始 += len(文[外述開始:]) - len(外述)
        外字句 = 会話字句を観測(外述)
        述部型, 非動作証明 = "未読解外側作用", None
        留保構造 = bool(re.search(r"ただし|但し|場合|とき|なら|上記|下記|以下|以上", 外述))
        # 最後の形容詞だけでは、前の一般動詞・連用接続・主語継承を読了しない。
        if (外字句 and not 留保構造 and not any(字.未知語 or 字.品詞[0] == "動詞" for 字 in 外字句)
                and 外字句[-1].品詞[0] == "形容詞" and 外字句[-1].活用形.startswith("終止形")
                and all(字.品詞[0] in ("名詞", "形状詞", "接尾辞", "接頭辞", "助詞", "連体詞", "副詞", "補助記号")
                        for 字 in 外字句[:-1])):
            述部型 = "形容詞"
            非動作証明 = {"読み": "一般動詞を含まない既知字句列と形容詞終止", "外述原文": 外述}
        elif not 留保構造 and (終止 := re.search(r"(?:である|です)$", 外述)):
            名詞述部 = 会話字句を観測(外述[:終止.start()])
            if (名詞述部 and 名詞述部[-1].品詞[:2] == ("名詞", "普通名詞") and
                    all(not 字.未知語 and (字.品詞[0] in ("名詞", "形状詞", "接尾辞", "接頭辞")
                        or 字.表層 == "の" and 字.品詞[0] == "助詞"
                        or 字.品詞[0] == "助動詞" and 字.辞書形 == "だ" and 字.活用形.startswith("連体形"))
                        for 字 in 名詞述部)):
                述部型 = "名詞述語"
                非動作証明 = {"読み": "既知名詞述部と明示コピュラ", "外述原文": 外述}
        # 字句の原位置は、注記を除いた表記ではなく元の全文から保持する。
        全字句 = 会話字句を観測(文)
    except 会話字句不成立:
        return None
    主要部 = 名詞字句[-1].表層
    主要部開始 = 文.rfind(主要部, 名詞開始, 格位置)
    部分 = [範囲("内部前件", 0, 左), 範囲("内部条件接続", 左, 後開始),
            範囲("連体述部", 後開始, 名詞開始), 範囲("名詞主要部", 主要部開始, 主要部開始 + len(主要部)),
            範囲("外側主格", 格位置, 格位置 + len(格)), 範囲("外側述部", 外述開始, len(文))]
    部分.extend(範囲("名詞注記", 名詞開始 + 項.start(), 名詞開始 + 項.end()) for 項 in 注記)
    字句 = []
    for 項 in 全字句:
        記録 = asdict(項)
        記録["品詞"] = list(項.品詞)
        記録["開始"] += 起点
        記録["終了"] += 起点
        字句.append(記録)
    return {"種別": "名詞内部の条件修飾", "開始": 起点, "終了": 起点 + len(文),
            "外側述部型": 述部型, "範囲": 部分, "字句": 字句,
            "外側非動作証明": 非動作証明,
            "外側未読解": None if 非動作証明 else {**範囲("未読外側作用", 外述開始, len(文)),
                "理由": "外側の一般動詞・連用接続・主語継承又は未知述部を非動作と証明できない"},
            "内部作用": 内部作用,
            "読み": "連体サ変・既知名詞主要部・外側主格への内部条件帰属"}


def _候補を読む(行):
    if (行["関係"].get("定義") or {}).get("報告定義"):
        # 報告の後続や引用内を外側の作用・条件・因果の核に転写しない。
        return None, None, False, [], None
    文, _ = _終止を除く(行["対応"]["原文"])
    起点 = 行["対応"]["開始"]
    局所 = _局所範囲を読む(文, 起点)
    条件 = None if 局所 else _条件を読む(文, 起点)
    時間事象 = 局所 and "時間事象帰属証明" in 局所
    作用 = None if 条件 or 時間事象 else _句を読む(文, 起点)
    if not 条件 and not 作用 and not 時間事象 and 行["関係"]["理由"]:
        結果文, _ = _終止を除く(行["関係"]["理由"]["結果"])
        位置 = 文.rfind(結果文)
        if 位置 >= 0 and 文[位置:] == 結果文:
            作用 = _句を読む(結果文, 起点 + 位置)
    if (not 条件 and not 作用 and not 時間事象 and not 行["関係"]["理由"]
            and (目的 := 行["関係"]["目的"]) and 目的.get("接続") != "連体用途"):
        手段文, _ = _終止を除く(目的["手段"])
        位置 = 文.rfind(手段文)
        if 位置 >= 0 and 文[位置:] == 手段文 and 文.count(手段文) == 1:
            作用 = _句を読む(手段文, 起点 + 位置)
    核候補 = [_照合(項["動作"]) + "する" for 項 in re.finditer(
        r"(?P<動作>[一-龥々ァ-ヴーA-Za-z・]{1,40})(?:" + _活用 + r")", 文)]
    try:
        接続条件 = any(re.match(r"(?:には|は|に)", 文[位置 + len(語):])
                       for 位置, 語 in 最上位位置(文, ("場合", "とき")))
    except ValueError:
        接続条件 = False
    条件候補 = not 局所 and bool(条件 or (核候補 and (接続条件 or
        re.match(r"(?:ただし|但し|なお|例外として)", 文) or
        (_引用.search(文) and re.search(r"ただし|但し|場合(?:には|は|に)|とき(?:には|は|に)|[^はがを、,。\n]+日は", 文)))))
    return 作用, 条件, 条件候補, 核候補, 局所


def _座標参照を除く(値):
    if type(値) is dict:
        return {鍵: _座標参照を除く(項) for 鍵, 項 in 値.items() if not 鍵.endswith("座標ID")}
    return 値


def _記載指紋(記載):
    return 指紋([{ "対応": 行["対応"], "節": 行["節"], "段落": 行["段落"]} for 行 in 記載])


def 資料作用束を付す(記載, 原資料):
    """全記載を列挙してから射影する。原資料は復元された本文と保存値。"""
    for 名前, (本文, 保存値) in 原資料.items():
        全行 = [行 for 行 in 記載 if 行["対応"]["資料"] == 名前]
        所有 = {"資料ID": 名前, "本文指紋": hashlib.sha256(本文.encode("utf-8")).hexdigest(),
                "原資料版": 保存値["内容"].get("データ", {}).get("版", "版指定なし"),
                "保存指紋": 指紋(保存値), "本文長": len(本文),
                "全記載ID": [行["ID"] for 行 in 全行],
                "全記載指紋": _記載指紋(全行)}
        for 行 in 全行:
            対応 = 行["対応"]
            if 本文[対応["開始"]:対応["終了"]] != 対応["原文"]:
                raise ValueError("資料作用の原文範囲が不一致")
            起点 = 対応["開始"]
            作用, 条件, 条件候補, 核候補, 局所 = _候補を読む(行)
            if 局所 and "時間事象帰属証明" in 局所:
                座標, 関係, 残差, 履歴 = _時間事象根拠族(行, 局所, 所有)
                行["資料作用"] = {"版": 資料作用版, "原資料": 所有, "記載ID": 行["ID"],
                    "作用": 作用, "条件": 条件, "条件候補": 条件候補, "動作核候補": 核候補,
                    "局所範囲": 局所, "局所限定": None,
                    "座標": 座標, "関係": 関係, "残差": 残差, "意味作用": 履歴}
                continue
            座標, 関係, 残差 = [], [], []
            由来 = 名前 + ":" + 所有["本文指紋"]
            基底 = 行["ID"] + ":資料作用"
            座標.append(_交換(HDS座標(基底, "原資料記載", 対応, 原文範囲=(起点, 対応["終了"]),
                                      由来=由来, 再開放条件=("原資料版又は全記載変更",))))
            枠 = 条件["帰結"] if 条件 else 作用
            if 枠:
                for 種別, 項 in 枠["役割"].items():
                    座標ID = 基底 + ":" + 種別
                    項["座標ID"] = 座標ID
                    if 種別 == "対象物" and 項["名詞構造"]["確定候補"]:
                        名詞 = 項["名詞構造"]
                        名詞["主要部座標ID"] = 座標ID + ":主要部"
                        最終字句 = 名詞["字句"][-1]
                        座標.append(_交換(HDS座標(名詞["主要部座標ID"], "名詞主要部候補", 最終字句,
                            原文範囲=tuple(名詞["主要部範囲"]), 由来=由来)))
                    座標.append(_交換(HDS座標(座標ID, 種別, 項, 原文範囲=(項["開始"], 項["終了"]), 由来=由来)))
                枠["座標ID"] = 基底 + (":条件帰結" if 条件 else ":作用")
                座標.append(_交換(HDS座標(枠["座標ID"], "条件帰結" if 条件 else "資料作用", 枠.copy(),
                                          原文範囲=(起点, 対応["終了"]), 由来=由来)))
                関係.append(_交換(HDS関係(基底 + ":格構造", tuple(項["座標ID"] for 項 in 枠["役割"].values()),
                                          (枠["座標ID"],), "原文格構造", 由来=由来)))
            if 条件:
                条件["座標ID"] = 基底 + ":条件"
                前 = 条件["前件"]
                座標.append(_交換(HDS座標(条件["座標ID"], "作用条件", 前,
                                          原文範囲=(前["開始"], 前["終了"]), 由来=由来)))
                if 条件["例外談話"]:
                    談話 = 条件["例外談話"]
                    談話["座標ID"] = 基底 + ":例外談話"
                    座標.append(_交換(HDS座標(談話["座標ID"], "例外談話標識", 談話,
                        原文範囲=(談話["開始"], 談話["終了"]), 由来=由来)))
            if 局所:
                局所["座標ID"] = 基底 + ":局所範囲"
                自己述定 = "自己述定証明" in 局所
                局所状態 = 値状態.推定 if 自己述定 and 局所["内容状態"] == "推定" else 値状態.確定
                座標.append(_交換(HDS座標(局所["座標ID"], 局所["種別"], 局所.copy(),
                    値状態=局所状態, 原文範囲=(局所["開始"], 局所["終了"]), 由来=由来)))
                関係.append(_交換(HDS関係(基底 + ":局所帰属", (基底,), (局所["座標ID"],),
                    "原資料内の自己述定帰属" if 自己述定 else "原資料内の修飾又は引用帰属",
                    (行["ID"],), 局所状態, 由来)))
                for 番号, 事象 in enumerate(局所.get("内部事象", ())):
                    if 事象["明示主体"] is None:
                        残差.append(_交換(HDS残差(基底 + ":内部主体未明示:" + str(番号),
                            "自己述定内部主体未明示", 事象["原文"], "内部事象の省略主体を外側主体へ補完しない",
                            (局所["座標ID"],), ("内部事象の主体を原資料で明示",))))
                if 局所["外側未読解"]:
                    外側 = 局所["外側未読解"]
                    残差.append(_交換(HDS残差(基底 + ":未読外側作用", "原資料外側作用未読解",
                        外側["原文"], 外側["理由"], (局所["座標ID"],),
                        ("外側の述部・格・連用接続・主語の継承を明示",))))
            if not 枠 and 核候補 and not 局所:
                残差.append(_交換(HDS残差(基底 + ":未読解", "資料作用未読解", 対応["原文"],
                                          "動作核候補の格構造又は引用帰属が未読解", (基底,),
                                          ("原文の行為者・対象物・動作の係り先を確定",))))
            限定文, _ = _終止を除く(対応["原文"])
            限定, 限定座標, 限定関係, 限定残差 = _局所限定束(行, _局所限定を読む(限定文, 起点), 由来)
            座標.extend(限定座標); 関係.extend(限定関係); 残差.extend(限定残差)
            履歴 = _交換(HDS意味作用(基底 + ":射影", "原資料作用射影", (基底,),
                                      tuple(項["座標ID"] for 項 in 座標[1:]),
                                      "全字句と原格による局所限定の有限読解又は未読保持" if 限定 is not None else
                                      "全字句と全境界候補による自己述定の有限読解" if 局所 and "自己述定証明" in 局所 else "明示格と終止サ変の有限読解",
                                      ("原資料版", "全記載", "原文区間", "肯否", "時点", "未読解候補") +
                                      (("内部主体未明示", "モダリティ") if 局所 and "自己述定証明" in 局所 else ()),
                                      検証=("原本文slice一致",)))
            行["資料作用"] = {"版": 資料作用版, "原資料": 所有, "記載ID": 行["ID"],
                              "作用": 作用, "条件": 条件, "条件候補": 条件候補, "動作核候補": 核候補,
                              "局所範囲": 局所,
                              "局所限定": 限定,
                              "座標": 座標, "関係": 関係, "残差": 残差, "意味作用": 履歴}


def _束を検査(記載):
    # 索引化・先頭検索の前に全束を検査する。同内容の複製も一意な根拠ではない。
    根拠ID群 = {鍵: set() for 鍵 in ("記載ID", "座標ID", "関係ID", "残差ID", "作用ID")}

    def 登録(鍵, 識別子):
        if type(識別子) is not str or not 識別子:
            raise ValueError("原資料作用束の" + 鍵 + "が不正")
        if 識別子 in 根拠ID群[鍵]:
            raise ValueError("原資料作用束の" + 鍵 + "重複")
        根拠ID群[鍵].add(識別子)

    for 行 in 記載:
        登録("記載ID", 行["ID"])
        射影 = 行.get("資料作用")
        if not 射影:
            raise ValueError("原資料作用束の版又は記載対応が不一致")
        for 列, 鍵 in (("座標", "座標ID"), ("関係", "関係ID"), ("残差", "残差ID")):
            for 項 in 射影[列]:
                登録(鍵, 項[鍵])
        登録("作用ID", 射影["意味作用"]["作用ID"])
    資料群 = {}
    for 行 in 記載:
        射影 = 行.get("資料作用")
        if not 射影 or 射影.get("版") != 資料作用版 or 射影.get("記載ID") != 行["ID"]:
            raise ValueError("原資料作用束の版又は記載対応が不一致")
        if "局所限定" not in 射影:
            raise ValueError("原資料局所限定の明示欄がありません")
        作用, 条件, 条件候補, 核候補, 局所 = _候補を読む(行)
        if (作用 != _座標参照を除く(射影["作用"]) or 条件 != _座標参照を除く(射影["条件"])
                or 条件候補 != 射影["条件候補"] or 核候補 != 射影["動作核候補"]
                or 局所 != _座標参照を除く(射影["局所範囲"])):
            raise ValueError("原資料作用候補が原文読解と不一致")
        名前 = 行["対応"]["資料"]
        所有 = 射影["原資料"]
        if 所有["資料ID"] != 名前 or (名前 in 資料群 and 資料群[名前] != 所有):
            raise ValueError("原資料作用束の資料版又は本文指紋が不一致")
        資料群[名前] = 所有
        if 局所 and "時間事象帰属証明" in 局所:
            期待 = _時間事象根拠族(行, 局所, 所有)
            if 指紋([射影[鍵] for 鍵 in ("座標", "関係", "残差", "意味作用")]) != 指紋(期待):
                raise ValueError("原資料時間事象の型・原範囲・HDS根拠族が再導出と不一致")
        起点, 終点 = 行["対応"]["開始"], 行["対応"]["終了"]
        if (行["ID"] != 名前 + ":" + str(起点) + ":" + str(終点)
                or not 0 <= 起点 < 終点 <= 所有["本文長"]):
            raise ValueError("原資料作用の記載識別子又は原範囲が不一致")
        限定文, _ = _終止を除く(行["対応"]["原文"])
        限定, 限定座標, 限定関係, 限定残差 = _局所限定束(行, _局所限定を読む(限定文, 起点), 名前 + ":" + 所有["本文指紋"])
        限定基底 = 行["ID"] + ":資料作用:局所限定"
        新関係種 = {"原主体範囲限定", "原連体前提の名詞主要部帰属", "原名詞述部範囲限定", "原同一文の連用主体範囲"}
        実限定族 = [
            [項 for 項 in 射影["座標"] if 項["座標ID"].startswith(限定基底)
             or 項["種別"] == "原資料局所限定" or 項["種別"].startswith("局所限定.")],
            [項 for 項 in 射影["関係"] if 項["関係ID"].startswith(限定基底) or 項["種別"] in 新関係種],
            [項 for 項 in 射影["残差"] if 項["残差ID"].startswith(限定基底) or 項["種別"] == "原資料限定作用域未読"]]
        if (指紋(射影["局所限定"]) != 指紋(限定)
                or 指紋(実限定族) != 指紋([限定座標, 限定関係, 限定残差])):
            raise ValueError("原資料局所限定の型・原範囲・HDS根拠族が再導出と不一致")
        座標群 = {項["座標ID"]: 項 for 項 in 射影["座標"]}
        if 射影["局所範囲"]:
            局所 = 射影["局所範囲"]
            座標 = 座標群.get(局所["座標ID"])
            if not 座標 or 座標["内容"] != 局所 or tuple(座標["原文範囲"]) != (局所["開始"], 局所["終了"]):
                raise ValueError("原資料の局所修飾又は引用帰属座標が不一致")
            if "自己述定証明" in 局所:
                状態 = "推定" if 局所["内容状態"] == "推定" else "確定"
                関係 = next((項 for 項 in 射影["関係"] if 項["関係ID"] == 行["ID"] + ":資料作用:局所帰属"), None)
                if (座標["値状態"] != 状態 or not 関係 or 関係["種別"] != "原資料内の自己述定帰属"
                        or tuple(関係["始点"]) != (行["ID"] + ":資料作用",)
                        or tuple(関係["終点"]) != (局所["座標ID"],) or tuple(関係["条件"]) != (行["ID"],)
                        or 関係["値状態"] != 状態 or 関係["由来"] != 座標["由来"]):
                    raise ValueError("原資料の自己述定状態又は帰属関係が不一致")
                由来 = 名前 + ":" + 所有["本文指紋"]
                値の状態 = 値状態.推定 if 状態 == "推定" else 値状態.確定
                期待座標 = _交換(HDS座標(局所["座標ID"], 局所["種別"], 局所.copy(),
                    値状態=値の状態, 原文範囲=(局所["開始"], 局所["終了"]), 由来=由来))
                期待関係 = _交換(HDS関係(行["ID"] + ":資料作用:局所帰属",
                    (行["ID"] + ":資料作用",), (局所["座標ID"],), "原資料内の自己述定帰属",
                    (行["ID"],), 値の状態, 由来))
                if 指紋(座標) != 指紋(期待座標) or 指紋(関係) != 指紋(期待関係):
                    raise ValueError("原資料の自己述定座標又は関係の由来が不一致")
                期待残差 = [_交換(HDS残差(行["ID"] + ":資料作用:内部主体未明示:" + str(番号),
                    "自己述定内部主体未明示", 項["原文"], "内部事象の省略主体を外側主体へ補完しない",
                    (局所["座標ID"],), ("内部事象の主体を原資料で明示",)))
                    for 番号, 項 in enumerate(局所["内部事象"]) if 項["明示主体"] is None]
                if 指紋(射影["残差"]) != 指紋(期待残差 + 限定残差):
                    raise ValueError("原資料の自己述定内部省略主体の残差が不一致")
        for 座標 in 射影["座標"]:
            左, 右 = 座標["原文範囲"]
            if not 起点 <= 左 <= 右 <= 終点:
                raise ValueError("原資料作用座標が記載範囲外")
            if "原文" in 座標["内容"] and 行["対応"]["原文"][左 - 起点:右 - 起点] != 座標["内容"]["原文"]:
                raise ValueError("原資料作用座標の原文不一致")
        枠 = 射影["条件"]["帰結"] if 射影["条件"] else 射影["作用"]
        if 枠:
            if 座標群[枠["座標ID"]]["内容"] != 枠:
                raise ValueError("原資料作用枠と座標が不一致")
            for 種別, 項 in 枠["役割"].items():
                if (座標群[項["座標ID"]]["内容"] != 項 or
                        項["値"] != (_照合(項["原文"]) if 種別 == "動作" else 項["原文"])):
                    raise ValueError("原資料作用格の照合値が原文と不一致")
                if 種別 == "対象物" and 項["名詞構造"]["確定候補"]:
                    名詞 = 項["名詞構造"]
                    主要部座標 = 座標群.get(名詞["主要部座標ID"])
                    if (not 主要部座標 or 主要部座標["種別"] != "名詞主要部候補"
                            or tuple(主要部座標["原文範囲"]) != tuple(名詞["主要部範囲"])
                            or 主要部座標["内容"] != 名詞["字句"][-1]):
                        raise ValueError("名詞主要部座標の品詞又は原範囲が不一致")
            活用 = 枠["役割"]["活用"]["値"]
            if (枠["動作基本形"] != 枠["役割"]["動作"]["値"] + "する"
                    or 枠["肯否"] != ("否定" if 活用 in ("しない", "しません", "しなかった") else "肯定")
                    or 枠["時制"] != ("過去" if 活用 in ("した", "しました", "しなかった") else "非過去")):
                raise ValueError("原資料作用の基本形・肯否・時制が不一致")
        if 射影["条件"]:
            条件 = 射影["条件"]
            if 座標群[条件["座標ID"]]["内容"] != 条件["前件"]:
                raise ValueError("原資料作用の条件前件と座標が不一致")
            if 条件["例外談話"]:
                談話 = 条件["例外談話"]
                if 座標群[談話["座標ID"]]["内容"] != 談話:
                    raise ValueError("例外談話標識と座標が不一致")
    for 名前, 所有 in 資料群.items():
        全行 = [行 for 行 in 記載 if 行["対応"]["資料"] == 名前]
        if (所有["全記載ID"] != [行["ID"] for 行 in 全行]
                or 所有["全記載指紋"] != _記載指紋(全行)):
            raise ValueError("原資料作用の全記載が欠落又は変更されています")


def _主要部省略候補(条件行, 作用行):
    条件 = 条件行["資料作用"]["条件"]
    作用 = 作用行["資料作用"]["作用"]
    前項 = 作用["役割"]["対象物"]
    後項 = 条件["帰結"]["役割"]["対象物"]
    前, 後 = 前項["名詞構造"], 後項["名詞構造"]
    if (not 条件["例外談話"] or 作用行["対応"]["開始"] >= 条件行["対応"]["開始"]
            or not 前["確定候補"] or not 後["確定候補"] or not 前["修飾範囲"]
            or len(後["字句"]) != 1 or 前["主要部"] != 後["主要部"]
            or 作用["肯否"] == 条件["帰結"]["肯否"]):
        return None
    return {"原対象": 前項, "省略表記": 後項, "主要部": 前["主要部"],
            "例外談話": 条件["例外談話"],
            "作用対比": {"動作基本形": 作用["動作基本形"], "原作用肯否": 作用["肯否"],
                         "帰結肯否": 条件["帰結"]["肯否"], "時制": 作用["時制"]},
            "読み": "例外動作の同一項における名詞連接修飾の省略候補"}


def _作用の明示型証拠(作用):
    """別作用への非交差に使う追加証拠。未知の格を単語差で除外しない。"""
    from ..会話字句 import 会話字句を観測, 会話字句不成立
    格 = {}
    try:
        for 種別, 項 in 作用["役割"].items():
            if 種別 == "活用":
                continue
            if 種別 == "数量":
                格[種別] = {"原文": 項["原文"], "開始": 項["開始"], "終了": 項["終了"],
                             "型": "既存数量格", "字句": 項["字句"]}
                continue
            列 = 会話字句を観測(項["原文"])
            if not 列 or any(字.未知語 for 字 in 列):
                return None
            if 種別 == "動作":
                if (列[-1].品詞[:3] != ("名詞", "普通名詞", "サ変可能") or
                        any(字.品詞[0] != "接頭辞" for 字 in 列[:-1])):
                    return None
            elif any(not (字.品詞[0] == "名詞" or 字.品詞[:2] == ("接尾辞", "名詞的")
                          or 字.品詞[0] == "接頭辞") for 字 in 列):
                return None
            字句 = []
            for 字 in 列:
                記録 = asdict(字)
                記録["品詞"] = list(字.品詞)
                記録["開始"] += 項["開始"]
                記録["終了"] += 項["開始"]
                字句.append(記録)
            格[種別] = {"原文": 項["原文"], "開始": 項["開始"], "終了": 項["終了"],
                         "型": "既知サ変" if 種別 == "動作" else "既知名詞格", "字句": 字句}
    except 会話字句不成立:
        return None
    return {"動作基本形": 作用["動作基本形"], "肯否": 作用["肯否"], "時制": 作用["時制"], "格": 格}


def 条件作用を結ぶ(記載):
    """採用集合とは独立に、全記載中の唯一の動作を証明する。"""
    _束を検査(記載)
    適用 = {}
    for 条件行 in 記載:
        条件 = 条件行["資料作用"]["条件"]
        if not 条件行["資料作用"]["条件候補"]:
            continue
        if not 条件:
            適用[条件行["ID"]] = {"確定": False, "候補": [], "未読解競合": [条件行["ID"]],
                                   "除外": [], "理由": "動作条件の帰結格構造又は引用帰属が未確定です",
                                   "原資料": 条件行["資料作用"]["原資料"], "関係": None,
                                   "残差": [_交換(HDS残差(条件行["ID"] + ":未読解条件", "条件作用域未確定",
                                       条件行["対応"]["原文"], "帰結又は引用帰属未読解",
                                       解消条件=("条件帰結と原資料の作用関係を明示",)))]}
            continue
        帰結 = 条件["帰結"]
        候補, 未読解, 除外, 省略候補 = [], [], [], {}
        for 行 in 記載:
            if 行 is 条件行 or 行["資料作用"]["条件"]:
                continue
            if (行["対応"]["資料"], 行["節"], 行["段落"]) != (
                    条件行["対応"]["資料"], 条件行["節"], 条件行["段落"]):
                除外.append({"記載ID": 行["ID"], "理由": "別原資料・節・段落の境界"})
                continue
            射影, 作用 = 行["資料作用"], 行["資料作用"]["作用"]
            if 射影["局所限定"] is not None:
                # 限定付き主体/名詞述部は旧サ変作用の無限定な候補にしない。
                # 未読の標識作用先も非作用として除外せず、競合へ残す。
                未読解.append(行["ID"])
                continue
            if not 作用:
                if 射影["局所範囲"] and (射影["局所範囲"]["外側非動作証明"] or
                        射影["局所範囲"]["種別"] == "明示報告内の引用条件"):
                    除外.append({"記載ID": 行["ID"], "理由": "原範囲で証明した局所修飾又は報告内引用",
                                 "局所範囲座標ID": 射影["局所範囲"]["座標ID"]})
                    continue
                if 射影["局所範囲"] and 射影["局所範囲"]["外側未読解"]:
                    未読解.append(行["ID"])
                    continue
                非作用 = (not 射影["動作核候補"]
                           and any(行["関係"][種別] for 種別 in ("定義", "叙述", "属性")))
                if 非作用 and not _引用.search(行["対応"]["原文"]):
                    除外.append({"記載ID": 行["ID"], "理由": "既存読解の非サ変記載"})
                else:
                    未読解.append(行["ID"])
                continue
            if 作用["動作基本形"] != 帰結["動作基本形"]:
                除外.append({"記載ID": 行["ID"], "理由": "動作基本形が完全不一致",
                             "明示型証拠": {"作用": _作用の明示型証拠(作用), "帰結": _作用の明示型証拠(帰結)}})
                continue
            競合 = [種別 for 種別 in ("行為者", "対象物", "数量", "時点", "ニ格", "デ格")
                    if 種別 in 帰結["役割"] and 種別 in 作用["役割"]
                    and _照合(帰結["役割"][種別]["値"]) != _照合(作用["役割"][種別]["値"])]
            省略 = _主要部省略候補(条件行, 行) if 競合 == ["対象物"] else None
            未指定格 = [種別 for 種別 in 帰結["役割"]
                        if 種別 not in ("動作", "活用") and 種別 not in 作用["役割"]]
            if 省略 and 作用["時制"] == 帰結["時制"] and not 未指定格:
                候補.append(行)
                省略候補[行["ID"]] = 省略
            elif 省略 and 未指定格 and 作用["時制"] == 帰結["時制"]:
                未読解.append(行["ID"])
            elif 競合 or 作用["時制"] != 帰結["時制"]:
                除外.append({"記載ID": 行["ID"], "理由": "明示格又は時制が競合", "競合格": 競合})
            elif 未指定格:
                未読解.append(行["ID"])
            else:
                候補.append(行)
        項候補, 項未確定 = [], []
        if 省略候補:
            主要部 = 帰結["役割"]["対象物"]["名詞構造"]["主要部"]
            for 行 in 記載:
                if (行["対応"]["資料"], 行["節"], 行["段落"]) != (
                        条件行["対応"]["資料"], 条件行["節"], 条件行["段落"]) or 行["資料作用"]["条件候補"]:
                    continue
                作用 = 行["資料作用"]["作用"]
                if not 作用 or "対象物" not in 作用["役割"]:
                    continue
                項 = 作用["役割"]["対象物"]
                名詞 = 項["名詞構造"]
                if not 名詞["確定候補"]:
                    項未確定.append(行["ID"])
                elif 名詞["主要部"] == 主要部:
                    項候補.append({"記載ID": 行["ID"], "行為者": 作用["役割"]["行為者"]["値"],
                                  "対象物": 項["値"], "座標ID": 項["座標ID"], "名詞構造": 名詞})
            所有候補 = {(_照合(項["行為者"]), _照合(項["対象物"])) for 項 in 項候補}
            項一意 = len(所有候補) == 1 and not 項未確定
        else:
            項一意 = True
        確定 = len(候補) == 1 and not 未読解 and 項一意
        理由 = ("全記載の同動作・明示格と例外談話の名詞主要部照応が唯一" if 省略候補 else
                "全記載の同動作・明示格が唯一") if 確定 else "動作条件の対象又は作用域が未確定です"
        始点 = (条件["座標ID"], 帰結["座標ID"])
        終点 = tuple(行["資料作用"]["作用"]["座標ID"] for 行 in 候補)
        関係 = _交換(HDS関係(条件["座標ID"] + ":適用", 始点, 終点, "条件の作用適用",
                             (条件行["ID"],), 値状態.確定 if 確定 else 値状態.未確定,
                             条件行["資料作用"]["原資料"]["本文指紋"]))
        残差 = [] if 確定 else [_交換(HDS残差(条件["座標ID"] + ":作用域残差", "条件作用域未確定",
                        条件行["対応"]["原文"], 理由, 始点 + 終点,
                        ("適用する動作の行為者・対象物・時点と未読解競合を明示",)))]
        照応 = []
        if 確定 and 省略候補:
            証拠 = 省略候補[候補[0]["ID"]]
            証拠.update({"全項候補": 項候補, "同一主題": 項候補[0]["行為者"],
                          "項未確定": 項未確定, "全記載指紋": 条件行["資料作用"]["原資料"]["全記載指紋"]})
            照応.append({"証拠": 証拠, "関係": _交換(HDS関係(条件["座標ID"] + ":対象物照応",
                (証拠["原対象"]["座標ID"], 証拠["原対象"]["名詞構造"]["主要部座標ID"],
                 条件["例外談話"]["座標ID"]),
                (証拠["省略表記"]["座標ID"], 証拠["省略表記"]["名詞構造"]["主要部座標ID"]),
                "例外動作の同一対象物照応", (候補[0]["ID"], 条件行["ID"]),
                由来=条件行["資料作用"]["原資料"]["本文指紋"]))})
        適用[条件行["ID"]] = {"確定": 確定, "候補": [行["ID"] for 行 in 候補],
                               "未読解競合": 未読解, "除外": 除外, "理由": 理由,
                               "主要部項候補": 項候補, "項未確定": 項未確定, "照応": 照応,
                               "原資料": 条件行["資料作用"]["原資料"], "関係": 関係, "残差": 残差,
                               "意味作用": _交換(HDS意味作用(条件["座標ID"] + ":作用域照合", "原資料条件作用照合",
                                      始点 + tuple(行["ID"] for 行 in 記載), (関係["関係ID"],),
                                      "全記載と未読解競合による明示動作・格の一意性照合",
                                      ("原資料版", "段落と引用境界", "全候補", "前件", "帰結肯否", "作用時点",
                                       "原対象表記", "名詞主要部品詞と原範囲", "例外談話と対象物照応"),
                                      検証=(理由,))) }
    return 適用


def 資料作用成果(記載):
    適用 = 条件作用を結ぶ(記載)
    return {"版": 資料作用版, "適用": 適用,
            "原資料": list({行["対応"]["資料"]: 行["資料作用"]["原資料"] for 行 in 記載}.values()),
            "座標": [項 for 行 in 記載 for 項 in 行["資料作用"]["座標"]],
            "関係": [項 for 行 in 記載 for 項 in 行["資料作用"]["関係"]] +
                    [項["関係"] for 項 in 適用.values() if 項["関係"]] +
                    [照応["関係"] for 項 in 適用.values() for 照応 in 項.get("照応", ())],
            "残差": [項 for 行 in 記載 for 項 in 行["資料作用"]["残差"]] +
                    [残差 for 項 in 適用.values() for 残差 in 項["残差"]],
            "意味作用": [行["資料作用"]["意味作用"] for 行 in 記載] +
                        [項["意味作用"] for 項 in 適用.values() if "意味作用" in 項]}
