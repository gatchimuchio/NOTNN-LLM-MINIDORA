def _名前群(文字):
    if type(文字) is not str or len(文字) > 1000:
        raise ValueError("一般依頼の対象名が長すぎます")
    # 引用した主題は分割しない。引用の混在を任意の文字列へ縮退させない。
    if "「" in 文字 or "」" in 文字:
        if not re.fullmatch(r'「[^「」\n]+」(?:と「[^「」\n]+」)*', 文字):
            raise ValueError("主題の引用・作用域が未対応です")
        群 = re.findall(r'「([^「」]+)」', 文字)
    else:
        群 = [項.strip() for 項 in re.split(r'と|および|及び|・', 文字)]
    if (not 1 <= len(群) <= 4 or len(set(群)) != len(群)
            or any(not 項 or len(項) > 128 or re.search(r'[\n\r、,。！？!?;；]', 項) for 項 in 群)):
        raise ValueError("主題は重複のない1〜4項目で指定してください")
    return 群


def 一般要求を検査(要求):
    if type(要求) is dict and 要求.get("版") in {一般会話要求版, 一般関係会話要求版}:
        return _一般会話要求を検査(要求)
    必須 = {"版", "対象", "主題", "操作", "形式", "範囲", "最大文字数"}
    if type(要求) is not dict or set(要求) != 必須 or 要求["版"] != 一般要求版:
        raise ValueError("一般文章要求の欄・版不一致")
    if type(要求["対象"]) is not list or not 0 <= len(要求["対象"]) <= 16:
        raise ValueError("一般文章要求の資料数上限")
    for 欄, 上限 in (("対象", 16), ("主題", 4), ("操作", 4)):
        群 = 要求[欄]
        if type(群) is not list or len(群) > 上限 or any(type(項) is not str or not 項.strip() or len(項) > 128 for 項 in 群):
            raise ValueError("一般文章要求の列型・文字上限:" + 欄)
        if len(set(群)) != len(群):
            raise ValueError("一般文章要求の重複:" + 欄)
    if not 要求["操作"] or any(項 not in ("要約", "説明", "対照", "確認提案") for 項 in 要求["操作"]):
        raise ValueError("一般文章要求の操作が未対応")
    if 要求["形式"] not in ("箇条書き", "文章", "引用") or 要求["範囲"] not in ("指定資料", "全資料", "公開取得"):
        raise ValueError("一般文章要求の表現・範囲が未対応")
    if type(要求["最大文字数"]) is not int or not 100 <= 要求["最大文字数"] <= 24000:
        raise ValueError("一般文章要求の文字予算は100〜24000")
    if 要求["範囲"] == "指定資料" and not 要求["対象"]:
        raise ValueError("対象資料を指定してください")
    if 要求["範囲"] != "指定資料" and 要求["対象"]:
        raise ValueError("全体選択・公開取得に固定対象を混在させない")
    if 要求["範囲"] == "公開取得" and (len(要求["主題"]) != 1 or "対照" in 要求["操作"]):
        raise ValueError("公開取得は単一主題の説明・要約・確認事項が対象です")
    if "対照" in 要求["操作"] and (要求["範囲"] != "指定資料" or len(要求["対象"]) < 2 or not 要求["主題"]):
        raise ValueError("文章の対照には2資料以上と明示した観点が必要です")
    return 正準(要求)


def _一般依頼v1を読む(入力):
    原文 = 入力["原文"]
    文 = 原文.strip().rstrip("。")
    前 = 入力.get("前回結果")
    if 文 in _再表現 and 前 is not None and 結果を復元(前).データ.get("種別") == "資料文章回答":
        if not 入力.get("前回有効"):
            raise ValueError("資料文章の起点が失効しています。再計算してください")
        return {"方式": "一般再表現", "原文": 原文, "形式": _再表現[文]}
    照応 = []
    前目的 = 入力.get("前回目的") or {}
    前要求 = 前目的.get("要求", {}) if 前目的.get("方式") == "一般資料" else {}
    代名 = next((語 for 語 in ("その資料", "前者", "後者") if 文.startswith(語)), None)
    if 代名:
        対象群 = 前要求.get("対象", [])
        必要数 = 1 if 代名 == "その資料" else 2
        if 前要求.get("範囲") != "指定資料" or len(対象群) != 必要数:
            raise ValueError("資料照応が一意でありません。資料名を明示してください")
        対象名 = 対象群[1 if 代名 == "後者" else 0]
        文 = '資料「' + 対象名 + '」' + 文[len(代名):]
        照応.append({"原表現": 代名, "資料": 対象名})
    if 文.startswith("それについて"):
        if len(前要求.get("主題", [])) != 1 or 前要求.get("範囲") != "指定資料":
            raise ValueError("主題照応が一意でありません。主題を明示してください")
        文 = '資料' + 'と'.join('「' + 名 + '」' for 名 in 前要求["対象"]) + 'の「' + 前要求["主題"][0] + '」' + 文[len("それ"):]
        照応.append({"原表現": "それ", "主題": 前要求["主題"][0]})
    # 従来の数量比較・登録・命題検討の構文は奪わない。
    if not any(語 in 文 for 語 in ("について", "観点で", "根拠付き", "要点を", "確認事項", "追加調査", "をもとに")):
        return None
    対象, 主題, 範囲, 操作部 = [], [], "指定資料", None
    一致 = re.fullmatch(rf'(?P<対象>{_資料列})(?:(?:の)?(?P<主題>.+?)について[、,]?\s*|を(?P<観点>.+?)の観点で|を(?:もとに[、,]?\s*)?)(?P<操作>.+)', 文)
    if 一致:
        対象 = re.findall(r'「([^「」]+)」', 一致["対象"])
        主題文 = 一致["主題"] or 一致["観点"]
        主題 = _名前群(主題文) if 主題文 else []
        操作部 = 一致["操作"]
    else:
        一致 = re.fullmatch(rf'(?P<主題>.+?)について[、,]?\s*(?P<対象>{_資料列})を(?:もとに[、,]?\s*)?(?P<操作>.+)', 文)
        if 一致:
            対象 = re.findall(r'「([^「」]+)」', 一致["対象"])
            主題, 操作部 = _名前群(一致["主題"]), 一致["操作"]
        else:
            一致 = re.fullmatch(r'(登録資料から|公開資料で)(?P<主題>.+?)について[、,]?\s*(?P<操作>.+)', 文)
            if 一致:
                範囲 = "全資料" if 一致[1] == "登録資料から" else "公開取得"
                主題, 操作部 = _名前群(一致["主題"]), 一致["操作"]
    if 操作部 is None:
        return None
    形式, 最大文字数, 操作, 調査 = "箇条書き", 24000, [], False
    # 全操作節を消費する。未知条件を「表示指定」と推定して落とさない。
    節群 = [節.strip() for 節 in re.split(r'[、,。]', 操作部.replace('してから', 'して、')) if 節.strip()]
    if not 1 <= len(節群) <= 8:
        raise ValueError("一般依頼の操作節数上限")
    指定形式, 指定予算 = None, None
    for 節 in 節群:
        節 = re.sub(r"てください$", "て", 節)
        予算 = re.fullmatch(r'([0-9]+)文字以内で', 節)
        if 予算:
            if 指定予算 is not None and 指定予算 != int(予算[1]):
                raise ValueError("文字予算の指定が競合しています")
            最大文字数 = 指定予算 = int(予算[1]); continue
        for 接頭, 値 in (("根拠付きで", None), ("箇条書きで", "箇条書き"), ("文章で", "文章"), ("引用形式で", "引用")):
            if 節.startswith(接頭):
                節 = 節[len(接頭):]
                if 値 is not None:
                    if 指定形式 is not None and 指定形式 != 値:
                        raise ValueError("表現形式の指定が競合しています")
                    形式 = 指定形式 = 値
        if not 節:
            continue
        if 節 in ("根拠も示して", "根拠を示して"):
            continue
        if 節 in _再表現:
            if 指定形式 is not None and 指定形式 != _再表現[節]:
                raise ValueError("表現形式の指定が競合しています")
            形式 = 指定形式 = _再表現[節]; continue
        if 節 not in _動作:
            raise ValueError("一般依頼の未対応条件:" + 節)
        動作 = _動作[節]
        if 動作 == "調査":
            調査 = True
        elif 動作 not in 操作:
            操作.append(動作)
    if 調査 != (範囲 == "公開取得"):
        raise ValueError("公開取得は『公開資料で…調べて』と明示してください")
    要求 = 一般要求を検査({"版": 一般要求版, "対象": 対象, "主題": 主題, "操作": 操作,
                         "形式": 形式, "範囲": 範囲, "最大文字数": 最大文字数})
    return {"方式": "一般資料", "原文": 原文, "要求": 要求, "照応": 照応}


def _一般会話要求を検査(要求):
    必須 = {"版", "対象", "主題", "操作", "形式", "範囲", "最大文字数",
            "問い", "比較対象", "観点", "詳細", "提示本文", "関係焦点", "肯否"}
    関係付き = 要求.get("版") == 一般関係会話要求版
    if 関係付き: 必須 = 必須 | {"関係要求", "動作目的要求"}
    if set(要求) != 必須:
        raise ValueError("一般会話要求の欄不一致")
    for 名, 上限 in (("対象", 16), ("主題", 4), ("比較対象", 4), ("観点", 4), ("操作", 4), ("関係焦点", 4)):
        群 = 要求[名]
        if (type(群) is not list or len(群) > 上限
                or any(type(項) is not str or not 項.strip() or len(項) > 128 for 項 in 群)
                or len(set(群)) != len(群)):
            raise ValueError("一般会話要求の列型・数・重複:" + 名)
    if not 要求["操作"] or set(要求["操作"]) - {"要約", "説明", "理由", "対照", "確認提案"}:
        raise ValueError("一般会話の操作が未対応")
    if 要求["形式"] not in ("箇条書き", "文章", "引用") or 要求["詳細"] not in ("簡潔", "標準", "詳細"):
        raise ValueError("一般会話の表示指定不正")
    if 要求["肯否"] not in ("肯定", "否定", "未指定"):
        raise ValueError("一般会話の問いの肯否不正")
    if 要求["範囲"] not in ("自動", "指定資料", "全資料", "公開取得"):
        raise ValueError("一般会話の範囲指定不正")
    if (要求["範囲"] == "指定資料") != bool(要求["対象"]):
        raise ValueError("一般会話の範囲と資料束縛が不一致")
    if type(要求["最大文字数"]) is not int or not 100 <= 要求["最大文字数"] <= 24000:
        raise ValueError("一般会話の文字予算は100〜24000")
    if type(要求["問い"]) is not str or not 要求["問い"].strip() or len(要求["問い"]) > 4096:
        raise ValueError("一般会話の問いの型・長さ不正")
    if type(要求["提示本文"]) is not str or len(要求["提示本文"]) > 100000:
        raise ValueError("一般会話の提示本文の型・長さ不正")
    要求["提示本文"].encode("utf-8")
    if "対照" in 要求["操作"] and len(要求["対象"]) < 2 and len(要求["比較対象"]) < 2:
        raise ValueError("比較対象を二つ以上指定してください")
    if not (要求["主題"] or 要求["比較対象"] or 要求["対象"] or 要求["提示本文"]):
        raise ValueError("確認待ち:説明する主題又は本文を提示してください")
    if 関係付き:
        _一般関係要求を検査(要求)
        _一般動作目的要求を検査(要求)
        if not (要求["関係要求"] or 要求["動作目的要求"]):
            raise ValueError("新一般会話要求には必須の原役割が必要です")
    return 正準(要求)


def _一般関係要求を検査(要求):
    """形成済み当回原役割の保存欄だけを検査する。世界述語を補完しない。"""
    from ..HDS会話契約 import 会話関係要求版
    群 = 要求["関係要求"]
    if type(群) is not list or len(群) > 4 or 群 and 要求["操作"] not in (["説明"], ["理由"]):
        raise ValueError("一般関係要求の数又は操作が不正です")
    for 項 in 群:
        if (type(項) is not dict or set(項) != {"版", "型", "原発話", "両端", "原語句", "焦点"}
                or 項["版"] != 会話関係要求版 or 項["型"] != "明示二端関係"
                or type(項["原発話"]) is not str or not 0 < len(項["原発話"]) <= 8000000):
            raise ValueError("一般関係要求の版・型・原発話が不正です")
        原発話 = 項["原発話"]
        if len(原発話.encode("utf-8")) > 8000000:
            raise ValueError("一般関係要求の原発話バイト上限")
        def 範囲(指定):
            if (type(指定) is not list or len(指定) != 2 or any(type(値) is not int for 値 in 指定)
                    or not 0 <= 指定[0] < 指定[1] <= len(原発話)):
                raise ValueError("一般関係要求の原文範囲が不正です")
            return 原発話[slice(*指定)]
        両端 = 項["両端"]
        if type(両端) is not list or len(両端) != 2:
            raise ValueError("一般関係要求は二つの明示端点が必要です")
        値群 = []
        for 端 in 両端:
            if type(端) is not dict or set(端) != {"値", "原文範囲"} or type(端["値"]) is not str:
                raise ValueError("一般関係要求の端点型が不正です")
            原句 = 範囲(端["原文範囲"])
            原値 = 原句[1:-1] if len(原句) >= 2 and (原句[0], 原句[-1]) in {("「", "」"), ("『", "』")} else 原句
            if 端["値"] != 原値 or 端["値"] not in 要求["主題"] + (要求["観点"] if 要求["操作"] == ["理由"] else []):
                raise ValueError("一般関係要求の端点が原句・当回主題へ束縛されていません")
            値群.append(端["値"])
        if len(set(値群)) != 2 or not set(値群) & set(要求["主題"]):
            raise ValueError("一般関係要求の端点が重複しています")
        原語句, 焦点 = 項["原語句"], 項["焦点"]
        if (type(原語句) is not dict or set(原語句) != {"原文", "原文範囲"}
                or type(原語句["原文"]) is not str or 範囲(原語句["原文範囲"]) != 原語句["原文"]
                or type(焦点) is not dict or set(焦点) != {"値", "原文範囲"}
                or 焦点["値"] != "関係" or 範囲(焦点["原文範囲"]) != "関係"
                or 要求["操作"] != ["理由"] and "関係" not in 要求["関係焦点"]
                or not 原語句["原文範囲"][0] <= 焦点["原文範囲"][0] < 焦点["原文範囲"][1] <= 原語句["原文範囲"][1]):
            raise ValueError("一般関係要求の原語句又は焦点が不正です")


