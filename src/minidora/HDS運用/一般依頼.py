def 一般依頼を読む(入力, *, 意味IR=None):
    """v1の局所契約を維持し、v2は同一Compilerの意味欄だけから形成する。"""
    if 意味IR is None:
        return _一般依頼v1を読む(入力)
    if 意味IR.原文 != 入力["原文"]:
        raise ValueError("一般会話のKernel原文が不一致")
    if any(項.作用ID == "会話作用射影:v3" for 項 in 意味IR.意味作用履歴):
        from ..HDS会話契約 import 会話契約を形成
        from .会話目的束 import 会話目的を読む
        所有 = 入力.get("セッションID")
        if type(所有) is not str or not 所有:
            raise ValueError("会話目的の所有セッションが必要です")
        from .会話文脈 import 会話形成証明を読む, 会話入力文脈を読む
        証明 = 会話形成証明を読む(意味IR, 入力)
        包 = 会話契約を形成(意味IR, 所有セッション=所有, **証明)
        文脈引数 = 会話入力文脈を読む(包, 入力)
        診断 = 会話残差を読む(意味IR)
        if 診断:
            raise 会話未読解(診断)
        会話目的を読む(包, 所有セッション=所有,
                 期待原文=入力["原文"], 意味IR=意味IR, **文脈引数)
        return {"方式": "一般会話目的束", "原文": 入力["原文"], "要求": 包,
                **文脈引数}
    意味欄 = 会話意味欄を読む(意味IR)
    try:
        従来 = _一般依頼v1を読む(入力)
    except ValueError:
        if 意味欄 is None or any(残差.種別 == "会話未消費" for 残差 in 意味IR.残差):
            raise
        従来 = None
    if 従来 is not None:
        return 従来
    未消費 = [残差 for 残差 in 意味IR.残差 if 残差.種別 == "会話未消費"]
    if 未消費:
        raise 会話未読解(会話残差を読む(意味IR))
    if 意味欄 is None:
        return None
    継承 = next((座標.内容 for 座標 in 意味IR.座標
                 if 座標.由来 == 会話射影由来 and 座標.種別 == "目的.会話継承"), None)
    if 継承 is None and any(座標.由来 == 会話射影由来 and 座標.種別 == "文脈.会話指示語"
                           for 座標 in 意味IR.座標):
        継承 = "照応"
    if 継承 == "再表現" and not 入力.get("前回有効"):
        raise ValueError("確認待ち:再表現する採用済み成果が失効しています")
    要求 = 一般要求を検査({"版": 一般会話要求版, **意味欄, "提示本文": 意味欄.get("提示本文", "")})
    話題変更 = any(座標.由来 == 会話射影由来 and 座標.種別 == "目的.会話話題変更" for 座標 in 意味IR.座標)
    根拠継承 = False
    if (継承 is None and not 話題変更 and 要求["範囲"] == "自動" and not 要求["提示本文"]
            and 入力.get("前回有効") and 入力.get("前回結果") is not None):
        from .内容構成 import 資料文章を検査
        前回 = 結果を復元(入力["前回結果"])
        if 資料文章を検査(前回):
            資料群 = 前回.データ["構造"]["資料群"]
            主題群 = 要求["比較対象"] or 要求["主題"]
            # 新目的の各対象が実原資料に記載される場合だけ、根拠を再利用する。
            # 前目的・表現・観点は継承せず、回答は新要求から再構成する。
            根拠継承 = bool(主題群) and all(
                any(主題 == 名前 or re.search(re.escape(主題) + r'(?=$|[\s、。：「」『』:;；!?！？]|は|が|の|を|に|で|と|も|から|について)',
                    結果を復元(項["資料"]).本文) for 名前, 項 in 資料群.items())
                for 主題 in 主題群)
    return {"方式": "一般資料", "原文": 入力["原文"], "要求": 要求, "継承": 継承, "根拠継承": 根拠継承,
            "意味座標": [座標.座標ID for 座標 in 意味IR.座標 if 座標.由来 == 会話射影由来],
            "訂正関係": [関係.関係ID for 関係 in 意味IR.関係
                         if 関係.由来 == 会話射影由来 and 関係.種別 == "目的条件置換"]}


def _一般会話計画を作る(要求, 入力, *, 継承=None, 根拠継承=False, 命令提示材料=None, 外部禁止=False, 取得時期=()):
    if type(外部禁止) is not bool or type(入力["外部許可"]) is not bool:
        raise ValueError("一般会話の実許可又は禁止条件の型が不正です")
    from dataclasses import asdict
    from ..能力合成 import 合成計画, 合成工程, 素材参照
    from ..製品版.型 import 能力結果, 参照資料
    from ..知識取得 import 知識取得要求
    from ..HDS会話契約 import 会話取得時期版
    if type(取得時期) not in (tuple, list) or len(取得時期) > 1:
        raise ValueError("一般会話の取得時期が一意ではありません")
    for 条件 in 取得時期:
        if (type(条件) is not dict or set(条件) != {"目的ID", "条件ID", "版", "作用", "基準", "原文", "原文範囲"}
                or {鍵: 条件[鍵] for 鍵 in ("版", "作用", "基準")} != {
                    "版": 会話取得時期版, "作用": "外部読取", "基準": "要求時点"}
                or any(type(条件[鍵]) is not str or not 条件[鍵] for 鍵 in ("目的ID", "条件ID", "原文"))
                or type(条件["原文範囲"]) is not list or len(条件["原文範囲"]) != 2
                or any(type(値) is not int for 値 in 条件["原文範囲"])
                or not 0 <= 条件["原文範囲"][0] < 条件["原文範囲"][1] <= len(入力["原文"])
                or 入力["原文"][slice(*条件["原文範囲"])] != 条件["原文"]):
            raise ValueError("一般会話の取得時期が当回の原要求へ束縛されていません")
    if 取得時期 and (要求["範囲"] != "公開取得" or 要求["提示本文"] or 命令提示材料 is not None):
        raise ValueError("当回の取得時期は明示公開取得だけに適用できます")
    素材 = {"一般:指示": 能力結果(True, "原問い・実根拠・条件から必要な意味内容を構成する"),
            "一般:要求": 能力結果(True, "", データ=要求)}
    工程群, 名前群, 前回資料, 前回取得記録, 前回 = [], [], {}, None, None
    if not 取得時期 and (継承 or 根拠継承) and 入力.get("前回有効") and 入力.get("前回結果") is not None:
        from .内容構成 import 資料文章を検査
        前回 = 結果を復元(入力["前回結果"])
        if not 資料文章を検査(前回):
            raise ValueError("継承する前回資料文章の意味構造が不整合")
        前回資料 = {名前: 結果を復元(項["資料"]) for 名前, 項 in 前回.データ["構造"]["資料群"].items()}
        前回取得記録 = deepcopy(前回.データ["構造"].get("取得記録"))
    if 要求["版"] == 一般関係会話要求版:
        原役割群 = 要求["関係要求"] + 要求["動作目的要求"]
        if any(入力["原文"] != 原役割["原発話"] for 原役割 in 原役割群):
            前要求 = None if 前回 is None else 前回.データ["構造"]["要求"]
            if (継承 != "照応" or not 前回資料 or 前要求 is None
                    or 前要求.get("版") != 一般関係会話要求版
                    or any(要求[名] != 前要求.get(名) for 名 in ("関係要求", "動作目的要求"))):
                raise ValueError("新一般会話要求の原条件が実入力又は検査済み前成果に一致しません")
    if 要求["提示本文"]:
        # 今回の資料区分は今回の原文に束縛する。旧根拠で上書きしない。
        前回資料, 前回取得記録 = {}, None
        名前群 = ["提示本文"]
        本文 = 要求["提示本文"]
        参照 = 参照資料("提示本文:" + 指紋({"原文": 入力["原文"], "本文": 本文}),
                        "提示本文", "利用者提示本文", 本文=本文)
        素材["一般:資料:0"] = 能力結果(True, 本文, 参照=(参照,))
        実範囲 = "提示本文"
    elif 命令提示材料 is not None:
        前回資料, 前回取得記録 = {}, None
        名前群 = ["提示本文"]
        素材["一般:資料:0"] = 命令提示材料
        実範囲 = "命令提示原文"
    elif 前回資料:
        名前群 = 要求["対象"] if 要求["範囲"] == "指定資料" else list(前回資料)
        if 継承 == "訂正" and not 要求["対象"]:
            主題群 = 要求["比較対象"] or 要求["主題"]
            if any(not any(主題 in 項.本文 for 項 in 前回資料.values()) for 主題 in 主題群):
                名前群 = []
                前回資料 = {}
        実範囲 = "前回実資料" if 名前群 else "公開取得"
    elif 要求["範囲"] in ("指定資料", "全資料"):
        名前群 = 要求["対象"] if 要求["範囲"] == "指定資料" else sorted(入力["資料"])
        実範囲 = 要求["範囲"]
    elif 要求["範囲"] == "自動":
        主題群 = 要求["比較対象"] or 要求["主題"]
        名前群 = [名前 for 名前, 項 in 入力["資料"].items()
                if any(主題 in 項["本文"] or 主題 == 名前 for 主題 in 主題群)]
        実範囲 = "会話資料" if 名前群 else "公開取得"
    else:
        実範囲 = "公開取得"
    if 名前群:
        if len(名前群) > 16:
            raise ValueError("確認待ち:回答資料が16件を超えています。範囲を明示してください")
        if 命令提示材料 is None and (not 要求["提示本文"] or 前回資料):
            for 番号, 名前 in enumerate(名前群):
                if 名前 in 前回資料:
                    素材["一般:資料:" + str(番号)] = 前回資料[名前]
                    continue
                if 名前 not in 入力["資料"]:
                    raise ValueError("確認待ち:資料不足:" + 名前)
                素材["一般:資料:" + str(番号)] = 結果を復元(入力["資料"][名前]["結果"])
        設定 = {"要求": 要求, "資料名": 名前群}
        if 前回取得記録 is not None and 前回資料:
            設定["取得記録"] = 前回取得記録
        素材["一般:要求"] = 能力結果(True, "", データ=設定)
        参照群 = tuple(素材参照("入力", "一般:資料:" + str(番号)) for 番号 in range(len(名前群)))
        構造能力 = "資料意味選択"
    elif 実範囲 != "公開取得":
        raise ValueError("確認待ち:回答に必要な資料がありません。本文又は資料名を提示してください")
    else:
        if 外部禁止:
            raise ValueError("確認待ち:この依頼は外部読取を禁止しています。根拠となる本文を提示するか、禁止条件と今回の読取許可を明示し直してください")
        if not 入力["外部許可"]:
            raise ValueError("確認待ち:この問いの根拠資料がありません。本文を提示するか、この問いの公開資料検索を許可してください")
        検索主題 = 要求["比較対象"] or 要求["主題"]
        if not 1 <= len(検索主題) <= 4:
            raise ValueError("確認待ち:公開取得する主題を1〜4件指定してください")
        参照群 = []
        for 番号, 主題 in enumerate(検索主題):
            検索関係 = 要求["関係焦点"]
            関係端点 = []
            for 関係 in 要求.get("関係要求", []):
                if 入力["原文"] != 関係["原発話"]:
                    raise ValueError("関係要求の原発話が実入力に一致しません")
                for 端 in 関係["両端"]:
                    if 端["値"] != 主題 and 端["値"] not in 関係端点: 関係端点.append(端["値"])
            検索語 = " ".join((主題, *要求["観点"], *関係端点, *検索関係))
            取得要求 = 知識取得要求(検索語, (主題,), 最大検索回数=2, 最大候補数=6,
                                    最大取得数=6, 最大資料数=3, 最大抜粋文字数=12000)
            取得要求.検証()
            設定名, 工程名 = "一般:取得設定:" + str(番号), "一般公開取得:" + str(番号)
            素材[設定名] = 能力結果(True, "", データ=正準(asdict(取得要求)))
            工程群.append(合成工程(工程名, ("知識取得",), "一般:指示", (), 設定名))
            参照群.append(素材参照("工程", 工程名))
        参照群 = tuple(参照群)
        構造能力 = "取得資料意味選択"
    素材["一般:束縛"] = 能力結果(True, "", データ={"元要求印": 指紋(要求), "実範囲": 実範囲, "資料名": 名前群})
    def 前(名前):
        return 素材参照("工程", 名前)
    工程群.extend((
        合成工程("一般意味選択", (構造能力,), "一般:指示", 参照群, "一般:要求"),
        合成工程("一般内容構成", ("資料内容構成",), "一般:指示", (前("一般意味選択"),)),
        合成工程("一般文章生成", ("文章作成",), "一般:指示", (前("一般内容構成"),)),
        合成工程("一般回答照合", ("資料文章照合",), "一般:指示", (前("一般意味選択"), 前("一般文章生成")))
    ))
    return 合成計画(tuple(工程群), ("一般回答照合",)), 素材, "資料文章回答"


def _会話目的束計画を作る(解釈, 入力):
    """操作と対象の対応を保ち、既存単一目的工程を同じHDSへ束ねる。"""
    from dataclasses import replace
    from ..能力合成 import 合成計画, 合成工程, 素材参照
    from ..製品版.型 import 能力結果
    from .会話目的束 import 会話目的を読む, 会話前目的対応を読む, 会話取得条件を読む, 会話取得時期を読む
    from .会話文脈 import (会話保存文脈を読む, 会話入力文脈を読む,
                       会話設定を作る, 命令提示材料を読む)
    from .値 import 計画を保存
    包 = 解釈["要求"]
    文脈 = 会話入力文脈を読む(包, 入力)
    if 指紋(文脈) != 指紋(会話保存文脈を読む(解釈)):
        raise ValueError("会話目的束の保存文脈と実入力文脈が不一致です")
    目的群 = 会話目的を読む(包, 所有セッション=入力["セッションID"], 期待原文=解釈["原文"],
                    **文脈)
    取得条件 = {項["目的ID"]: 項 for 項 in 会話取得条件を読む(
        包, 所有セッション=入力["セッションID"], 期待原文=解釈["原文"], **文脈)}
    取得時期 = 会話取得時期を読む(包, 所有セッション=入力["セッションID"],
                        期待原文=解釈["原文"], **文脈)
    if 解釈["原文"] != 入力["原文"]:
        raise ValueError("確認待ち:目的束の再計算には原依頼との明示対応が必要です")
    素材, 工程群, 子群, 出力群, 共通取得 = {}, [], [], [], {}
    対応群 = 会話前目的対応を読む(包, 所有セッション=入力["セッションID"],
                              期待原文=解釈["原文"], **文脈)
    前目的対応 = {項["目的ID"]: 項 for 項 in 対応群}
    前子 = {}
    if 文脈["前採用包"] is not None:
        if not 入力.get("前回有効") or 入力.get("前回結果") is None:
            raise ValueError("確認待ち:会話目的の前成果が有効ではありません")
        前回 = 結果を復元(入力["前回結果"])
        if (前回.データ.get("種別") != "会話目的束回答"
                or 指紋(前回.データ["契約包"]) != 指紋(文脈["前採用包"])):
            raise ValueError("確認待ち:会話目的の前採用成果対応が不一致です")
        前子 = {項["目的ID"]: 項 for 項 in 前回.データ["目的成果"]}
    for 番号, 行 in enumerate(目的群):
        元 = 前目的対応.get(行["目的ID"])
        子入力 = 入力
        命令材料 = None
        子解釈 = {"方式": "一般資料", "原文": 入力["原文"], "要求": 行["要求"]}
        時期 = [deepcopy(条件) for 条件 in 取得時期 if 条件["目的ID"] == 行["目的ID"]]
        if 時期:
            子解釈["取得時期"] = 時期
        if 元 is not None:
            元目的 = 元["元目的ID"]
            if 元["方式"] == "再実行":
                子入力 = {**入力, "前回結果": None, "前回有効": False}
                子解釈["前命令目的ID"] = 元目的
                命令材料 = 命令提示材料を読む(包, 元目的, 入力)
            else:
                if 元目的 not in 前子:
                    raise ValueError("確認待ち:会話目的の元目的と実前子成果が不一致です")
                # 観点だけの訂正は根拠対象を保持する。対象訂正は現在資料を取り直す。
                対象訂正 = 元["方式"] == "訂正" and any(
                    項["対象役割"] in {"対象.会話主題", "対象.会話資料", "対象.会話比較"}
                    for 項 in 元["変更"])
                if not 対象訂正:
                    子入力 = {**入力, "前回結果": deepcopy(前子[元目的]["子成果"])}
                    子解釈.update({"継承": 元["方式"], "前束目的ID": 元目的})
                if 元["方式"] == "訂正":
                    子解釈["訂正元目的ID"] = 元目的
        子計画, 子素材, _ = _一般会話計画を作る(行["要求"], 子入力,
                                       継承=子解釈.get("継承"), 命令提示材料=命令材料,
                                       外部禁止=取得条件[行["目的ID"]]["外部禁止"], 取得時期=時期)
        接頭 = "会話目的:" + str(番号) + ":"
        素材対応 = {名: 接頭 + 名 for 名 in 子素材}
        工程対応 = {項.識別子: 接頭 + 項.識別子 for 項 in 子計画.工程}
        省略取得 = set()
        for 項 in 子計画.工程:
            if 項.能力候補 == ("知識取得",) and not 項.入力 and 項.設定参照 is not None:
                印 = 指紋(子素材[項.設定参照].データ)
                if 印 in 共通取得:
                    工程対応[項.識別子] = 共通取得[印]
                    省略取得.add(項.識別子)
                else:
                    共通取得[印] = 工程対応[項.識別子]
        if len(共通取得) > 4:
            raise ValueError("確認待ち:目的束全体の公開取得要求は4件までです。対象又は問いを分けてください")
        素材.update({素材対応[名]: 値 for 名, 値 in 子素材.items()})
        新子工程 = []
        for 項 in 子計画.工程:
            新 = replace(項, 識別子=工程対応[項.識別子], 指示参照=素材対応[項.指示参照],
                      設定参照=素材対応[項.設定参照] if 項.設定参照 is not None else None,
                      入力=tuple(素材参照(参照.領域,
                               (素材対応 if 参照.領域 == "入力" else 工程対応)[参照.識別子]) for 参照 in 項.入力))
            新子工程.append(新)
            if 項.識別子 not in 省略取得:
                工程群.append(新)
        出力 = 工程対応[子計画.出力工程[0]]
        出力群.append(素材参照("工程", 出力))
        子群.append({"目的ID": 行["目的ID"], "素材対応": 素材対応,
                   "計画": 計画を保存(合成計画(tuple(新子工程), (出力,))), "出力": 出力,
                   "解釈": 子解釈})
    素材["一般:子計画"] = 能力結果(True, "", データ={"子計画": 子群})
    素材["一般:束指示"] = 能力結果(True, "目的ごとの対象・操作・原根拠・数量・保持条件を照合する")
    素材["一般:束設定"] = 能力結果(True, "", データ=会話設定を作る(包, 文脈))
    工程群.extend((
        合成工程("一般:束内容", ("資料内容構成",), "一般:束指示", tuple(出力群), "一般:束設定"),
        合成工程("一般:束文章", ("文章作成",), "一般:束指示", (素材参照("工程", "一般:束内容"),)),
        合成工程("一般:束照合", ("資料文章照合",), "一般:束指示",
                  (*出力群, 素材参照("工程", "一般:束文章")), "一般:束設定"),
    ))
    return 合成計画(tuple(工程群), ("一般:束照合",)), 素材, "会話目的束回答"


def 一般計画を作る(解釈, 入力):
    from ..能力合成 import 合成計画, 合成工程, 素材参照
    from ..製品版.型 import 能力結果
    if 解釈["方式"] == "一般会話目的束":
        return _会話目的束計画を作る(解釈, 入力)
    if 解釈["方式"] == "一般再表現":
        if not 入力.get("前回有効"):
            raise ValueError("再表現の起点が失効")
        素材 = {"一般:前回": 結果を復元(入力["前回結果"]),
              "一般:指示": 能力結果(True, "採用済み資料文章の内容・根拠を保持して再表現する"),
              "一般:形式": 能力結果(True, "", データ={"形式": 解釈["形式"]})}
        return 合成計画((合成工程("一般再表現", ("資料文章再表現",), "一般:指示",
            (素材参照("入力", "一般:前回"),), "一般:形式"),), ("一般再表現",)), 素材, "資料文章回答"
    要求 = 一般要求を検査(解釈["要求"])
    if 要求["版"] in {一般会話要求版, 一般関係会話要求版}:
        return _一般会話計画を作る(要求, 入力, 継承=解釈.get("継承"), 根拠継承=解釈.get("根拠継承", False),
                              取得時期=解釈.get("取得時期", ()))
    素材 = {"一般:指示": 能力結果(True, "提供文章を原文・条件・主題対応とともに構成する"),
          "一般:要求": 能力結果(True, "", データ=要求)}
    工程群 = []
    if 要求["範囲"] == "公開取得":
        if not 入力["外部許可"]:
            raise ValueError("公開資料の調査にはセッションと今回依頼の外部読取許可が必要です")
        素材["一般:取得設定"] = 能力結果(True, "", データ={"検索語": 要求["主題"][0], "必要語": 要求["主題"],
            "最低資料数": 1, "最大資料数": 4, "最大取得数": 6, "最大抜粋文字数": 12000})
        工程群.append(合成工程("一般公開取得", ("知識取得",), "一般:指示", (), "一般:取得設定"))
        参照群 = (素材参照("工程", "一般公開取得"),)
        構造能力 = "取得資料意味選択"
    else:
        名前群 = 要求["対象"] if 要求["範囲"] == "指定資料" else sorted(入力["資料"])
        if not 1 <= len(名前群) <= 16:
            raise ValueError("一般文章の入力資料は1〜16件です")
        for 番号, 名前 in enumerate(名前群):
            if 名前 not in 入力["資料"]:
                raise ValueError("確認待ち:資料不足:" + 名前)
            # 利用者の資料名とシステム用素材住所を分離する。
            素材["一般:資料:" + str(番号)] = 結果を復元(入力["資料"][名前]["結果"])
        素材["一般:要求"] = 能力結果(True, "", データ={"要求": 要求, "資料名": 名前群})
        参照群 = tuple(素材参照("入力", "一般:資料:" + str(番号)) for 番号 in range(len(名前群)))
        構造能力 = "資料意味選択"
    def 前(名前):
        return 素材参照("工程", 名前)
    工程群.extend((
        合成工程("一般意味選択", (構造能力,), "一般:指示", 参照群, "一般:要求"),
        合成工程("一般内容構成", ("資料内容構成",), "一般:指示", (前("一般意味選択"),)),
        合成工程("一般文章生成", ("文章作成",), "一般:指示", (前("一般内容構成"),)),
        合成工程("一般回答照合", ("資料文章照合",), "一般:指示", (前("一般意味選択"), 前("一般文章生成")))
    ))
    return 合成計画(tuple(工程群), ("一般回答照合",)), 素材, "資料文章回答"
