"""日本語の明示関係を命題へ接続する有限表層。未知の意味・係り先を補完しない。"""
from __future__ import annotations
import re
import unicodedata
from ..命題句 import 最上位位置
from ..命題解釈 import 命題を読む, 命題を表現
from ..命題構造 import 命題式, 原子, 結合, 反対, 文脈を付す

関係言語版 = "HDS関係言語-v2"
_指示 = frozenset(("それ", "これ", "同装置", "同対象"))
_未対応指示 = frozenset(("彼", "彼女", "同者", "あれ", "私", "わたし", "あなた", "前者", "後者"))
_制限 = ("ただし", "除く", "除き", "限り", "かもしれ", "らしい", "はず", "予定", "推定", "おそらく", "恐らく", "とは限ら", "必要十分", "のみ", "例外")
_名 = re.compile(r'[^\s「」『』（）()、。，,；;：:！？!?]{1,80}\Z')
_動作根 = r'[一-龥々〆ヶァ-ヴーA-Za-z0-9_・/-]{1,60}'
_裸状態 = re.compile(_動作根 + r'\Z')


def _対象(文字):
    if (not _名.fullmatch(文字) or any(語 in 文字 for 語 in ("なら", "場合", "とき", "かつ", "または", "と", "が", "は"))
            or 文字 in _指示 | _未対応指示):
        raise ValueError("主体の構造・参照が未確定:" + 文字[:80])
    return 文字


def _未束縛参照を検査(式: 命題式) -> None:
    """局所照応後にも残る指示語定数を、引用を含む全ての項で拒否する。

    既存命題文法は別の語彙境界を持つ。括弧・否定・量化を経由しても
    v5で未対応の照応を定数へ読み替えない。明示的な束縛変数は別物とする。
    呼出前に式全体の構造・束縛・容量を検査する。
    """
    for 項 in 式.項:
        if 項.種別 == "定数" and 項.名前 in _指示 | _未対応指示:
            raise ValueError("未束縛の照応先を定数にしない:" + 項.名前)
    for 子 in 式.子:
        _未束縛参照を検査(子)


def 関係文を読む(原文: str, *, 先行主体: str | None = None):
    """式・一意な明示主体・変換履歴を返す。時制、様相、否定を同一視しない。"""
    if type(原文) is not str or not 0 < len(原文) <= 4096:
        raise ValueError("関係文の型・文字上限")
    if any(unicodedata.category(字) in ("Cf", "Cs") or (unicodedata.category(字) == "Cc" and 字 not in "\n\r\t") for 字 in 原文):
        raise ValueError("関係文の不可視制御文字")
    if 先行主体 is not None:
        _対象(先行主体)
    履歴 = []

    def 解析(文, 参照=None, 深さ=0, 裸=False, 省略=False):
        if 深さ > 12:
            raise ValueError("関係文の構成深さ上限")
        文 = 文.strip()
        if not 文:
            raise ValueError("空の関係節")
        # v6で有限に対応する必要条件は、通常の含意とは向きを区別して保持する。
        # 「必要十分」は別契約なので、必要条件として部分採用しない。
        if "必要十分" in 文:
            raise ValueError("必要十分条件の双方向化は未対応")
        必要 = re.fullmatch(r'(.+?)ためには[、,]?\s*(.+?)(?:こと)?(?:が|は)必要(?:である|です)?', 文, re.S)
        if 必要:
            目的文 = 必要[1].strip().removesuffix("こと")
            条件文 = 必要[2].strip().removesuffix("こと")
            目的式, 目的主体 = 解析(目的文, 参照, 深さ + 1, 省略=省略)
            条件式, 条件主体 = 解析(条件文, 目的主体 or 参照, 深さ + 1, 裸=True, 省略=True)
            履歴.append("必要条件:目的→必要条件（逆向きへ使わない）")
            return 結合("含意", 目的式, 条件式), 目的主体 if 目的主体 == 条件主体 else None
        必要 = re.fullmatch(r'(.+?)(?:こと)?は(.+?)ための必要条件(?:である|です)?', 文, re.S)
        if 必要:
            条件文 = 必要[1].strip().removesuffix("こと")
            目的文 = 必要[2].strip().removesuffix("こと")
            条件式, 条件主体 = 解析(条件文, 参照, 深さ + 1, 裸=True, 省略=省略)
            目的式, 目的主体 = 解析(目的文, 条件主体 or 参照, 深さ + 1, 省略=True)
            履歴.append("必要条件:目的→必要条件（逆向きへ使わない）")
            return 結合("含意", 目的式, 条件式), 目的主体 if 目的主体 == 条件主体 else None
        限定必要 = re.fullmatch(r'(.+?)(?:な場合|の場合|場合|なとき|とき)(?:に限り|のみ)[、,]?\s*(.+)', 文, re.S)
        if 限定必要:
            条件文, 目的文 = 限定必要[1].strip(), 限定必要[2].strip()
            条件式, 条件主体 = 解析(条件文, 参照, 深さ + 1, 裸=True, 省略=省略)
            目的式, 目的主体 = 解析(目的文, 条件主体 or 参照, 深さ + 1, 省略=True)
            履歴.append("必要条件:「場合に限り/のみ」=目的→条件")
            return 結合("含意", 目的式, 条件式), 目的主体 if 目的主体 == 条件主体 else None
        # 対応不明の条件・留保を名詞や動作名へ押し込まない。
        if any(語 in 文 for 語 in _制限):
            raise ValueError("未対応の留保・限定作用域")
        時点 = re.fullmatch(r'(?:時点「([^「」]+)」では|([0-9]{4})年では)[（(](.*)[）)]', 文, re.S)
        if 時点:
            式, 主体 = 解析(時点[3], None, 深さ + 1)
            履歴.append("明示時点保持")
            return 文脈を付す(式, 時点=時点[1] or 時点[2] + "年"), 主体
        様相 = re.fullmatch(r'(可能性として|義務として)[（(](.*)[）)]', 文, re.S)
        if 様相:
            式, 主体 = 解析(様相[2], None, 深さ + 1)
            履歴.append("明示様相保持")
            return 文脈を付す(式, 様相="可能" if 様相[1] == "可能性として" else "義務"), 主体
        # 最上位だけを区切る。引用・括弧内の条件を外側へ移さない。
        条件 = list(最上位位置(文, ("ならば", "であれば", "な場合には", "な場合は", "な場合", "なときには", "なときは", "なとき", "場合には", "場合は", "場合", "ときには", "ときは", "とき", "なら")))
        if 条件:
            if len(条件) != 1:
                raise ValueError("複数条件の係り先を括弧で指定してください")
            位置, 接続 = 条件[0]
            前 = 文[:位置].removeprefix("もしも").removeprefix("もし").strip()
            後 = 文[位置 + len(接続):].lstrip("、, ")
            前式, 前主体 = 解析(前, 参照, 深さ + 1, 裸=True, 省略=省略)
            後式, 後主体 = 解析(後, 前主体, 深さ + 1, 省略=True)
            履歴.append("条件節:" + 接続 + "（前件を事実化しない）")
            return 結合("含意", 前式, 後式), 前主体 if 前主体 == 後主体 else None
        接続群 = list(最上位位置(文, ("であり、", "であり,", "かつ", "および", "または")))
        if 接続群:
            種類 = {"選言" if 語 == "または" else "連言" for _, 語 in 接続群}
            if len(種類) != 1 or len(接続群) > 7:
                raise ValueError("連言・選言の作用域または節数が未対応")
            部分, 前 = [], 0
            for 位置, 接続 in 接続群:
                部分.append(文[前:位置] + ("である" if 接続.startswith("であり") else ""))
                前 = 位置 + len(接続)
            部分.append(文[前:])
            式群, 主体群, 現主体 = [], [], 参照
            for 番号, 節 in enumerate(部分):
                式, 主体 = 解析(節, 現主体, 深さ + 1, 省略=省略 or 番号 > 0)
                式群.append(式); 主体群.append(主体)
                現主体 = 主体 if len(set(主体群)) == 1 else None
            履歴.append("接続:" + next(iter(種類)))
            return 結合(next(iter(種類)), *式群), 主体群[0] if len(set(主体群)) == 1 else None
        # 明示指示語は名詞として既存解析器へ渡さない。否定の「ではない」の「は」とも区別する。
        指示一致 = re.match(r"^(それ|これ|同装置|同対象)(は|が)", 文)
        if 指示一致:
            if 参照 is None:
                raise ValueError("照応先が一意でありません")
            履歴.append("照応:" + 指示一致[1] + "→" + 参照)
            return 解析(参照 + 文[len(指示一致[1]):], None, 深さ + 1, 裸=裸)
        # 既存の明示命題文法も使用する。候補が複数なら勝手に一つを選ばない。
        try:
            候補 = 命題を読む(文)
        except ValueError:
            候補 = ()
        if 候補:
            if len(候補) != 1:
                raise ValueError("命題の意味候補が複数")
            主体 = None
            主格 = list(最上位位置(文, ("は", "が")))
            単純式 = 候補[0].式
            if 単純式.種別 == "否定":
                単純式 = 単純式.子[0]
            if 主格 and 単純式.種別 == "原子" and len(単純式.項) == 1:
                主体 = _対象(文[:主格[0][0]])
                if 単純式.項[0].名前 != 主体:
                    主体 = None
            履歴.append("既存命題文法")
            return 候補[0].式, 主体
        主格 = list(最上位位置(文, ("は", "が")))
        if len(主格) > 1:
            raise ValueError("主体・係り先が複数")
        if 主格:
            位置, 助詞 = 主格[0]
            主体, 述部 = 文[:位置], 文[位置 + len(助詞):]
            if 主体 in _指示:
                if 参照 is None:
                    raise ValueError("照応先が一意でありません")
                履歴.append("照応:" + 主体 + "→" + 参照)
                主体 = 参照
            else:
                主体 = _対象(主体)
        else:
            if 参照 is None or not 省略:
                raise ValueError("同一文内の主体の省略先が一意でありません")
            主体, 述部 = 参照, 文
            履歴.append("局所主体補完:" + 主体)
        # サ変の活用だけを明示同値として接続。進行・過去・能力は別の述語。
        活用 = (
            ("していません", "している", True), ("していない", "している", True),
            ("しています", "している", False), ("している", "している", False),
            ("しませんでした", "した", True), ("しなかった", "した", True),
            ("しました", "した", False), ("した", "した", False),
            ("できません", "できる", True), ("できない", "できる", True),
            ("できます", "できる", False), ("できる", "できる", False),
            ("しません", "する", True), ("しない", "する", True),
            ("します", "する", False), ("する", "する", False),
        )
        for 語尾, 正形, 否定 in 活用:
            一致 = re.fullmatch("(" + _動作根 + ")" + 語尾, 述部)
            if 一致:
                式 = 原子(一致[1] + 正形, 主体)
                履歴.append("活用:" + 語尾 + "→" + ("否定:" if 否定 else "") + 正形)
                return (反対(式) if 否定 else 式), 主体
        if 裸 and _裸状態.fullmatch(述部):
            述部 += "である"
            履歴.append("条件内の名詞述語")
        候補 = 命題を読む(主体 + "は" + 述部)
        if len(候補) != 1:
            raise ValueError("述部の意味候補が複数")
        履歴.append("主格・省略の明示接続")
        return 候補[0].式, 主体

    式, 主体 = 解析(原文.strip().removesuffix("。"), 先行主体)
    式.検査()
    _未束縛参照を検査(式)
    return 式, 主体, 履歴


def _条件片を読む(原文: str):
    原文 = 原文.strip().removesuffix("こと")
    try:
        return 関係文を読む(原文)
    except ValueError as 最初:
        # 「有効な場合」等から取り出した名詞述語だけを、明示コピュラへ戻して再試行する。
        try:
            return 関係文を読む(原文 + "である")
        except ValueError:
            raise 最初


def 例外節を読む(原文: str):
    """直前の含意にだけ結び付けられる有限な例外節を読む。

    戻り値は例外条件、明示された例外時帰結（なければNone）、変換履歴。
    例外条件が不成立だと推定する処理は行わない。
    """
    if type(原文) is not str or not 0 < len(原文) <= 4096:
        raise ValueError("例外節の型・文字上限")
    文 = 原文.strip().removesuffix("。").strip()
    if not 文.startswith("ただし"):
        raise ValueError("例外節は『ただし』で明示してください")
    本文 = 文[len("ただし"):].lstrip("、, ")
    除外 = re.fullmatch(r'(.+?)(?:な場合|の場合|場合|なとき|とき)(?:は)?(?:を)?除く', 本文, re.S)
    if 除外:
        条件, _, 履歴 = _条件片を読む(除外[1])
        return 条件, None, [*履歴, "例外条件:成立時は直前規則を適用しない"]
    明示 = re.fullmatch(r'(.+?)(?:な場合|の場合|場合|なとき|とき)(?:には|は)[、,]?\s*(.+)', 本文, re.S)
    if 明示:
        条件, 主体, 履歴1 = _条件片を読む(明示[1])
        帰結, _, 履歴2 = 関係文を読む(明示[2], 先行主体=主体)
        return 条件, 帰結, [*履歴1, *履歴2, "例外条件:直前規則をガードし例外時帰結を別規則化"]
    # 「ただしAならB」は条件と帰結が明示されるため、有限な例外規則として扱える。
    try:
        式, _, 履歴 = 関係文を読む(本文)
    except ValueError:
        raise ValueError("例外節の条件・作用域が未対応")
    if 式.種別 != "含意":
        raise ValueError("例外節の作用域が直前規則へ一意に接続できない")
    return 式.子[0], 式.子[1], [*履歴, "例外条件:直前規則をガードし例外時帰結を別規則化"]


def 関係式を表現(式):
    """サ変原子の説明だけを整える。原資料や旧命題生成器は変更しない。"""
    if (式.種別 == "原子" and len(式.項) == 1 and 式.時点 == "未指定" and 式.様相 == "記載"
            and re.fullmatch(_動作根 + r"(?:する|した|している|できる)", 式.述語)):
        return 式.項[0].名前 + "は" + 式.述語
    if 式.種別 == "否定" and 式.時点 == "未指定" and 式.様相 == "記載":
        return "否定（" + 関係式を表現(式.子[0]) + "）"
    return 命題を表現(式)
