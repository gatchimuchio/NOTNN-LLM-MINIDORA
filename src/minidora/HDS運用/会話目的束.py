"""同一会話参照ビューを既存の単一目的要求へ降ろす純粋な読取。

原文の再解析、能力選択、採否、原記録所有の認定は行わない。
原包の保存と同セッションの実COMMIT・資料依存検証は呼出元責任。
"""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json

from ..HDS会話契約 import 会話契約を検査, 会話作用禁止版, 会話取得時期版
from .一般依頼 import 一般要求を検査, 一般会話要求版

_保持役割 = frozenset({"条件", "例外", "数値", "否定", "主語", "時点"})
_列役割 = {"対象.会話主題": "主題", "対象.会話資料": "対象", "対象.会話比較": "比較対象",
          "条件.会話観点": "観点", "関係.会話問い焦点": "関係焦点"}
_単値役割 = {"条件.会話問い方向": "肯否", "条件.会話範囲": "範囲",
            "表現.会話形式": "形式", "表現.会話詳細": "詳細", "表現.会話文字上限": "最大文字数"}
_役割辺 = {"要求対象", "要求観点", "要求関係", "問い方向", "要求範囲", "条件適用", "表現適用"}


def _取得時期を読む(ビュー, 目的ID):
    座標 = {項["座標ID"]: 項 for 項 in ビュー["座標"]}
    群 = [座標[辺["始点"][0]] for 辺 in ビュー["関係"]
         if 辺["種別"] == "条件適用" and 辺["終点"] == [目的ID]
         and 座標[辺["始点"][0]]["内容"]["値"]["役割"] == "取得時期"]
    if len(群) > 1:
        raise ValueError("同目的の取得時期が一意ではありません")
    return [{"目的ID": 目的ID, "条件ID": 項["座標ID"], **deepcopy(項["内容"]["値"]["値"]),
             "原文": 項["内容"]["原文"], "原文範囲": deepcopy(項["原文範囲"])} for 項 in 群]


def _単値(群, 名, 既定):
    値 = [項["内容"]["値"] for 項 in 群]
    if 値 and any(項 != 値[0] for 項 in 値):
        raise ValueError("会話目的の単一役割が競合しています:" + 名)
    return 値[0] if 値 else 既定


def _保持を読む(条件群, 表現群, 前対応, 保持辺, 元保持辺):
    if any(項["内容"]["値"]["役割"] != "出力保持" for 項 in 条件群):
        raise ValueError("会話目的の条件役割が未接続です")
    原条件 = [前対応.get(項["座標ID"], 項) for 項 in 条件群]
    原表現 = [前対応.get(項["座標ID"], 項) for 項 in 表現群]
    if any(項["内容"]["根拠"] == "原文" and 項["内容"]["値"]["値"] != 項["内容"]["原文"] for 項 in 原条件):
        raise ValueError("原保持句が原文へ束縛されていません")
    対応 = {項["座標ID"]: [] for 項 in 条件群}
    結果 = []
    for 項, 元表現 in zip(表現群, 原表現):
        値, 範囲 = 項["内容"]["値"], 項["原文範囲"]
        if (値 not in _保持役割 or 元表現["内容"]["根拠"] not in {"原文", "前束"} or 元表現["内容"]["根拠"] == "原文"
                and (元表現["原文範囲"] is None or 元表現["内容"]["原文"] != 値)):
            raise ValueError("会話目的の型保持が未解釈又は原文へ未束縛です")
        含有 = []
        for 条件, 元条件 in zip(条件群, 原条件):
            if 項["内容"]["根拠"] != 条件["内容"]["根拠"]:
                continue
            外, 内 = 元条件["原文範囲"], 元表現["原文範囲"]
            範囲対応 = 外 is not None and 内 is not None and 外[0] <= 内[0] < 内[1] <= 外[1]
            if 保持辺:
                if (条件["座標ID"], 項["座標ID"]) not in 保持辺:
                    continue
                if 項["内容"]["根拠"] == "前束":
                    # 元包自身の実辺、又は旧原範囲の一意な包含だけを継承する。
                    一意範囲 = 範囲対応 and sum(
                        元["原文範囲"] is not None and 内 is not None
                        and 元["原文範囲"][0] <= 内[0] < 内[1] <= 元["原文範囲"][1]
                        for 元 in 原条件) == 1
                    if (元条件["座標ID"], 元表現["座標ID"]) not in 元保持辺 and not 一意範囲:
                        raise ValueError("型保持の対応が前採用包の実辺又は一意な原範囲へ一致しません")
                elif not 範囲対応:
                    raise ValueError("型保持の対応が原保持句の原範囲へ一致しません")
                含有.append(条件)
            elif 範囲対応:
                含有.append(条件)
            elif (外 is None and 内 is None and 元条件["内容"]["根拠"] == 元表現["内容"]["根拠"] == "前束"
                  and len(原条件) == 1):
                # 前の実採用ビューにある同目的の型保持対。原保持句を新原文へ作り直さない。
                含有.append(条件)
        if len(含有) != 1:
            raise ValueError("型保持と原保持句の対応が一意ではありません")
        対応[含有[0]["座標ID"]].append(項["座標ID"])
        if 値 not in 結果:
            結果.append(値)
    if any(not 群 for 群 in 対応.values()):
        raise ValueError("原保持句に型保持の意味降下がありません")
    return 結果


def _指紋(値):
    文 = json.dumps(値, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(文.encode("utf-8")).hexdigest()


def _前束を照合(ビュー, 前採用包, 文脈証明, 所有, 前命令包=None, 命令証明=()):
    座標 = {項["座標ID"]: 項 for 項 in ビュー["座標"]}
    前参照 = {名: 項 for 名, 項 in 座標.items() if 項["種別"] in {"文脈.会話参照", "文脈.会話命令参照"}}
    if 前命令包 is not None and not any(項["種別"] == "文脈.会話命令参照" for 項 in 前参照.values()):
        raise ValueError("供与された命令源と当前契約の実命令参照用途が一致しません")
    if len({項["種別"] for 項 in 前参照.values()}) > 1:
        raise ValueError("現在目的の現行成果利用と命令再実行の混合は未接続です")
    if not 前参照:
        if any(辺["種別"] in {"目的継承", "命令再実行"} for 辺 in ビュー["関係"]):
            raise ValueError("目的継承の前参照がありません")
        return {}, {}, []
    前源 = {}
    for 種, 包, 証明群 in (("文脈.会話参照", 前採用包, 文脈証明), ("文脈.会話命令参照", 前命令包, 命令証明)):
        if not any(項["種別"] == 種 for 項 in 前参照.values()):
            continue
        if type(包) is not dict or not 証明群:
            raise ValueError("会話目的の前採用包/前命令包と呼出側の用途別証明が必要です")
        自己証明 = [項 for 項 in 証明群 if 項["前束印"] == 包["意味束印"]]
        if len(自己証明) != 1 or 種 == "文脈.会話命令参照" and 自己証明[0].get("原要求印") != 包["原文印"]:
            raise ValueError("元命令の実証明又は原要求印が一致しません")
        前 = 会話契約を検査(包, 所有セッション=所有, 文脈証明=文脈証明, 命令証明=命令証明)
        if 前["会話残差ID"] or 前["意味作用"]["損失"] or any(
                項["値状態"] != "確定" or 項["暫定性"] != "原則暫定" or 項.get("再開放条件")
                for 項 in 前["座標"] + 前["関係"]):
            raise ValueError("前採用包に未確定又は未解決の役割があります")
        元役割 = {名: set() for 名 in 包["目的参照"]}
        for 辺 in 前["関係"]:
            if 辺["種別"] in _役割辺:
                for 目的ID in 元役割:
                    if 辺["始点"] == [目的ID]: 元役割[目的ID].add(辺["終点"][0])
                    elif 辺["終点"] == [目的ID]: 元役割[目的ID].add(辺["始点"][0])
        前源[種] = (包, 前, {項["座標ID"]: 項 for 項 in 前["座標"]}, 元役割, 自己証明[0])
    対応 = {}
    for 名, 項 in 前参照.items():
        元包, _, 元座標, _, _ = 前源[項["種別"]]
        値 = 項["内容"]["値"]
        元 = 元座標.get(値["座標ID"])
        if (値["前束印"] != 元包["意味束印"] or 元 is None or 元["種別"] != 値["役割"]
                or _指紋(元["内容"]["値"]) != 値["値印"]):
            raise ValueError("前採用包の実役割と前束参照が一致しません")
        対応[名] = 元
    目的元 = {}
    for 辺 in ビュー["関係"]:
        if 辺["種別"] in {"目的継承", "命令再実行"}:
            参照ID = 辺["始点"][0]
            目的元[辺["終点"][0]] = (対応[参照ID]["座標ID"], 前参照[参照ID]["種別"])
    if "文脈.会話命令参照" in 前源:
        現目的 = [項["座標ID"] for 項 in ビュー["座標"] if 項["種別"] == "目的.会話操作"]
        if (set(現目的) != set(目的元) or any(種 != "文脈.会話命令参照" for _, 種 in 目的元.values())
                or [目的元[名][0] for 名 in 現目的] != 前源["文脈.会話命令参照"][0]["目的参照"]):
            raise ValueError("命令再実行の全目的が元命令の目的列へ同順一意に対応しません")
    結果 = {}
    使用元 = {目的ID: set() for 目的ID in 目的元}
    for 名, 項 in 座標.items():
        if 項["種別"] in {"文脈.会話参照", "文脈.会話命令参照"} or 項["内容"]["根拠"] != "前束":
            continue
        元 = 対応[項["内容"]["前束参照"]]
        目的群 = []
        if 項["種別"] == "目的.会話操作":
            目的群 = [名]
        else:
            for 辺 in ビュー["関係"]:
                if 辺["種別"] in _役割辺:
                    if 辺["始点"] == [名]: 目的群.extend(辺["終点"])
                    elif 辺["終点"] == [名]: 目的群.extend(辺["始点"])
        参照種 = 前参照[項["内容"]["前束参照"]]["種別"]
        if not 目的群 or any(目的ID not in 目的元 or 目的元[目的ID][1] != 参照種 or (
                元["座標ID"] != 目的元[目的ID][0] if 項["種別"] == "目的.会話操作"
                else 元["座標ID"] not in 前源[参照種][3][目的元[目的ID][0]]) for 目的ID in 目的群):
            raise ValueError("前束役割が元目的anchorの実適用辺へ一致しません")
        結果[名] = 元
        for 目的ID in 目的群:
            if 項["種別"] != "目的.会話操作": 使用元[目的ID].add(元["座標ID"])
    for 項 in ビュー["座標"]:
        if 項["種別"] != "目的.会話変更": continue
        値 = 項["内容"]["値"]
        許容 = ({"目的.会話操作", "表現.会話形式", "表現.会話詳細", "表現.会話数量", "表現.会話文字上限",
                "関係.会話問い焦点", "条件.会話問い方向"}
              if 値["役割"] == "再表現" else {"対象.会話主題", "対象.会話資料", "対象.会話比較", "条件.会話観点"}
              if 値["役割"] == "訂正" else set())
        if 値["対象役割"] not in 許容:
            raise ValueError("会話目的の変更役割が未接続です")
        辺群 = [辺 for 辺 in ビュー["関係"] if 辺["始点"] == [項["座標ID"]]]
        先 = {辺["種別"]: 辺["終点"][0] for 辺 in 辺群}
        目的ID, 前ID = 先["変更対象"], 先["変更前"]
        if 前ID not in 対応 or 目的ID not in 目的元:
            raise ValueError("会話変更が前採用目的へ束縛されていません")
        元ID = 対応[前ID]["座標ID"]
        元目的ID, 参照種 = 目的元[目的ID]
        if 参照種 != "文脈.会話参照" or 前参照[前ID]["種別"] != 参照種 or 元ID != 元目的ID and 元ID not in 前源[参照種][3][元目的ID]:
            raise ValueError("会話変更前が別の元目的の役割です")
        if 元ID != 元目的ID: 使用元[目的ID].add(元ID)
        新 = 座標[先["変更後"]]
        if 新["内容"]["根拠"] != "原文":
            raise ValueError("会話変更後に現在の明示原文がありません")
        if 値["対象役割"] == "表現.会話数量" and 新["内容"]["値"]["単位"] != 対応[前ID]["内容"]["値"]["単位"]:
            raise ValueError("会話数量の変更単位が一致しません")
    for 目的ID, (元ID, 種) in 目的元.items():
        if 種 != "文脈.会話命令参照":
            continue
        元目的 = 前源[種][2][元ID]
        if 座標[目的ID]["内容"]["値"] != 元目的["内容"]["値"]:
            raise ValueError("命令再実行の作用が実元目的と一致しません")
        実役割 = []
        for 辺 in ビュー["関係"]:
            if 辺["種別"] not in _役割辺: continue
            if 辺["始点"] == [目的ID]: 実役割.extend(辺["終点"])
            elif 辺["終点"] == [目的ID]: 実役割.extend(辺["始点"])
        if any(名 not in 結果 for 名 in 実役割):
            raise ValueError("命令再実行へ実元目的にない新役割を追加できません")
    if any(使用元[目的ID] != 前源[種][3][元ID] for 目的ID, (元ID, 種) in 目的元.items()):
        raise ValueError("元目的の役割を明示変更又は継承せず取り落としています")
    保持辺, 対応行 = {}, []
    for 目的ID, (元ID, 種) in 目的元.items():
        元包, 元ビュー, _, _, 証明 = 前源[種]
        保持辺[目的ID] = {(辺["始点"][0], 辺["終点"][0]) for 辺 in 元ビュー["関係"] if 辺["種別"] == "保持対応"}
        変更群 = []
        for 項 in ビュー["座標"]:
            if 項["種別"] != "目的.会話変更": continue
            先 = {辺["種別"]: 辺["終点"][0] for 辺 in ビュー["関係"] if 辺["始点"] == [項["座標ID"]]}
            if 先["変更対象"] == 目的ID:
                変更群.append({"対象役割": 項["内容"]["値"]["対象役割"], "前座標ID": 対応[先["変更前"]]["座標ID"], "後座標ID": 先["変更後"]})
        訂正 = any(項["種別"] == "目的.会話変更" and 項["内容"]["値"]["役割"] == "訂正"
                 and any(辺["種別"] == "変更対象" and 辺["始点"] == [項["座標ID"]] and 辺["終点"] == [目的ID] for 辺 in ビュー["関係"])
                 for 項 in ビュー["座標"])
        対応行.append({"目的ID": 目的ID, "元目的ID": 元ID, "前束印": 元包["意味束印"], "原記録ID": 証明["原記録ID"],
                    "方式": "再実行" if 種 == "文脈.会話命令参照" else "訂正" if 訂正 else "照応", "変更": 変更群})
    return 結果, 保持辺, 対応行


def _会話目的を読取る(契約包, *, 所有セッション, 期待原文=None, 意味IR=None, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    """1〜4の目的を適用辺ごとに読取る。未接続条件を既定へ消さない。"""
    if 前採用包 is not None and 前命令包 is not None:
        raise ValueError("前採用包と前命令包の元源を混合できません")
    ビュー = 会話契約を検査(契約包, 所有セッション=所有セッション,
                       期待原文=期待原文, 意味IR=意味IR, 文脈証明=文脈証明, 命令証明=命令証明)
    座標 = {項["座標ID"]: 項 for 項 in ビュー["座標"]}
    関係 = ビュー["関係"]
    if ビュー["会話残差ID"]:
        群 = [項 for 項 in ビュー["残差"] if 項["残差ID"] in ビュー["会話残差ID"]]
        raise ValueError("会話目的の未消費残差:" + "；".join(項["残差ID"] + ":" + 項["理由"] for 項 in 群))
    if ビュー["意味作用"]["損失"]:
        raise ValueError("会話目的に未解決の意味損失があります")
    for 項 in ビュー["座標"] + 関係:
        # 原則暫定は既存HDS全体の通常属性。局所値の未確定とは区別する。
        if 項["値状態"] != "確定" or 項["暫定性"] != "原則暫定" or 項.get("再開放条件"):
            raise ValueError("会話目的の未確定又は未接続の暫定条件:" + 項.get("座標ID", 項.get("関係ID", "")))
    前対応, 元保持辺, 前目的対応 = _前束を照合(ビュー, 前採用包, 文脈証明, 所有セッション, 前命令包, 命令証明)
    原型前ビュー = None
    def 原条件源(項):
        nonlocal 原型前ビュー
        if 項["座標ID"] not in 前対応:
            return 項, 座標, ビュー["原文"]
        元 = 前対応[項["座標ID"]]
        if 元["内容"]["根拠"] != "原文" or 元["原文範囲"] is None:
            raise ValueError("型付き原条件のさらに前の原源は未接続です")
        if 原型前ビュー is None:
            元包 = 前採用包 if 前採用包 is not None else 前命令包
            # 前束を照合が検査済みの実原包。原文をコンパイルし直さない。
            原型前ビュー = json.loads(元包["証明正準JSON"])
        元座標 = {行["座標ID"]: 行 for 行 in 原型前ビュー["座標"]}
        if 元座標.get(元["座標ID"]) != 元:
            raise ValueError("型付き前条件の元座標が実原包に一致しません")
        return 元, 元座標, 原型前ビュー["原文"]
    if not 前対応 and any(項["種別"] == "目的.会話変更" for 項 in ビュー["座標"]):
        raise ValueError("会話目的の変更又は前束所有が未接続です")
    if any(項["種別"] == "文節従属" for 項 in 関係):
        raise ValueError("会話目的の文節従属条件が未接続です")
    結果, 上限群 = [], []
    for 目的ID in 契約包["目的参照"]:
        目的 = 座標[目的ID]
        所属 = [項 for 項 in 関係 if 項["種別"] == "文節所属" and 項["終点"] == [目的ID]]
        文節 = 座標[所属[0]["始点"][0]]
        束縛 = []
        for 辺 in 関係:
            if 辺["始点"] == [目的ID] and 辺["種別"] in {"要求対象", "要求観点", "要求関係", "問い方向", "要求範囲"}:
                束縛.append(座標[辺["終点"][0]])
            elif 辺["終点"] == [目的ID] and 辺["種別"] in {"条件適用", "表現適用"}:
                束縛.append(座標[辺["始点"][0]])
        材料 = [座標[辺["始点"][0]] for 辺 in 関係 if 辺["種別"] == "材料適用" and 辺["終点"] == [目的ID]]
        if len(材料) > 1:
            raise ValueError("一目的の提示本文区分が複数です")
        本文 = 材料[0]["内容"]["原文"] if 材料 else ""
        要求 = {"版": 一般会話要求版, "対象": [], "主題": [], "操作": [目的["内容"]["値"]],
              "形式": "文章", "範囲": "自動", "最大文字数": 24000, "問い": 文節["内容"]["原文"],
              "比較対象": [], "観点": [], "詳細": "標準", "提示本文": 本文, "関係焦点": [], "肯否": "未指定"}
        数量, 保持表現, 条件, 単値 = [], [], [], {}
        for 項 in 束縛:
            種, 値 = 項["種別"], 項["内容"]["値"]
            if 種 in _列役割:
                if 種 == "対象.会話資料" and 値 == "提示本文":
                    if not 材料 and 項["座標ID"] not in 前対応:
                        raise ValueError("提示本文の対象に材料適用がありません")
                    if 材料:
                        continue
                名 = _列役割[種]
                if 値 in 要求[名]:
                    raise ValueError("会話目的の同一対象役割が重複しています:" + 名)
                要求[名].append(値)
            elif 種 in _単値役割:
                単値.setdefault(_単値役割[種], []).append(項)
            elif 種 == "表現.会話数量":
                数量.append(deepcopy(値))
            elif 種 == "表現.会話保持":
                保持表現.append(項)
            elif 種 == "条件.会話適用":
                条件.append(項)
            elif 種 == "情報源.会話提示本文":
                if not 材料 or 値 != 本文:
                    raise ValueError("本文役割と材料適用の実本文が不一致です")
            else:
                raise ValueError("会話目的の未接続役割:" + 種)
        if 本文 and 要求["対象"]:
            raise ValueError("提示本文と登録資料の混在束縛は未接続です")
        if 要求["対象"]:
            要求["範囲"] = "指定資料"
        for 名, 群 in 単値.items():
            要求[名] = _単値(群, 名, 要求[名])
        明示上限 = 要求["最大文字数"] if "最大文字数" in 単値 else None
        if 明示上限 is not None and not 1 <= 明示上限 <= 24000:
            raise ValueError("会話目的の明示文字上限が既存v2予算へ降ろせません")
        if 明示上限 is not None:
            # 元の出力上限は数量条件にも保存し、生成予算の下限へ置換しない。
            数量.append({"単位": "文字", "関係": "以内", "数": 明示上限})
        文字量 = [項["数"] for 項 in 数量 if 項["単位"] == "文字"]
        if 文字量:
            実上限 = min(文字量)
            if any(項["単位"] == "文字" and 項["関係"] == "一致" and 項["数"] > (明示上限 or 24000) for 項 in 数量):
                raise ValueError("会話目的の一致文字数量と文字上限が競合しています")
            明示上限 = max(100, min(明示上限 or 24000, 実上限))
        elif 明示上限 is not None:
            明示上限 = max(100, 明示上限)
        保持辺 = {(辺["始点"][0], 辺["終点"][0]) for 辺 in 関係 if 辺["種別"] == "保持対応"
                 and 辺["始点"][0] in {項["座標ID"] for 項 in 条件}}
        _取得時期を読む(ビュー, 目的ID)
        # 版付きの取得条件は別readerへ渡す。未知の文字列条件は従来拒否。
        条件 = [項 for 項 in 条件 if 項["内容"]["値"] != {
            "役割": "作用禁止", "値": {"版": 会話作用禁止版, "作用": "外部読取"}}
            and 項["内容"]["値"] != {"役割": "取得時期", "値": {
                "版": 会話取得時期版, "作用": "外部読取", "基準": "要求時点"}}]
        条件 = [項 for 項 in 条件 if 項["内容"]["値"]["役割"] not in {"同発話対応", "関係要求", "動作目的要求"}]
        保持 = _保持を読む(条件, 保持表現, 前対応, 保持辺, 元保持辺.get(目的ID, set()))
        関係群 = [項 for 項 in 束縛 if 項["種別"] == "条件.会話適用" and 項["内容"]["値"]["役割"] == "関係要求"]
        動作群 = [項 for 項 in 束縛 if 項["種別"] == "条件.会話適用" and 項["内容"]["値"]["役割"] == "動作目的要求"]
        if 要求["操作"] == ["理由"]:
            # 検索限定だけにせず、原の同発話対応で結ばれた関係を内容側にも必須保持。
            子 = [項["内容"]["値"]["値"]["補足目的ID"] for 項 in ビュー["座標"]
                 if 項["種別"] == "条件.会話適用" and 項["内容"]["値"]["役割"] == "同発話対応"
                 and 項["内容"]["値"]["値"]["元目的ID"] == 目的ID
                 and 項["内容"]["値"]["値"]["方式"] in {"関係端点補足", "理由参照関係補足"}]
            関係群.extend(座標[辺["始点"][0]] for 辺 in 関係 if 辺["種別"] == "条件適用"
                        and 辺["終点"][0] in 子 and 座標[辺["始点"][0]]["種別"] == "条件.会話適用"
                        and 座標[辺["始点"][0]]["内容"]["値"]["役割"] == "関係要求")
        if 関係群 or 動作群:
            from .一般依頼 import 一般関係会話要求版
            要求["版"], 要求["関係要求"], 要求["動作目的要求"] = 一般関係会話要求版, [], []
            for 項 in 関係群:
                原条件, 原座標, 原発話 = 原条件源(項)
                内 = 原条件["内容"]["値"]["値"]
                def 原役割(名):
                    元 = 原座標[名]
                    return {"値": 元["内容"]["値"], "原文範囲": list(元["原文範囲"])}
                要求["関係要求"].append({"版": 内["版"], "型": 内["型"], "原発話": 原発話,
                    "両端": [原役割(名) for 名 in 内["両端ID"]],
                    "原語句": {"原文": 原条件["内容"]["原文"], "原文範囲": list(内["原語句範囲"])},
                    "焦点": 原役割(内["焦点ID"])})
            for 項 in 動作群:
                原条件, _, 原発話 = 原条件源(項)
                内 = 原条件["内容"]["値"]["値"]
                要求["動作目的要求"].append({名: deepcopy(値) for 名, 値 in 内.items() if 名 != "焦点ID"})
                要求["動作目的要求"][-1]["原発話"] = 原発話
        結果.append({"目的ID": 目的ID, "文節ID": 文節["座標ID"], "要求": 要求, "数量": 数量, "保持": 保持})
        上限群.append(明示上限)
    明示合計 = sum(値 for 値 in 上限群 if 値 is not None)
    未指定数 = 上限群.count(None)
    残り = 24000 - 明示合計
    if 残り < 100 * 未指定数:
        raise ValueError("会話目的束の総文字予算24000が不足しています")
    配分, 余り = divmod(残り, 未指定数) if 未指定数 else (0, 0)
    外部主題 = set()
    for 番号, 行 in enumerate(結果):
        上限 = 上限群[番号]
        if 上限 is None:
            上限 = 配分 + (1 if 余り else 0)
            余り = max(0, 余り - 1)
        行["要求"]["最大文字数"] = 上限
        行["要求"] = 一般要求を検査(行["要求"])
        if 行["要求"]["範囲"] in {"自動", "公開取得"} and not 行["要求"]["提示本文"]:
            外部主題.update(行["要求"]["主題"] + 行["要求"]["比較対象"])
    if len(外部主題) > 4:
        raise ValueError("会話目的束の外部主題合計が4を超えています")
    return 結果, 前目的対応


def 会話目的を読む(契約包, *, 所有セッション, 期待原文=None, 意味IR=None, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    return _会話目的を読取る(契約包, 所有セッション=所有セッション, 期待原文=期待原文, 意味IR=意味IR,
                      前採用包=前採用包, 文脈証明=文脈証明, 前命令包=前命令包, 命令証明=命令証明)[0]


def 会話前目的対応を読む(契約包, *, 所有セッション, 期待原文=None, 意味IR=None, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    """同じ検査済みビューから元目的と利用方式を返す。rawを再分析しない。"""
    return _会話目的を読取る(契約包, 所有セッション=所有セッション, 期待原文=期待原文, 意味IR=意味IR,
                      前採用包=前採用包, 文脈証明=文脈証明, 前命令包=前命令包, 命令証明=命令証明)[1]


def 会話取得条件を読む(契約包, *, 所有セッション, 期待原文=None, 意味IR=None, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    """検査済み条件辺を読むだけ。取得権限の発行・原文再分類はしない。"""
    会話目的を読む(契約包, 所有セッション=所有セッション, 期待原文=期待原文, 意味IR=意味IR,
               前採用包=前採用包, 文脈証明=文脈証明, 前命令包=前命令包, 命令証明=命令証明)
    ビュー = 会話契約を検査(契約包, 所有セッション=所有セッション, 期待原文=期待原文,
                       意味IR=意味IR, 文脈証明=文脈証明, 命令証明=命令証明)
    座標 = {項["座標ID"]: 項 for 項 in ビュー["座標"]}
    結果 = []
    for 目的ID in 契約包["目的参照"]:
        条件群 = [座標[辺["始点"][0]] for 辺 in ビュー["関係"]
              if 辺["種別"] == "条件適用" and 辺["終点"] == [目的ID]
              and 座標[辺["始点"][0]]["内容"]["値"] == {
                  "役割": "作用禁止", "値": {"版": 会話作用禁止版, "作用": "外部読取"}}]
        結果.append({"目的ID": 目的ID, "外部禁止": bool(条件群),
                     "条件ID": [項["座標ID"] for 項 in 条件群],
                     "原文": [項["内容"]["原文"] for 項 in 条件群]})
    return 結果


def 会話取得時期を読む(契約包, *, 所有セッション, 期待原文=None, 意味IR=None, 前採用包=None, 文脈証明=(), 前命令包=None, 命令証明=()):
    """当回の取得行為へ束縛された原時期を読む。現在事実や権限を発行しない。"""
    引数 = {"所有セッション": 所有セッション, "期待原文": 期待原文, "意味IR": 意味IR,
          "前採用包": 前採用包, "文脈証明": 文脈証明, "前命令包": 前命令包, "命令証明": 命令証明}
    会話目的を読む(契約包, **引数)
    ビュー = 会話契約を検査(契約包, 所有セッション=所有セッション, 期待原文=期待原文,
                       意味IR=意味IR, 文脈証明=文脈証明, 命令証明=命令証明)
    return [項 for 目的ID in 契約包["目的参照"] for 項 in _取得時期を読む(ビュー, 目的ID)]
