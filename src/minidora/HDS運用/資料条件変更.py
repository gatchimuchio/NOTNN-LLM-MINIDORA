def 資料条件変更要求を検査(要求):
    欄 = {"版", "変更照合", "取消指定", "書換指定", "主張", "資料", "形式", "最大文字数",
          "原条件対応", "原支持", "適用", "作用禁止", "確認待ち", "原変更", "対象", "範囲", "不足調査"}
    if (type(要求) is not dict or set(要求) != 欄 or 要求["版"] != 資料条件変更要求版
            or 要求["原条件対応"] != {"状態": "未形成", "条件ID": None}
            or 要求["原支持"] != "未判定" or 要求["適用"] != "未適用"
            or 要求["形式"] not in ("文章", "箇条書き", "引用")
            or type(要求["最大文字数"]) is not int or not 100 <= 要求["最大文字数"] <= 24000
            or 要求["対象"] != ["提示本文"] or 要求["範囲"] != "指定資料" or 要求["不足調査"] is not False
            or type(要求["作用禁止"]) is not list or type(要求["確認待ち"]) is not list
            or any(type(s) is not str for s in 要求["確認待ち"])):
        raise ValueError("資料条件変更の要求型・版・未適用境界が不一致")
    元 = 要求["原変更"]
    元欄 = {"所有セッション", "原文", "目的ID", "文節ID", "文節範囲", "行為座標ID", "行為範囲", "行為原文", "契約印", "意味IR印", "HDS残差"}
    if (type(元) is not dict or set(元) != 元欄 or any(type(元[k]) is not str or not 元[k] for k in 元欄 - {"行為範囲", "文節範囲", "HDS残差"})
            or type(元["HDS残差"]) is not list or any(len(元[k]) != 64 or any(c not in "0123456789abcdef" for c in 元[k]) for k in ("契約印", "意味IR印"))):
        raise ValueError("資料条件変更の原HDS由来が不正")
    def 原区間(span,text):
        if (type(span) is not list or len(span) != 2 or any(type(v) is not int for v in span)
                or not 0 <= span[0] < span[1] <= len(元["原文"]) or 元["原文"][slice(*span)] != text):
            raise ValueError("資料条件変更の原文spanが不一致")
    原区間(元["行為範囲"], 元["行為原文"])
    文節範囲=元["文節範囲"]
    if type(文節範囲) is not list or len(文節範囲)!=2 or any(type(v) is not int for v in 文節範囲): raise ValueError("原制御文節範囲が不正")
    原区間(文節範囲,元["原文"][slice(*文節範囲)])
    材料 = 要求["資料"]
    if (type(材料) is not dict or set(材料) != {"方式", "対象", "区分ID", "原文範囲", "本文"}
            or 材料["方式"] != "提示原文" or 材料["対象"] != [] or type(材料["区分ID"]) is not str or not 材料["区分ID"]):
        raise ValueError("資料条件変更の提示資料対応が不正")
    原区間(材料["原文範囲"], 材料["本文"])
    if 材料["原文範囲"][0]<文節範囲[1]: raise ValueError("提示材料が原制御へ重複")
    from ..HDS会話契約 import 会話主張変更版
    内 = 要求["変更照合"]
    if (type(内) is not dict or 内.get("版") != 会話主張変更版 or 内.get("行為") != "変更照合"
            or set(内) != {"版", "行為", "取消指定", "書換指定"} or 内["取消指定"] is None and 内["書換指定"] is None):
        raise ValueError("資料条件変更の内側意図が不正")
    for k in ("取消指定", "書換指定"):
        a,b = 内[k],要求[k]
        if a is None:
            if b is not None: raise ValueError("資料条件変更の指定が異義")
            continue
        if type(a) is not dict or type(b) is not dict: raise ValueError("資料条件変更指定の型不正")
        expected=deepcopy(a)
        for key,span in a.items():
            if key.endswith("範囲"):
                if type(span) is not list or len(span)!=2: raise ValueError("資料条件変更指定の原範囲不正")
                text=元["原文"][slice(*span)]; 原区間(span,text)
                if not 文節範囲[0] <= span[0] < span[1] <= 文節範囲[1]: raise ValueError("資料条件変更指定が原制御範囲外")
                expected[key.removesuffix("範囲")+"原文"]=text
        if expected!=b: raise ValueError("資料条件変更の指定原文が不一致")
    P=要求["主張"]
    if 要求["書換指定"] is None:
        if P is not None: raise ValueError("取消だけの架空主張")
    else:
        if (type(P) is not dict or set(P)!={"座標ID","原文範囲","本文"} or P["座標ID"]!=要求["書換指定"]["主張座標ID"]): raise ValueError("書換主張と実焦点が不一致")
        原区間(P["原文範囲"], P["本文"])
        if not 文節範囲[0]<=P["原文範囲"][0]<P["原文範囲"][1]<=文節範囲[1]: raise ValueError("書換主張が制御範囲外")
    for 禁止 in 要求["作用禁止"]:
        if 禁止.get("内容",{}).get("値") != {"役割":"作用禁止","値":{"版":"HDS会話作用禁止-v1","作用":"外部読取"}}:
            raise ValueError("資料条件変更の作用禁止が不正")
    return 正準(要求)


def _書換主体範囲を読む(要求):
    P=要求["主張"]
    結果={"状態":"未形成","原主張":P,"役割":{},"字句":[],"座標":[],"関係":[],"診断":[]}
    if P is None:
        結果["診断"].append("取消のみのため書換主張がありません")
        return 結果
    文=P["本文"];起点=P["原文範囲"][0]
    try: 字句=会話字句を観測(文)
    except 会話字句不成立 as e:
        結果["診断"].append(str(e));return 結果
    結果["字句"]=[{**asdict(t),"開始":起点+t.開始,"終了":起点+t.終了} for t in 字句]
    if (not 字句 or len(字句)>128 or 字句[0].開始!=0 or 字句[-1].終了!=len(文)
            or any(a.終了!=b.開始 for a,b in zip(字句,字句[1:])) or any(t.未知語 or 文[t.開始:t.終了]!=t.表層 for t in 字句)):
        結果["診断"].append("書換主張の全文既知字句被覆が未形成");return 結果
    位=[i for i,t in enumerate(字句) if t.表層=="誰" and t.品詞[0]=="代名詞"]
    if len(位)!=1:
        結果["診断"].append("全称主体範囲の量化原文を一意に読めません");return 結果
    i=位[0];役割={}
    if i:
        if (i<2 or 字句[i-1].表層!="は" or 字句[i-1].品詞[:2]!=("助詞","係助詞") or not _自己名詞句(字句[:i-1])):
            結果["診断"].append("書換主張の明示話題又は量化の作用先が未対応");return 結果
        役割["話題"]={"原文":文[:字句[i-1].開始],"開始":起点,"終了":起点+字句[i-1].開始}
    if (i+3>=len(字句) or 字句[i+1].表層!="で" or 字句[i+1].品詞[:2]!=("助詞","格助詞")
            or 字句[i+2].表層!="も" or 字句[i+2].品詞[:2]!=("助詞","係助詞")):
        結果["診断"].append("誰でもの原量化構造が未対応");return 結果
    V=_限定用言(文,字句[i+3:],起点)
    if V is None:
        結果["診断"].append("量化後の用言・肯否・時点の全文型が未形成");return 結果
    量={"原文":文[字句[i].開始:字句[i+2].終了],"開始":起点+字句[i].開始,"終了":起点+字句[i+2].終了,
        "種別":"全称主体範囲","領域":"原主張内の主体範囲","世界個体生成":False}
    役割.update(主体範囲=量,用言=V)
    元=要求["原変更"];由来=元["所有セッション"]+":"+元["意味IR印"]
    基底=P["座標ID"]+":書換主体範囲"
    from .解釈 import 構造を保存
    座標=[構造を保存(HDS座標(基底+":"+k,"資料変更."+k,v,原文範囲=(v["開始"],v["終了"]),由来=由来)) for k,v in 役割.items()]
    関係=[構造を保存(HDS関係(基底+":量化作用",(基底+":主体範囲",),(基底+":用言",),"原書換主張の全称主体範囲",(P["座標ID"],),由来=由来))]
    結果.update(状態="全文型成立",役割=役割,座標=座標,関係=関係)
    return 結果


def 資料条件変更を読む(資料群,要求):
    要求=資料条件変更要求を検査(要求)
    if (type(資料群) is not dict or set(資料群)!={"提示本文"} or not isinstance(資料群["提示本文"],能力結果)
            or not 資料群["提示本文"].成立 or 資料群["提示本文"].本文!=要求["資料"]["本文"]):
        raise ValueError("資料条件変更の実提示材料が原要求と不一致")
    from .関係読解 import _一資料記載を読む
    from .資料回答 import 記載関係を読む
    群={名:_一資料記載を読む(名,値) for 名,値 in 資料群.items()}
    # 既存原記載 producer が読む実保存値二欄。一般要求への偽装・意味選択検査迂回はしない。
    記載=記載関係を読む({"資料順":list(群),"資料群":群})
    _束を検査(記載)
    P=_書換主体範囲を読む(要求)
    候補=[行 for 行 in 記載 if 行["資料作用"]["局所限定"] is not None
          and 行["資料作用"]["局所限定"]["読解"]["状態"]=="読解"
          and 行["資料作用"]["局所限定"]["読解"]["種別"]=="主体範囲限定"]
    確認=[];照合={"状態":"未形成","対象対応":"未形成","実対象一致":False,"仮定":None,"原記載ID":None,"原支持":"未判定","適用":"未適用"}
    if 要求["取消指定"] is not None:
        確認.append("取消選択「"+要求["取消指定"]["選択原文"]+"」が指す条件の原文を確認してください。取消は未適用です。")
    全局所=bool(記載) and all(行["資料作用"]["局所限定"] is not None and 行["資料作用"]["局所限定"]["読解"]["状態"]=="読解" for 行 in 記載)
    if P["状態"]!="全文型成立":確認.extend(P["診断"])
    elif 要求["原変更"]["HDS残差"]:確認.append("当回の原HDS残差が書換主体範囲へ与える影響を確認してください")
    elif not 全局所 or len(候補)!=1:確認.append("資料の限定・否定の全作用域と、書換対象の原記載を一意に確認してください")
    else:
        原=候補[0];役=原["資料作用"]["局所限定"]["読解"]["役割"]
        A,B=役["用言"],P["役割"]["用言"]
        同用言=all(A[k]==B[k] for k in ("辞書形列","肯否","時制","様相","別基本動詞への変換"))
        元話題=役.get("話題");新話題=P["役割"].get("話題")
        if not 同用言:確認.append("原用言「"+A["原文"]+"」と書換用言「"+B["原文"]+"」の動作・肯否・時点が一致しません。対応を確認してください")
        elif 元話題 is None:確認.append("原限定の話題・対象の原文を明示してください")
        elif 新話題 is not None and 元話題["原文"]!=新話題["原文"]:確認.append("原話題「"+元話題["原文"]+"」と書換話題「"+新話題["原文"]+"」の対応が一致しません")
        else:
            仮定=None if 新話題 is not None else "書換主張が資料の同じ話題・原用言を対象にしているのであれば"
            照合.update(状態="原限定保持照合" if 仮定 is None else "明示仮定内の原限定保持照合",
                対象対応="明示話題の原表記一致" if 仮定 is None else "未形成",実対象一致=仮定 is None,仮定=仮定,
                原記載ID=原["ID"],原資料所有=deepcopy(原["資料作用"]["原資料"]),原限定=deepcopy(原["資料作用"]["局所限定"]),
                用言対応={"辞書形列":A["辞書形列"],"肯否":A["肯否"],"時制":A["時制"],"様相":A["様相"],"世界判断":"未認定"},
                範囲差={"原主体":役["主体NP"],"原限定標識":役["限定標識"],"書換主体":P["役割"]["主体範囲"],"意味同等":"原主体限定を保持する証明がない"},
                保持記載ID=[行["ID"] for 行 in 記載])
            if 仮定:確認.append("書換主張の対象が資料の話題「"+元話題["原文"]+"」と同じかを確認してください。実対象対応は未形成です。")
    return 正準({"版":資料条件変更読解版,"要求":要求,"資料群":群,"公開資料群":{},"取得":None,"取得状態":"未要求",
        "原記載":記載,"書換主体範囲":P,"原限定保持照合":照合,"原条件対応":{"状態":"未形成","条件ID":None},
        "取消状態":"未対応" if 要求["取消指定"] is not None else "未要求","原支持":"未判定","適用":"未適用","確認待ち":確認,
        "束縛印":指紋({"原変更":要求["原変更"],"資料":要求["資料"],"保存値":結果を保存(資料群["提示本文"])}),
        "境界":"原文の主体範囲と限定保持の照合。取消・書換は未適用で、許可・能力可能・十分条件・存在・世界の支持反証は未認定。"})
