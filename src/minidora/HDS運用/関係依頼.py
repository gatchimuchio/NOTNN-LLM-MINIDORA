"""普通の関係質問を既存HDS工程へ接続する。解釈不能な目的・指定を捨てない。"""
from __future__ import annotations
from copy import deepcopy
import re
from .値 import 結果を復元, 結果を保存, 指紋, 正準
from .関係読解 import 関係要求版, 関係要求を検査, 主張採用要求版
from .資料条件変更 import 資料条件変更要求版, 旧資料条件変更要求版, 資料条件変更要求を検査

_資料列 = r'(?:資料)?「[^「」\n]+」(?:\s*と\s*(?:資料)?「[^「」\n]+」)*'
_再表現 = {"箇条書きにして": "箇条書き", "文章にして": "文章", "引用形式にして": "引用"}
旧会話主張接続版 = "HDS会話主張接続-v1"
会話主張接続版 = "HDS会話主張接続-v2"
会話主張変更接続版 = "HDS会話主張変更接続-v1"


def 会話主張要求を読む(契約包, *, 所有セッション, 期待原文=None, 意味IR=None, 接続版=会話主張接続版):
    """同じHDS会話ビューの主張・情報源役割だけを降ろす。真偽は判定しない。"""
    from ..HDS会話契約 import 会話契約を検査, 会話主張要求版, 会話作用禁止版, 会話主張変更版
    if 接続版 not in (旧会話主張接続版, 会話主張接続版):
        raise ValueError("主張接続の指定版が未対応です")
    ビュー = 会話契約を検査(契約包, 所有セッション=所有セッション,
                       期待原文=期待原文, 意味IR=意味IR)
    座標 = {項["座標ID"]: 項 for 項 in ビュー["座標"]}
    目的列 = [座標[名] for 名 in 契約包["目的参照"]]
    if not any(項["内容"]["値"] == "主張検討" for 項 in 目的列):
        return None
    if len(目的列) != 1 or 目的列[0]["内容"]["値"] != "主張検討":
        raise ValueError("主張検討は単一の明示目的だけに対応します")
    if ビュー["会話残差ID"] or ビュー["意味作用"]["損失"]:
        raise ValueError("主張検討の未消費残差又は意味損失があります")
    if 契約包["文脈束縛"] or any(項["種別"] in {"目的.会話変更", "文脈.会話参照", "文脈.会話命令参照"}
                              for 項 in ビュー["座標"]):
        raise ValueError("主張検討の前束又は変更は未接続です")
    if any(項["値状態"] != "確定" or 項["暫定性"] != "原則暫定" or 項.get("再開放条件")
           for 項 in ビュー["座標"] + ビュー["関係"]):
        raise ValueError("主張検討の未確定役割があります")
    目的ID = 目的列[0]["座標ID"]
    関係 = ビュー["関係"]
    if any(辺["種別"] == "文節従属" for 辺 in 関係):
        raise ValueError("主張検討の文節従属条件は未接続です")
    def 先(種):
        return [座標[辺["終点"][0]] for 辺 in 関係 if 辺["種別"] == 種 and 辺["始点"] == [目的ID]]
    def 元(種):
        return [座標[辺["始点"][0]] for 辺 in 関係 if 辺["種別"] == 種 and 辺["終点"] == [目的ID]]
    所属 = 元("文節所属")
    if len(所属) != 1 or 所属[0]["種別"] != "対象.会話文節" or 所属[0]["原文範囲"] is None:
        raise ValueError("主張検討の所属制御文節が一意ではありません")
    文節 = 所属[0]
    制御 = [座標[辺["始点"][0]] for 辺 in 関係 if 辺["種別"] == "区分所属"
          and 辺["終点"] == [文節["座標ID"]]]
    if (len(制御) != 1 or 制御[0]["種別"] != "情報源.会話入力区分"
            or 制御[0]["内容"]["値"] != "制御" or 制御[0]["原文範囲"] is None
            or not 制御[0]["原文範囲"][0] <= 文節["原文範囲"][0] < 文節["原文範囲"][1] <= 制御[0]["原文範囲"][1]):
        raise ValueError("主張検討の制御文節と制御区分の実範囲が不一致です")
    def 制御文節内(項):
        範囲 = 項["原文範囲"]
        if 範囲 is None or not 文節["原文範囲"][0] <= 範囲[0] < 範囲[1] <= 文節["原文範囲"][1]:
            raise ValueError("主張検討の役割が所属制御文節の実範囲にありません")
    制御文節内(目的列[0])
    焦点, 条件, 表現, 材料, 対象 = 先("要求関係"), 元("条件適用"), 元("表現適用"), 元("材料適用"), 先("要求対象")
    行為群 = [項 for 項 in 条件 if 項["内容"]["値"].get("役割") == "問い条件"
           and type(項["内容"]["値"].get("値")) is dict
           and 項["内容"]["値"]["値"].get("版") in {会話主張要求版, 会話主張変更版}]
    if len(行為群) != 1 or 行為群[0]["原文範囲"] is None:
        raise ValueError("主張検討の明示行為条件が一意ではありません")
    制御文節内(行為群[0])
    行為値 = 行為群[0]["内容"]["値"]["値"]
    変更照合 = 行為値["版"] == 会話主張変更版
    必要焦点数 = 0 if 変更照合 and 行為値["書換指定"] is None else 1
    if len(焦点) != 必要焦点数 or 焦点 and 焦点[0]["原文範囲"] is None:
        raise ValueError("主張検討の原主張が一意の原文範囲にありません")
    主張 = None
    if 焦点:
        項 = 焦点[0]
        制御文節内(項)
        主張 = {"座標ID": 項["座標ID"], "原文範囲": 項["原文範囲"], "本文": 項["内容"]["値"]}
        if ビュー["原文"][slice(*主張["原文範囲"])] != 主張["本文"]:
            raise ValueError("主張検討の原主張sliceが不一致です")
    許容条件 = {行為群[0]["座標ID"]} | {項["座標ID"] for 項 in 条件 if 項["内容"]["値"] == {
        "役割": "作用禁止", "値": {"版": 会話作用禁止版, "作用": "外部読取"}}}
    if any(項["座標ID"] not in 許容条件 for 項 in 条件):
        raise ValueError("主張検討の未接続条件があります")
    if 先("要求観点") or 先("問い方向"):
        raise ValueError("主張検討の観点又は別方向の問いは未接続です")
    形式, 予算 = "箇条書き", 24000
    種群 = set()
    for 項 in 表現:
        種 = 項["種別"]
        if 種 in 種群:
            raise ValueError("主張検討の表現指定が競合しています")
        種群.add(種)
        if 種 == "表現.会話形式":
            形式 = 項["内容"]["値"]
        elif 種 == "表現.会話文字上限":
            予算 = 項["内容"]["値"]
        else:
            raise ValueError("主張検討の数量・保持・詳細表現は未接続です")
    範囲群 = 先("要求範囲")
    if len(範囲群) > 1 or 範囲群 and 範囲群[0]["内容"]["値"] != "指定資料":
        raise ValueError("主張検討の取得範囲は未接続です")
    if any(項["種別"] != "対象.会話資料" for 項 in 対象):
        raise ValueError("主張検討の資料以外の対象役割は未接続です")
    既定提示ID = None
    if len(対象) == len(材料) == 1 and not 範囲群:
        原 = 材料[0]
        原範囲 = 原["原文範囲"]
        if (対象[0]["原文範囲"] is None and 対象[0]["内容"] == {
                "値": "提示本文", "原文": "", "根拠": "既定", "前束参照": None}
                and 原["種別"] == "情報源.会話入力区分"
                and 原["内容"]["値"] == "提示本文" and 原["内容"]["根拠"] == "原文"
                and 原範囲 is not None and 制御[0]["原文範囲"][1] <= 原範囲[0] < 原範囲[1]
                and 原["内容"]["原文"] == ビュー["原文"][slice(*原範囲)]):
            # 原文に資料名のない提示依頼だけ、同目的の実材料適用を対象の由来とする。
            # 原P・行為・明示対象の制御範囲検査は上書きしない。
            既定提示ID = 対象[0]["座標ID"]
    for 項 in 対象 + 範囲群:
        if 項["座標ID"] != 既定提示ID:
            制御文節内(項)
    名前 = [項["内容"]["値"] for 項 in 対象]
    if len(材料) == 1 and not 範囲群 and 名前 in ([], ["提示本文"]):
        原 = 材料[0]
        資料 = {"方式": "提示原文", "対象": [], "区分ID": 原["座標ID"],
              "原文範囲": 原["原文範囲"], "本文": 原["内容"]["原文"]}
        名前 = ["提示本文"]
    elif not 材料 and len(範囲群) == 1 and 1 <= len(名前) <= 4 and len(set(名前)) == len(名前):
        資料 = {"方式": "登録資料", "対象": 名前, "区分ID": None, "原文範囲": None, "本文": ""}
    else:
        raise ValueError("主張検討の提示原文と登録資料を混合又は省略できません")
    if 変更照合:
        if 資料["方式"] != "提示原文":
            raise ValueError("主張変更の登録資料条件束は未接続です")
        def 原指定(指定):
            if 指定 is None: return None
            結果 = deepcopy(指定)
            for 名, 範囲 in 指定.items():
                if 名.endswith("範囲"):
                    結果[名.removesuffix("範囲") + "原文"] = ビュー["原文"][slice(*範囲)]
            return 結果
        取消, 書換 = 原指定(行為値["取消指定"]), 原指定(行為値["書換指定"])
        確認 = []
        if 取消 is not None:
            確認.append("提示資料の原範囲" + str(資料["原文範囲"]) + "内で、選択原句「" + 取消["選択原文"]
                      + "」" + str(取消["選択範囲"]) + "が指す取消対象の条件の原文を示してください")
        if 書換 is not None:
            確認.append("書換主張「" + 主張["本文"] + "」" + str(主張["原文範囲"])
                      + "の対象・利用者の範囲と、維持する条件の原文を確認してください")
        要求 = {"版": 資料条件変更要求版, "変更照合": deepcopy(行為値), "取消指定": 取消,
              "書換指定": 書換, "主張": 主張, "資料": 資料, "形式": 形式, "最大文字数": 予算,
              "原条件対応": {"状態": "未形成", "条件ID": None}, "原支持": "未判定", "適用": "未適用",
              "作用禁止": [deepcopy(項) for 項 in 条件 if 項["内容"]["値"]["役割"] == "作用禁止"],
              "確認待ち": 確認}
        if 意味IR is None:
            raise ValueError("資料条件変更の当回原HDS意味IRが必要です")
        from .解釈 import 構造を保存
        要求.update(対象=名前, 範囲="指定資料", 不足調査=False, 原変更={
            "所有セッション": 所有セッション, "原文": ビュー["原文"], "目的ID": 目的ID,
            "文節ID": 文節["座標ID"], "文節範囲": 文節["原文範囲"], "行為座標ID": 行為群[0]["座標ID"],
            "行為範囲": 行為群[0]["原文範囲"], "行為原文": ビュー["原文"][slice(*行為群[0]["原文範囲"])],
            "契約印": 指紋(契約包), "意味IR印": 指紋(構造を保存(意味IR)), "HDS残差": 構造を保存(意味IR)["残差"]})
        要求 = 資料条件変更要求を検査(要求)
        return 正準({"版": 会話主張変更接続版, "目的ID": 目的ID, "文節ID": 文節["座標ID"],
                   "行為": "変更照合", "主張": 主張, "資料": 資料, "要求": 要求})
    要求 = {"版": 関係要求版, "対象": 名前, "範囲": "指定資料", "問い": 主張["本文"],
          "形式": 形式, "不足調査": False, "最大文字数": 予算}
    if 接続版 == 会話主張接続版:
        if 意味IR is None:
            raise ValueError("主張採用の原HDS意味IRが必要です")
        from .解釈 import 構造を保存
        行為 = 行為群[0]
        要求.update(版=主張採用要求版, 原主張={
            "所有セッション": 所有セッション, "原文": ビュー["原文"], "目的ID": 目的ID,
            "文節ID": 文節["座標ID"], "行為": 行為値["行為"], "行為座標ID": 行為["座標ID"],
            "行為範囲": 行為["原文範囲"], "行為原文": ビュー["原文"][slice(*行為["原文範囲"])],
            "主張": 主張, "資料": 資料, "契約印": 指紋(契約包), "意味IR印": 指紋(構造を保存(意味IR)),
            "HDS残差": 構造を保存(意味IR)["残差"]})
        要求 = 関係要求を検査(要求)
    # 自然文Pの既存関係文法対応は計画側の既存検査へ任せ、ここでは同じ原IRを保存できる。
    return 正準({"版": 接続版, "目的ID": 目的ID, "文節ID": 所属[0]["座標ID"],
               "行為": 行為群[0]["内容"]["値"]["値"]["行為"], "主張": 主張, "資料": 資料, "要求": 要求})


def 会話主張HDSを検査(解釈, 所有セッション):
    """保存した実HDSから主張接続を再導出する。原文を再コンパイルしない。"""
    from ..HDS再生 import HDSIR復元
    from ..HDSコア入力射影 import HDSコア入力へ
    from .構文化接続 import 局所接続を構成
    from .解釈 import 構造を保存
    if (type(解釈) is not dict or set(解釈) != {"方式", "原文", "接続", "要求", "会話契約", "HDS"}
            or 解釈["方式"] != "関係検討" or type(解釈["HDS"]) is not dict
            or set(解釈["HDS"]) != {"全文", "局所作用ビュー", "コア入力", "責任対応"}
            or type(解釈["HDS"]["全文"]) is not dict or 解釈["HDS"]["全文"].get("手順") is not None):
        raise ValueError("主張接続の原解釈又はHDS保存欄が不正です")
    再 = HDSIR復元(解釈["HDS"]["全文"])
    if 指紋(構造を保存(再)) != 指紋(解釈["HDS"]["全文"]) or 再.原文 != 解釈["原文"]:
        raise ValueError("主張接続のHDS全文が保存時と完全同値ではありません")
    if 指紋(構造を保存(HDSコア入力へ(再))) != 指紋(解釈["HDS"]["コア入力"]):
        raise ValueError("主張接続のコア入力がHDS全文の射影と不一致です")
    局所, 責任 = 局所接続を構成(再)
    if (指紋(構造を保存(局所)) != 指紋(解釈["HDS"]["局所作用ビュー"])
            or 指紋(構造を保存(責任)) != 指紋(解釈["HDS"]["責任対応"])):
        raise ValueError("主張接続の局所ビュー又は責任がHDS全文と不一致です")
    接続 = 会話主張要求を読む(解釈["会話契約"], 所有セッション=所有セッション,
                        期待原文=解釈["原文"], 意味IR=局所,
                        接続版=旧会話主張接続版 if 解釈["接続"].get("版") == 旧会話主張接続版 else 会話主張接続版)
    if (接続 is None or 指紋(接続) != 指紋(解釈["接続"])
            or 指紋(接続["要求"]) != 指紋(解釈["要求"])):
        raise ValueError("主張接続の要求又は原資料対応が原IRと不一致です")
    return 接続


def 主張資料を読む(解釈, 入力):
    from ..製品版.型 import 能力結果, 参照資料
    if 入力["原文"] != 解釈["原文"]:
        raise ValueError("主張資料と実原要求が不一致です")
    接続 = 会話主張HDSを検査(解釈, 入力["セッションID"])
    資料 = 接続["資料"]
    if 資料["方式"] == "提示原文":
        始, 終 = 資料["原文範囲"]
        本文 = 入力["原文"][始:終]
        if 本文 != 資料["本文"]:
            raise ValueError("主張資料の実提示spanが不一致です")
        印 = 指紋({"原文": 入力["原文"], "本文": 本文, "範囲": [始, 終]})
        参照 = 参照資料("主張提示本文:" + 印, "提示本文", "利用者提示本文", 本文=本文)
        return {"提示本文": 能力結果(True, 本文, 参照=(参照,))}
    結果 = {}
    for 名前 in 資料["対象"]:
        if 名前 not in 入力["資料"]:
            raise ValueError("確認待ち:主張の根拠資料を提示してください:" + 名前)
        結果[名前] = 結果を復元(入力["資料"][名前]["結果"])
    return 結果


def 主張回答を検査(回答, 解釈, 入力):
    """既存関係回答の全源を当回IRに照合する。診断を回答成立にしない。"""
    from .関係内容 import 関係回答を検査
    if not 関係回答を検査(回答):
        return False
    原資料 = 主張資料を読む(解釈, 入力)
    構造 = 回答.データ["構造"]
    return (構造["要求"] == 解釈["要求"]
            and 回答.データ["表示形式"] == 解釈["要求"]["形式"]
            and set(構造["資料群"]) == set(原資料)
            and 構造["公開資料群"] == {} and 構造["取得"] is None
            and all(項["資料"] == 結果を保存(原資料[名]) for 名, 項 in 構造["資料群"].items()))


def 関係依頼を読む(入力, *, 意味IR=None):
    if 意味IR is not None and any(項.種別 == "目的.会話操作" and type(項.内容) is dict
                               and 項.内容.get("値") == "主張検討" for 項 in 意味IR.座標):
        from ..HDS会話契約 import 会話契約を形成
        from ..HDS会話意味射影 import 会話残差を読む, 会話未読解
        包 = 会話契約を形成(意味IR, 所有セッション=入力["セッションID"])
        診断 = 会話残差を読む(意味IR)
        if 診断:
            raise 会話未読解(診断)
        接続 = 会話主張要求を読む(包, 所有セッション=入力["セッションID"],
                            期待原文=入力["原文"], 意味IR=意味IR)
        return {"方式": "関係検討", "原文": 入力["原文"], "接続": 接続,
                "要求": deepcopy(接続["要求"]), "会話契約": 包}
    原文 = 入力["原文"]
    文 = 原文.strip().rstrip("。")
    前 = 入力.get("前回結果")
    if 文 in _再表現 and 前 is not None and 結果を復元(前).データ.get("種別") == "関係資料回答":
        if not 入力.get("前回有効"):
            raise ValueError("関係回答の起点が失効しています。再計算してください")
        return {"方式": "関係再表現", "原文": 原文, "形式": _再表現[文]}
    横断 = re.fullmatch(rf'(?P<資料>{_資料列})を結び付けて[、,]\s*資料「(?P<照会>[^「」\n]+)」(?:でいう|の)[、,]?\s*(?P<後>.+)', 文, re.S)
    一致 = re.fullmatch(rf'(?P<資料>{_資料列})(?:をもとに|から|では)[、,]?\s*(?P<後>.+)', 文, re.S)
    if 横断:
        対象, 範囲, 後 = re.findall(r'「([^「」]+)」', 横断["資料"]), "指定資料", 横断["後"]
    elif re.match(rf"{_資料列}を結び付けて", 文):
        raise ValueError("資料横断には選択資料と照会資料を明示してください")
    elif 一致:
        対象, 範囲, 後 = re.findall(r'「([^「」]+)」', 一致["資料"]), "指定資料", 一致["後"]
    elif 文.startswith("登録資料から"):
        対象, 範囲, 後 = [], "全資料", 文[len("登録資料から"):].lstrip("、, ")
    else:
        return None
    # 資料要約・数量演算など他の経路を奪わない。
    if not any(語 in 後 for 語 in ("かどうか", "の根拠と条件", "なぜ")):
        return None
    問い, 尾 = None, None
    for 書式 in (
        r'(?P<問い>.+?)かどうか(?:を)?(?:説明して|確認して|教えて)(?:ください)?(?P<尾>.*)',
        r'「(?P<問い>[^「」]+)」の根拠と条件を説明して(?:ください)?(?P<尾>.*)',
        r'なぜ(?P<問い>.+?)のか(?:を)?説明して(?:ください)?(?P<尾>.*)',
    ):
        質問 = re.fullmatch(書式, 後, re.S)
        if 質問:
            問い, 尾 = 質問["問い"].strip(), 質問["尾"]
            break
    if 問い is None:
        raise ValueError("関係質問の未対応構文")
    if 問い.startswith("「") and 問い.endswith("」"):
        問い = 問い[1:-1]
    形式, 予算, 調査 = None, None, False
    if 尾 and not re.match(r'^[、,。]', 尾):
        raise ValueError("関係質問の未消費条件:" + 尾)
    for 節 in (項.strip() for 項 in re.split(r'[、,。]', 尾) if 項.strip()):
        if 節 in _再表現:
            if 形式 is not None and 形式 != _再表現[節]:
                raise ValueError("関係回答の形式指定が競合")
            形式 = _再表現[節]
        elif 節 in ("不足は公開資料で調べて", "足りない情報は公開資料で調べて"):
            調査 = True
        elif re.fullmatch(r'[0-9]+文字以内で', 節):
            値 = int(節.removesuffix("文字以内で"))
            if 予算 is not None and 予算 != 値:
                raise ValueError("関係回答の文字予算が競合")
            予算 = 値
        else:
            raise ValueError("関係質問の未対応条件:" + 節)
    要求値 = {"版": 関係要求版, "対象": 対象, "範囲": 範囲, "問い": 問い,
                          "形式": 形式 or "箇条書き", "不足調査": 調査, "最大文字数": 24000 if 予算 is None else 予算}
    if 横断:
        要求値.update(版="HDS資料横断要求-v1", 照会資料=横断["照会"])
    要求 = 関係要求を検査(要求値)
    return {"方式": "関係資料", "原文": 原文, "要求": 要求}


def 関係計画を作る(解釈, 入力):
    from ..能力合成 import 合成計画, 合成工程, 素材参照
    from ..製品版.型 import 能力結果
    if 解釈.get("要求", {}).get("版") in (旧資料条件変更要求版, 資料条件変更要求版):
        if 入力["原文"] != 解釈["原文"]:
            raise ValueError("主張変更と実原要求が不一致です")
        接続 = 会話主張HDSを検査(解釈, 入力["セッションID"])
        if 接続["版"] != 会話主張変更接続版:
            raise ValueError("主張変更の型が保存実HDSと不一致です")
        if 解釈["要求"]["版"] == 旧資料条件変更要求版:
            raise ValueError("旧資料条件変更意図は新版へ無言変換しません")
    if 解釈["方式"] == "関係再表現":
        if not 入力.get("前回有効"):
            raise ValueError("関係回答の起点失効")
        素材 = {"関係:前回": 結果を復元(入力["前回結果"]), "関係:指示": 能力結果(True, "採用済み関係説明を根拠とともに再表現する"),
                "関係:形式": 能力結果(True, "", データ={"形式": 解釈["形式"]})}
        return 合成計画((合成工程("関係再表現", ("関係文章再表現",), "関係:指示",
            (素材参照("入力", "関係:前回"),), "関係:形式"),), ("関係再表現",)), 素材, "関係資料回答"
    要求 = 関係要求を検査(解釈["要求"])
    if 要求["版"] == 主張採用要求版 and 解釈["方式"] != "関係検討":
        raise ValueError("主張採用要求には当回の原HDS主張接続が必要です")
    if 要求["不足調査"] and not 入力["外部許可"]:
        raise ValueError("不足調査にはセッションと今回依頼の外部読取許可が必要です")
    主張資料 = 主張資料を読む(解釈, 入力) if 解釈["方式"] == "関係検討" else None
    名前 = list(主張資料) if 主張資料 is not None else 要求["対象"] if 要求["範囲"] == "指定資料" else sorted(入力["資料"])
    if not 1 <= len(名前) <= 8:
        raise ValueError("関係質問の資料は1〜8件です")
    素材 = {"関係:指示": 能力結果(True, "原資料の関係・条件・実導出・不足を保持して説明する"),
            "関係:設定": 能力結果(True, "", データ={"要求": 要求, "資料名": 名前})}
    for 番号, 名 in enumerate(名前):
        if 主張資料 is not None:
            素材["関係:資料:" + str(番号)] = 主張資料[名]
            continue
        if 名 not in 入力["資料"]:
            raise ValueError("確認待ち:資料不足:" + 名)
        素材["関係:資料:" + str(番号)] = 結果を復元(入力["資料"][名]["結果"])
    工程 = [合成工程("関係読解", ("資料関係読解",), "関係:指示",
                     tuple(素材参照("入力", "関係:資料:" + str(番号)) for 番号 in range(len(名前))), "関係:設定")]
    起点 = "関係読解"
    def 前(名):
        return 素材参照("工程", 名)
    if 要求["不足調査"]:
        工程.extend((合成工程("関係不足取得", ("関係不足資料取得",), "関係:指示", (前(起点),)),
                     合成工程("関係追加読解", ("取得関係読解",), "関係:指示", (前("関係不足取得"),))))
        起点 = "関係追加読解"
    工程.extend((合成工程("関係内容構成", ("関係内容構成",), "関係:指示", (前(起点),)),
                 合成工程("関係文章生成", ("文章作成",), "関係:指示", (前("関係内容構成"),)),
                 合成工程("関係回答照合", ("関係文章照合",), "関係:指示", (前(起点), 前("関係文章生成")))))
    return 合成計画(tuple(工程), ("関係回答照合",)), 素材, "関係資料回答"
