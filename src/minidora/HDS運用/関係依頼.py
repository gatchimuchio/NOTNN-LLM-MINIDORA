"""普通の関係質問を既存HDS工程へ接続する。解釈不能な目的・指定を捨てない。"""
from __future__ import annotations
import re
from .値 import 結果を復元
from .関係読解 import 関係要求版, 関係要求を検査

_資料列 = r'(?:資料)?「[^「」\n]+」(?:\s*と\s*(?:資料)?「[^「」\n]+」)*'
_再表現 = {"箇条書きにして": "箇条書き", "文章にして": "文章", "引用形式にして": "引用"}


def 関係依頼を読む(入力):
    原文 = 入力["原文"]
    文 = 原文.strip().rstrip("。")
    前 = 入力.get("前回結果")
    if 文 in _再表現 and 前 is not None and 結果を復元(前).データ.get("種別") == "関係資料回答":
        if not 入力.get("前回有効"):
            raise ValueError("関係回答の起点が失効しています。再計算してください")
        return {"方式": "関係再表現", "原文": 原文, "形式": _再表現[文]}
    一致 = re.fullmatch(rf'(?P<資料>{_資料列})(?:をもとに|から|では)[、,]?\s*(?P<後>.+)', 文, re.S)
    if 一致:
        対象, 範囲, 後 = re.findall(r'「([^「」]+)」', 一致["資料"]), "指定資料", 一致["後"]
    elif 文.startswith("登録資料から"):
        対象, 範囲, 後 = [], "全資料", 文[len("登録資料から"):].lstrip("、, ")
    else:
        return None
    # 資料要約・数量演算など他の経路を奪わない。
    if not any(語 in 後 for 語 in ("かどうか", "の根拠と条件", "なぜ")):
        return None
    問い, 尾 = None, None
    for 書式 in (
        r'(?P<問い>.+?)かどうか(?:を)?(?:説明して|確認して|教えて)(?:ください)?(?P<尾>.*)',
        r'「(?P<問い>[^「」]+)」の根拠と条件を説明して(?:ください)?(?P<尾>.*)',
        r'なぜ(?P<問い>.+?)のか(?:を)?説明して(?:ください)?(?P<尾>.*)',
    ):
        質問 = re.fullmatch(書式, 後, re.S)
        if 質問:
            問い, 尾 = 質問["問い"].strip(), 質問["尾"]
            break
    if 問い is None:
        raise ValueError("関係質問の未対応構文")
    if 問い.startswith("「") and 問い.endswith("」"):
        問い = 問い[1:-1]
    形式, 予算, 調査 = None, None, False
    if 尾 and not re.match(r'^[、,。]', 尾):
        raise ValueError("関係質問の未消費条件:" + 尾)
    for 節 in (項.strip() for 項 in re.split(r'[、,。]', 尾) if 項.strip()):
        if 節 in _再表現:
            if 形式 is not None and 形式 != _再表現[節]:
                raise ValueError("関係回答の形式指定が競合")
            形式 = _再表現[節]
        elif 節 in ("不足は公開資料で調べて", "足りない情報は公開資料で調べて"):
            調査 = True
        elif re.fullmatch(r'[0-9]+文字以内で', 節):
            値 = int(節.removesuffix("文字以内で"))
            if 予算 is not None and 予算 != 値:
                raise ValueError("関係回答の文字予算が競合")
            予算 = 値
        else:
            raise ValueError("関係質問の未対応条件:" + 節)
    要求 = 関係要求を検査({"版": 関係要求版, "対象": 対象, "範囲": 範囲, "問い": 問い,
                          "形式": 形式 or "箇条書き", "不足調査": 調査, "最大文字数": 24000 if 予算 is None else 予算})
    return {"方式": "関係資料", "原文": 原文, "要求": 要求}


def 関係計画を作る(解釈, 入力):
    from ..能力合成 import 合成計画, 合成工程, 素材参照
    from ..製品版.型 import 能力結果
    if 解釈["方式"] == "関係再表現":
        if not 入力.get("前回有効"):
            raise ValueError("関係回答の起点失効")
        素材 = {"関係:前回": 結果を復元(入力["前回結果"]), "関係:指示": 能力結果(True, "採用済み関係説明を根拠とともに再表現する"),
                "関係:形式": 能力結果(True, "", データ={"形式": 解釈["形式"]})}
        return 合成計画((合成工程("関係再表現", ("関係文章再表現",), "関係:指示",
            (素材参照("入力", "関係:前回"),), "関係:形式"),), ("関係再表現",)), 素材, "関係資料回答"
    要求 = 関係要求を検査(解釈["要求"])
    if 要求["不足調査"] and not 入力["外部許可"]:
        raise ValueError("不足調査にはセッションと今回依頼の外部読取許可が必要です")
    名前 = 要求["対象"] if 要求["範囲"] == "指定資料" else sorted(入力["資料"])
    if not 1 <= len(名前) <= 8:
        raise ValueError("関係質問の資料は1〜8件です")
    素材 = {"関係:指示": 能力結果(True, "原資料の関係・条件・実導出・不足を保持して説明する"),
            "関係:設定": 能力結果(True, "", データ={"要求": 要求, "資料名": 名前})}
    for 番号, 名 in enumerate(名前):
        if 名 not in 入力["資料"]:
            raise ValueError("確認待ち:資料不足:" + 名)
        素材["関係:資料:" + str(番号)] = 結果を復元(入力["資料"][名]["結果"])
    工程 = [合成工程("関係読解", ("資料関係読解",), "関係:指示",
                     tuple(素材参照("入力", "関係:資料:" + str(番号)) for 番号 in range(len(名前))), "関係:設定")]
    起点 = "関係読解"
    def 前(名):
        return 素材参照("工程", 名)
    if 要求["不足調査"]:
        工程.extend((合成工程("関係不足取得", ("関係不足資料取得",), "関係:指示", (前(起点),)),
                     合成工程("関係追加読解", ("取得関係読解",), "関係:指示", (前("関係不足取得"),))))
        起点 = "関係追加読解"
    工程.extend((合成工程("関係内容構成", ("関係内容構成",), "関係:指示", (前(起点),)),
                 合成工程("関係文章生成", ("文章作成",), "関係:指示", (前("関係内容構成"),)),
                 合成工程("関係回答照合", ("関係文章照合",), "関係:指示", (前(起点), 前("関係文章生成")))))
    return 合成計画(tuple(工程), ("関係回答照合",)), 素材, "関係資料回答"
