"""提供文字列を原文範囲付きで読解し、未解釈・欠落を残して抽出的に説明する。

全文判定の代替ではない。読めた記載の局所導出を資料全体の真偽へ昇格させない。
言語模型の知識、検索結果、因果、重要度を補完しない。ネットワークを利用しない。
"""
from __future__ import annotations

from copy import deepcopy
from dataclasses import asdict
from hashlib import sha256
import re
from .会話意味 import 意味指紋
from .能力合成 import _符号化
from .命題句 import 構成句を分ける
from .命題構造 import 命題記載, 命題を復元
from .命題解釈 import 命題を読む
from .命題推論 import 命題推論器, 推論上限
from .文脈命題 import 文脈資料を読む
from .明示語彙 import 述語別名を検査, 命題の述語を対応付ける
from .導出説明 import 導出説明を構成

資料読解版 = 'MINIDORA-資料読解-v0.1'
_限界 = ('提供文字列の対応構文だけを抽出しています。未解釈記載や欠落が結論を変更する可能性を残します。'
    '局所導出は抽出した記載を前提とした結果であり、資料全体の判定・実世界の真実性・取得元の網羅性は未認定です。'
    '抽出外を無関係とは認定せず、未導出を否定へ変えません。複数資料間の暗黙の時点・対象同一性も未同定です。')


def _欄(値, 必須, 任意=()):
    if type(値) is not dict or not set(必須) <= set(値) <= set(必須) | set(任意):
        raise ValueError('資料読解の欄不正')


def _文字(値, 最大):
    if type(値) is not str or not 値.strip() or len(値) > 最大:
        raise ValueError('資料読解の文字列型・上限')
    値.encode('utf-8', 'strict')
    return 値


def 資料を読解(要求: dict) -> dict:
    _欄(要求, ('資料',), ('問い', '述語別名', '最大表示記載'))
    if len(_符号化(要求)) > 300_000:
        raise ValueError('資料読解の要求バイト上限')
    要求 = deepcopy(要求)
    資料群 = 要求['資料']
    if type(資料群) is not list or not 1 <= len(資料群) <= 8:
        raise ValueError('資料読解の資料数・型')
    表示数 = 要求.get('最大表示記載', 8)
    if type(表示数) is not int or not 1 <= 表示数 <= 32:
        raise ValueError('資料読解の表示記載上限')
    別名 = 要求.get('述語別名', ())
    語彙 = 述語別名を検査(別名)
    if '問い' in 要求:
        _文字(要求['問い'], 4096)
    読取, 原記載, 残差, 資料情報, 語彙記録 = [], [], [], [], []
    名前群, 総文字数 = set(), 0
    for 資料 in 資料群:
        _欄(資料, ('名前', '本文'), ('欠落',))
        名前, 本文 = _文字(資料['名前'], 80), _文字(資料['本文'], 32000)
        if 名前 != 名前.strip() or any(ord(c) < 32 for c in 名前) or 名前 in 名前群:
            raise ValueError('資料読解の資料名不正・重複')
        名前群.add(名前)
        総文字数 += len(本文)
        if 総文字数 > 32000:
            raise ValueError('資料読解の総本文上限')
        欠落 = 資料.get('欠落', [])
        if type(欠落) is not list or len(欠落) > 32:
            raise ValueError('資料読解の欠落欄の型・上限')
        for 記録 in 欠落:
            _文字(記録, 256)
        資料情報.append({'名前': 名前, '本文SHA256': sha256(本文.encode()).hexdigest(),
                        '欠落': 欠落, '取得元の網羅性': '未確認'})
        try:
            範囲群 = list(構成句を分ける(本文))
        except ValueError as 例外:
            # 壊れた引用の内外を推定して一部だけ読まない。原文全体を残差として保持する。
            残差.append({'資料': 名前, '識別子': 名前 + ':全体', '原文': 本文,
                         '範囲': [0, len(本文)], '理由': '構成境界未確定:' + str(例外)})
            continue
        if len(範囲群) + len(読取) + len(残差) > 128:
            raise ValueError('資料読解の記載数上限。途中の読取を採用しない')
        for 番号, (開始, 終了) in enumerate(範囲群):
            原文 = 本文[開始:終了]
            識別子 = 名前 + ':' + str(番号)
            記録 = {'資料': 名前, '識別子': 識別子, '原文': 原文, '範囲': [開始, 終了]}
            射影文 = 原文.strip()
            変換 = []
            # リスト記号以外を削らない。見出し・注記・自由な前置きは残差にする。
            行頭 = re.match(r'^(?:[-*・]|[0-9]{1,3}[.)])\s+', 射影文)
            if 行頭:
                射影文 = 射影文[行頭.end():]
                変換.append({'作用': '明示リスト記号の分離', '原文': 行頭[0]})
            try:
                候補 = 文脈資料を読む(射影文, 名前)['記載候補']
                if len(候補) != 1:
                    raise ValueError('独立した一記載へ分解できない')
                読み = 候補[0]['候補']
                if len(読み) != 1:
                    残差.append({**記録, '理由': '意味候補未確定', '候補': 読み})
                    continue
                式 = 命題を復元(読み[0]['式'])
                式, 対応 = 命題の述語を対応付ける(式, 語彙)
                一記載 = 命題記載(識別子, 式, 名前, 原文, (開始, 終了))
                # 読める構文と推論器で使える式の違いも残す。条件を切り捨てて受理しない。
                命題推論器((一記載,))
                原記載.append(一記載)
                読取.append({**記録, '式': 式.辞書(), '射影文': 読み[0]['射影文'],
                             '表記変換': 変換, '解消': 読み[0]['解消']})
                語彙記録.extend({'記載': 識別子, **行} for 行 in 対応)
            except (ValueError, TypeError, KeyError, RecursionError) as 例外:
                残差.append({**記録, '理由': '未解釈:' + str(例外)})
    問い状態, 局所判定, 導出説明 = '未指定', None, None
    問い残差 = ''
    if '問い' in 要求:
        try:
            候補 = 命題を読む(要求['問い'])
            if len(候補) != 1:
                raise ValueError('問いの読みが複数。括弧で作用域を明示してください')
            問い式, 対応 = 命題の述語を対応付ける(候補[0].式, 語彙)
            語彙記録.extend({'記載': '問い', **行} for 行 in 対応)
            問い状態 = '解釈済み'
        except (ValueError, TypeError, KeyError, RecursionError) as 例外:
            問い状態, 問い残差 = '未解釈', str(例外)
        if 問い状態 == '解釈済み' and 原記載:
            # 予算超過は報告全体を不成立にする。部分導出を完成した結果として返さない。
            局所判定 = 命題推論器(tuple(原記載), 上限=推論上限(操作数=50000)).判定(問い式)
            導出説明 = 導出説明を構成(局所判定, [asdict(行) for 行 in 原記載])
    # 同一式は一項目へ束ねるが、独立した裏付け数へ加算せず全出典を残す。
    集約 = {}
    for 行 in 読取:
        鍵 = 意味指紋(行['式'])
        if 鍵 not in 集約:
            集約[鍵] = {'代表': 行['識別子'], '同式記載': []}
        集約[鍵]['同式記載'].append(行['識別子'])
    if '問い' in 要求:
        使用 = 導出説明['使用記載'] if 導出説明 else []
        選択法 = '問いの支持・反証の実導出に使った記載'
    else:
        使用 = [行['代表'] for 行 in 集約.values()]
        選択法 = '同一式をまとめた原文出現順。重要度の評価ではない'
    欠落数 = sum(len(行['欠落']) for 行 in 資料情報)
    報告 = {'版': 資料読解版, '要求': 要求,
            '状態': '抽出不能' if not 読取 else '部分読解' if 残差 or 欠落数 else '対応構文読解',
            '資料': 資料情報, '抽出記載': 読取, '未解釈': 残差,
            '語彙対応': 語彙記録, '同式集約': list(集約.values()),
            '問い状態': 問い状態, '問い残差': 問い残差, '局所判定': 局所判定,
            '導出説明': 導出説明, '選択法': 選択法, '選択記載': 使用[:表示数],
            '選択対象数': len(使用), '非表示対象数': max(0, len(使用) - 表示数),
            '資料全体判定': '未認定', '事実認定': False, '限界': _限界}
    報告['記録SHA256'] = 意味指紋(報告)
    return 報告


def 読解報告を検査(報告: dict) -> bool:
    try:
        return _符号化(報告) == _符号化(資料を読解(報告['要求']))
    except (ValueError, TypeError, KeyError, AttributeError, RecursionError):
        return False


def 読解説明節(報告: dict, *, 詳細: bool) -> list[dict]:
    """呼出側の再計算済み報告から作る。長さを減らしても境界と未解釈数は落とさない。"""
    節 = []
    def 追加(役割, 本文, 根拠=()):
        節.append({'役割': 役割, '本文': 本文, '根拠': list(根拠)})
    追加('読解境界', '抽出できた記載に限定して説明します。資料全体の判定ではありません。')
    追加('読解範囲', f"抽出{len(報告['抽出記載'])}記載／未解釈{len(報告['未解釈'])}記載。" +
        f"記録された欠落{sum(len(行['欠落']) for 行 in 報告['資料'])}件。取得元の網羅性は未確認です。")
    for 別名 in 報告['要求'].get('述語別名', ()):
        追加('語彙条件', f"明示定義（{別名['出典']}）：{別名['表記']}/{別名['引数数']}={別名['正規名']}。帰属内部は置換しません。")
    if '問い' in 報告['要求']:
        追加('問い', '問い：' + 報告['要求']['問い'])
        if 報告['局所判定']:
            追加('局所導出', '抽出記載を前提とした局所判定は「' + 報告['局所判定']['判定'] + '」です。')
            if 報告['局所判定']['判定'] == '未確定':
                追加('未導出', '有限導出では支持・反証の根拠が得られませんでした。前提不足と未対応推論をここでは同定していません。')
        elif 報告['問い状態'] == '未解釈':
            追加('問い未解釈', '問いの意味を確定していません：' + 報告['問い残差'])
        else:
            追加('抽出不足', '推論に使える記載を抽出できず、問いを判定していません。')
    追加('選択方法', 報告['選択法'])
    対応 = {行['識別子']: 行 for 行 in 報告['抽出記載']}
    for 識別子 in 報告['選択記載']:
        行 = 対応[識別子]
        追加('抽出原文', f"[{識別子}] {行['原文']}", (識別子,))
        for 解消 in 行['解消']:
            追加('照応条件', f"「{解消['原文']}」→「{解消['束縛先']}」：{解消['理由']}。", (識別子,))
    if 報告['非表示対象数']:
        追加('表示省略', f"表示上限により、選択対象のうち{報告['非表示対象数']}記載を本文では省略しています。報告データに保持しています。")
    if 詳細:
        if 報告['導出説明']:
            追加('導出境界', 報告['導出説明']['境界'])
            節.extend(deepcopy(報告['導出説明']['節']))
        for 行 in 報告['未解釈']:
            追加('未解釈原文', f"[{行['識別子']}] 未解釈：{行['原文']}（{行['理由']}）", (行['識別子'],))
        for 資料 in 報告['資料']:
            for 欠落 in 資料['欠落']:
                追加('欠落', f"[{資料['名前']}] 欠落記録：{欠落}")
    if not 報告['抽出記載']:
        追加('抽出不足', '対応する記載は抽出できませんでした。原資料に情報が存在しないという意味ではありません。')
    return 節
