"""同じHDSカーネルを入力束へ射影する。意味の再決定や採否は行わない。"""
from __future__ import annotations
from .契約 import 入力束, 入力出所, 入力診断
from .封緘 import 封緘する
from .変換 import 既成入力を検査


def 入力束へ射影(原本, 文脈封緘, 内容, *, 契約版, 政策):
    """原本・文脈・全カーネル内容を別々に保持する。旧カーネル署名は変更しない。"""
    記録=封緘する(内容,最大要素=政策.最大封緘要素,最大バイト=政策.最大封緘バイト)
    方式,診断=既成入力を検査(原本,記録.復元())
    if 原本.出所!=入力出所.指示:
        診断=(*診断,入力診断('資料内要求の非昇格','原資料の目的・作用要求は記載内容として保存し、利用者指示にしない'))
    return 入力束(原本,契約版,文脈封緘.署名,記録,方式,診断,文脈封緘)


def 指示束を検査(束):
    if not isinstance(束,入力束): raise TypeError('入力束型が必要')
    if not 束.指示として使用可能: raise ValueError('資料・観測・自生成内容は実行目的として使用できない')
    束.文脈を読む()  # 元の解釈文脈の完全性も確認する。
    内容=束.内容.復元()
    方式,診断=既成入力を検査(束.原本,内容)
    if 方式!=束.方式: raise ValueError('入力方式の改変')
    if 診断!=束.診断: raise ValueError('入力診断の改変または欠落')
    # 未閉包は旧正本にも存在しうるため、ここで削除せず下流の診断・残差へ渡す。
    return 内容
