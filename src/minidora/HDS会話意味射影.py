# 「ない」を含む形容詞語幹を否定接辞と混同しないための言語語彙。
_肯定形容詞 = ("少ない", "危ない", "切ない", "つまらない", "くだらない", "もったいない", "だらしない")


def _引用を隠す(文):
    """引用の位置と長さを保持し、引用内部を制御句として照合しない。"""
    return re.sub(r'「[^「」]*」|『[^『』]*』', lambda 一致: " " * len(一致[0]), 文)


def _問い述部の末を分ける(述部):
    文 = 述部.strip().rstrip("。？?！!").strip()
    文 = re.sub(r'(?:のです|のでしょう|のか|です|でしょう|か)$', "", 文).strip()
    語 = 会話字句を観測(文)
    if (語 and 語[-1].表層 == "の" and 語[-1].品詞[:2] in
            (("助詞", "終助詞"), ("助詞", "準体助詞"))):
        文 = 文[:語[-1].開始].rstrip()
    return 文


def 問いの否定を読む(述部):
    """末尾の否定接辞だけを読む。疑問終助詞と属格・形容詞語幹は区別する。"""
    文 = _問い述部の末を分ける(述部)
    if any(文.endswith(語) for 語 in _肯定形容詞):
        return False
    return bool(re.search(r'(?:ない|ぬ|ません|なかった|ではありません|でありません)$', 文))


def 会話依頼末を読む(文):
    """引用外の依頼活用だけを読む。未知の動詞を読解作用へ置換しない。"""
    外 = _引用を隠す(文).rstrip("。？！!?：: \t\r\n")
    字 = [項 for 項 in 会話字句を観測(外) if not 項.表層.isspace()]
    if not 字:
        return False
    # 過去・通常の報告、引用内の依頼は提示材料の制御根拠にしない。
    if 字[-1].辞書形 in {"た", "です", "ます"}:
        return False
    if 字[-1].辞書形 in {"くださる", "くれる", "ほしい"}:
        return any(項.品詞[0] == "動詞" for 項 in 字[:-1])
    if 字[-1].品詞[0] == "動詞" and "命令形" in 字[-1].活用形:
        return True
    return (字[-1].表層 in {"て", "で"} and 字[-1].品詞[0] == "助詞"
            and len(字) > 1 and 字[-2].品詞[0] in {"動詞", "助動詞"})


class 会話未読解(ValueError):
    """検査済み原IRの会話残差だけ。保存不正・内部例外の代替にしない。"""
    def __init__(self, 診断):
        self.診断 = deepcopy(診断)
        本文 = []
        for 項 in 診断:
            範囲 = "、".join(str(tuple(対)) for 対 in 項["原文範囲"])
            本文.append("原文" + 範囲 + "「" + 項["原文"] + "」: " + 項["理由"]
                        + "。確認: " + "；".join(項["解消条件"]))
        super().__init__("確認待ち:依頼の意味が未確定です。" + "；".join(本文))


def 会話残差を読む(ir):
    """残差の出自・原句・範囲を照合し、既存の解消条件を配送する。"""
    if type(ir) is not HDSIR:
        raise ValueError("会話診断には同一HDSIRが必要です")
    座標 = ir.座標辞書()
    if len(座標) != len(ir.座標):
        raise ValueError("会話診断の意味座標が重複しています")
    制御, _, _ = _保持した区分を読む(ir)
    結果 = []
    for 項 in ir.残差:
        if type(項) is not HDS残差:
            raise ValueError("会話診断の原残差型が不正です")
        if 項.種別 != "会話未消費":
            continue
        if (type(項) is not HDS残差 or type(項.原文) is not str or not 項.原文
                or type(項.理由) is not str or not 項.理由
                or type(項.影響座標) is not tuple or not set(項.影響座標) <= set(座標)
                or type(項.解消条件) is not tuple or not 項.解消条件
                or any(type(条件) is not str or not 条件 for 条件 in 項.解消条件)):
            raise ValueError("会話残差の構造又は参照が不正です")
        指定 = re.search(r':原文範囲=\(([0-9]+), ([0-9]+)\)$', 項.理由)
        if 指定:
            群 = [(int(指定[1]), int(指定[2]))]
            if not (0 <= 群[0][0] < 群[0][1] <= len(制御)
                    and ir.原文[slice(*群[0])] == 項.原文):
                raise ValueError("会話残差の原句と指定範囲が不一致です")
        else:
            群 = [一致.span() for 一致 in re.finditer(re.escape(項.原文), 制御)]
            if not 群:
                raise ValueError("会話残差の原句が制御区分にありません")
        条件 = list(項.解消条件)
        結果.append({"残差ID": 項.残差ID, "種別": 項.種別, "原文": 項.原文,
                     "原文範囲": [list(対) for 対 in 群], "理由": 項.理由,
                     "影響座標": list(項.影響座標), "解消条件": 条件})
    return 結果


def 会話制御文を分ける(原文):
    """提示構造を持つ読解要求から、原文範囲を保った非実行本文を分ける。

    単なる改行では分けない。空行で区分した依頼と本文も提示構造として読むが、
    後続が表示指定や追加依頼だけなら制御文に残す。資料内の命令は実行しない。
    """
    一致 = re.match(r'(?P<制御>[^\r\n]+)\r?\n(?P<本文>[\s\S]+)', 原文)
    制御 = _引用を隠す(一致["制御"]) if 一致 else ""
    if 一致 and re.search(r'要約|まとめ|要点|説明|比較|読んで', 制御) and (
        re.search(r'(?:次の|以下の|この)(?:文章|文|本文)|次を|以下を', 制御)
        or re.search(r'(?:要約|説明|比較)(?:して|してください)[：:]\s*$', 制御)
    ):
        return 一致["制御"], 一致["本文"], 一致.span("本文")
    段落 = re.match(r'(?P<制御>[\s\S]+?)\r?\n[ \t]*\r?\n(?P<本文>[\s\S]+)', 原文)
    if 段落:
        先行 = _引用を隠す(段落["制御"])
        読解依頼 = re.search(r'要約|まとめ|要点|説明|解説|比較|比べ|対照|整理|読んで|教えて', 先行)
        依頼末 = re.search(r'(?:して|ください|下さい|教えて|まとめて|比べて|読んで|ほしい|たい)(?:[。！？!?：:]|\s)*$', 先行)
        本文外 = _引用を隠す(段落["本文"]).strip()
        本文句 = [節.strip() for 節 in re.split(r'[。！？!?\r\n]+', 本文外) if 節.strip()]
        # 空行後の表示指定を、提示資料に変えて消費済みとしない。
        依頼だけ = bool(本文句) and all(re.search(
            r'(?:て|で|ください|下さい|ほしい|たい|(?:文字|文|項目|件|点)(?:以内|以下)(?:に|で)?|箇条書きに|文章に|引用形式に|詳しく|短く)$', 節
        ) for 節 in 本文句)
        一般依頼 = 会話依頼末を読む(段落["制御"])
        if (読解依頼 and 依頼末 or 一般依頼) and 本文外 and not 依頼だけ:
            return 段落["制御"], 段落["本文"], 段落.span("本文")
    return 原文, "", None


def 会話入力区分を保持(ir, 制御, 本文, 本文範囲):
    """Kernelの前段で確定した提示区分を同じIRに保存する。"""
    if not 本文:
        return ir
    if (本文範囲 is None or ir.原文[:len(制御)] != 制御
            or ir.原文[slice(*本文範囲)] != 本文
            or 本文範囲[1] != len(ir.原文) or 本文範囲[0] < len(制御)):
        raise ValueError("会話入力区分の原文対応不一致")
    区分 = [("制御", 0, len(制御)), ("区切り", len(制御), 本文範囲[0]),
            ("提示本文", *本文範囲)]
    追加群 = tuple(HDS座標("会話区分:" + 名, "情報源.会話入力区分",
                        {"役割": 名, "本文": ir.原文[始:終]}, 原文範囲=(始, 終), 由来=会話区分由来)
                 for 名, 始, 終 in 区分 if 始 < 終)
    既存ID = {座標.座標ID for 座標 in ir.座標}
    if 既存ID.intersection(座標.座標ID for 座標 in 追加群):
        raise ValueError("会話入力区分のID重複")
    履歴 = HDS意味作用("会話入力区分保持", "原文役割区分", (),
                       tuple(座標.座標ID for 座標 in 追加群), "前段の制御と非実行資料の区分を保持",
                       保持構造=("原文", "原文範囲", "提示本文は非実行データ"))
    return replace(ir, 座標=(*ir.座標, *追加群), 意味作用履歴=(*ir.意味作用履歴, 履歴))


def _保持した区分を読む(ir):
    群 = [座標 for 座標 in ir.座標 if 座標.由来 == 会話区分由来]
    if not 群:
        return ir.原文, "", None
    欄, 位置 = {}, 0
    for 座標 in 群:
        内容 = 座標.内容
        if (座標.種別 != "情報源.会話入力区分" or type(内容) is not dict
                or set(内容) != {"役割", "本文"} or 内容["役割"] not in ("制御", "区切り", "提示本文")
                or 内容["役割"] in 欄 or 座標.原文範囲 is None):
            raise ValueError("保存した会話入力区分の形不一致")
        if (type(座標.原文範囲) is not tuple or len(座標.原文範囲) != 2
                or any(type(値) is not int for 値 in 座標.原文範囲)):
            raise ValueError("保存した会話入力区分の範囲型不一致")
        始, 終 = 座標.原文範囲
        if 始 != 位置 or not 始 < 終 <= len(ir.原文) or ir.原文[始:終] != 内容["本文"]:
            raise ValueError("保存した会話入力区分の原文対応不一致")
        欄[内容["役割"]] = 座標
        位置 = 終
    if (位置 != len(ir.原文) or list(欄) not in (["制御", "提示本文"], ["制御", "区切り", "提示本文"])
            or "区切り" in 欄 and 欄["区切り"].内容["本文"].strip()):
        raise ValueError("保存した会話入力区分の全域被覆不一致")
    return 欄["制御"].内容["本文"], 欄["提示本文"].内容["本文"], 欄["提示本文"].原文範囲


def _焦点要求(ir, 文脈=None):
    候補 = [getattr(文脈, "現在焦点", None)]
    候補.extend(座標.内容 for 座標 in ir.座標 if 座標.種別 == "文脈.参照先")
    for 内容 in 候補:
        if type(内容) is dict:
            値 = 内容
            if 値.get("方式") == "継続":
                値 = 値.get("目的", {})
            要求 = 値.get("要求", 値)
            if type(要求) is dict and 要求.get("版") in _一般版:
                return deepcopy(要求)
    return None


def _語群(文, *, 複数=False):
    文 = 文.strip()
    if not 文:
        return []
    if re.fullmatch(r'「[^「」\n]+」(?:\s*と\s*「[^「」\n]+」)*', 文):
        群 = re.findall(r'「([^「」]+)」', 文)
    else:
        最上位 = dict(最上位位置(文, ("および", "及び", "と", "、", "・")))
        境界 = []
        for 語 in 会話字句を観測(文):
            if 語.開始 not in 最上位 or 最上位[語.開始] != 語.表層:
                continue
            接続 = 語.表層 in ("および", "及び") and 語.品詞[0] == "接続詞"
            列挙 = 複数 and (語.表層 == "と" and 語.品詞[:2] == ("助詞", "格助詞")
                           or 語.表層 in ("、", "・") and 語.品詞[0] == "補助記号")
            if 接続 or 列挙:
                境界.append((語.開始, 語.終了))
        群, 始 = [], 0
        for 左, 右 in 境界:
            群.append(文[始:左].strip().strip("「」『』 "))
            始 = 右
        群.append(文[始:].strip().strip("「」『』 "))
    if len(群) > 4 or any(not 項 or len(項) > 128 or re.search(r'[\r\n。!?！？;；]', 項) for 項 in 群):
        raise ValueError("会話の対象は1〜4件、各128文字以内で指定してください")
    if len(set(群)) != len(群):
        raise ValueError("会話の対象が重複しています")
    return 群


def _添加対象を読む(文):
    """最上位の添加だけを同じ作用の対象列へ結ぶ。引用内は対象名。"""
    境界 = tuple(最上位位置(文, ("だけではなく", "だけじゃなく", "だけでなく")))
    if not 境界:
        return None
    if len(境界) != 1 or not 文.endswith("も"):
        raise ValueError("添加の対象と共通作用域が未確定です")
    位置, 標識 = 境界[0]
    前, 後 = 文[:位置].strip(), 文[位置 + len(標識):-1].strip()
    return _語群(前) + _語群(後)


def _属格位置(文):
    return _助詞位置(文, ("の",), ("格助詞",))


def _助詞位置(文, 標識, 細別):
    # 品詞は字句候補。引用・文法役割の責任はこのKernelの構造照合に残す。
    最上位 = dict(最上位位置(文, 標識))
    return [(語.開始, 語.表層) for 語 in 会話字句を観測(文)
            if 最上位.get(語.開始) == 語.表層 and 語.品詞[0] == "助詞" and 語.品詞[1] in 細別]


def _問う関係を分ける(文):
    """問いの主体・述部を分離するだけで、問いの命題を事実採用しない。"""
    主格 = _助詞位置(文, ("は", "が"), ("格助詞", "係助詞"))
    if not 主格:
        return _語群(文), [], "未指定"
    位置, 助詞 = 主格[0]
    主体, 述部 = 文[:位置].strip(), 文[位置 + len(助詞):].strip()
    述部 = _問い述部の末を分ける(述部)
    方向 = "否定" if 問いの否定を読む(述部) else "肯定"
    # 疑問代名詞は問われる属性として保持し、未確認の値に置き換えない。
    if re.fullmatch(r'どこ|いつ|誰|だれ|何|なに|何人|いくら|どれ', 述部):
        属性境界 = _属格位置(主体)
        属性 = (主体[:属性境界[0][0]], 主体[属性境界[0][0] + 1:]) if 属性境界 else None
        if 属性:
            return _語群(属性[0]), [属性[1], 述部], "未指定"
        return _語群(主体), [述部], "未指定"
    return _語群(主体), [述部], 方向


def 会話意味欄を読む(ir):
    """同一Kernelの座標から局所作用契約の欄を取り出す。原文を再解釈しない。"""
    種別欄 = {値: 欄 for 欄, 値 in _欄種別.items()}
    列欄 = {"主題", "対象", "比較対象", "観点", "操作", "関係焦点"}
    欄 = {名: [] for 名 in 列欄}
    発見 = False
    for 座標 in ir.座標:
        if 座標.由来 != 会話射影由来 or 座標.種別 not in 種別欄:
            continue
        名 = 種別欄[座標.種別]
        発見 = True
        if 名 in 列欄:
            欄[名].append(座標.内容)
        elif 名 in 欄:
            raise ValueError("会話意味欄の重複:" + 名)
        else:
            欄[名] = 座標.内容
    return 欄 if 発見 else None


def 会話射影の対象(ir: HDSIR) -> bool:
    """既存の管理・計算・数量責任を保つ、共通の入口条件。"""
    制御, _, _ = _保持した区分を読む(ir)
    文 = 制御.strip().strip("：:").rstrip("。？?！!").strip()
    文 = re.sub(r'(?:ください|下さい)$', "", 文)
    # 数式・管理・数量計算・明示関係質問はその既存意味責任に残す。
    if not 文 or re.match(r'(?:本文資料|命題資料|仮説資料|介入資料|知識「|資料「.+?」を(?:登録|更新)|記憶から|知識(?:全体)?から)', 文):
        return False
    if ir.実行核.作用 in ("算術", "計数") or re.search(
        r'(?:(?<!再)計算|検算|微分|積分|因数分解|展開)(?:して|せよ|しろ|した結果|結果)'
        r'|の[A-Za-z_][A-Za-z_0-9]*による(?:微分|積分)は|かどうか|の根拠と条件', _引用を隠す(文)
    ):
        return False
    # 属性数量を比較する既存の二資料・二時点契約へ、一般文章の座標を混在させない。
    数量対象 = re.match(
        r'(?:(?:CSV|JSON)?資料「[^「」]+」と(?:CSV|JSON)?(?:資料)?「[^「」]+」の'
        r'|(?:(?:CSV|JSON)?資料「[^「」]+」|この資料)の[0-9]{4}年と[0-9]{4}年の'
        r'|この(?:2つ|二つ)の)(?P<属性>.+)', 文)
    if 数量対象 and any(数量対象["属性"].endswith(語) for 語 in 比較述語):
        return False
    return True


def HDS会話意味を射影(ir: HDSIR, *, 文脈=None) -> HDSIR:
    原文 = ir.原文
    制御, 提示本文, 本文範囲 = _保持した区分を読む(ir)
    文 = 制御.strip().strip("：:").rstrip("。？?！!").strip()
    文 = re.sub(r'(?:ください|下さい)$', "", 文)
    if not 会話射影の対象(ir):
        return ir
