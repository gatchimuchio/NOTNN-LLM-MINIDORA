"""実際の支持・反証の根拠グラフだけを、原記載と作用へ戻して説明する。

短い証明や最善の説明を探索する機構ではない。仮定を独立した事実へ昇格させない。
呼出側は元要求から報告全体を再計算・照合する。
"""
from __future__ import annotations

from .命題構造 import 命題を復元
from .命題解釈 import 命題を表現

導出説明版 = 'MINIDORA-導出説明-v0.1'
記載を使わない導出の説明 = ('原記載を使わず、適用した論理規則から得た結果です。'
    '資料の事実認定ではありません。')
_作用 = frozenset(('資料記載', '連言分解', '存在の局所証人', '全称具体化', '連言構成',
    '選言導入', '条件適用', '問いの仮定', '仮定を閉じた条件導出', '任意個体からの全称導出',
    '存在証拠', '場合の仮定', '全場合を閉じた選言除去'))


def 導出説明を構成(判定: dict, 記載: list[dict]) -> dict:
    """両側の根拠を親から順に辿る。出典不明・循環・未知作用では説明を補作しない。"""
    if type(判定) is not dict or type(記載) is not list or len(記載) > 256:
        raise ValueError('導出説明の入力型・上限')
    対応 = {}
    for 記録 in 記載:
        if type(記録) is not dict or type(記録.get('識別子')) is not str:
            raise ValueError('導出説明の記載型')
        識別子 = 記録['識別子']
        if 識別子 in 対応:
            raise ValueError('導出説明の記載ID重複')
        対応[識別子] = 記録
    グラフ = 判定.get('導出')
    if type(グラフ) is not dict or len(グラフ) > 4096:
        raise ValueError('導出説明のグラフ型・上限')
    訪問済, 訪問中, 順序, 使用 = set(), set(), [], []

    def 辿る(識別子, 深さ=0):
        if 識別子 in 訪問中 or 深さ > 128:
            raise ValueError('導出説明の循環・深さ上限')
        if 識別子 in 訪問済:
            return
        if type(識別子) is not str or 識別子 not in グラフ:
            raise ValueError('導出説明の根拠参照欠落')
        節点 = グラフ[識別子]
        if type(節点) is not dict or 節点.get('作用') not in _作用:
            raise ValueError('導出説明の未知作用')
        if type(節点.get('親')) not in (list, tuple) or len(節点['親']) > 32:
            raise ValueError('導出説明の親型・上限')
        訪問中.add(識別子)
        for 親 in 節点['親']:
            辿る(親, 深さ + 1)
        訪問中.remove(識別子)
        訪問済.add(識別子)
        if 節点['作用'] == '資料記載':
            出典 = 節点.get('出典')
            if 出典 not in 対応:
                raise ValueError('導出説明の原記載欠落')
            if 出典 not in 使用:
                使用.append(出典)
        順序.append(識別子)

    for 極 in ('支持', '反証'):
        起点 = 判定.get(極)
        if 起点 is not None:
            辿る(起点)
    節 = []
    for 識別子 in 順序:
        節点 = グラフ[識別子]
        # 実推論の導出には存在証人・任意個体がある。入力資料側では引き続き拒否する。
        表現 = 命題を表現(命題を復元(節点['式'], 内部許可=True))
        作用 = 節点['作用']
        if 作用 == '資料記載':
            原 = 対応[節点['出典']]
            本文 = f"根拠[{原['識別子']}]（{原['資料']}）：{原['原文']}"
            役割 = '使用記載'
        elif 作用 in ('問いの仮定', '場合の仮定'):
            本文 = f'導出内の仮定：{表現}。提供された事実ではなく、この導出の仮定範囲だけで使います。'
            役割 = '局所仮定'
        else:
            本文 = f'導出（{作用}）：{表現}'
            役割 = '導出作用'
        節.append({'役割': 役割, '本文': 本文, '根拠': [識別子, *節点['親']]})
    return {'版': 導出説明版, '使用記載': 使用, '節': 節,
            '境界': '支持と反証の実導出を表示する。途中の仮定は独立した事実ではない。最短の説明は未保証。'}
